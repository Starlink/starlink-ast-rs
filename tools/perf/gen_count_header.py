"""Write ast_counts.h and ast_counts.c into a copy of the reference source tree.

ast_counts.h is prepended to every src/*.c file of a counting build.  It
includes the PAL, ERFA and libm headers first (all include-guarded, so the
file's own later includes are no-ops), then redefines each PAL, ERFA and
counted libm function as a call that first counts itself under its C symbol
name.  The names match starlink-ast's `call-counts` keys.

    gen_count_header.py <copy of reference/starlink-ast>
"""
import pathlib
import re
import sys

LIBM = ["sin", "cos", "tan", "asin", "acos", "atan", "atan2", "exp", "log",
        "log10", "pow", "sqrt", "hypot", "sinh", "cosh", "tanh"]

root = pathlib.Path(sys.argv[1])
names = []
for hdr in ("pal2ast.h", "erfa2ast.h"):
    for m in re.finditer(r"^#define\s+((?:pal|era)\w+)\s+(ast\w+)\s*$",
                         (root / hdr).read_text(), re.M):
        names.append((m.group(1), m.group(2)))
if len(names) < 100:
    sys.exit(f"found only {len(names)} PAL/ERFA names; header format changed?")

h = ["/* Generated by tools/perf/gen_count_header.py; counting build only. */",
     "#ifndef AST_COUNTS_INCLUDED", "#define AST_COUNTS_INCLUDED",
     "#if HAVE_CONFIG_H", "#include <config.h>", "#endif",
     "#include <math.h>", '#include "pal.h"', '#include "erfa.h"',
     "void ast_counts_hit( const char *name );", ""]
for short, sym in names:
    h += [f"#undef {short}",
          f'#define {short}(...) ( ast_counts_hit( "{sym}" ), {sym}( __VA_ARGS__ ) )']
for f in LIBM:
    h.append(f'#define {f}(...) ( ast_counts_hit( "{f}" ), ({f})( __VA_ARGS__ ) )')
h += ["#endif", ""]
(root / "ast_counts.h").write_text("\n".join(h))

c = r'''/* Generated by tools/perf/gen_count_header.py; counting build only. */
#include <stdio.h>
#include <string.h>

#define AST_COUNTS_MAX 1024
static struct { const char *name; unsigned long long n; } table[ AST_COUNTS_MAX ];
static int used = 0;

void ast_counts_hit( const char *name ) {
   int i;
   for( i = 0; i < used; i++ ) {
      if( table[ i ].name == name || !strcmp( table[ i ].name, name ) ) {
         table[ i ].n++;
         return;
      }
   }
   if( used < AST_COUNTS_MAX ) {
      table[ used ].name = name;
      table[ used ].n = 1;
      used++;
   }
}

void ast_counts_reset( void ) { used = 0; }

static int cmp( const void *a, const void *b ) {
   return strcmp( *(const char * const *) a, *(const char * const *) b );
}

int ast_counts_dump( char *buf, int max ) {
   const char *order[ AST_COUNTS_MAX ];
   int i, j, len = 0;
   for( i = 0; i < used; i++ ) order[ i ] = table[ i ].name;
   qsort( order, (size_t) used, sizeof order[ 0 ], cmp );
   if( max > 0 ) buf[ 0 ] = 0;
   for( i = 0; i < used; i++ ) {
      for( j = 0; j < used && table[ j ].name != order[ i ]; j++ );
      int w = snprintf( buf + len, (size_t) ( max - len ), "%s\t%llu\n",
                        table[ j ].name, table[ j ].n );
      if( w < 0 || w >= max - len ) break;
      len += w;
   }
   return len;
}
'''
(root / "ast_counts.c").write_text(c.replace("#include <string.h>", "#include <stdlib.h>\n#include <string.h>", 1))
print(f"ast_counts.h: {len(names)} PAL/ERFA names, {len(LIBM)} libm functions")
