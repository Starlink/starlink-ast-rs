/* skyframe_attrs_probe -- capture every SkyFrame attribute as the C library
 * reports it, for each setting applied to a default SkyFrame, together with
 * the Native dump of each: the SkyFrame's own attributes (System,
 * AlignSystem, Equinox, NegLon, Projection, SkyRef, SkyRefIs, SkyRefP,
 * SkyTol, AlignOffset, AsTime, IsLatAxis, IsLonAxis, LatAxis, LonAxis) and
 * the Frame attributes whose SkyFrame defaults follow them (Title, Epoch,
 * Label, Symbol, Unit, Format, Direction, Top, Bottom).
 *
 * A setting of "PERM" swaps the two axes with astPermAxes; settings are
 * applied in order, separated by ";".
 *
 * Prints Rust source for crates/ast-core/tests/skyframe_attrs_oracle/cases.rs:
 *
 *   ./skyframe_attrs_probe > ../../crates/ast-core/tests/skyframe_attrs_oracle/cases.rs
 */
#include <float.h>
#include <stdio.h>
#include <string.h>
#include "ast.h"

static const char *settings[] = {
   "",
   "System=FK5", "System=FK4", "System=FK4-NO-E", "System=J2000",
   "System=GAPPT", "System=ECLIPTIC", "System=HELIOECLIPTIC",
   "System=GALACTIC", "System=SUPERGALACTIC", "System=AZEL",
   "System=UNKNOWN",
   "AlignSystem=FK5", "AlignSystem=GALACTIC",
   "Equinox=1950", "System=FK5;Equinox=2010", "System=FK4;Equinox=1900",
   "System=ECLIPTIC;Equinox=1980",
   "Epoch=1990", "System=FK4;Epoch=1970",
   "NegLon=1", "Projection=Orthographic",
   "SkyRef(1)=1.5", "SkyRef(2)=0.25", "SkyRef(1)=1.5;SkyRef(2)=0.25",
   "SkyRefIs=Pole", "SkyRefIs=Origin", "SkyRefIs=Ignored",
   "SkyRef(1)=1.5;SkyRef(2)=0.25;SkyRefIs=Origin",
   "SkyRef(1)=1.5;SkyRef(2)=0.25;SkyRefIs=Pole",
   "SkyRefP(1)=0.5", "SkyRefP(2)=1.2",
   "SkyRef(1)=1.5;SkyRef(2)=0.25;SkyRefP(2)=1.2;SkyRefIs=Origin",
   "SkyTol=0.01", "AlignOffset=1",
   "AsTime(1)=0", "AsTime(2)=1", "System=GALACTIC;AsTime(1)=1",
   "PERM", "PERM;SkyRef(1)=0.25", "PERM;AsTime(2)=0",
   "PERM;System=GALACTIC", "PERM;SkyRef(1)=0.25;SkyRef(2)=1.5;SkyRefIs=Origin",
   NULL
};

/* Attribute name, kind (s = string, i = integer, d = double) and whether it
   is per-axis (read on axes 1 and 2) and read-only. */
static const struct { const char *name; char kind; int per_axis; int ro; } attrs[] = {
   { "System", 's', 0, 0 }, { "AlignSystem", 's', 0, 0 },
   { "Equinox", 'd', 0, 0 }, { "Epoch", 'd', 0, 0 },
   { "NegLon", 'i', 0, 0 }, { "Projection", 's', 0, 0 },
   { "SkyRef", 'd', 1, 0 }, { "SkyRefIs", 's', 0, 0 },
   { "SkyRefP", 'd', 1, 0 }, { "SkyTol", 'd', 0, 0 },
   { "AlignOffset", 'i', 0, 0 }, { "AsTime", 'i', 1, 0 },
   { "IsLatAxis", 'i', 1, 1 }, { "IsLonAxis", 'i', 1, 1 },
   { "LatAxis", 'i', 0, 1 }, { "LonAxis", 'i', 0, 1 },
   { "Title", 's', 0, 0 }, { "Label", 's', 1, 0 }, { "Symbol", 's', 1, 0 },
   { "Unit", 's', 1, 0 }, { "Format", 's', 1, 0 }, { "Direction", 'i', 1, 0 },
   { "Top", 'd', 1, 0 }, { "Bottom", 'd', 1, 0 },
   { NULL, 0, 0, 0 }
};

static void lit( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void flit( double value ) {
   char buf[ 40 ];
   if( value == AST__BAD ) { fputs( "BAD", stdout ); return; }
   if( value == DBL_MAX ) { fputs( "f64::MAX", stdout ); return; }
   if( value == -DBL_MAX ) { fputs( "-f64::MAX", stdout ); return; }
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

/* A default SkyFrame with each ";"-separated setting applied in turn. The
   SkyRef and SkyRefP values are in radians, set with astSetD so that no
   axis formatting is involved. */
static AstFrame *make( const char *setting ) {
   AstFrame *f = (AstFrame *) astSkyFrame( " " );
   char buf[ 200 ], *tok, *save;
   snprintf( buf, sizeof( buf ), "%s", setting );
   for( tok = strtok_r( buf, ";", &save ); tok; tok = strtok_r( NULL, ";", &save ) ) {
      if( !strcmp( tok, "PERM" ) ) {
         int perm[ 2 ] = { 2, 1 };
         astPermAxes( f, perm );
      } else if( !strncmp( tok, "SkyRef", 6 ) ) {
         char name[ 40 ];
         double v;
         sscanf( tok, "%39[^=]=%lf", name, &v );
         if( strchr( name, '(' ) ) {
            astSetD( f, name, v );
         } else {
            astSet( f, "%s", tok );
         }
      } else {
         astSet( f, "%s", tok );
      }
      if( !astOK ) astClearStatus;
   }
   return f;
}

static char dumpbuf[ 65536 ];
static void sink( const char *line ) {
   strncat( dumpbuf, line, sizeof( dumpbuf ) - strlen( dumpbuf ) - 2 );
   strcat( dumpbuf, "\n" );
}

int main( void ) {
   int status = 0;
   int s, a, axis;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/skyframe_attrs_probe.c against\n"
           "// the C library at the submodule pin. Do not edit.\n\n"
           "// Each value is printed with 17 digits so that it reads back exactly,\n"
           "// including the limits of a latitude axis, which C computes as pi/2.\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "use ast_core::constants::BAD_VALUE as BAD;\n\n"
           "/// An attribute value as C reports it.\n"
           "#[derive(Debug, Clone, Copy, PartialEq)]\n"
           "pub enum V {\n    S(&'static str),\n    I(i32),\n    D(f64),\n}\n\n"
           "/// `(settings, attribute, axis (0 for none), value, astTest result)`;\n"
           "/// the test result is `None` for a read-only attribute.\n"
           "pub type ValueCase = (&'static str, &'static str, usize, V, Option<bool>);\n\n"
           "pub const VALUE_CASES: &[ValueCase] = &[\n" );

   for( s = 0; settings[ s ]; s++ ) {
      AstFrame *f = make( settings[ s ] );
      for( a = 0; attrs[ a ].name; a++ ) {
         int first = attrs[ a ].per_axis ? 1 : 0;
         int last = attrs[ a ].per_axis ? 2 : 0;
         for( axis = first; axis <= last; axis++ ) {
            char key[ 40 ];
            if( axis ) {
               snprintf( key, sizeof( key ), "%s(%d)", attrs[ a ].name, axis );
            } else {
               snprintf( key, sizeof( key ), "%s", attrs[ a ].name );
            }
            printf( "    (" ); lit( settings[ s ] ); printf( ", " );
            lit( attrs[ a ].name ); printf( ", %d, ", axis );
            if( attrs[ a ].kind == 's' ) {
               const char *v = astGetC( f, key );
               printf( "V::S(" ); lit( v ? v : "<NULL>" ); printf( ")" );
            } else if( attrs[ a ].kind == 'i' ) {
               printf( "V::I(%d)", astGetI( f, key ) );
            } else {
               printf( "V::D(" ); flit( astGetD( f, key ) ); printf( ")" );
            }
            if( attrs[ a ].ro ) {
               printf( ", None),\n" );
            } else {
               printf( ", Some(%s)),\n", astTest( f, key ) ? "true" : "false" );
            }
            if( !astOK ) astClearStatus;
         }
      }
      f = astAnnul( f );
   }
   printf( "];\n\n" );

   printf( "/// `(settings, astWrite dump)`.\n"
           "pub const DUMP_CASES: &[(&str, &str)] = &[\n" );
   for( s = 0; settings[ s ]; s++ ) {
      AstFrame *f = make( settings[ s ] );
      AstChannel *ch = astChannel( NULL, sink, " " );
      dumpbuf[ 0 ] = '\0';
      astWrite( ch, f );
      ch = astAnnul( ch );
      f = astAnnul( f );
      printf( "    (\n        " ); lit( settings[ s ] );
      printf( ",\n        r#\"%s\"#,\n    ),\n", dumpbuf );
   }
   printf( "];\n" );

   return astOK ? 0 : 1;
}
