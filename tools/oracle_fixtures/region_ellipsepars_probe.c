/* region_ellipsepars_probe -- capture astEllipsePars (ellipse.c
 * EllipsePars and CalcPars): the centre, the half-lengths of the axes, the
 * angle from the second axis to the primary axis, and the ends of the two
 * axes, in the current Frame, for a Cartesian Ellipse and an ICRS Ellipse
 * given by form 1, a Cartesian Ellipse given by form 0 whose second point
 * is not the end of the secondary axis, and a Cartesian Ellipse mapped
 * through a ZoomMap by the protected astMapRegion, which leaves its current
 * Frame different from its base Frame.
 *
 * Prints Rust source for crates/ast-core/tests/region_ellipsepars_oracle/cases.rs:
 *
 *   ./region_ellipsepars_probe > ../../crates/ast-core/tests/region_ellipsepars_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

extern void *astMapRegion_( void *, void *, void *, int * );
extern AstObject *astMakeId_( AstObject *, int * );

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

/* One case: `(name, [centre, a, b, angle, p1, p2] flattened)`. */
static void emit( const char *name, AstEllipse *e ) {
   double c[ 2 ], a, b, ang, p1[ 2 ], p2[ 2 ];
   double v[ 9 ];
   int i;
   astEllipsePars( e, c, &a, &b, &ang, p1, p2 );
   v[ 0 ] = c[ 0 ]; v[ 1 ] = c[ 1 ]; v[ 2 ] = a; v[ 3 ] = b; v[ 4 ] = ang;
   v[ 5 ] = p1[ 0 ]; v[ 6 ] = p1[ 1 ]; v[ 7 ] = p2[ 0 ]; v[ 8 ] = p2[ 1 ];
   printf( "    (\"%s\", [", name );
   for( i = 0; i < 9; i++ ) {
      lit( v[ i ] );
      printf( i < 8 ? ", " : "" );
   }
   printf( "]),\n" );
}

int main( void ) {
   int status = 0;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_ellipsepars_probe.c. Do not edit.\n\n"
           "/// `(case, [centre x, centre y, a, b, angle, p1 x, p1 y, p2 x, p2 y])`.\n"
           "pub const CASES: &[(&str, [f64; 9])] = &[\n" );
   {
      double c[] = { 1.0, 2.0 }, ax[] = { 2.0, 1.0 }, ang = 0.3;
      emit( "cartesian", astEllipse( astFrame( 2, " " ), 1, c, ax, &ang, NULL, " " ) );
   }
   {
      double c[] = { 1.0, 0.8 }, ax[] = { 0.2, 0.1 }, ang = 0.3;
      emit( "sky", astEllipse( astSkyFrame( "System=ICRS" ), 1, c, ax, &ang, NULL, " " ) );
   }
   {
      double c[] = { 0.0, 0.0 }, p1[] = { 2.0, 0.0 }, p2[] = { 1.0, 0.866 };
      emit( "form0", astEllipse( astFrame( 2, " " ), 0, c, p1, p2, NULL, " " ) );
   }
   {
      double c[] = { 1.0, 2.0 }, ax[] = { 2.0, 1.0 }, ang = 0.3;
      AstEllipse *e = astEllipse( astFrame( 2, " " ), 1, c, ax, &ang, NULL, " " );
      int s = 0;
      void *p = astMapRegion_( astMakePointer( e ), astMakePointer( astZoomMap( 2, 3.0, " " ) ),
                               astMakePointer( astFrame( 2, " " ) ), &s );
      emit( "zoomed", (AstEllipse *) astMakeId_( p, &s ) );
   }
   printf( "];\n" );
   return status;
}
