/* plot_curve_probe -- draw grid lines with astGridLine (plot.c GridLine,
 * AxPlot, Crv, CrvLine, Map1, and the polyline buffer Opoly/Fpoly) on
 * assorted Plots through C's grf_log.c, and capture the call log and SVG.
 *
 * Prints Rust source for crates/starlink-ast/tests/plot_curve_oracle/cases.rs:
 *
 *   ./plot_curve_probe > ../../crates/starlink-ast/tests/plot_curve_oracle/cases.rs
 *
 * Build and run from reference/starlink-ast/build (configured with
 * -DCMAKE_C_FLAGS=-ffp-contract=off), compiling grf_log.c in as
 * grf_log_probe.c's header describes:
 *
 *   cc -ffp-contract=off -O3 -DHAVE_CONFIG_H -I. -Isrc -I../src -I.. \
 *      ../../../tools/oracle_fixtures/plot_curve_probe.c ../src/grf_log.c \
 *      -L. -last -Wl,-force_load,libast_err.a -lm -Wl,-rpath,$PWD \
 *      -o ../../../tools/oracle_fixtures/plot_curve_probe
 *   ../../../tools/oracle_fixtures/plot_curve_probe > ...
 */
#include "plot_draw_probe.h"

struct line { int axis; double start[ 2 ]; double length; };

struct curve_case {
   const char *name;
   const char *head;      /* header under HEADS, or NULL for astFrame(2) */
   float gbox[ 4 ];
   double pbox[ 4 ];
   const char *attr;
   int nline;
   struct line lines[ 4 ];
};

