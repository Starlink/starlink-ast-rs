int main( void ) {
   int status_value = 0;
   int *status = &status_value;
   size_t icase;
   int i;

   astWatch( status );
   printf( "// Generated by tools/oracle_fixtures/plot_curve_probe.c.\n"
           "// Do not edit.\n\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "/// One grid line: the 1-based axis it follows, its start and its\n"
           "/// length.\n"
           "pub type Line = (usize, [f64; 2], f64);\n\n"
           "/// A Plot, the grid lines drawn on it, and what C's grf_log wrote.\n"
           "pub struct Case {\n"
           "    pub name: &'static str,\n"
           "    /// A header under fixtures/wcsconv/inputs, or None for a\n"
           "    /// 2-D Frame.\n"
           "    pub head: Option<&'static str>,\n"
           "    pub gbox: [f32; 4],\n"
           "    pub pbox: [f64; 4],\n"
           "    pub attr: &'static str,\n"
           "    pub lines: &'static [Line],\n"
           "    pub log: &'static str,\n"
           "    pub svg: Svg,\n"
           "}\n\n"
           SVG_DECL
           "pub const CASES: &[Case] = &[\n" );

   for( icase = 0; icase < sizeof( cases ) / sizeof( cases[ 0 ] ); icase++ ) {
      const struct curve_case *c = cases + icase;
      AstFrameSet *fs;
      AstPlot *pl;
      if( c->head ) {
         char path[ 512 ];
         snprintf( path, sizeof( path ), "%s%s", HEADS, c->head );
         fs = read_head( path, "" );
         pl = astPlot( fs, c->gbox, c->pbox, "" );
         fs = astAnnul( fs );
      } else {
         AstFrame *fr = astFrame( 2, "" );
         pl = astPlot( fr, c->gbox, c->pbox, "" );
         fr = astAnnul( fr );
      }
      astSet( pl, "%s", c->attr );

      printf( "    Case {\n        name: " );
      rstr( c->name );
      printf( ",\n        head: " );
      if( c->head ) { printf( "Some(" ); rstr( c->head ); printf( ")" ); }
      else printf( "None" );
      printf( ",\n        gbox: [" );
      for( i = 0; i < 4; i++ ) { if( i ) printf( ", " ); flit( c->gbox[ i ] ); }
      printf( "],\n        pbox: [" );
      for( i = 0; i < 4; i++ ) { if( i ) printf( ", " ); flit( c->pbox[ i ] ); }
      printf( "],\n        attr: " );
      rstr( c->attr );
      printf( ",\n        lines: &[" );
      for( i = 0; i < c->nline; i++ ) {
         if( i ) printf( ", " );
         printf( "(%d, [", c->lines[ i ].axis );
         flit( c->lines[ i ].start[ 0 ] );
         printf( ", " );
         flit( c->lines[ i ].start[ 1 ] );
         printf( "], " );
         flit( c->lines[ i ].length );
         printf( ")" );
      }
      printf( "],\n" );

      capture_start();
      for( i = 0; i < c->nline; i++ ) {
         astGridLine( pl, c->lines[ i ].axis, c->lines[ i ].start,
                      c->lines[ i ].length );
      }
      capture_end();
      printf( "    },\n" );
      if( !astOK ) {
         fprintf( stderr, "case %s failed with status %d\n", c->name, astStatus );
         return 1;
      }
      pl = astAnnul( pl );
   }
   printf( "];\n" );
   return 0;
}
