# Capture the call logs of C's grid test programs for the port's gate 2.
#
# Runs the reference build's ast_tester/testgrid over every case of
# ast_tester/fixtures/plot/cases.txt twice: with the case's attributes, and
# with NumLab=0,TextLab=0,DrawTitle=0 added so that only lines are drawn.
# testgrid writes the grf_log call log of astGrid when its fourth argument
# names a file not ending in .svg. The logs are written as Rust source to
# crates/starlink-ast/tests/grid_oracle/cases.rs.
#
#   ./tools/oracle_fixtures/capture_grid_logs.sh
#
# AST_REFERENCE names the reference checkout (default reference/starlink-ast)
# and AST_BUILD its build directory (default $AST_REFERENCE/build), which must
# be configured with -DCMAKE_C_FLAGS=-ffp-contract=off, since the port does
# not fuse multiplies and adds: the script fails if libast contains a fused
# multiply-add.
set -euo pipefail

root=$(cd "$(dirname "$0")/../.." && pwd)
ref=${AST_REFERENCE:-$root/reference/starlink-ast}
build=${AST_BUILD:-$ref/build}
testgrid=$build/ast_tester/testgrid
fixtures=$ref/ast_tester/fixtures
out=$root/crates/starlink-ast/tests/grid_oracle/cases.rs

[ -x "$testgrid" ] || { echo "no testgrid at $testgrid" >&2; exit 1; }
lib=
for f in "$build"/libast.dylib "$build"/libast.so; do
   if [ -e "$f" ]; then lib=$f; break; fi
done
[ -n "$lib" ] || { echo "no libast in $build" >&2; exit 1; }
if [ "$(uname)" = Darwin ]; then
   nfma=$(otool -tv "$lib" | grep -c fmadd || true)
else
   nfma=$(objdump -d "$lib" | grep -c 'v\?fmadd' || true)
fi
if [ "$nfma" != 0 ]; then
   echo "$lib has $nfma fused multiply-adds; configure with -DCMAKE_C_FLAGS=-ffp-contract=off" >&2
   exit 1
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
commit=$(git -C "$ref" rev-parse --short HEAD)

{
   echo "// Generated by tools/oracle_fixtures/capture_grid_logs.sh from the C"
   echo "// library at $commit. Do not edit."
   echo
   echo "/// For each case of fixtures/plot/cases.txt: its name, the call log of"
   echo "/// its grid, and the call log with NumLab=0,TextLab=0,DrawTitle=0 added."
   echo "pub const CASES: &[(&str, &str, &str)] = &["
   while IFS='|' read -r name head attr fattr box rest; do
      case "$name" in \#*|"") continue ;; esac
      name=$(echo "$name" | xargs)
      head=$(echo "$head" | xargs)
      attr=$(echo "$attr" | xargs)
      fattr=$(echo "$fattr" | xargs)
      box=$(echo "$box" | xargs)
      lines=${attr:+$attr,}NumLab=0,TextLab=0,DrawTitle=0
      # shellcheck disable=SC2086
      "$testgrid" "$fixtures/$head" "$attr" "$fattr" "$tmp/full.log" $box >/dev/null
      # shellcheck disable=SC2086
      "$testgrid" "$fixtures/$head" "$lines" "$fattr" "$tmp/lines.log" $box >/dev/null
      printf '    (\n        "%s",\n        r##"' "$name"
      cat "$tmp/full.log"
      printf '"##,\n        r##"'
      cat "$tmp/lines.log"
      printf '"##,\n    ),\n'
   done < "$fixtures/plot/cases.txt"
   echo "];"
} > "$out"
echo "wrote $out"
