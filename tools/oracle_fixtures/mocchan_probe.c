/* mocchan_probe -- capture MocChan reads and writes (mocchan.c).
 *
 * Writes: the lines astWrite passes to the sink for two Mocs in string and
 * JSON form with the default MocLineLen and with MocLineLen 20 and 6, the
 * returned value and status, and the same for a MocLineLen too short for a
 * value and for an Object that is not a Moc. Reads: the Moc astRead makes
 * (its MaxOrder and string form), the MocFormat after it, and the status,
 * for text split across lines (inside a value too), JSON, an empty source,
 * blank lines and malformed text. Also the MocLineLen and MocFormat values
 * after setting and clearing them.
 *
 * Prints Rust source for crates/starlink-ast/tests/mocchan_oracle/cases.rs:
 *
 *   ./mocchan_probe > ../../crates/starlink-ast/tests/mocchan_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static const char **lines;
static int iline;
static int started;
static int status = 0;

static const char *source( void ) {
   return lines[ iline ] ? lines[ iline++ ] : NULL;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void sink( const char *line ) {
   printf( "%s", started ? ", " : "" );
   str( line );
   started = 1;
}

static AstMoc *low( void ) {
   AstMoc *m = astMoc( " " );
   astAddCell( m, AST__OR, 2, 37 );
   astAddCell( m, AST__OR, 1, 3 );
   astAddCell( m, AST__OR, 2, 100 );
   astAddCell( m, AST__XOR, 1, 25 );
   astAddCell( m, AST__OR, 0, 7 );
   return m;
}

static AstMoc *high( void ) {
   AstMoc *m = astMoc( " " );
   astAddCell( m, AST__OR, 15, 1234567890 );
   astAddCell( m, AST__OR, 10, 5 );
   astAddCell( m, AST__OR, 3, 700 );
   astAddCell( m, AST__OR, 3, 702 );
   astAddCell( m, AST__OR, 8, 99999 );
   return m;
}

/* `(case, Moc, MocFormat, MocLineLen, lines, returned value, status)`. A
   MocLineLen below -100 leaves it unset. */
static void wcase( const char *name, const char *mname, AstObject *obj,
                   const char *format, int linelen ) {
   int ret;
   AstMocChan *ch = astMocChan( source, sink, " " );
   if( format ) astSetC( ch, "MocFormat", format );
   if( linelen > -100 ) astSetI( ch, "MocLineLen", linelen );
   printf( "    (\"%s\", \"%s\", \"%s\", %d, &[", name, mname, format ? format : "",
           linelen );
   started = 0;
   ret = astWrite( ch, obj );
   printf( "], %d, %d),\n", ret, status );
   astClearStatus;
}

/* `(case, lines, MocFormat before, read a Moc, MaxOrder, string form,
   MocFormat after, status)`. */
static void rcase( const char *name, const char **text, const char *before ) {
   int i, rstatus;
   AstMocChan *ch = astMocChan( source, NULL, " " );
   AstObject *obj;
   char buf[ 2000 ];
   size_t size = 0;
   if( before ) astSetC( ch, "MocFormat", before );
   lines = text;
   iline = 0;
   obj = astRead( ch );
   rstatus = status;
   astClearStatus;
   printf( "    (\"%s\", &[", name );
   for( i = 0; text[ i ]; i++ ) {
      printf( "%s", i ? ", " : "" );
      str( text[ i ] );
   }
   printf( "], \"%s\", %s, ", before ? before : "", obj ? "true" : "false" );
   if( obj ) {
      astGetMocString( (AstMoc *) obj, 0, sizeof( buf ), buf, &size );
      buf[ size ] = 0;
      printf( "%d, ", astGetI( obj, "MaxOrder" ) );
      str( buf );
   } else {
      printf( "-1, \"\"" );
   }
   printf( ", \"%s\", %d),\n", astGetC( ch, "MocFormat" ), rstatus );
}

int main( void ) {
   AstMocChan *ch;
   AstObject *lo = (AstObject *) low(), *hi = (AstObject *) high();
   AstObject *zm = (AstObject *) astZoomMap( 2, 2.0, " " );

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/mocchan_probe.c. Do not edit.\n\n" );
   printf( "/// `(case, Moc, MocFormat set, MocLineLen set (below -100 for unset),\n" );
   printf( "/// lines written, returned value, status)`.\n" );
   printf( "pub type Write = (&'static str, &'static str, &'static str, i32,\n" );
   printf( "    &'static [&'static str], i32, i32);\n" );
   printf( "pub const WRITES: &[Write] = &[\n" );
   wcase( "low", "low", lo, NULL, -1000 );
   wcase( "low_json", "low", lo, "JSON", -1000 );
   wcase( "low_string", "low", lo, "STRING", -1000 );
   wcase( "low_unknown", "low", lo, "UNKNOWN", -1000 );
   wcase( "high", "high", hi, NULL, -1000 );
   wcase( "high_json", "high", hi, "JSON", -1000 );
   wcase( "high_20", "high", hi, NULL, 20 );
   wcase( "high_json_20", "high", hi, "JSON", 20 );
   wcase( "high_6", "high", hi, NULL, 6 );
   wcase( "high_json_6", "high", hi, "JSON", 6 );
   wcase( "high_3", "high", hi, NULL, 3 );
   wcase( "high_json_3", "high", hi, "JSON", 3 );
   wcase( "high_0", "high", hi, NULL, 0 );
   wcase( "high_negative", "high", hi, NULL, -5 );
   wcase( "zoommap", "zoommap", zm, NULL, -1000 );
   printf( "];\n\n" );

   printf( "/// `(case, lines read, MocFormat set before, read a Moc, MaxOrder,\n" );
   printf( "/// string form, MocFormat after, status)`.\n" );
   printf( "pub type Read = (&'static str, &'static [&'static str], &'static str, bool,\n" );
   printf( "    i32, &'static str, &'static str, i32);\n" );
   printf( "pub const READS: &[Read] = &[\n" );
   {
      const char *t1[] = { "3/1-5,9 4/100-103 5/", NULL };
      const char *t2[] = { "3/1-", "5,", "9 4/10", "0-103", " 5/", NULL };
      const char *t3[] = { "{\"1\":[1,2,4],", " \"3\":[ 10", "0 , 101 ],\"5\":[]}", NULL };
      const char *t4[] = { NULL };
      const char *t5[] = { "", "  ", "2/7", "", NULL };
      const char *t6[] = { "3/1 x", NULL };
      const char *t7[] = { "{\"1\":[1]", NULL };
      const char *t8[] = { "", NULL };
      const char *t9[] = { "2/7", "{\"1\":[1]}", NULL };
      rcase( "string", t1, NULL );
      rcase( "string_split", t2, NULL );
      rcase( "json_split", t3, NULL );
      rcase( "json_after_string", t3, "STRING" );
      rcase( "empty", t4, NULL );
      rcase( "empty_after_json", t4, "JSON" );
      rcase( "blank_lines", t5, NULL );
      rcase( "bad", t6, NULL );
      rcase( "bad_after_json", t6, "JSON" );
      rcase( "bad_json", t7, "STRING" );
      rcase( "blank_only", t8, NULL );
      rcase( "string_then_json", t9, NULL );
   }
   printf( "];\n\n" );

   {
      const char *t10[] = { "2/7 x", "3/1", NULL };
      AstObject *obj;
      char buf[ 100 ];
      size_t size = 0;
      int first;
      ch = astMocChan( source, NULL, " " );
      lines = t10;
      iline = 0;
      obj = astRead( ch );
      first = status;
      astClearStatus;
      obj = astRead( ch );
      astGetMocString( (AstMoc *) obj, 0, sizeof( buf ), buf, &size );
      buf[ size ] = 0;
      printf( "/// Reading [\"2/7 x\", \"3/1\"] twice: the status of the first read\n" );
      printf( "/// and the string form of the Moc from the second.\n" );
      printf( "pub const RETRY: (i32, &str) = (%d, ", first );
      str( buf );
      printf( ");\n\n" );
   }

   ch = astMocChan( source, sink, " " );
   printf( "/// MocLineLen and MocFormat: default, set to -5, cleared; MocFormat set\n" );
   printf( "/// to JSON, set to UNKNOWN; whether each was set.\n" );
   printf( "pub const ATTRS: (i32, i32, bool, i32, &str, &str, bool, &str, bool) = (" );
   printf( "%d, ", astGetI( ch, "MocLineLen" ) );
   astSetI( ch, "MocLineLen", -5 );
   printf( "%d, %s, ", astGetI( ch, "MocLineLen" ),
           astTest( ch, "MocLineLen" ) ? "true" : "false" );
   astClear( ch, "MocLineLen" );
   printf( "%d, \"%s\", ", astGetI( ch, "MocLineLen" ), astGetC( ch, "MocFormat" ) );
   astSetC( ch, "MocFormat", "Json" );
   printf( "\"%s\", %s, ", astGetC( ch, "MocFormat" ),
           astTest( ch, "MocFormat" ) ? "true" : "false" );
   astSetC( ch, "MocFormat", "unknown" );
   printf( "\"%s\", %s);\n", astGetC( ch, "MocFormat" ),
           astTest( ch, "MocFormat" ) ? "true" : "false" );
   return 0;
}
