/* frameset_current_probe -- capture how a FrameSet's Current attribute is
 * set, cleared and written. Current is unset until astAddFrame or
 * astSetCurrent sets it, and an unset Current is the last Frame
 * (frameset.c GetCurrent). Dump writes a set Current as "Currnt" and an
 * unset one commented out. astRemoveFrame clears a set Current when the
 * current Frame is removed, and renumbers it when an earlier one is.
 *
 * Prints Rust source for crates/starlink-ast/tests/frameset_current_oracle/cases.rs:
 *
 *   ./frameset_current_probe > ../../crates/starlink-ast/tests/frameset_current_oracle/cases.rs
 */
#include <stdio.h>
#include "ast.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void sink( const char *line ) {
   printf( "            " );
   str( line );
   printf( ",\n" );
}

/* Print the step's name, whether Current is set, and the FrameSet's dump. */
static void emit( const char *name, AstFrameSet *fs ) {
   AstChannel *ch = astChannel( NULL, sink, " " );
   printf( "    (\n        \"%s\",\n        %s,\n        &[\n", name,
           astTest( fs, "Current" ) ? "true" : "false" );
   astWrite( ch, fs );
   printf( "        ],\n    ),\n" );
   ch = astAnnul( ch );
}

/* A FrameSet of "n" one-axis Frames, each with its index as its Domain. */
static AstFrameSet *frameset( int n ) {
   AstFrameSet *fs;
   AstFrame *f;
   char domain[ 20 ];
   int i;

   f = astFrame( 1, "Domain=F1" );
   fs = astFrameSet( f, " " );
   f = astAnnul( f );
   for( i = 2; i <= n; i++ ) {
      sprintf( domain, "Domain=F%d", i );
      f = astFrame( 1, domain );
      astAddFrame( fs, AST__BASE, astUnitMap( 1, " " ), f );
      f = astAnnul( f );
   }
   return fs;
}

int main( void ) {
   AstFrameSet *fs;
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/frameset_current_probe.c. Do not edit.\n\n"
           "/// `(step, whether Current is set, the FrameSet's dump)`.\n"
           "pub type Step = (&'static str, bool, &'static [&'static str]);\n\n"
           "pub const STEPS: &[Step] = &[\n" );

   fs = frameset( 1 );
   emit( "one_frame", fs );
   fs = astAnnul( fs );

   fs = frameset( 3 );
   emit( "three_frames", fs );
   astClear( fs, "Current" );
   emit( "three_cleared", fs );
   astRemoveFrame( fs, 1 );
   emit( "cleared_remove_first", fs );
   fs = astAnnul( fs );

   fs = frameset( 3 );
   astRemoveFrame( fs, 1 );
   emit( "set_remove_first", fs );
   astRemoveFrame( fs, 2 );
   emit( "set_remove_current", fs );
   fs = astAnnul( fs );

   fs = frameset( 3 );
   astSetI( fs, "Current", 1 );
   astRemoveFrame( fs, 3 );
   emit( "set_first_remove_last", fs );
   fs = astAnnul( fs );

   printf( "];\n" );
   return 0;
}
