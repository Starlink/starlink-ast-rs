/* dsb_topo_probe -- capture the DSBSpecFrame values that go through C's
 * TopoMap (dsbspecframe.c:2051), which converts between the current system
 * and topocentric frequency in Hz. TopoMap overlays the DSBSpecFrame onto a
 * new SpecFrame, aligns it in the topocentric rest frame, and converts to a
 * copy of it set to topocentric frequency in Hz, so the SpecOrigin and the
 * alignment settings take part in the conversion.
 *
 * Each case sets up an LSRK frequency DSBSpecFrame in GHz, applies its own
 * settings, and sets DSBCentre=230 in the current system. It prints
 * DSBCentre, ImagFreq, and two points converted from the upper to the lower
 * sideband with AlignSideBand set, each None where C reports an error.
 *
 * Prints Rust source for crates/starlink-ast/tests/dsb_topo_oracle/cases.rs:
 *
 *   ./dsb_topo_probe > ../../crates/starlink-ast/tests/dsb_topo_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

/* Print a value, or None and clear the status if it raised an error. */
static void opt( double v ) {
   if( astOK ) {
      printf( "Some(" );
      num( v );
      printf( ")" );
   } else {
      printf( "None" );
      astClearStatus;
   }
}

static void emit( const char *name, const char *settings ) {
   AstFrame *usb, *lsb;
   AstFrameSet *fs;
   double in[ 2 ] = { 0.5, 1.0 };
   double out[ 2 ];

   usb = (AstFrame *) astDSBSpecFrame( "System=FREQ,Unit=GHz,StdOfRest=LSRK,"
                                       "Epoch=2005.0,IF=4,SideBand=USB,"
                                       "AlignSideBand=1" );
   astSetRefPos( usb, NULL, 2.6, 0.35 );
   if( *settings ) astSet( usb, settings, " " );
   astSetD( usb, "DSBCentre", 230.0 );

   printf( "    (\"%s\", ", name );
   opt( astGetD( usb, "DSBCentre" ) ); printf( ", " );
   opt( astGetD( usb, "ImagFreq" ) ); printf( ", " );

   lsb = astCopy( usb );
   astSet( lsb, "SideBand=LSB", " " );
   fs = astConvert( usb, lsb, "" );
   if( fs ) astTran1( fs, 2, in, 1, out );
   if( astOK && fs ) {
      printf( "Some([" );
      num( out[ 0 ] ); printf( ", " );
      num( out[ 1 ] ); printf( "])" );
   } else {
      printf( "None" );
      astClearStatus;
   }
   printf( "),\n" );
}

int main( void ) {
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/dsb_topo_probe.c. Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// The points converted from the upper to the lower sideband.\n"
           "pub const POINTS: [f64; 2] = [0.5, 1.0];\n\n"
           "/// `(name, DSBCentre, ImagFreq, the points in the lower sideband)`,\n"
           "/// each None where C reports an error.\n"
           "pub type Case = (&'static str, Option<f64>, Option<f64>, Option<[f64; 2]>);\n\n"
           "pub const CASES: &[Case] = &[\n" );

   emit( "plain", "" );
   emit( "origin", "SpecOrigin=229" );
   emit( "align_bary", "AlignStdOfRest=BARY" );
   emit( "origin_align_offset", "SpecOrigin=229,AlignSpecOffset=1" );
   emit( "origin_align_bary", "SpecOrigin=229,AlignStdOfRest=BARY" );

   printf( "];\n" );
   return 0;
}
