/* remove_regions_probe -- capture what astRemoveRegions makes of Mappings
 * that hold Regions: each class removes them from its own components
 * (cmpmap.c, tranmap.c, ratemap.c, normmap.c, cmpframe.c, region.c
 * RemoveRegions), a series CmpMap drops a component that became a UnitMap,
 * and a parallel CmpMap or TranMap of two UnitMaps becomes one UnitMap.
 *
 * Each case is the dump of a Mapping and the dump of what astRemoveRegions
 * returns. A bare Region is not a case: C returns its Frame, and the port,
 * whose Frames are not Mappings, a UnitMap.
 *
 * Prints Rust source for crates/starlink-ast/tests/remove_regions_oracle/cases.rs:
 *
 *   ./remove_regions_probe > ../../crates/starlink-ast/tests/remove_regions_oracle/cases.rs
 */
#include <stdio.h>
#include "ast.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void print_dump( const char *line ) {
   printf( "            " );
   str( line );
   printf( ",\n" );
}

static void dump( AstObject *obj ) {
   AstChannel *ch = astChannel( NULL, print_dump, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
}

static void emit( const char *name, AstMapping *map ) {
   AstMapping *result;
   printf( "    (\n        \"%s\",\n        &[\n", name );
   dump( (AstObject *) map );
   printf( "        ],\n        &[\n" );
   result = astRemoveRegions( map );
   dump( (AstObject *) result );
   printf( "        ],\n    ),\n" );
   result = astAnnul( result );
   map = astAnnul( map );
}

/* A circle of radius 1 about (1,2) in a plain 2-D Frame. */
static AstRegion *circle( void ) {
   double centre[] = { 1.0, 2.0 }, radius[] = { 1.0 };
   return (AstRegion *) astCircle( astFrame( 2, " " ), 1, centre, radius, NULL, " " );
}

int main( void ) {
   AstMapping *zoom;
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/remove_regions_probe.c. Do not edit.\n\n"
           "/// `(case, the Mapping's dump, the dump of astRemoveRegions's result)`.\n"
           "pub type Case = (&'static str, &'static [&'static str], &'static [&'static str]);\n\n"
           "pub const CASES: &[Case] = &[\n" );

   emit( "cmpmap_series_region_first",
         (AstMapping *) astCmpMap( circle(), astZoomMap( 2, 3.0, " " ), 1, " " ) );

   zoom = (AstMapping *) astZoomMap( 2, 3.0, " " );
   astInvert( zoom );
   emit( "cmpmap_series_inverted_component", (AstMapping *) astCmpMap( zoom, circle(), 1, " " ) );

   zoom = (AstMapping *) astCmpMap( astZoomMap( 2, 4.0, " " ), circle(), 1, " " );
   astInvert( zoom );
   emit( "cmpmap_series_inverted", zoom );

   emit( "cmpmap_parallel_two_regions",
         (AstMapping *) astCmpMap( circle(), circle(), 0, " " ) );
   emit( "cmpmap_parallel_one_region",
         (AstMapping *) astCmpMap( circle(), astZoomMap( 1, 2.0, " " ), 0, " " ) );
   emit( "cmpmap_without_regions",
         (AstMapping *) astCmpMap( astZoomMap( 2, 2.0, " " ), astZoomMap( 2, 5.0, " " ), 1, " " ) );

   emit( "tranmap_two_regions", (AstMapping *) astTranMap( circle(), circle(), " " ) );
   emit( "tranmap_one_region",
         (AstMapping *) astTranMap( circle(), astZoomMap( 2, 2.0, " " ), " " ) );

   emit( "ratemap_region",
         (AstMapping *) astRateMap( astCmpMap( circle(), astZoomMap( 2, 3.0, " " ), 1, " " ),
                                    1, 1, " " ) );

   emit( "normmap_region", (AstMapping *) astNormMap( circle(), " " ) );
   emit( "normmap_cmpframe",
         (AstMapping *) astNormMap( astCmpFrame( circle(), astSkyFrame( " " ), " " ), " " ) );

   printf( "];\n" );
   return status;
}
