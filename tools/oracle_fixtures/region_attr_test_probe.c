/* region_attr_test_probe -- capture whether the Region attributes Negated,
 * Adaptive and RegionFS are set (region.c TestNegated, TestAdaptive and
 * TestRegionFS) after construction, negation, setting, clearing, reading a
 * dump (region.c Load) and copying (region.c Copy). RegionFS is protected,
 * so it is reached with astMakePointer.
 *
 * Prints Rust source for crates/ast-core/tests/region_attr_test_oracle/cases.rs:
 *
 *   ./region_attr_test_probe > ../../crates/ast-core/tests/region_attr_test_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern int astGetRegionFS_( void *, int * );
extern int astTestRegionFS_( void *, int * );
extern void astSetRegionFS_( void *, int, int * );

static char dump[ 20000 ];
static char *next_line;

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static const char *source( void ) {
   static char line[ 1000 ];
   char *nl;
   size_t n;
   if( !next_line || !*next_line ) return NULL;
   nl = strchr( next_line, '\n' );
   n = nl ? (size_t)( nl - next_line ) : strlen( next_line );
   memcpy( line, next_line, n );
   line[ n ] = 0;
   next_line = nl ? nl + 1 : next_line + n;
   return line;
}

/* One case: `(name, [Negated, TestNegated, Adaptive, TestAdaptive, RegionFS,
   TestRegionFS])`. */
static void emit( const char *name, AstObject *r ) {
   int s = 0;
   printf( "    (\"%s\", [%s, %s, %s, %s, %s, %s]),\n", name,
           astGetI( r, "Negated" ) ? "true" : "false",
           astTest( r, "Negated" ) ? "true" : "false",
           astGetI( r, "Adaptive" ) ? "true" : "false",
           astTest( r, "Adaptive" ) ? "true" : "false",
           astGetRegionFS_( astMakePointer( r ), &s ) ? "true" : "false",
           astTestRegionFS_( astMakePointer( r ), &s ) ? "true" : "false" );
}

static AstObject *reread( AstObject *r ) {
   AstChannel *ch;
   AstObject *loaded;
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, r );
   ch = astAnnul( ch );
   next_line = dump;
   ch = astChannel( source, NULL, " " );
   loaded = astRead( ch );
   ch = astAnnul( ch );
   return loaded;
}

int main( void ) {
   int status = 0;
   double lo[] = { 0.0, 0.0 }, hi[] = { 1.0, 1.0 };
   AstObject *box;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_attr_test_probe.c. Do not edit.\n\n"
           "/// `(case, [Negated, TestNegated, Adaptive, TestAdaptive, RegionFS, TestRegionFS])`.\n"
           "pub const CASES: &[(&str, [bool; 6])] = &[\n" );
   box = (AstObject *) astBox( astFrame( 2, " " ), 1, lo, hi, NULL, " " );
   emit( "built", box );
   astNegate( box );
   emit( "negated", box );
   emit( "negated_reread", reread( box ) );
   astNegate( box );
   emit( "negated_twice", box );
   emit( "negated_twice_reread", reread( box ) );
   astClear( box, "Negated" );
   astSetI( box, "Adaptive", 0 );
   emit( "not_adaptive", box );
   emit( "not_adaptive_reread", reread( box ) );
   astClear( box, "Adaptive" );
   emit( "cleared", box );
   emit( "cleared_reread", reread( box ) );
   astSetRegionFS_( astMakePointer( box ), 0, &status );
   emit( "no_region_fs", box );
   emit( "no_region_fs_copy", astCopy( box ) );
   printf( "];\n" );
   return status;
}
