/* fitschan_axis_count_probe -- capture how many pixel and WCS axes a
 * FITS-WCS read gives. FitsToStore (fitschan.c) takes the number of pixel
 * axes as the highest CRPIX index in the primary or any alternate axis
 * description, whatever NAXIS says; each axis description has WCSAXES WCS
 * axes, or as many as there are pixel axes; and AddFrame joins a
 * description with a different number of axes to the pixel Frame with a
 * PermMap. MakeFitsFrameSet reads nothing when there is no CRPIX.
 *
 * For each header: whether astRead gave a FrameSet, nothing, or an error;
 * Ncard after the read; the names of the cards then left, in order, which
 * shows where any warning was written; and, for a FrameSet, the number of
 * axes of each Frame and the current Frame's position for pixel
 * (2, 3, 4, ...).
 *
 * Prints Rust source for crates/ast-core/tests/fitschan_axis_count_oracle/cases.rs:
 *
 *   ./fitschan_axis_count_probe > ../../crates/ast-core/tests/fitschan_axis_count_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void emit( const char *name, const char **header ) {
   AstFitsChan *fc;
   AstFrameSet *fs;
   AstFrame *frm;
   double in[ 100 ], out[ 100 ];
   char num[ 40 ];
   char card[ 81 ];
   int i, nin, nout, ifrm, err;

   printf( "    (\n        \"%s\",\n        &[", name );
   for( i = 0; header[ i ]; i++ ) {
      printf( "%s", i ? ", " : "" );
      str( header[ i ] );
   }
   printf( "],\n" );

   fc = astFitsChan( NULL, NULL, " " );
   for( i = 0; header[ i ]; i++ ) astPutFits( fc, header[ i ], 0 );
   astClear( fc, "Card" );
   fs = (AstFrameSet *) astRead( fc );
   err = !astOK;
   astClearStatus;

   if( err ) {
      printf( "        \"error\",\n" );
   } else if( !fs ) {
      printf( "        \"none\",\n" );
   } else {
      printf( "        \"frameset\",\n" );
   }
   printf( "        %d,\n", astGetI( fc, "Ncard" ) );
   printf( "        &[" );
   astClear( fc, "Card" );
   for( i = 0; astFindFits( fc, "%f", card, 1 ); i++ ) {
      card[ 8 ] = 0;
      while( strlen( card ) && card[ strlen( card ) - 1 ] == ' ' ) card[ strlen( card ) - 1 ] = 0;
      printf( "%s", i ? ", " : "" );
      str( card );
   }
   printf( "],\n" );

   printf( "        &[" );
   if( fs ) {
      for( ifrm = 1; ifrm <= astGetI( fs, "Nframe" ); ifrm++ ) {
         frm = astGetFrame( fs, ifrm );
         printf( "%s%d", ifrm > 1 ? ", " : "", astGetI( frm, "Naxes" ) );
         frm = astAnnul( frm );
      }
   }
   printf( "],\n        &[" );
   if( fs ) {
      nin = astGetI( fs, "Nin" );
      nout = astGetI( fs, "Nout" );
      for( i = 0; i < nin; i++ ) in[ i ] = i + 2.0;
      astTranN( fs, 1, nin, 1, in, 1, nout, 1, out );
      for( i = 0; i < nout; i++ ) {
         sprintf( num, "%.17g", out[ i ] );
         if( !strpbrk( num, ".en" ) ) strcat( num, ".0" );
         printf( "%s%s", i ? ", " : "", num );
      }
      fs = astAnnul( fs );
   }
   printf( "],\n    ),\n" );
   fc = astAnnul( fc );
}

