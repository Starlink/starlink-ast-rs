/* region_cmplist_probe -- capture the protected astCmpRegionList
 * (cmpregion.c CmpRegionList and XORCheck): the operator and Regions it
 * lists for nested ANDs, nested ORs, an XOR, an OR containing an XOR, and
 * an OR of two ANDs equivalent to an XOR; and the dump of that last
 * CmpRegion (cmpregion.c Dump, which writes it as an XOR).
 *
 * Circles A, B and C have radius 1 and centres (0,0), (3,0) and (6,0).
 *
 * Prints Rust source for crates/starlink-ast/tests/region_cmplist_oracle/cases.rs:
 *
 *   ./region_cmplist_probe > ../../crates/starlink-ast/tests/region_cmplist_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern int astCmpRegionList_( void *, int *, void ***, int * );
extern AstObject *astMakeId_( AstObject *, int * );

static char dump[ 40000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

static const char *dumped( AstObject *obj ) {
   AstChannel *ch;
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   return dump;
}

static AstRegion *circle( double x ) {
   double c[ 2 ], r = 1.0;
   c[ 0 ] = x;
   c[ 1 ] = 0.0;
   return (AstRegion *) astCircle( astFrame( 2, " " ), 1, c, &r, NULL, " " );
}

/* One case: `(name, operator code, the listed Regions' dumps)`. */
static void emit( const char *name, AstCmpRegion *cr ) {
   int s = 0, n = 0, i, oper;
   void **list = NULL;
   oper = astCmpRegionList_( astMakePointer( cr ), &n, &list, &s );
   printf( "    (\"%s\", %d, &[\n", name, oper );
   for( i = 0; i < n; i++ ) {
      printf( "        " );
      str( dumped( astMakeId_( list[ i ], &s ) ) );
      printf( ",\n" );
   }
   printf( "    ]),\n" );
   list = astFree( list );
}

int main( void ) {
   int status = 0;
   AstRegion *a, *b, *c, *nb, *nc;
   AstCmpRegion *hand;

   astWatch( &status );
   a = circle( 0.0 );
   b = circle( 3.0 );
   c = circle( 6.0 );
   nb = (AstRegion *) astCopy( b );
   nc = (AstRegion *) astCopy( c );
   astNegate( nb );
   astNegate( nc );
   hand = astCmpRegion( astCmpRegion( b, nc, AST__AND, " " ),
                        astCmpRegion( nb, c, AST__AND, " " ), AST__OR, " " );

   printf( "// Generated by tools/oracle_fixtures/region_cmplist_probe.c. Do not edit.\n\n"
           "/// `(case, operator: 1 AND, 2 OR, 3 XOR, the listed Regions' dumps)`.\n"
           "pub const CASES: &[(&str, i32, &[&str])] = &[\n" );
   emit( "a_and_b_and_c", astCmpRegion( a, astCmpRegion( b, c, AST__AND, " " ), AST__AND, " " ) );
   emit( "a_or_b_or_c", astCmpRegion( astCmpRegion( a, b, AST__OR, " " ), c, AST__OR, " " ) );
   emit( "a_or_b_and_c", astCmpRegion( a, astCmpRegion( b, c, AST__AND, " " ), AST__OR, " " ) );
   emit( "b_xor_c", astCmpRegion( b, c, AST__XOR, " " ) );
   emit( "a_or_b_xor_c", astCmpRegion( a, astCmpRegion( b, c, AST__XOR, " " ), AST__OR, " " ) );
   emit( "hand_xor", hand );
   printf( "];\n\n/// The dump of the OR of (B AND NOT C) and (NOT B AND C).\n"
           "pub const HAND_XOR_DUMP: &str = " );
   str( dumped( (AstObject *) hand ) );
   printf( ";\n" );
   return status;
}
