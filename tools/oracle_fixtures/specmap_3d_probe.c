/* specmap_3d_probe -- capture 3-dimensional SpecMaps, whose second and
 * third axes give the RA and Dec of each point's source (specmap.c
 * Transform and FrameChange). Each case is the dump of the SpecMap and its
 * forward and inverse transformations of points that include bad values;
 * the last cases are the dumps of what astSimplify makes of SpecMap runs.
 *
 * Prints Rust source for crates/ast-core/tests/specmap_3d_oracle/cases.rs:
 *
 *   ./specmap_3d_probe > ../../crates/ast-core/tests/specmap_3d_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

#define BAD AST__BAD
#define NP 6

/* Add a conversion with the arguments that follow it. */
#define ADD( map, cvt, ... ) do { \
   double a_[] = { __VA_ARGS__ }; \
   astSpecAdd( map, cvt, (int) ( sizeof( a_ )/sizeof( a_[ 0 ] ) ), a_ ); \
} while( 0 )

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void print_dump( const char *line ) {
   printf( "            " );
   str( line );
   printf( ",\n" );
}

/* Print a value as a Rust f64 literal, with the fewest digits that read
   back as the same value. */
static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void dump( AstObject *obj ) {
   AstChannel *ch = astChannel( NULL, print_dump, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
}

static void points( double in[ 3 ][ NP ] ) {
   int i, k;
   printf( "        &[\n" );
   for( i = 0; i < NP; i++ ) {
      printf( "            [" );
      for( k = 0; k < 3; k++ ) {
         if( k ) printf( ", " );
         lit( in[ k ][ i ] );
      }
      printf( "],\n" );
   }
   printf( "        ],\n" );
}

static void emit( const char *name, AstSpecMap *map ) {
   static double in[ 3 ][ NP ] = {
      { 1.0E11, 2.3E11, 4.0E14, BAD, 1.0E11, 3.0E11 },
      { 0.0, 1.2, 4.5, 2.0, BAD, 6.1 },
      { 0.3, -0.9, 1.1, 0.2, 0.5, BAD }
   };
   double out[ 3 ][ NP ];

   printf( "    (\n        \"%s\",\n        &[\n", name );
   dump( (AstObject *) map );
   printf( "        ],\n" );
   points( in );
   astTranN( map, NP, 3, NP, (const double *) in, 1, 3, NP, (double *) out );
   points( out );
   astTranN( map, NP, 3, NP, (const double *) in, 0, 3, NP, (double *) out );
   points( out );
   printf( "    ),\n" );
}

static void emit_simp( const char *name, AstMapping *map ) {
   AstMapping *simp = astSimplify( map );
   printf( "    (\n        \"%s\",\n        &[\n", name );
   dump( (AstObject *) map );
   printf( "        ],\n        &[\n" );
   dump( (AstObject *) simp );
   printf( "        ],\n    ),\n" );
   simp = astAnnul( simp );
}

int main( void ) {
   AstSpecMap *map, *map2;
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/specmap_3d_probe.c. Do not edit.\n\n"
           "/// `(case, the SpecMap's dump, input points, forward outputs, inverse outputs)`.\n"
           "pub type Case = (\n"
           "    &'static str,\n"
           "    &'static [&'static str],\n"
           "    &'static [[f64; 3]],\n"
           "    &'static [[f64; 3]],\n"
           "    &'static [[f64; 3]],\n"
           ");\n\n"
           "/// `(case, a Mapping's dump, the dump of its simplification)`.\n"
           "pub type SimplifyCase = (&'static str, &'static [&'static str], &'static [&'static str]);\n\n"
           "pub const CASES: &[Case] = &[\n" );

   map = astSpecMap( 3, 0, " " );
   ADD( map, "LKF2HL", 0.1, 0.2 );
   emit( "lsrk", map );
   map = astAnnul( map );

   map = astSpecMap( 3, 0, " " );
   ADD( map, "HLF2TP", -2.6, 0.35, 4000.0, 53000.0, 0.1, 0.2 );
   emit( "topocentric", map );
   map = astAnnul( map );

   map = astSpecMap( 3, 0, " " );
   ADD( map, "FRTOVL", 1.0E11 );
   ADD( map, "VLTOFR", 1.0E11 );
   ADD( map, "GEF2HL", 53000.0, 0.1, 0.2 );
   ADD( map, "HLF2BY", 53000.0, 0.1, 0.2 );
   ADD( map, "HLF2GL", 0.1, 0.2 );
   ADD( map, "LGF2HL", 0.1, 0.2 );
   ADD( map, "HLF2LD", 0.1, 0.2 );
   emit( "chain", map );
   map = astAnnul( map );

   map = astSpecMap( 3, 0, " " );
   ADD( map, "USF2HL", 1.5E4, 0.7, -0.4 );
   astSpecAdd( map, "FRTOWV", 0, NULL );
   astInvert( map );
   emit( "user_inverted", map );
   map = astAnnul( map );

   printf( "];\n\npub const SIMPLIFY_CASES: &[SimplifyCase] = &[\n" );

   map = astSpecMap( 3, 0, " " );
   ADD( map, "LKF2HL", 0.1, 0.2 );
   map2 = astCopy( map );
   astInvert( map2 );
   emit_simp( "cancelling_pair", (AstMapping *) astCmpMap( map, map2, 1, " " ) );
   map2 = astAnnul( map2 );

   map2 = astSpecMap( 3, 0, " " );
   astSpecAdd( map2, "FRTOWV", 0, NULL );
   emit_simp( "merged_pair", (AstMapping *) astCmpMap( map, map2, 1, " " ) );
   map2 = astAnnul( map2 );
   map = astAnnul( map );

   printf( "];\n" );
   return status;
}
