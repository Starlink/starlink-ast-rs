/* region_mask_probe -- capture astMask8D (region.c Mask<X>, and pointlist.c
 * Mask<X> for a PointList) for Regions masked inside and outside on small
 * grids, one larger than the Region's bounding box: with no Mapping, through a ZoomMap from the Region's Frame to the
 * grid, a negated Box, a PointList with a point outside the grid, a 1-D
 * Interval, and the AST__NGDIN and AST__GBDIN errors.
 *
 * Each case masks an array with the value 1: an array of zeros, or for the
 * "_prefilled" cases one holding 0, 1, 2 in turn, as doubles or (the "_ub"
 * cases) unsigned chars. The PointList case
 * needs pointlist.c from ba5a6199 or later, which ignores a point outside
 * the grid rather than writing beyond the array.
 *
 * Prints Rust source for crates/starlink-ast/tests/region_mask_oracle/cases.rs:
 *
 *   ./region_mask_probe > ../../crates/starlink-ast/tests/region_mask_oracle/cases.rs
 */
#include <stdio.h>
#include "ast.h"

/* One case: `(name, Ok((count, the values as digits in array order)))` or
   `Err(code)`. `prefill` fills the array with 0, 1, 2 in turn rather than
   zeros, and `ub` masks unsigned chars rather than doubles. */
static void emit_as( const char *name, AstRegion *reg, AstMapping *map, int inside,
                     int ndim, const AstDim lbnd[], const AstDim ubnd[], int prefill,
                     int ub, int *status ) {
   double data[ 400 ];
   unsigned char bytes[ 400 ];
   AstDim n, npix = 1;
   int i;
   for( i = 0; i < ndim; i++ ) npix *= ubnd[ i ] - lbnd[ i ] + 1;
   if( npix < 1 ) npix = 1;
   for( i = 0; i < npix && i < 400; i++ ) {
      data[ i ] = prefill ? i % 3 : 0.0;
      bytes[ i ] = prefill ? i % 3 : 0;
   }
   if( ub ) {
      n = astMask8UB( reg, map, inside, ndim, lbnd, ubnd, bytes, 1 );
      for( i = 0; i < npix && i < 400; i++ ) data[ i ] = bytes[ i ];
   } else {
      n = astMask8D( reg, map, inside, ndim, lbnd, ubnd, data, 1.0 );
   }
   printf( "    (\"%s\", ", name );
   if( !astOK ) {
      printf( "Err(\"%s\")", astStatus == AST__NGDIN ? "Ngdin" :
              astStatus == AST__GBDIN ? "Gbdin" : "Other" );
      astClearStatus;
   } else {
      printf( "Ok((%ld, \"", (long) n );
      for( i = 0; i < npix; i++ ) putchar( '0' + (int) data[ i ] );
      printf( "\"))" );
   }
   printf( "),\n" );
}

static void emit( const char *name, AstRegion *reg, AstMapping *map, int inside,
                  int ndim, const AstDim lbnd[], const AstDim ubnd[], int *status ) {
   emit_as( name, reg, map, inside, ndim, lbnd, ubnd, 0, 0, status );
}

int main( void ) {
   int status = 0;
   AstFrame *f2, *f1;
   AstRegion *reg;
   AstDim l5[] = { 1, 1 }, u5[] = { 5, 5 }, u6[] = { 6, 6 };

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_mask_probe.c. Do not edit.\n\n"
           "/// `Ok((count, the values as digits in array order))` or\n"
           "/// `Err(the error code)`.\n"
           "pub type Expected = Result<(usize, &'static str), &'static str>;\n\n"
           "/// `(case, what C gives)`.\n"
           "pub const CASES: &[(&str, Expected)] = &[\n" );

   f2 = astFrame( 2, " " );
   f1 = astFrame( 1, " " );
   {
      double cen[] = { 3.0, 3.0 }, rad = 2.0;
      reg = (AstRegion *) astCircle( f2, 1, cen, &rad, NULL, " " );
      emit( "circle_inside", reg, NULL, 1, 2, l5, u5, &status );
      emit( "circle_outside", reg, NULL, 0, 2, l5, u5, &status );
      emit_as( "circle_inside_prefilled", reg, NULL, 1, 2, l5, u5, 1, 0, &status );
      emit_as( "circle_outside_prefilled", reg, NULL, 0, 2, l5, u5, 1, 0, &status );
      emit_as( "circle_inside_ub", reg, NULL, 1, 2, l5, u5, 1, 1, &status );
      emit_as( "circle_outside_ub", reg, NULL, 0, 2, l5, u5, 1, 1, &status );
   }
   {
      double cen[] = { 5.0, 5.0 }, rad = 1.0;
      AstDim u10[] = { 10, 10 };
      reg = (AstRegion *) astCircle( f2, 1, cen, &rad, NULL, " " );
      emit_as( "small_circle_inside_prefilled", reg, NULL, 1, 2, l5, u10, 1, 0, &status );
      emit_as( "small_circle_outside_prefilled", reg, NULL, 0, 2, l5, u10, 1, 0, &status );
   }
   {
      double cen[] = { 1.5, 1.5 }, rad = 1.0;
      reg = (AstRegion *) astCircle( f2, 1, cen, &rad, NULL, " " );
      emit( "circle_through_zoommap", reg, (AstMapping *) astZoomMap( 2, 2.0, " " ),
            1, 2, l5, u6, &status );
   }
   {
      double l[] = { 2.0, 2.0 }, u[] = { 4.0, 4.0 };
      reg = (AstRegion *) astBox( f2, 1, l, u, NULL, " " );
      astNegate( reg );
      emit( "negated_box_inside", reg, NULL, 1, 2, l5, u6, &status );
      emit( "negated_box_outside", reg, NULL, 0, 2, l5, u6, &status );
   }
   {
      double pts[] = { 2.0, 4.0, 10.0, 3.0, 1.0, 10.0 };
      reg = (AstRegion *) astPointList( f2, 3, 2, 3, pts, NULL, " " );
      emit( "pointlist_inside", reg, NULL, 1, 2, l5, u5, &status );
      emit( "pointlist_outside", reg, NULL, 0, 2, l5, u5, &status );
      emit_as( "pointlist_outside_prefilled", reg, NULL, 0, 2, l5, u5, 1, 0, &status );
      emit_as( "pointlist_inside_ub", reg, NULL, 1, 2, l5, u5, 1, 1, &status );
   }
   {
      double l[] = { 3.0 }, u[] = { 7.0 };
      AstDim l1[] = { 1 }, u1[] = { 10 };
      reg = (AstRegion *) astInterval( f1, l, u, NULL, " " );
      emit( "interval_inside", reg, NULL, 1, 1, l1, u1, &status );
   }
   {
      double cen[] = { 3.0, 3.0 }, rad = 2.0;
      AstDim lbad[] = { 6, 1 };
      reg = (AstRegion *) astCircle( f2, 1, cen, &rad, NULL, " " );
      emit( "map_with_wrong_inputs", reg, (AstMapping *) astUnitMap( 3, " " ),
            1, 2, l5, u5, &status );
      emit( "lower_bound_above_upper", reg, NULL, 1, 2, lbad, u5, &status );
   }

   printf( "];\n" );
   return 0;
}
