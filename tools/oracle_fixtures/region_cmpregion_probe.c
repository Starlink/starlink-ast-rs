/* region_cmpregion_probe -- capture CmpRegion construction, membership,
 * mesh and dump (cmpregion.c astInitCmpRegion, Transform, RegBaseMesh,
 * Dump): an FK5 Circle ANDed with a Galactic Box, which astInitCmpRegion
 * maps into FK5, tested at FK5 positions and meshed; and the XOR of two
 * Boxes, which C makes from AND and OR and dumps as the two Boxes XORed.
 *
 * Prints Rust source for crates/starlink-ast/tests/region_cmpregion_oracle/cases.rs:
 *
 *   ./region_cmpregion_probe > ../../crates/starlink-ast/tests/region_cmpregion_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static char dump[ 40000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void membership( const char *name, AstRegion *reg, int np, const double *x,
                        const double *y ) {
   double xo[ 10 ], yo[ 10 ];
   int i;
   astTran2( reg, np, x, y, 1, xo, yo );
   printf( "pub const %s: &str = \"", name );
   for( i = 0; i < np; i++ ) putchar( xo[ i ] == AST__BAD ? '0' : '1' );
   printf( "\";\n" );
}

int main( void ) {
   int status = 0, np, ip;
   AstChannel *ch;
   AstRegion *cmp;
   static double m[ 2 * 4000 ];

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_cmpregion_probe.c. Do not edit.\n\n" );
   {
      double cen[] = { 1.0, 0.5 }, rad = 0.1;
      double gcen[] = { 2.857, -0.346 }, gcor[] = { 3.057, -0.146 };
      double x[] = { 1.0, 1.05, 1.3 }, y[] = { 0.5, 0.5, 0.5 };
      AstRegion *circle = (AstRegion *) astCircle( astSkyFrame( "System=FK5" ), 1, cen,
                                                   &rad, NULL, " " );
      AstRegion *box = (AstRegion *) astBox( astSkyFrame( "System=Galactic" ), 0, gcen,
                                             gcor, NULL, " " );
      cmp = (AstRegion *) astCmpRegion( circle, box, AST__AND, " " );
      printf( "/// Membership of (1.0, 0.5), (1.05, 0.5) and (1.3, 0.5) in the FK5\n"
              "/// Circle ANDed with the Galactic Box.\n" );
      membership( "SKY_AND", cmp, 3, x, y );
      astGetRegionMesh( cmp, 1, 4000, 2, &np, m );
      printf( "/// Its mesh, point by point.\npub const SKY_AND_MESH: &[f64] = &[" );
      for( ip = 0; ip < np; ip++ ) {
         lit( m[ ip ] ); printf( ", " ); lit( m[ 4000 + ip ] ); printf( ", " );
      }
      printf( "];\n" );
   }
   {
      double l1[] = { 0.0, 0.0 }, u1[] = { 2.0, 2.0 }, l2[] = { 1.0, 1.0 }, u2[] = { 3.0, 3.0 };
      double x[] = { 0.5, 1.5, 2.5, 4.0 }, y[] = { 0.5, 1.5, 2.5, 4.0 };
      AstFrame *f = astFrame( 2, " " );
      cmp = (AstRegion *) astCmpRegion( astBox( f, 1, l1, u1, NULL, " " ),
                                        astBox( f, 1, l2, u2, NULL, " " ), AST__XOR, " " );
      printf( "/// Membership of (0.5, 0.5), (1.5, 1.5), (2.5, 2.5) and (4, 4) in the XOR\n"
              "/// of the Boxes [0,2]x[0,2] and [1,3]x[1,3].\n" );
      membership( "XOR", cmp, 4, x, y );
      dump[ 0 ] = 0;
      ch = astChannel( NULL, sink, " " );
      astWrite( ch, cmp );
      ch = astAnnul( ch );
      printf( "/// C's dump of the XOR.\npub const XOR_DUMP: &str = " );
      str( dump );
      printf( ";\n" );
   }
   return status;
}
