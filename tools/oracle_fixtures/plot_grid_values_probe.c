/* plot_grid_values_probe -- read the values an invisible-ink grid chooses
 * for each Plot attribute with a dynamic default (plot.c GetAttrib, through
 * GetUsedGap and the other GetUsed functions, which run astGrid with the
 * protected Ink attribute zero), and the grf_log call log of one such grid.
 *
 * The Plots are those of ast_tester/fixtures/plot/cases.txt, built as
 * ast_tester/testgrid.c builds them, and variants with more attributes set.
 * The call log is captured around astGetC( plot, "LabelAt(1)" ), which no
 * case sets, so it always runs a grid.
 *
 * Prints Rust source for
 * crates/starlink-ast/tests/plot_grid_values_oracle/cases.rs:
 *
 *   ./plot_grid_values_probe > ../../crates/starlink-ast/tests/plot_grid_values_oracle/cases.rs
 *
 * Build and run from reference/starlink-ast/build as plot_curve_probe.c's
 * header describes, with this file in place of plot_curve_probe.c.
 */
#include "plot_draw_probe.h"

/* The attributes read, in UsedValues order. */
static const char *names[] = {
   "Gap(1)", "Gap(2)", "LogGap(1)", "LogGap(2)", "Centre(1)", "Centre(2)",
   "Edge(1)", "Edge(2)", "LabelAt(1)", "LabelAt(2)", "LabelUnits(1)",
   "LabelUnits(2)", "LogTicks(1)", "LogTicks(2)", "LogLabel(1)", "LogLabel(2)",
   "MinTick(1)", "MinTick(2)", "TextLab(1)", "TextLab(2)", "MajTickLen(1)",
   "MajTickLen(2)", "Grid", "Labelling", "Border",
};

/* Variants: a cases.txt case with more attributes, or a 2-D Frame. */
struct variant { const char *name; const char *base; const char *extra; };
static const struct variant variants[] = {
   { "car3_mintick", "car3", "MinTick(1)=5" },
   { "car3_interior", "car3", "Labelling=interior" },
   { "aitoff_exterior", "aitoff", "Labelling=exterior,ForceExterior=1" },
   { "tsc_edges", "tsc", "Edge(1)=top,Edge(2)=right" },
   { "zpn_labelat", "zpn", "LabelAt(2)=0.5" },
   { "frame", NULL, "" },
   { "frame_gap", NULL, "Gap(1)=2.5,Centre(2)=0.3" },
   { "frame_log", NULL, "LogPlot(1)=1" },
   { "frame_log_linear", NULL, "LogPlot(1)=1,LogTicks(1)=0" },
   { "frame_loggap", NULL, "LogPlot(1)=1,LogGap(1)=100" },
   { "frame_digits", NULL, "Digits(1)=3" },
};

static void values( const char *name, AstPlot *pl ) {
   size_t i;
   printf( "    GridValues {\n        name: " );
   rstr( name );
   printf( ",\n" );
   capture_start();
   (void) astGetC( pl, "LabelAt(1)" );
   capture_end();
   astGrfLogInit( NULL );
   printf( "        values: &[" );
   for( i = 0; i < sizeof( names ) / sizeof( names[ 0 ] ); i++ ) {
      const char *v = astGetC( pl, names[ i ] );
      if( i ) printf( ", " );
      if( astOK ) {
         rstr( v );
      } else {
         printf( "\"error %d\"", astStatus );
         astClearStatus;
      }
   }
   printf( "],\n    },\n" );
   astGrfLogClose();
}

int main( void ) {
   int status_value = 0;
   struct grid_case cases[ 64 ];
   int ncase, i;
   size_t v;
   astWatch( &status_value );
   ncase = read_grid_cases( cases, 64 );
   printf( "// Generated by tools/oracle_fixtures/plot_grid_values_probe.c.\n"
           "// Do not edit.\n\n"
           "/// The names of the values, in the order each case gives them.\n"
           "pub const NAMES: &[&str] = &[" );
   for( v = 0; v < sizeof( names ) / sizeof( names[ 0 ] ); v++ ) {
      if( v ) printf( ", " );
      rstr( names[ v ] );
   }
   printf( "];\n\n"
           "/// A variant: its name, the cases.txt case it builds on (None for\n"
           "/// a Plot of a 2-D Frame with plot box 0 0 10 10, or 1 0 1000 10\n"
           "/// when it sets LogPlot), and the attributes it adds.\n"
           "pub const VARIANTS: &[(&str, Option<&str>, &str)] = &[\n" );
   for( v = 0; v < sizeof( variants ) / sizeof( variants[ 0 ] ); v++ ) {
      printf( "    (" );
      rstr( variants[ v ].name );
      printf( ", " );
      if( variants[ v ].base ) { printf( "Some(" ); rstr( variants[ v ].base ); printf( ")" ); }
      else printf( "None" );
      printf( ", " );
      rstr( variants[ v ].extra );
      printf( "),\n" );
   }
   printf( "];\n\n"
           "/// The values C's string getter gives a Plot (a cases.txt case or a\n"
           "/// variant), as C prints them, and the call log of the invisible\n"
           "/// grid behind LabelAt(1).\n"
           "pub struct GridValues {\n"
           "    pub name: &'static str,\n"
           "    pub log: &'static str,\n"
           "    pub svg: Svg,\n"
           "    pub values: &'static [&'static str],\n"
           "}\n\n"
           SVG_DECL
           "pub const CASES: &[GridValues] = &[\n" );
   for( i = 0; i < ncase; i++ ) {
      struct grid_case *c = cases + i;
      AstPlot *pl = testgrid_plot( c->head, c->fattr, c->has_box ? c->box : NULL, c->attr );
      values( c->name, pl );
      pl = astAnnul( pl );
   }
   for( v = 0; v < sizeof( variants ) / sizeof( variants[ 0 ] ); v++ ) {
      const struct variant *va = variants + v;
      AstPlot *pl = NULL;
      if( va->base ) {
         for( i = 0; i < ncase; i++ ) {
            struct grid_case *c = cases + i;
            if( !strcmp( c->name, va->base ) ) {
               pl = testgrid_plot( c->head, c->fattr, c->has_box ? c->box : NULL, c->attr );
            }
         }
      } else {
         float gbox[ 4 ] = { 0.1f, 0.1f, 0.9f, 0.9f };
         double pbox[ 4 ] = { 0.0, 0.0, 10.0, 10.0 };
         double lbox[ 4 ] = { 1.0, 0.0, 1000.0, 10.0 };
         AstFrame *fr = astFrame( 2, "" );
         pl = astPlot( fr, gbox, strstr( va->extra, "LogPlot" ) ? lbox : pbox, "" );
         fr = astAnnul( fr );
      }
      astSet( pl, "%s", va->extra );
      values( va->name, pl );
      pl = astAnnul( pl );
   }
   printf( "];\n" );
   return astOK ? 0 : 1;
}
