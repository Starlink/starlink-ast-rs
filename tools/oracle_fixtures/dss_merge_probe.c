/* dss_merge_probe -- capture the plate centre of the DssMap that a DssMap
 * and a preceding WinMap merge into. C's DssMap MapMerge rebuilds the DssMap
 * from the FITS cards astDssFits writes (dssmap.c), which hold the plate
 * centre as sexagesimal hours or degrees, minutes and seconds, so the merged
 * centre is the original after that round trip. The input is
 * crates/starlink-ast/tests/fixtures/simplify/dssmap_winmap_absorb.map with its
 * PltRA and PltDec replaced.
 *
 * Run from tools/oracle_fixtures; prints Rust source for
 * crates/starlink-ast/tests/dss_merge_oracle/cases.rs:
 *
 *   ./dss_merge_probe > ../../crates/starlink-ast/tests/dss_merge_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static char base[ 200000 ], text[ 200000 ], dump[ 400000 ];
static const char *source;

static const char *next_line( void ) {
   static char line[ 400 ];
   const char *end;
   size_t n;
   if( !*source ) return NULL;
   end = strchr( source, '\n' );
   n = end - source;
   memcpy( line, source, n );
   line[ n ] = 0;
   source = end + 1;
   return line;
}

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

/* Replace the value of "key" (up to the tab before its comment). */
static void set_value( char *s, const char *key, const char *value ) {
   static char tmp[ 200000 ];
   char *p = strstr( s, key ), *q = strchr( p, '\t' );
   size_t pre = p - s;
   memcpy( tmp, s, pre );
   tmp[ pre ] = 0;
   strcat( tmp, key );
   strcat( tmp, value );
   strcat( tmp, " " );
   strcat( tmp, q );
   strcpy( s, tmp );
}

/* The value of "key" in the dump. */
static double get_value( const char *key ) {
   return strtod( strstr( dump, key ) + strlen( key ), NULL );
}

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void emit( const char *ra, const char *dec ) {
   AstChannel *ch;
   AstMapping *map, *simp;
   strcpy( text, base );
   set_value( text, "PltRA = ", ra );
   set_value( text, "PltDec = ", dec );
   source = text;
   ch = astChannel( next_line, NULL, " " );
   map = (AstMapping *) astRead( ch );
   ch = astAnnul( ch );
   simp = astSimplify( map );
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, simp );
   ch = astAnnul( ch );
   if( !astIsADssMap( simp ) ) {
      fprintf( stderr, "%s %s did not merge\n", ra, dec );
      exit( 1 );
   }
   printf( "    (\"%s\", \"%s\", ", ra, dec );
   lit( get_value( "PltRA = " ) );
   printf( ", " );
   lit( get_value( "PltDec = " ) );
   printf( "),\n" );
}

int main( void ) {
   int status = 0;
   FILE *f = fopen( "../../crates/starlink-ast/tests/fixtures/simplify/dssmap_winmap_absorb.map", "r" );
   size_t n;
   astWatch( &status );
   if( !f ) {
      fprintf( stderr, "cannot open the fixture\n" );
      return 1;
   }
   n = fread( base, 1, sizeof( base ) - 1, f );
   base[ n ] = 0;
   fclose( f );
   printf( "// Generated by tools/oracle_fixtures/dss_merge_probe.c. Do not edit.\n\n"
           "/// `(PltRA, PltDec as written in the input, C's merged PltRA, PltDec)`.\n"
           "pub const CASES: &[(&str, &str, f64, f64)] = &[\n" );
   emit( "0.1", "0.7" );
   emit( "1.234567890123456", "-0.3333333333333333" );
   emit( "5.9", "-1.2" );
   emit( "2.8272374655684112", "-1.0518122540502668" );
   printf( "];\n" );
   return status;
}
