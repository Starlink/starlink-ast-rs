/* fitschan_linear_probe -- capture how a FITS-WCS write describes a 1-D
 * axis that is linear, nearly linear or logarithmic in pixel coordinates.
 * OtherAxes (fitschan.c) uses a linear description when IsMapLinear finds
 * the axis linear, a -LOG one when LogAxis finds it logarithmic, and
 * otherwise none; MakeIntWorld then decides whether the result is linear
 * enough to write.
 *
 * Each FrameSet maps a 1-D GRID Frame to a 1-D Frame with a MathMap
 * "y = a*x + e*x*x" or "y = a*exp(b*x)", and is written with NAXIS1 set.
 * For each: the value astWrite returns and the cards written.
 *
 * Prints Rust source for crates/ast-core/tests/fitschan_linear_oracle/cases.rs:
 *
 *   ./fitschan_linear_probe > ../../crates/ast-core/tests/fitschan_linear_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void emit( const char *name, const char *fwd, const char *inv, int naxis1 ) {
   AstFrame *grid, *wcs;
   AstMathMap *map;
   AstFrameSet *fs;
   AstFitsChan *fc;
   char card[ 81 ];
   int ret;

   grid = astFrame( 1, "Domain=GRID" );
   wcs = astFrame( 1, "Domain=X" );
   map = astMathMap( 1, 1, 1, &fwd, 1, &inv, " " );
   fs = astFrameSet( grid, " " );
   astAddFrame( fs, AST__BASE, map, wcs );

   fc = astFitsChan( NULL, NULL, "Encoding=FITS-WCS" );
   sprintf( card, "NAXIS1  = %d", naxis1 );
   astPutFits( fc, card, 0 );
   ret = astWrite( fc, fs );
   astClearStatus;

   printf( "    (\"%s\", ", name );
   str( fwd );
   printf( ", " );
   str( inv );
   printf( ", %d, %d, &[\n", naxis1, ret );
   astClear( fc, "Card" );
   while( astFindFits( fc, "%f", card, 1 ) ) {
      printf( "        " );
      str( card );
      printf( ",\n" );
   }
   printf( "    ]),\n" );
   fc = astAnnul( fc );
   fs = astAnnul( fs );
}

int main( void ) {
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/fitschan_linear_probe.c. Do not edit.\n\n" );
   printf( "/// `(name, forward function, inverse function, NAXIS1, astWrite's value,\n"
           "/// the cards written)`.\n" );
   printf( "pub type Case = (&'static str, &'static str, &'static str, i32, i32,\n"
           "    &'static [&'static str]);\n\n" );
   printf( "pub const CASES: &[Case] = &[\n" );
   emit( "linear", "y=2*x+5", "x=(y-5)/2", 100 );
   emit( "far_from_zero", "y=39062.5*x+1.1e11", "x=(y-1.1e11)/39062.5", 20 );
   emit( "curved_1e-9", "y=x+1e-9*x*x", "x=(-1+sqrt(1+4e-9*y))/2e-9", 100 );
   emit( "curved_1e-8", "y=x+1e-8*x*x", "x=(-1+sqrt(1+4e-8*y))/2e-8", 100 );
   emit( "curved_1e-7", "y=x+1e-7*x*x", "x=(-1+sqrt(1+4e-7*y))/2e-7", 100 );
   emit( "curved_1e-6", "y=x+1e-6*x*x", "x=(-1+sqrt(1+4e-6*y))/2e-6", 100 );
   emit( "curved_1e-4", "y=x+1e-4*x*x", "x=(-1+sqrt(1+4e-4*y))/2e-4", 100 );
   emit( "curved_1e-2", "y=x+1e-2*x*x", "x=(-1+sqrt(1+4e-2*y))/2e-2", 100 );
   emit( "exponential", "y=2*exp(0.01*x)", "x=log(y/2)/0.01", 100 );
   emit( "exponential_1e-3", "y=2*exp(1e-3*x)", "x=log(y/2)/1e-3", 100 );
   emit( "exponential_1e-4", "y=2*exp(1e-4*x)", "x=log(y/2)/1e-4", 100 );
   emit( "exponential_1e-5", "y=2*exp(1e-5*x)", "x=log(y/2)/1e-5", 100 );
   emit( "exponential_1e-6", "y=2*exp(1e-6*x)", "x=log(y/2)/1e-6", 100 );
   printf( "];\n" );
   return 0;
}
