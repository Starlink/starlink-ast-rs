/* spline_inverse_probe -- capture the forward and iterative inverse
 * transformations of the SplineMap in testsplinemap_c.c, bit for bit: the
 * spline fitted by SciPy in fixtures/programs/testsplinemap/2dspline_c.dat,
 * forward at the test's positions and inverse at the results (splinemap.c
 * Transform, whose Newton-Raphson steps are solved by palDmat).
 *
 * Run from tools/oracle_fixtures; prints Rust source for
 * crates/ast-core/tests/spline_inverse_oracle/cases.rs:
 *
 *   ./spline_inverse_probe > ../../crates/ast-core/tests/spline_inverse_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

#define NX 150
#define NY 100
#define K 4
#define NPOS 10

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   if( v == AST__BAD ) {
      printf( "BAD_VALUE" );
      return;
   }
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void list( const char *name, const double *v ) {
   int i;
   printf( "pub const %s: [f64; %d] = [", name, NPOS );
   for( i = 0; i < NPOS; i++ ) {
      lit( v[ i ] );
      printf( ", " );
   }
   printf( "];\n" );
}

static void read_values( FILE *in, int n, double *v ) {
   int i;
   for( i = 0; i < n; i++ ) {
      if( fscanf( in, "%lf", v + i ) != 1 ) {
         fprintf( stderr, "short fixture\n" );
         exit( 1 );
      }
   }
}

int main( void ) {
   int status = 0;
   static double tx[ NX + K ], ty[ NY + K ], cu[ NX*NY ], cv[ NX*NY ];
   double xin[ NPOS ] = { 0.0, 12.5, 12.0, 1.0, 15.0, 1.0, 95.0, 149.5, 151.2, 77.77 };
   double yin[ NPOS ] = { -1.0, 8.8, 8.0, 1.0, 15.0, 76.0, 100.0, 99.8, 82.3, 54.3 };
   double u[ NPOS ], v[ NPOS ], x[ NPOS ], y[ NPOS ];
   FILE *in = fopen( "../../crates/ast-core/tests/fixtures/programs/testsplinemap/2dspline_c.dat", "r" );
   AstSplineMap *sm;

   astWatch( &status );
   if( !in ) {
      fprintf( stderr, "cannot open the fixture\n" );
      return 1;
   }
   read_values( in, NX + K, tx );
   read_values( in, NY + K, ty );
   read_values( in, NX*NY, cu );
   read_values( in, NX*NY, cv );
   fclose( in );

   sm = astSplineMap( K, K, NX, NY, tx, ty, cu, cv, " " );
   astTran2( sm, NPOS, xin, yin, 1, u, v );
   astTran2( sm, NPOS, u, v, 0, x, y );

   printf( "// Generated by tools/oracle_fixtures/spline_inverse_probe.c. Do not edit.\n\n"
           "use ast_core::constants::BAD_VALUE;\n\n"
           "/// C's forward transformation of testsplinemap_c.c's positions.\n" );
   list( "U", u );
   list( "V", v );
   printf( "/// C's inverse transformation of `U`, `V`.\n" );
   list( "X", x );
   list( "Y", y );
   return status;
}
