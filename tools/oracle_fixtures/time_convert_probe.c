/* time_convert_probe -- capture the Mapping astConvert finds between two
 * TimeFrames (timeframe.c Match, SubFrame, MakeTimeMapping, MakeMap).
 *
 * The TimeScale grid converts between every pair of time scales in four
 * configurations:
 *   0  the two Frames share every property;
 *   1  they differ in observer position, DUT1, DTAI and LTOffset, and the
 *      destination's AlignTimeScale is left at its default (TAI);
 *   2  as 1, aligning in UTC;
 *   3  as 1, aligning in LAST.
 * The System grid converts between every pair of time systems, with
 * TimeOrigins and Units set, in the TT time scale.
 *
 * ObsLon and ObsLat are set with the protected setters, which take
 * radians; the other values are exactly representable.
 *
 * Prints Rust source for crates/starlink-ast/tests/time_convert_oracle/cases.rs:
 *
 *   ./time_convert_probe > ../../crates/starlink-ast/tests/time_convert_oracle/cases.rs
 */
#include <float.h>
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern void astSetObsLat_( void *, double, int * );
extern void astSetObsLon_( void *, double, int * );

static const char *scales[] = {
   "TAI", "UTC", "UT1", "GMST", "LAST", "LMST", "TT", "TDB", "TCB", "TCG", "LT"
};
#define NSCALE ( (int) ( sizeof( scales ) / sizeof( scales[ 0 ] ) ) )

static const char *systems[] = { "MJD", "JD", "JEPOCH", "BEPOCH" };
static const char *origins[] = { "55000.5", "2455000.5", "2009.25", "2009.5" };
static const char *units[] = { "d", "h", "yr", "yr" };
#define NSYS 4

/* Observer properties for configurations 1-3:
   { obslon rad, obslat rad, Dut1 s, Dtai s, LTOffset h }. */
static const double props[ 2 ][ 5 ] = {
   { -2.7135, 0.3459, 0.25, 35.0, -10.0 },
   { 1.2345, -0.5013, -0.5, 37.0, 1.0 },
};

/* Points: MJD offsets from the origin 55000.5 used by the scale grid. */
static const double points[ 2 ] = { 0.25, 1.75 };

static void flit( double value ) {
   char buf[ 40 ];
   if( value == AST__BAD ) { fputs( "BAD", stdout ); return; }
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

static void emit( const char *label, AstTimeFrame *from, AstTimeFrame *to,
                  const double in[ 2 ] ) {
   double out[ 2 ];
   AstFrameSet *fs = astConvert( from, to, "" );
   printf( "    (\"%s\", ", label );
   if( !astOK ) {
      astClearStatus;
      printf( "Err(())),\n" );
   } else if( !fs ) {
      printf( "Ok(None)),\n" );
   } else {
      astTran1( fs, 2, in, 1, out );
      printf( "Ok(Some([" ); flit( out[ 0 ] ); printf( ", " ); flit( out[ 1 ] );
      printf( "]))),\n" );
      fs = astAnnul( fs );
   }
}

static AstTimeFrame *scale_frame( int c, const char *ts, int is_to ) {
   int status = 0;
   AstTimeFrame *f = astTimeFrame( "System=MJD,TimeOrigin=55000.5" );
   astSetC( f, "TimeScale", ts );
   if( c > 0 ) {
      const double *p = props[ is_to ];
      astSetObsLon_( astMakePointer( f ), p[ 0 ], &status );
      astSetObsLat_( astMakePointer( f ), p[ 1 ], &status );
      astSetD( f, "Dut1", p[ 2 ] );
      astSetD( f, "Dtai", p[ 3 ] );
      astSetD( f, "LTOffset", p[ 4 ] );
      if( is_to && c == 2 ) astSetC( f, "AlignTimeScale", "UTC" );
      if( is_to && c == 3 ) astSetC( f, "AlignTimeScale", "LAST" );
   }
   return f;
}

int main( void ) {
   int status = 0, c, i, j;
   char label[ 80 ];
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/time_convert_probe.c against\n"
           "// the C library at u/timj/norm-unit 5a2cac2a, past the submodule pin.\n"
           "// Do not edit.\n\n"
           "// Each value is printed with 17 digits so that it reads back exactly.\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "#[allow(unused_imports)]\n"
           "use starlink_ast::constants::BAD_VALUE as BAD;\n\n"
           "/// `[obslon rad, obslat rad, Dut1 s, Dtai s, LTOffset h]` of the source\n"
           "/// and destination Frames in configurations 1-3.\n"
           "pub const PROPS: [[f64; 5]; 2] = [" );
   for( i = 0; i < 2; i++ ) {
      printf( "%s[", i ? ", " : "" );
      for( j = 0; j < 5; j++ ) { if( j ) printf( ", " ); flit( props[ i ][ j ] ); }
      printf( "]" );
   }
   printf( "];\n\n/// The points the TimeScale grid transforms.\n"
           "pub const POINTS: [f64; 2] = [" );
   flit( points[ 0 ] ); printf( ", " ); flit( points[ 1 ] );
   printf( "];\n\n"
           "/// `(case, result)`: `s<config>:<from>:<to>` for the TimeScale grid and\n"
           "/// `y:<from>:<to>` for the System grid. The result is the two\n"
           "/// transformed points, `Ok(None)` when no conversion exists, or\n"
           "/// `Err(())` when C reports an error.\n"
           "pub type TimeCase = (&'static str, Result<Option<[f64; 2]>, ()>);\n\n"
           "pub const CASES: &[TimeCase] = &[\n" );

   for( c = 0; c < 4; c++ ) {
      for( i = 0; i < NSCALE; i++ ) {
         for( j = 0; j < NSCALE; j++ ) {
            AstTimeFrame *from = scale_frame( c, scales[ i ], 0 );
            AstTimeFrame *to = scale_frame( c, scales[ j ], 1 );
            snprintf( label, sizeof( label ), "s%d:%s:%s", c, scales[ i ], scales[ j ] );
            emit( label, from, to, points );
            from = astAnnul( from );
            to = astAnnul( to );
         }
      }
   }

   for( i = 0; i < NSYS; i++ ) {
      for( j = 0; j < NSYS; j++ ) {
         double in[ 2 ] = { 0.25, 1.75 };
         AstTimeFrame *from = astTimeFrame( "TimeScale=TT" );
         AstTimeFrame *to = astTimeFrame( "TimeScale=TT" );
         astSetC( from, "System", systems[ i ] );
         astSetC( from, "TimeOrigin", origins[ i ] );
         astSetC( from, "Unit", units[ i ] );
         astSetC( to, "System", systems[ j ] );
         astSetC( to, "TimeOrigin", origins[ j ] );
         astSetC( to, "Unit", units[ j ] );
         snprintf( label, sizeof( label ), "y:%s:%s", systems[ i ], systems[ j ] );
         emit( label, from, to, in );
         from = astAnnul( from );
         to = astAnnul( to );
      }
   }

   printf( "];\n" );
   return 0;
}
