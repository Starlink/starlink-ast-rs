/* xphmap_probe -- capture the forward and inverse transformations of an
 * XphMap of each projection type, bit for bit (xphmap.c Transform), over a
 * half-pixel grid that covers the whole HEALPix layout at order 1, so every
 * facet and every edge rule is exercised. XphMap has no public constructor,
 * so each is read from a dump.
 *
 * Prints Rust source for crates/starlink-ast/tests/xphmap_oracle/cases.rs:
 *
 *   ./xphmap_probe > ../../crates/starlink-ast/tests/xphmap_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

#define ORDER 1
#define NSTEP 25           /* -1.0 to 11.0 in steps of 0.5 */
#define NPOINT ( NSTEP*NSTEP )

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   if( v == AST__BAD ) {
      printf( "B" );
      return;
   }
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void list( const double *v ) {
   int i;
   printf( "&[" );
   for( i = 0; i < NPOINT; i++ ) {
      lit( v[ i ] );
      printf( "," );
   }
   printf( "]" );
}

int main( void ) {
   int status = 0, i, j, k, fwd;
   const char *types[] = { "HPX0", "HPX12", "XPHN", "XPHS" };
   double x[ NPOINT ], y[ NPOINT ], u[ NPOINT ], v[ NPOINT ];
   char dump[ 256 ];
   AstMapping *map;

   astWatch( &status );
   for( i = 0; i < NSTEP; i++ ) {
      for( j = 0; j < NSTEP; j++ ) {
         x[ i*NSTEP + j ] = -1.0 + 0.5*i;
         y[ i*NSTEP + j ] = -1.0 + 0.5*j;
      }
   }
   printf( "// Generated by tools/oracle_fixtures/xphmap_probe.c. Do not edit.\n\n"
           "use starlink_ast::constants::BAD_VALUE as B;\n\n"
           "/// The HEALPix order of every case.\n"
           "pub const ORDER: i64 = %d;\n\n"
           "/// The input grid: x and y from -1 to 11 in steps of 0.5, x varying slowest.\n"
           "pub const STEPS: usize = %d;\n\n"
           "/// `(projection type, forward, C's x outputs, C's y outputs)`.\n"
           "pub const CASES: &[(&str, bool, &[f64], &[f64])] = &[\n", ORDER, NSTEP );
   for( k = 0; k < 4; k++ ) {
      snprintf( dump, sizeof dump, " Begin XphMap\n    Nin = 2\n IsA Mapping\n"
                "    Order = %d\n    Type = \"%s\"\n End XphMap\n", ORDER, types[ k ] );
      map = astFromString( dump );
      for( fwd = 1; fwd >= 0; fwd-- ) {
         astTran2( map, NPOINT, x, y, fwd, u, v );
         printf( "    (\"%s\", %s, ", types[ k ], fwd ? "true" : "false" );
         list( u );
         printf( ", " );
         list( v );
         printf( "),\n" );
      }
      map = astAnnul( map );
   }
   printf( "];\n" );
   return status;
}
