/* sky_norm_probe -- capture SkyFrame Norm (skyframe.c Norm) for points with
 * a bad coordinate, past either pole, just short of 2pi, and with NegLon set,
 * on an unpermuted and a permuted SkyFrame; and the SkyTol and Equinox
 * setters (skyframe.c:11436, 11658).
 *
 * Prints Rust source for crates/ast-core/tests/sky_norm_oracle/cases.rs:
 *
 *   ./sky_norm_probe > ../../crates/ast-core/tests/sky_norm_oracle/cases.rs
 */
#include <float.h>
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void flit( double value ) {
   char buf[ 40 ];
   if( value == AST__BAD ) { fputs( "BAD", stdout ); return; }
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

static const double points[][ 2 ] = {
   { 7.0, 4.0 }, { AST__BAD, 4.0 }, { 7.0, AST__BAD }, { 1.0, 2.0 }, { 4.0, 2.0 },
   { 1.0, -2.0 }, { 4.0, -2.0 }, { 6.283185307179586, 0.1 }, { -0.5, 0.2 },
   { 3.5, 1.0 }, { 12.0, -5.0 },
};
#define NPOINT ( (int) ( sizeof( points ) / sizeof( points[ 0 ] ) ) )

int main( void ) {
   int status = 0, p, n, i, perm[ 2 ] = { 2, 1 };
   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/sky_norm_probe.c against\n"
           "// the C library at u/timj/norm-unit 5a2cac2a, past the submodule pin.\n"
           "// Do not edit.\n\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "use ast_core::constants::BAD_VALUE as BAD;\n\n"
           "/// `(permuted, neglon, input, normalised)`.\n"
           "pub const NORM_CASES: &[(bool, bool, [f64; 2], [f64; 2])] = &[\n" );
   for( p = 0; p < 2; p++ ) {
      for( n = 0; n < 2; n++ ) {
         for( i = 0; i < NPOINT; i++ ) {
            AstSkyFrame *f = astSkyFrame( " " );
            double v[ 2 ];
            if( p ) astPermAxes( f, perm );
            if( n ) astSetI( f, "NegLon", 1 );
            v[ 0 ] = points[ i ][ 0 ];
            v[ 1 ] = points[ i ][ 1 ];
            astNorm( f, v );
            printf( "    (%s, %s, [", p ? "true" : "false", n ? "true" : "false" );
            flit( points[ i ][ 0 ] ); printf( ", " ); flit( points[ i ][ 1 ] );
            printf( "], [" ); flit( v[ 0 ] ); printf( ", " ); flit( v[ 1 ] ); printf( "]),\n" );
            f = astAnnul( f );
         }
      }
   }
   printf( "];\n\n" );
   {
      AstSkyFrame *f = astSkyFrame( "System=HELIOECLIPTIC" );
      AstSkyFrame *g = astSkyFrame( " " );
      astSetD( f, "Equinox", 1975.0 );
      astSetD( g, "SkyTol", -0.5 );
      printf( "/// Whether Equinox is set after setting it on a HELIOECLIPTIC SkyFrame.\n"
              "pub const HELIO_EQUINOX_SET: bool = %s;\n\n", astTest( f, "Equinox" ) ? "true" : "false" );
      printf( "/// SkyTol after setting -0.5.\npub const SKYTOL: f64 = " );
      flit( astGetD( g, "SkyTol" ) ); printf( ";\n" );
   }
   return 0;
}
