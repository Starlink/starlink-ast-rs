/* region_errors_probe -- capture the errors C's Region constructors and
 * setters report, and the values its loader repairs: astSetUnc given a
 * Region that cannot be re-centred, or one in a Frame that cannot be
 * converted (region.c SetUnc); astSetFillFactor outside 0 to 1 (region.c
 * astMAKE_SET for FillFactor); a dump whose Fill is out of range, or whose
 * MeshSz is below 5 (region.c Load); and BAD coordinates given to astBox
 * (box.c astInitBox) and astCircle (circle.c astInitCircle); astPolygon
 * given a 3-D Frame, no vertices, one or two vertices, or a BAD vertex
 * (polygon.c astInitPolygon); and astEllipse given a 3-D Frame, BAD values,
 * a negative or zero axis, or form-0 points that do not determine an
 * ellipse, which C accepts and rejects only when the Ellipse is used
 * (ellipse.c astInitEllipse and Cache); and a Box dump whose points have
 * three values for its 2-D Frame (region.c Load). Also astSetUnc given an
 * uncertainty whose current Frame is in another Domain but whose base
 * Frame is in the Region's, which region.c Conv finds by converting
 * FrameSet to FrameSet, and the dump of the Region it gives.
 *
 * Each error is recorded as the status C is left holding, which for a pair
 * of astError calls is the second one's.
 *
 * Prints Rust source for crates/starlink-ast/tests/region_errors_oracle/cases.rs:
 *
 *   ./region_errors_probe > ../../crates/starlink-ast/tests/region_errors_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern void *astMapRegion_( void *, void *, void *, int * );
extern AstObject *astMakeId_( AstObject *, int * );

static char dump[ 20000 ];
static char *next_line;

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static const char *source( void ) {
   static char line[ 1000 ];
   char *nl;
   size_t n;
   if( !next_line || !*next_line ) return NULL;
   nl = strchr( next_line, '\n' );
   n = nl ? (size_t)( nl - next_line ) : strlen( next_line );
   memcpy( line, next_line, n );
   line[ n ] = 0;
   next_line = nl ? nl + 1 : next_line + n;
   return line;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

/* Replace the first line containing `key` with `with`. */
static void replace_line( const char *key, const char *with ) {
   static char out[ 20000 ];
   char *at = strstr( dump, key ), *start, *end;
   start = at;
   while( start > dump && start[ -1 ] != '\n' ) start--;
   end = strchr( at, '\n' );
   out[ 0 ] = 0;
   strncat( out, dump, (size_t)( start - dump ) );
   strcat( out, with );
   strcat( out, end );
   strcpy( dump, out );
}

static void code( const char *name, int *status ) {
   printf( "pub const %s: i32 = %d;\n", name, *status );
   astClearStatus;
}

int main( void ) {
   int status = 0;
   double bad = AST__BAD, c[] = { 0.0, 0.0 }, r = 1.0, p[] = { 1.0, 1.0 };
   double x[] = { 0.0, 1.0, 0.0 };
   double b0[] = { AST__BAD, 0.0 }, b1[] = { 1.0, AST__BAD };
   AstRegion *circle, *poly, *box3, *loaded;
   AstChannel *ch;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_errors_probe.c. Do not edit.\n\n" );

   circle = (AstRegion *) astCircle( astFrame( 2, " " ), 1, c, &r, NULL, " " );

   printf( "/// astSetUnc given a Polygon, which cannot be re-centred.\n" );
   poly = (AstRegion *) astPolygon( astFrame( 2, " " ), 3, 3, x, NULL, " " );
   astSetUnc( circle, poly );
   code( "SETUNC_SHAPE", &status );
   printf( "/// astSetUnc given a Box in a 3-D Frame of another Domain.\n" );
   box3 = (AstRegion *) astBox( astFrame( 3, "Domain=OTHER" ), 1,
                                (double[]){ 0.0, 0.0, 0.0 },
                                (double[]){ 1.0, 1.0, 1.0 }, NULL, " " );
   astSetUnc( circle, box3 );
   code( "SETUNC_FRAME", &status );
   printf( "/// Whether a failed astSetUnc leaves an earlier uncertainty in place.\n" );
   astSetUnc( circle, (AstRegion *) astBox( astFrame( 2, " " ), 1, c, p, NULL, " " ) );
   astSetUnc( circle, poly );
   astClearStatus;
   printf( "pub const SETUNC_KEEPS_OLD: bool = %s;\n",
           astGetUnc( circle, 0 ) ? "true" : "false" );

   printf( "/// astSetFillFactor(1.5) after FillFactor = 0.5, and the value left.\n" );
   astSetD( circle, "FillFactor", 0.5 );
   astSetD( circle, "FillFactor", 1.5 );
   code( "FILL_HIGH", &status );
   printf( "pub const FILL_AFTER: f64 = %.17g;\n", astGetD( circle, "FillFactor" ) );
   printf( "/// astSetFillFactor(-0.1).\n" );
   astSetD( circle, "FillFactor", -0.1 );
   code( "FILL_LOW", &status );

   astSetI( circle, "MeshSize", 10 );
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, circle );
   ch = astAnnul( ch );
   {
      static char base[ 20000 ];
      strcpy( base, dump );

      replace_line( "Fill = ", "   Fill = 2" );
      printf( "/// A Circle dump whose Fill is 2.\npub const LOAD_FILL_DUMP: &str = " );
      str( dump );
      printf( ";\n" );
      next_line = dump;
      ch = astChannel( source, NULL, " " );
      loaded = astRead( ch );
      ch = astAnnul( ch );
      printf( "/// Reading it.\n" );
      code( "LOAD_FILL", &status );
      (void) loaded;

      strcpy( dump, base );
      replace_line( "MeshSz = ", "   MeshSz = -3" );
      printf( "/// A Circle dump whose MeshSz is -3.\npub const LOAD_MESH_DUMP: &str = " );
      str( dump );
      printf( ";\n" );
      next_line = dump;
      ch = astChannel( source, NULL, " " );
      loaded = astRead( ch );
      ch = astAnnul( ch );
      printf( "/// The MeshSize C reads from it.\npub const LOAD_MESH_SIZE: i32 = %d;\n",
              astGetI( loaded, "MeshSize" ) );
      astClearStatus;
   }

   printf( "/// astBox form 0 with a BAD centre, and with a BAD corner.\n" );
   astBox( astFrame( 2, " " ), 0, b0, p, NULL, " " );
   code( "BOX_CENTRE", &status );
   astBox( astFrame( 2, " " ), 0, c, b1, NULL, " " );
   code( "BOX_CORNER", &status );
   printf( "/// astBox form 1 with a BAD lower bound, and with a BAD upper bound.\n" );
   astBox( astFrame( 2, " " ), 1, b0, p, NULL, " " );
   code( "BOX_LOWER", &status );
   astBox( astFrame( 2, " " ), 1, c, b1, NULL, " " );
   code( "BOX_UPPER", &status );

   printf( "/// astCircle form 1 with a BAD centre, and with a BAD radius.\n" );
   astCircle( astFrame( 2, " " ), 1, b0, &r, NULL, " " );
   code( "CIRCLE_CENTRE", &status );
   astCircle( astFrame( 2, " " ), 1, c, &bad, NULL, " " );
   code( "CIRCLE_RADIUS", &status );
   printf( "/// astCircle form 0 with a BAD circumference point.\n" );
   astCircle( astFrame( 2, " " ), 0, c, b1, NULL, " " );
   code( "CIRCLE_CIRCUM", &status );
   printf( "/// astPolygon in a 3-D Frame, and with no vertices.\n" );
   astPolygon( astFrame( 3, " " ), 3, 3, x, NULL, " " );
   code( "POLY_NAXES", &status );
   astPolygon( astFrame( 2, " " ), 0, 3, x, NULL, " " );
   code( "POLY_EMPTY", &status );
   printf( "/// astPolygon with a BAD Y at vertex 2 and a BAD X at vertex 3.\n" );
   {
      double v[] = { 0.0, 1.0, AST__BAD, 0.0, AST__BAD, 1.0 };
      astPolygon( astFrame( 2, " " ), 3, 3, v, NULL, " " );
      code( "POLY_BAD", &status );
   }
   printf( "/// Bounded for a Polygon of vertex (0,0), and of vertices (0,0) and (1,0).\n" );
   {
      double v1[] = { 0.0, 0.0 }, v2[] = { 0.0, 1.0, 0.0, 0.0 };
      printf( "pub const POLY_ONE_BOUNDED: bool = %s;\n",
              astGetI( astPolygon( astFrame( 2, " " ), 1, 1, v1, NULL, " " ), "Bounded" ) ? "true" : "false" );
      printf( "pub const POLY_TWO_BOUNDED: bool = %s;\n",
              astGetI( astPolygon( astFrame( 2, " " ), 2, 2, v2, NULL, " " ), "Bounded" ) ? "true" : "false" );
   }
   code( "POLY_FEW", &status );

   printf( "/// astEllipse form 1 in a 3-D Frame, and with a BAD centre, axis and angle.\n" );
   {
      double c3[] = { 0.0, 0.0, 0.0 }, ax[] = { 2.0, 1.0 }, ang = 0.3;
      double axbad[] = { 2.0, AST__BAD }, cbad[] = { AST__BAD, 0.0 };
      double inx[] = { 0.5 }, iny[] = { 0.5 }, outx[ 1 ], outy[ 1 ];
      AstRegion *e;
      astEllipse( astFrame( 3, " " ), 1, c3, ax, &ang, NULL, " " );
      code( "ELL_NAXES", &status );
      astEllipse( astFrame( 2, " " ), 1, cbad, ax, &ang, NULL, " " );
      code( "ELL_CENTRE", &status );
      astEllipse( astFrame( 2, " " ), 1, c, axbad, &ang, NULL, " " );
      code( "ELL_AXIS", &status );
      astEllipse( astFrame( 2, " " ), 1, c, ax, &bad, NULL, " " );
      code( "ELL_ANGLE", &status );

      printf( "/// astEllipse form 1 with axes (-2, 1): built, and (0.5, 0.5) transformed.\n" );
      ax[ 0 ] = -2.0;
      e = (AstRegion *) astEllipse( astFrame( 2, " " ), 1, c, ax, &ang, NULL, " " );
      code( "ELL_NEGATIVE", &status );
      astTran2( e, 1, inx, iny, 1, outx, outy );
      printf( "pub const ELL_NEGATIVE_OUT: [f64; 2] = [%.17g, %.17g];\n", outx[ 0 ], outy[ 0 ] );
      code( "ELL_NEGATIVE_USE", &status );

      printf( "/// astEllipse form 1 with axes (0, 1): built, then used.\n" );
      ax[ 0 ] = 0.0;
      e = (AstRegion *) astEllipse( astFrame( 2, " " ), 1, c, ax, &ang, NULL, " " );
      code( "ELL_ZERO", &status );
      astTran2( e, 1, inx, iny, 1, outx, outy );
      code( "ELL_ZERO_USE", &status );

      printf( "/// The dump of a form-0 Ellipse whose first point is its centre, read and used.\n" );
      e = (AstRegion *) astEllipse( astFrame( 2, " " ), 0, c, c, p, NULL, " " );
      dump[ 0 ] = 0;
      ch = astChannel( NULL, sink, " " );
      astWrite( ch, e );
      ch = astAnnul( ch );
      printf( "pub const ELL_DEGENERATE_DUMP: &str = " );
      str( dump );
      printf( ";\n" );
      next_line = dump;
      ch = astChannel( source, NULL, " " );
      loaded = astRead( ch );
      ch = astAnnul( ch );
      code( "ELL_DEGENERATE_LOAD", &status );
      astTran2( loaded, 1, inx, iny, 1, outx, outy );
      code( "ELL_DEGENERATE_USE", &status );
   }
   printf( "/// A 2-D Box dump holding a 3-D Box's PointSet, and reading it.\n" );
   {
      static char d2[ 20000 ], d3[ 20000 ], out[ 20000 ];
      char *p2, *e2, *p3, *e3;
      double lo3[] = { 0.0, 0.0, 0.0 }, hi3[] = { 1.0, 1.0, 1.0 };
      AstObject *b2 = (AstObject *) astBox( astFrame( 2, " " ), 1, c, p, NULL, " " );
      AstObject *b3 = (AstObject *) astBox( astFrame( 3, " " ), 1, lo3, hi3, NULL, " " );
      dump[ 0 ] = 0;
      ch = astChannel( NULL, sink, " " );
      astWrite( ch, b2 );
      ch = astAnnul( ch );
      strcpy( d2, dump );
      dump[ 0 ] = 0;
      ch = astChannel( NULL, sink, " " );
      astWrite( ch, b3 );
      ch = astAnnul( ch );
      strcpy( d3, dump );
      p2 = strstr( d2, "Begin PointSet" );
      e2 = strstr( p2, "End PointSet" );
      p3 = strstr( d3, "Begin PointSet" );
      e3 = strstr( p3, "End PointSet" );
      out[ 0 ] = 0;
      strncat( out, d2, (size_t)( p2 - d2 ) );
      strncat( out, p3, (size_t)( e3 - p3 ) );
      strcat( out, e2 );
      strcpy( dump, out );
      printf( "pub const LOAD_NCOORD_DUMP: &str = " );
      str( dump );
      printf( ";\n" );
      next_line = dump;
      ch = astChannel( source, NULL, " " );
      loaded = astRead( ch );
      ch = astAnnul( ch );
      code( "LOAD_NCOORD", &status );
   }
   printf( "/// astSetUnc given a Circle in Domain FOO mapped by a ZoomMap of 2 into\n"
           "/// Domain BAR, on a Circle in Domain FOO, and the dump of the result.\n" );
   {
      double cen[] = { 1.0, 0.5 }, rad = 0.1, urad = 0.01;
      int s = 0;
      AstRegion *target = (AstRegion *) astCircle( astFrame( 2, "Domain=FOO" ), 1, cen, &rad, NULL, " " );
      AstRegion *u = (AstRegion *) astCircle( astFrame( 2, "Domain=FOO" ), 1, cen, &urad, NULL, " " );
      AstObject *umapped = astMakeId_( astMapRegion_( astMakePointer( u ),
                                       astMakePointer( astZoomMap( 2, 2.0, " " ) ),
                                       astMakePointer( astFrame( 2, "Domain=BAR" ) ), &s ), &s );
      astSetUnc( target, umapped );
      code( "SETUNC_OTHER_CURRENT", &status );
      dump[ 0 ] = 0;
      ch = astChannel( NULL, sink, " " );
      astWrite( ch, target );
      ch = astAnnul( ch );
      printf( "pub const SETUNC_OTHER_CURRENT_DUMP: &str = " );
      str( dump );
      printf( ";\n" );
   }
   return 0;
}
