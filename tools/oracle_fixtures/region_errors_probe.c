/* region_errors_probe -- capture the errors C's Region constructors and
 * setters report, and the values its loader repairs: astSetUnc given a
 * Region that cannot be re-centred, or one in a Frame that cannot be
 * converted (region.c SetUnc); astSetFillFactor outside 0 to 1 (region.c
 * astMAKE_SET for FillFactor); a dump whose Fill is out of range, or whose
 * MeshSz is below 5 (region.c Load); and BAD coordinates given to astBox
 * (box.c astInitBox) and astCircle (circle.c astInitCircle).
 *
 * Each error is recorded as the status C is left holding, which for a pair
 * of astError calls is the second one's.
 *
 * Prints Rust source for crates/ast-core/tests/region_errors_oracle/cases.rs:
 *
 *   ./region_errors_probe > ../../crates/ast-core/tests/region_errors_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static char dump[ 20000 ];
static char *next_line;

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static const char *source( void ) {
   static char line[ 1000 ];
   char *nl;
   size_t n;
   if( !next_line || !*next_line ) return NULL;
   nl = strchr( next_line, '\n' );
   n = nl ? (size_t)( nl - next_line ) : strlen( next_line );
   memcpy( line, next_line, n );
   line[ n ] = 0;
   next_line = nl ? nl + 1 : next_line + n;
   return line;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

/* Replace the first line containing `key` with `with`. */
static void replace_line( const char *key, const char *with ) {
   static char out[ 20000 ];
   char *at = strstr( dump, key ), *start, *end;
   start = at;
   while( start > dump && start[ -1 ] != '\n' ) start--;
   end = strchr( at, '\n' );
   out[ 0 ] = 0;
   strncat( out, dump, (size_t)( start - dump ) );
   strcat( out, with );
   strcat( out, end );
   strcpy( dump, out );
}

static void code( const char *name, int *status ) {
   printf( "pub const %s: i32 = %d;\n", name, *status );
   astClearStatus;
}

int main( void ) {
   int status = 0;
   double bad = AST__BAD, c[] = { 0.0, 0.0 }, r = 1.0, p[] = { 1.0, 1.0 };
   double x[] = { 0.0, 1.0, 0.0 };
   double b0[] = { AST__BAD, 0.0 }, b1[] = { 1.0, AST__BAD };
   AstRegion *circle, *poly, *box3, *loaded;
   AstChannel *ch;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_errors_probe.c. Do not edit.\n\n" );

   circle = (AstRegion *) astCircle( astFrame( 2, " " ), 1, c, &r, NULL, " " );

   printf( "/// astSetUnc given a Polygon, which cannot be re-centred.\n" );
   poly = (AstRegion *) astPolygon( astFrame( 2, " " ), 3, 3, x, NULL, " " );
   astSetUnc( circle, poly );
   code( "SETUNC_SHAPE", &status );
   printf( "/// astSetUnc given a Box in a 3-D Frame of another Domain.\n" );
   box3 = (AstRegion *) astBox( astFrame( 3, "Domain=OTHER" ), 1,
                                (double[]){ 0.0, 0.0, 0.0 },
                                (double[]){ 1.0, 1.0, 1.0 }, NULL, " " );
   astSetUnc( circle, box3 );
   code( "SETUNC_FRAME", &status );
   printf( "/// Whether a failed astSetUnc leaves an earlier uncertainty in place.\n" );
   astSetUnc( circle, (AstRegion *) astBox( astFrame( 2, " " ), 1, c, p, NULL, " " ) );
   astSetUnc( circle, poly );
   astClearStatus;
   printf( "pub const SETUNC_KEEPS_OLD: bool = %s;\n",
           astGetUnc( circle, 0 ) ? "true" : "false" );

   printf( "/// astSetFillFactor(1.5) after FillFactor = 0.5, and the value left.\n" );
   astSetD( circle, "FillFactor", 0.5 );
   astSetD( circle, "FillFactor", 1.5 );
   code( "FILL_HIGH", &status );
   printf( "pub const FILL_AFTER: f64 = %.17g;\n", astGetD( circle, "FillFactor" ) );
   printf( "/// astSetFillFactor(-0.1).\n" );
   astSetD( circle, "FillFactor", -0.1 );
   code( "FILL_LOW", &status );

   astSetI( circle, "MeshSize", 10 );
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, circle );
   ch = astAnnul( ch );
   {
      static char base[ 20000 ];
      strcpy( base, dump );

      replace_line( "Fill = ", "   Fill = 2" );
      printf( "/// A Circle dump whose Fill is 2.\npub const LOAD_FILL_DUMP: &str = " );
      str( dump );
      printf( ";\n" );
      next_line = dump;
      ch = astChannel( source, NULL, " " );
      loaded = astRead( ch );
      ch = astAnnul( ch );
      printf( "/// Reading it.\n" );
      code( "LOAD_FILL", &status );
      (void) loaded;

      strcpy( dump, base );
      replace_line( "MeshSz = ", "   MeshSz = -3" );
      printf( "/// A Circle dump whose MeshSz is -3.\npub const LOAD_MESH_DUMP: &str = " );
      str( dump );
      printf( ";\n" );
      next_line = dump;
      ch = astChannel( source, NULL, " " );
      loaded = astRead( ch );
      ch = astAnnul( ch );
      printf( "/// The MeshSize C reads from it.\npub const LOAD_MESH_SIZE: i32 = %d;\n",
              astGetI( loaded, "MeshSize" ) );
      astClearStatus;
   }

   printf( "/// astBox form 0 with a BAD centre, and with a BAD corner.\n" );
   astBox( astFrame( 2, " " ), 0, b0, p, NULL, " " );
   code( "BOX_CENTRE", &status );
   astBox( astFrame( 2, " " ), 0, c, b1, NULL, " " );
   code( "BOX_CORNER", &status );
   printf( "/// astBox form 1 with a BAD lower bound, and with a BAD upper bound.\n" );
   astBox( astFrame( 2, " " ), 1, b0, p, NULL, " " );
   code( "BOX_LOWER", &status );
   astBox( astFrame( 2, " " ), 1, c, b1, NULL, " " );
   code( "BOX_UPPER", &status );

   printf( "/// astCircle form 1 with a BAD centre, and with a BAD radius.\n" );
   astCircle( astFrame( 2, " " ), 1, b0, &r, NULL, " " );
   code( "CIRCLE_CENTRE", &status );
   astCircle( astFrame( 2, " " ), 1, c, &bad, NULL, " " );
   code( "CIRCLE_RADIUS", &status );
   printf( "/// astCircle form 0 with a BAD circumference point.\n" );
   astCircle( astFrame( 2, " " ), 0, c, b1, NULL, " " );
   code( "CIRCLE_CIRCUM", &status );
   return 0;
}
