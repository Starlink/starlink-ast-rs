/* system_change_probe -- capture what setting or clearing the System does
 * to a SpecFrame, TimeFrame or FluxFrame whose Label, Symbol, Title and Unit
 * were set (specframe.c, timeframe.c, fluxframe.c SetSystem and
 * ClearSystem): the attributes with System-specific defaults are cleared,
 * and the Unit last used with the new System is restored, or cleared.
 *
 * Prints Rust source for crates/starlink-ast/tests/system_change_oracle/cases.rs:
 *
 *   ./system_change_probe > ../../crates/starlink-ast/tests/system_change_oracle/cases.rs
 */
#include <stdio.h>
#include "ast.h"

static void emit( const char *name, AstFrame *f ) {
   printf( "    (\"%s\", \"%s\", ", name, astGetC( f, "System" ) );
   printf( "\"%s\", ", astGetC( f, "Label(1)" ) );
   printf( "\"%s\", ", astGetC( f, "Symbol(1)" ) );
   printf( "\"%s\", ", astGetC( f, "Title" ) );
   printf( "\"%s\"),\n", astGetC( f, "Unit(1)" ) );
}

static const char *mine = "Label(1)=Mine,Symbol(1)=M,Title=Mine";

int main( void ) {
   int status = 0;
   AstFrame *f;
   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/system_change_probe.c against\n"
           "// the C library at u/timj/norm-unit 5a2cac2a, past the submodule pin.\n"
           "// Do not edit.\n\n"
           "/// `(case, System, Label(1), Symbol(1), Title, Unit(1))` afterwards.\n"
           "pub const CASES: &[(&str, &str, &str, &str, &str, &str)] = &[\n" );

   f = (AstFrame *) astSpecFrame( "System=FREQ,Unit=MHz" ); astSet( f, mine, " " );
   astSet( f, "System=VRAD" );
   emit( "spec_set_vrad", f );
   astSet( f, "System=FREQ" );
   emit( "spec_set_back_to_freq", f );

   f = (AstFrame *) astSpecFrame( "System=FREQ,Unit=MHz" ); astSet( f, mine, " " );
   astClear( f, "System" );
   emit( "spec_clear", f );

   f = (AstFrame *) astSpecFrame( "System=WAVE,Unit=nm" ); astSet( f, mine, " " );
   astClear( f, "System" );
   emit( "spec_clear_unchanged", f );

   f = (AstFrame *) astTimeFrame( "System=MJD" ); astSet( f, mine, " " );
   astSet( f, "System=JD" );
   emit( "time_set_jd", f );

   f = (AstFrame *) astTimeFrame( "System=JD" ); astSet( f, mine, " " );
   astClear( f, "System" );
   emit( "time_clear", f );

   f = (AstFrame *) astTimeFrame( "System=BEPOCH" ); astSet( f, mine, " " );
   astClear( f, "System" );
   emit( "time_clear_bepoch", f );

   f = (AstFrame *) astFluxFrame( AST__BAD, NULL, "System=FLXDN,Unit=Jy" );
   astSet( f, mine, " " );
   astSet( f, "System=SFCBR" );
   emit( "flux_set_sfcbr", f );

   printf( "];\n" );
   return 0;
}
