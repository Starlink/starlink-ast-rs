/* fitschan_encodings_probe -- capture what each FITS encoding writes for a
 * set of headers: each header is read into a FrameSet, which is written
 * back to the same FitsChan with each encoding in turn. Each encoding's
 * writer (fitschan.c WcsFromStore, PCFromStore, IRAFFromStore,
 * AIPSFromStore, AIPSPPFromStore, CLASSFromStore, DSSFromStore) first
 * checks that the FitsStore suits it, and writes nothing if not.
 *
 * A case may set the FrameSet's Epoch between the read and the write.
 *
 * For each header and encoding: the value astWrite returns, Ncard, the
 * cards that are not used (astFindFits), and the name of every card,
 * those a read consumed included, from a dump of the FitsChan
 * (fitschan.c Dump), which shows that a failed write keeps them.
 *
 * Prints Rust source for crates/ast-core/tests/fitschan_encodings_oracle/cases.rs:
 *
 *   ./fitschan_encodings_probe > ../../crates/ast-core/tests/fitschan_encodings_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
