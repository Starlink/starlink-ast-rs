static const char *encodings[] = { "FITS-WCS", "FITS-PC", "FITS-IRAF", "FITS-AIPS",
                                   "FITS-AIPS++", "FITS-CLASS", "DSS", NULL };

static void sink( const char *line ) {
   const char *eq;
   if( !strncmp( line, "    Nm", 6 ) && ( eq = strchr( line, '"' ) ) ) {
      printf( "            \"%.*s\",\n", (int)( strchr( eq + 1, '"' ) - eq - 1 ), eq + 1 );
   }
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void emit_epoch( const char *name, const char **header, const char *epoch ) {
   AstFitsChan *fc;
   AstObject *fs;
   AstChannel *ch;
   char card[ 81 ];
   int i, ienc, ret;

   printf( "    (\n        \"%s\",\n        &[", name );
   for( i = 0; header[ i ]; i++ ) {
      printf( "%s", i ? ", " : "" );
      str( header[ i ] );
   }
   printf( "],\n        \"%s\",\n        &[\n", epoch ? epoch : "" );
   for( ienc = 0; encodings[ ienc ]; ienc++ ) {
      fc = astFitsChan( NULL, NULL, " " );
      for( i = 0; header[ i ]; i++ ) astPutFits( fc, header[ i ], 0 );
      astClear( fc, "Card" );
      fs = astRead( fc );
      if( fs && epoch ) astSetC( fs, "Epoch", epoch );
      astSet( fc, "Encoding=%s", encodings[ ienc ] );
      ret = fs ? astWrite( fc, fs ) : -1;
      astClearStatus;
      printf( "          (\"%s\", %d, %d, &[\n", encodings[ ienc ], ret,
              astGetI( fc, "Ncard" ) );
      astClear( fc, "Card" );
      while( astFindFits( fc, "%f", card, 1 ) ) {
         printf( "            " );
         str( card );
         printf( ",\n" );
      }
      printf( "          ], &[\n" );
      ch = astChannel( NULL, sink, " " );
      astWrite( ch, fc );
      ch = astAnnul( ch );
      printf( "          ]),\n" );
      if( fs ) fs = astAnnul( fs );
      fc = astAnnul( fc );
   }
   printf( "        ],\n    ),\n" );
}

static void emit( const char *name, const char **header ) {
   emit_epoch( name, header, NULL );
}

