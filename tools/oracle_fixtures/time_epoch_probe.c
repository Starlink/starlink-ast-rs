/* time_epoch_probe -- capture the Epoch a TimeFrame gives when only its
 * TimeOrigin is set. C's GetEpoch (timeframe.c:2480) converts the origin to
 * a TDB MJD. For UT1, GMST, LAST and LMST it first maps the origin to UT1,
 * but then converts the raw TimeOrigin, not that UT1 value, with the
 * Mapping from UTC MJD in days to TDB (timeframe.c:2556).
 *
 * Each case sets System, TimeScale and TimeOrigin in that order, then the
 * listed extra settings, and prints the Epoch as a TDB MJD, or None where C
 * reports an error. A BEPOCH TimeFrame is given only the TT timescale,
 * the one C accepts for it.
 *
 * Prints Rust source for crates/starlink-ast/tests/time_epoch_oracle/cases.rs:
 *
 *   ./time_epoch_probe > ../../crates/starlink-ast/tests/time_epoch_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern double astGetEpoch_( void *, int * );

int main( void ) {
   int status = 0;
   const char *systems[] = { "MJD", "JD", "JEPOCH", "BEPOCH", NULL };
   const char *origins[] = { "55000.5", "2455000.5", "2009.5", "2009.5" };
   const char *scales[] = { "TAI", "UTC", "UT1", "GMST", "LAST", "LMST", "TT", "TDB",
                            "TCG", "TCB", "LT", NULL };
   const char *extras[] = { "", "Dut1=0.3", "ObsLon=60,Dut1=0.3", NULL };
   int i, j, k;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/time_epoch_probe.c. Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// `(System, TimeScale, TimeOrigin, extra settings, Epoch as a TDB MJD)`.\n"
           "pub const CASES: &[(&str, &str, f64, &str, Option<f64>)] = &[\n" );
   for( i = 0; systems[ i ]; i++ ) {
      for( j = 0; scales[ j ]; j++ ) {
         /* C accepts only TT for a BEPOCH TimeFrame. */
         if( !strcmp( systems[ i ], "BEPOCH" ) && strcmp( scales[ j ], "TT" ) ) continue;
         for( k = 0; extras[ k ]; k++ ) {
            AstFrame *f = (AstFrame *) astTimeFrame( " " );
            double e;
            char buf[ 40 ];
            astSet( f, "System=%s", systems[ i ] );
            astSet( f, "TimeScale=%s", scales[ j ] );
            astSet( f, "TimeOrigin=%s", origins[ i ] );
            if( *extras[ k ] ) astSet( f, "%s", extras[ k ] );
            e = astGetEpoch_( astMakePointer( f ), &status );
            printf( "    (\"%s\", \"%s\", %s, \"%s\", ", systems[ i ], scales[ j ],
                    origins[ i ], extras[ k ] );
            if( astOK ) {
               snprintf( buf, sizeof( buf ), "%.17g", e );
               if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
               printf( "Some(%s)),\n", buf );
            } else {
               printf( "None),\n" );
               astClearStatus;
            }
         }
      }
   }
   printf( "];\n" );
   return 0;
}
