/* time_scale_set_probe -- capture which TimeFrame settings C rejects, and
 * the TimeOrigin that results otherwise. SetTimeScale raises AST__ATTIN for
 * a timescale other than TT on a BEPOCH TimeFrame, and OriginScale raises
 * AST__INCTS when the TimeOrigin cannot be converted to the new timescale
 * (timeframe.c SetTimeScale, ClearTimeScale, OriginScale). SetSystem to
 * BEPOCH first sets Unit to "yr" and TimeScale to TT, and SetUnit on a
 * BEPOCH TimeFrame rejects any Unit but "yr" (timeframe.c SetSystem,
 * SetUnit).
 *
 * Each case starts from an MJD TimeFrame with TimeOrigin=55000.5 in the
 * "from" timescale, applies the ";"-separated steps of an action, each a
 * setting or "clear" to clear the TimeScale, and prints the error name or
 * the resulting System, TimeScale, Unit and TimeOrigin.
 *
 * Prints Rust source for crates/ast-core/tests/time_scale_set_oracle/cases.rs:
 *
 *   ./time_scale_set_probe > ../../crates/ast-core/tests/time_scale_set_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"
#include "ast_err.h"

static const char *scales[] = { "TAI", "UTC", "UT1", "GMST", "LAST", "LMST", "TT",
                                "TDB", "TCB", "TCG", "LT", NULL };

static void emit( const char *from, const char *action ) {
   int status_value;
   AstFrame *f = (AstFrame *) astTimeFrame( "System=MJD" );
   astSet( f, "TimeScale=%s", from );
   astSet( f, "TimeOrigin=55000.5" );
   {
      char steps[ 80 ], *step;
      strcpy( steps, action );
      for( step = strtok( steps, ";" ); step; step = strtok( NULL, ";" ) ) {
         if( !strcmp( step, "clear" ) ) {
            astClear( f, "TimeScale" );
         } else {
            astSet( f, "%s", step );
         }
      }
   }
   printf( "    (\"%s\", \"%s\", ", from, action );
   if( !astOK ) {
      status_value = astStatus;
      astClearStatus;
      printf( "Err(\"%s\")),\n", status_value == AST__ATTIN ? "Attin" :
              status_value == AST__INCTS ? "Incts" : "other" );
      return;
   }
   {
      char buf[ 40 ];
      snprintf( buf, sizeof( buf ), "%.17g", astGetD( f, "TimeOrigin" ) );
      if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
      printf( "Ok((\"%s\", \"%s\", \"%s\", %s))),\n", astGetC( f, "System" ),
              astGetC( f, "TimeScale" ), astGetC( f, "Unit(1)" ), buf );
   }
}

int main( void ) {
   int status = 0;
   int i, j;
   char action[ 40 ];
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/time_scale_set_probe.c. Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// `(from TimeScale, action, Err(error) or Ok((System, TimeScale, Unit,\n"
           "/// TimeOrigin)))`.\n"
           "pub type Case = (&'static str, &'static str,\n"
           "                 Result<(&'static str, &'static str, &'static str, f64), &'static str>);\n\n"
           "pub const CASES: &[Case] = &[\n" );
   for( i = 0; scales[ i ]; i++ ) {
      for( j = 0; scales[ j ]; j++ ) {
         sprintf( action, "TimeScale=%s", scales[ j ] );
         emit( scales[ i ], action );
      }
      emit( scales[ i ], "clear" );
      emit( scales[ i ], "System=BEPOCH" );
   }
   emit( "TT", "System=BEPOCH;TimeScale=UTC" );
   emit( "TT", "System=BEPOCH;TimeScale=TT" );
   emit( "TT", "System=BEPOCH;Unit(1)=d" );
   emit( "TT", "System=BEPOCH;Unit(1)=yr" );
   emit( "TT", "System=BEPOCH;clear" );
   emit( "UTC", "System=BEPOCH;System=MJD" );
   emit( "UTC", "System=BEPOCH;System=MJD;TimeScale=UTC" );
   printf( "];\n" );
   return 0;
}
