/* region_frame_probe -- capture the Frame methods a Region forwards to the
 * current Frame of its FrameSet (region.c Offset2, Resolve, AxDistance,
 * AxOffset, SystemString, PickAxes, SubFrame through astConvert), for a
 * Circle in an ICRS SkyFrame, where a Cartesian answer differs from the
 * spherical one; and astGetRegionPoints, which gives the defining points in
 * the current Frame, for a mapped Box.
 *
 * Prints Rust source for crates/ast-core/tests/region_frame_oracle/cases.rs:
 *
 *   ./region_frame_probe > ../../crates/ast-core/tests/region_frame_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void array( const char *name, const double *v, int n ) {
   int i;
   printf( "pub const %s: [f64; %d] = [", name, n );
   for( i = 0; i < n; i++ ) {
      lit( v[ i ] );
      if( i < n - 1 ) printf( ", " );
   }
   printf( "];\n" );
}

int main( void ) {
   int status = 0;
   AstSkyFrame *sky, *gal;
   AstCircle *circle;
   AstFrame *picked;
   double cen[] = { 1.0, 1.2 }, rad = 0.01;
   double p2[] = { 1.5, 1.2 }, p3[] = { 1.2, 1.3 }, p4[ 2 ], d1, d2;
   double out[ 2 ], v[ 4 ];
   int ax[] = { 2, 1 };

   astWatch( &status );
   sky = astSkyFrame( "System=ICRS" );
   circle = astCircle( sky, 1, cen, &rad, NULL, " " );
   gal = astSkyFrame( "System=Galactic" );

   printf( "// Generated by tools/oracle_fixtures/region_frame_probe.c. Do not edit.\n\n"
           "/// The Circle: centre (1.0, 1.2) and radius 0.01 in an ICRS SkyFrame.\n"
           "pub const CENTRE: [f64; 2] = [1.0, 1.2];\n"
           "pub const RADIUS: f64 = 0.01;\n\n"
           "/// astOffset2(circle, CENTRE, 1.0, 0.5): the point and the angle.\n" );
   v[ 2 ] = astOffset2( circle, cen, 1.0, 0.5, out );
   v[ 0 ] = out[ 0 ];
   v[ 1 ] = out[ 1 ];
   array( "OFFSET2", v, 3 );

   printf( "/// astResolve(circle, CENTRE, (1.5, 1.2), (1.2, 1.3)): the point, d1, d2.\n" );
   astResolve( circle, cen, p2, p3, p4, &d1, &d2 );
   v[ 0 ] = p4[ 0 ];
   v[ 1 ] = p4[ 1 ];
   v[ 2 ] = d1;
   v[ 3 ] = d2;
   array( "RESOLVE", v, 4 );

   printf( "/// astAxDistance(circle, 1, 0.1, 6.2) and astAxOffset(circle, 1, 6.2, 0.2).\n" );
   v[ 0 ] = astAxDistance( circle, 1, 0.1, 6.2 );
   v[ 1 ] = astAxOffset( circle, 1, 6.2, 0.2 );
   array( "AX_DISTANCE_OFFSET", v, 2 );

   picked = astPickAxes( circle, 2, ax, NULL );
   printf( "/// The class of astPickAxes(circle, [2, 1]) and its System.\n"
           "pub const PICKED: (&str, &str) = (\"%s\", \"%s\");\n",
           astGetC( picked, "Class" ), astGetC( picked, "System" ) );
   printf( "/// System of the Circle.\n"
           "pub const SYSTEM: &str = \"%s\";\n", astGetC( circle, "System" ) );
   printf( "/// Whether astConvert(galactic, circle) and astConvert(circle, galactic)\n"
           "/// find a conversion.\n"
           "pub const CONVERTS: (bool, bool) = (%s, %s);\n",
           astConvert( gal, circle, "" ) ? "true" : "false",
           astConvert( circle, gal, "" ) ? "true" : "false" );

   /* astGetRegionPoints of a Box [0,1]x[0,1] mapped by ZoomMap(2). */
   {
      double l[] = { 0.0, 0.0 }, u[] = { 1.0, 1.0 }, pts[ 4 ];
      int npoint;
      AstFrame *f = astFrame( 2, " " );
      AstRegion *b = astMapRegion( astBox( f, 1, l, u, NULL, " " ),
                                   astZoomMap( 2, 2.0, " " ), f );
      astGetRegionPoints( b, 2, 2, &npoint, pts );
      printf( "/// astGetRegionPoints of a Box [0,1]x[0,1] mapped by ZoomMap(2): x of\n"
              "/// each point, then y.\n" );
      array( "MAPPED_BOX_POINTS", pts, 4 );
   }
   return status;
}
