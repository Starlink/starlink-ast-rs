/* min_max_axes_probe -- capture MinAxes and MaxAxes after sequences of
 * settings (frame.c DefaultMinAxes, DefaultMaxAxes, ConsistentMinAxes,
 * ConsistentMaxAxes, and the cmpframe.c GetMinAxes / GetMaxAxes defaults),
 * and whether astFindFrame then matches a plain Frame template against a
 * plain Frame target of each axis count.
 *
 * Prints Rust source for crates/starlink-ast/tests/min_max_axes_oracle/cases.rs:
 *
 *   ./min_max_axes_probe > ../../crates/starlink-ast/tests/min_max_axes_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static const char *classes[] = { "Frame2", "SkyFrame", "CmpFrame" };

/* Each sequence is a ';'-separated list of "MinAxes=n", "MaxAxes=n",
   "-MinAxes" (clear) or "-MaxAxes". */
static const char *sequences[] = {
   "",
   "MinAxes=3",
   "MaxAxes=1",
   "MinAxes=1",
   "MaxAxes=5",
   "MinAxes=4;MaxAxes=2",
   "MaxAxes=1;MinAxes=3",
   "MinAxes=3;-MinAxes",
   "MaxAxes=1;-MaxAxes",
   "MinAxes=0;MaxAxes=0",
};
#define NSEQ ( (int) ( sizeof( sequences ) / sizeof( sequences[ 0 ] ) ) )

static AstFrame *make( int c ) {
   if( c == 0 ) return astFrame( 2, " " );
   if( c == 1 ) return (AstFrame *) astSkyFrame( " " );
   return (AstFrame *) astCmpFrame( astFrame( 1, " " ), astFrame( 1, " " ), " " );
}

static void apply( AstFrame *f, const char *seq ) {
   char buf[ 200 ], *tok;
   strcpy( buf, seq );
   for( tok = strtok( buf, ";" ); tok; tok = strtok( NULL, ";" ) ) {
      if( tok[ 0 ] == '-' ) astClear( f, tok + 1 ); else astSet( f, "%s", tok );
   }
}

int main( void ) {
   int status = 0, c, i, n;
   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/min_max_axes_probe.c against\n"
           "// the C library at u/timj/norm-unit 5a2cac2a, past the submodule pin.\n"
           "// Do not edit.\n\n"
           "/// `(class, settings, MinAxes, MaxAxes, TestMinAxes, TestMaxAxes)`.\n"
           "pub type AxesCase = (&'static str, &'static str, usize, usize, bool, bool);\n\n"
           "pub const AXES_CASES: &[AxesCase] = &[\n" );
   for( c = 0; c < 3; c++ ) {
      for( i = 0; i < NSEQ; i++ ) {
         AstFrame *f = make( c );
         apply( f, sequences[ i ] );
         printf( "    (\"%s\", \"%s\", %d, %d, %s, %s),\n", classes[ c ], sequences[ i ],
                 astGetI( f, "MinAxes" ), astGetI( f, "MaxAxes" ),
                 astTest( f, "MinAxes" ) ? "true" : "false",
                 astTest( f, "MaxAxes" ) ? "true" : "false" );
         f = astAnnul( f );
      }
   }
   printf( "];\n\n"
           "/// `(settings on a 2-axis Frame template, target axis count, whether\n"
           "/// astFindFrame matches)`.\n"
           "pub type FindCase = (&'static str, usize, bool);\n\n"
           "pub const FIND_CASES: &[FindCase] = &[\n" );
   for( i = 0; i < NSEQ; i++ ) {
      for( n = 1; n <= 4; n++ ) {
         AstFrame *t = astFrame( 2, " " );
         AstFrame *target = astFrame( n, " " );
         AstFrameSet *fs;
         apply( t, sequences[ i ] );
         fs = astFindFrame( target, t, "" );
         printf( "    (\"%s\", %d, %s),\n", sequences[ i ], n, fs ? "true" : "false" );
         if( fs ) fs = astAnnul( fs );
         t = astAnnul( t );
         target = astAnnul( target );
      }
   }
   printf( "];\n" );
   return 0;
}
