/* escapes_probe -- format axis values and split formatted values into
 * fields (frame.c Format and Fields, skyaxis.c DHmsFormat and AxisFields,
 * axis.c AxisFormat and AxisFields) with graphical escape sequences off and
 * on (object.c astEscapes), as a Plot turns them on while drawing.
 *
 * Prints Rust source for crates/starlink-ast/tests/escapes_oracle/cases.rs, which
 * the crate's unit tests read:
 *
 *   ./escapes_probe > ../../crates/starlink-ast/tests/escapes_oracle/cases.rs
 *
 * Build from reference/starlink-ast/build (configured with
 * -DCMAKE_C_FLAGS=-ffp-contract=off):
 *
 *   cc -ffp-contract=off -O3 -I. ../../../tools/oracle_fixtures/escapes_probe.c \
 *      -L. -last -Wl,-force_load,libast_err.a -lm -Wl,-rpath,$PWD \
 *      -o ../../../tools/oracle_fixtures/escapes_probe
 */
#include <float.h>
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern int astFields_( void *, int, const char *, const char *, int, char **,
                       int *, double *, int * );

static void rstr( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void flit( double value ) {
   char buf[ 40 ];
   if( value == AST__BAD ) { fputs( "crate::constants::BAD_VALUE", stdout ); return; }
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

struct fcase { int sky; int axis; const char *fmt; double value; };

static const struct fcase cases[] = {
   { 1, 1, "gd", 1.0 }, { 1, 2, "gd", -0.5 }, { 1, 1, "ghms", 2.5 },
   { 1, 2, "gdm", 0.7 }, { 1, 2, "gdms.2", -0.123456 }, { 1, 1, "ghms.1", 6.2 },
   { 1, 1, "ghm", 0.01 }, { 1, 1, "gm", 0.004 }, { 1, 2, "gs", 1.0e-5 },
   { 1, 1, "hms", 2.5 }, { 1, 2, "ldms", 0.7 }, { 1, 2, "+zgdms", 0.3 },
   { 0, 1, "%&g", 1.0e4 }, { 0, 1, "%&g", 2.5e-3 }, { 0, 2, "%&.3g", -42.0 },
   { 0, 1, "%&g", 1.0 },
};

int main( void ) {
   int status_value = 0;
   size_t i;
   int esc;
   AstSkyFrame *sky;
   AstFrame *plain;
   astWatch( &status_value );
   sky = astSkyFrame( "" );
   plain = astFrame( 2, "" );
   printf( "// Generated by tools/oracle_fixtures/escapes_probe.c.\n"
           "// Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// `(sky, axis, format, value, escapes, formatted, field lengths,\n"
           "/// value read back)`: a SkyFrame's or a 2-D Frame's axis value\n"
           "/// formatted with escape sequences off or on, and astFields of the\n"
           "/// result.\n"
           "#[allow(clippy::type_complexity)]\n"
           "pub(crate) const CASES: &[(bool, usize, &str, f64, bool, &str, &[usize], f64)] = &[\n" );
   for( esc = 0; esc < 2; esc++ ) {
      astEscapes( esc );
      for( i = 0; i < sizeof( cases ) / sizeof( cases[ 0 ] ); i++ ) {
         const struct fcase *c = cases + i;
         AstFrame *fr = c->sky ? (AstFrame *) sky : plain;
         char attr[ 32 ], text[ 200 ];
         char *fields[ 10 ];
         int nc[ 10 ], nf, k;
         double val;
         snprintf( attr, sizeof( attr ), "Format(%d)", c->axis );
         astSetC( fr, attr, c->fmt );
         snprintf( text, sizeof( text ), "%s", astFormat( fr, c->axis, c->value ) );
         nf = astFields_( astMakePointer( fr ), c->axis - 1, c->fmt, text, 10, fields, nc, &val, &status_value );
         printf( "    (%s, %d, ", c->sky ? "true" : "false", c->axis );
         rstr( c->fmt );
         printf( ", " );
         flit( c->value );
         printf( ", %s, ", esc ? "true" : "false" );
         rstr( text );
         printf( ", &[" );
         for( k = 0; k < nf; k++ ) printf( "%s%d", k ? ", " : "", nc[ k ] );
         printf( "], " );
         flit( val );
         printf( "),\n" );
      }
   }
   astEscapes( 0 );
   printf( "];\n" );
   if( !astOK ) return 1;
   return 0;
}
