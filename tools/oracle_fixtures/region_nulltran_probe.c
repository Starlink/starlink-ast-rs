/* region_nulltran_probe -- capture astTransform of a NullRegion
 * (nullregion.c Transform): a negated NullRegion, before and after the
 * protected astMapRegion through a ZoomMap of 2, and an un-negated one,
 * each given a good point and two points with one BAD axis.
 *
 * Prints Rust source for crates/starlink-ast/tests/region_nulltran_oracle/cases.rs:
 *
 *   ./region_nulltran_probe > ../../crates/starlink-ast/tests/region_nulltran_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern void *astMapRegion_( void *, void *, void *, int * );
extern AstObject *astMakeId_( AstObject *, int * );

static void lit( double v ) {
   if( v == AST__BAD ) {
      printf( "BAD_VALUE" );
   } else {
      char buf[ 40 ];
      sprintf( buf, "%.17g", v );
      printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
   }
}

/* One case: `(name, [x0, y0, x1, y1, x2, y2])`, the transformed points. */
static void emit( const char *name, AstObject *r ) {
   double x[ 3 ] = { 1.0, AST__BAD, 4.0 }, y[ 3 ] = { 2.0, 3.0, AST__BAD };
   double xo[ 3 ], yo[ 3 ];
   int i;
   astTran2( r, 3, x, y, 1, xo, yo );
   printf( "    (\"%s\", [", name );
   for( i = 0; i < 3; i++ ) {
      lit( xo[ i ] );
      printf( ", " );
      lit( yo[ i ] );
      printf( i < 2 ? ", " : "" );
   }
   printf( "]),\n" );
}

int main( void ) {
   int status = 0, s = 0;
   AstNullRegion *nr;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_nulltran_probe.c. Do not edit.\n\n"
           "use starlink_ast::constants::BAD_VALUE;\n\n"
           "/// The points every case transforms, as (x, y).\n"
           "pub const POINTS: [[f64; 2]; 3] = [[1.0, 2.0], [BAD_VALUE, 3.0], [4.0, BAD_VALUE]];\n\n"
           "/// `(case, the transformed points, x then y for each)`.\n"
           "pub const CASES: &[(&str, [f64; 6])] = &[\n" );
   nr = astNullRegion( astFrame( 2, " " ), NULL, "Negated=1" );
   emit( "negated", (AstObject *) nr );
   emit( "negated_zoomed",
         astMakeId_( astMapRegion_( astMakePointer( nr ),
                                    astMakePointer( astZoomMap( 2, 2.0, " " ) ),
                                    astMakePointer( astFrame( 2, " " ) ), &s ), &s ) );
   astSetI( nr, "Negated", 0 );
   emit( "plain", (AstObject *) nr );
   printf( "];\n" );
   return status;
}
