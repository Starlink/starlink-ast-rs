/* region_convex_probe -- capture astConvex<X> (polygon.c MAKE_CONVEX,
 * ConvexHull, FindBoxEdge, PartHull): the Polygon C makes round the pixels
 * of a 2-D array that pass a comparison with a value, for each comparison,
 * with pixel centres at integer PIXEL coordinates and with the Starlink
 * convention (starpix) that puts them at half-integers, for a float and an
 * int array, for a single selected pixel and for none.
 *
 * Prints Rust source for crates/ast-core/tests/region_convex_oracle/cases.rs:
 *
 *   ./region_convex_probe > ../../crates/ast-core/tests/region_convex_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

#define NX 7
#define NY 6

static char dump[ 20000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

/* One case: `(name, C's dump, or "" when C returns no Polygon)`. */
static void emit( const char *name, AstPolygon *poly ) {
   AstChannel *ch;
   dump[ 0 ] = 0;
   if( poly ) {
      ch = astChannel( NULL, sink, " " );
      astWrite( ch, poly );
      ch = astAnnul( ch );
   }
   printf( "    (\"%s\", ", name );
   str( dump );
   printf( "),\n" );
}

int main( void ) {
   int status = 0, i;
   /* A blob of values, row by row, x varying fastest. */
   static const float F[ NX*NY ] = {
      0, 0, 0, 0, 0, 0, 0,
      0, 0, 3, 3, 0, 0, 0,
      0, 3, 5, 5, 3, 0, 0,
      0, 3, 5, 7, 5, 3, 0,
      0, 0, 3, 5, 3, 0, 0,
      0, 0, 0, 3, 0, 0, 0 };
   int I[ NX*NY ];
   float one[ NX*NY ];
   AstDim lbnd[ 2 ] = { 1, 1 }, ubnd[ 2 ] = { NX, NY };
   AstDim lbnd2[ 2 ] = { -3, 10 }, ubnd2[ 2 ] = { -3 + NX - 1, 10 + NY - 1 };

   for( i = 0; i < NX*NY; i++ ) {
      I[ i ] = (int) F[ i ];
      one[ i ] = 0.0f;
   }
   one[ 2*NX + 4 ] = 1.0f;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_convex_probe.c. Do not edit.\n\n"
           "/// The array every case but \"single\" tests, row by row, x varying fastest.\n"
           "pub const ARRAY: [f32; %d] = [", NX*NY );
   for( i = 0; i < NX*NY; i++ ) printf( "%g.0%s", F[ i ], i < NX*NY - 1 ? ", " : "" );
   printf( "];\n/// Its dimensions.\npub const DIMS: (usize, usize) = (%d, %d);\n\n"
           "/// `(case, C's dump, or \"\" when C returns no Polygon)`.\n"
           "pub const CASES: &[(&str, &str)] = &[\n", NX, NY );
   emit( "eq5", astConvex8F( 5.0f, AST__EQ, F, lbnd, ubnd, 0 ) );
   emit( "ge3", astConvex8F( 3.0f, AST__GE, F, lbnd, ubnd, 0 ) );
   emit( "gt3", astConvex8F( 3.0f, AST__GT, F, lbnd, ubnd, 0 ) );
   emit( "le0", astConvex8F( 0.0f, AST__LE, F, lbnd, ubnd, 0 ) );
   emit( "lt5", astConvex8F( 5.0f, AST__LT, F, lbnd, ubnd, 0 ) );
   emit( "ne0", astConvex8F( 0.0f, AST__NE, F, lbnd, ubnd, 0 ) );
   emit( "ne0_starpix", astConvex8F( 0.0f, AST__NE, F, lbnd2, ubnd2, 1 ) );
   emit( "int_ge5", astConvex8I( 5, AST__GE, I, lbnd2, ubnd2, 0 ) );
   emit( "single", astConvex8F( 1.0f, AST__EQ, one, lbnd, ubnd, 0 ) );
   emit( "none", astConvex8F( 9.0f, AST__EQ, F, lbnd, ubnd, 0 ) );
   printf( "];\n" );
   return status;
}
