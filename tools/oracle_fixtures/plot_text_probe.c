int main( void ) {
   int status_value = 0;
   size_t icase;
   int i;
   astWatch( &status_value );
   printf( "// Generated by tools/oracle_fixtures/plot_text_probe.c.\n"
           "// Do not edit.\n\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "/// One text: the string, its position in the current Frame, its\n"
           "/// up-vector and C's justification code.\n"
           "pub type Text = (&'static str, [f64; 2], [f32; 2], &'static str);\n\n"
           "/// A Plot, the texts drawn on it, and what C's grf_log wrote.\n"
           "pub struct Case {\n"
           "    pub name: &'static str,\n"
           "    /// A header under fixtures/wcsconv/inputs, or None for a\n"
           "    /// 2-D Frame.\n"
           "    pub head: Option<&'static str>,\n"
           "    pub gbox: [f32; 4],\n"
           "    pub pbox: [f64; 4],\n"
           "    pub attr: &'static str,\n"
           "    pub texts: &'static [Text],\n"
           "    pub log: &'static str,\n"
           "    pub svg: Svg,\n"
           "}\n\n"
           SVG_DECL
           "pub const CASES: &[Case] = &[\n" );
   for( icase = 0; icase < sizeof( cases ) / sizeof( cases[ 0 ] ); icase++ ) {
      const struct text_case *c = cases + icase;
      AstPlot *pl;
      if( c->head ) {
         char path[ 512 ];
         AstFrameSet *fs;
         snprintf( path, sizeof( path ), "%s%s", HEADS, c->head );
         fs = read_head( path, "" );
         pl = astPlot( fs, c->gbox, c->pbox, "" );
         fs = astAnnul( fs );
      } else {
         AstFrame *fr = astFrame( 2, "" );
         pl = astPlot( fr, c->gbox, c->pbox, "" );
         fr = astAnnul( fr );
      }
      astSet( pl, "%s", c->attr );
      printf( "    Case {\n        name: " );
      rstr( c->name );
      printf( ",\n        head: " );
      if( c->head ) { printf( "Some(" ); rstr( c->head ); printf( ")" ); }
      else printf( "None" );
      printf( ",\n        gbox: [" );
      for( i = 0; i < 4; i++ ) { if( i ) printf( ", " ); flit( c->gbox[ i ] ); }
      printf( "],\n        pbox: [" );
      for( i = 0; i < 4; i++ ) { if( i ) printf( ", " ); flit( c->pbox[ i ] ); }
      printf( "],\n        attr: " );
      rstr( c->attr );
      printf( ",\n        texts: &[\n" );
      for( i = 0; i < c->ntext; i++ ) {
         const struct text *t = c->texts + i;
         printf( "            (" );
         rstr( t->text );
         printf( ", [" );
         flit( t->pos[ 0 ] );
         printf( ", " );
         flit( t->pos[ 1 ] );
         printf( "], [" );
         flit( t->up[ 0 ] );
         printf( ", " );
         flit( t->up[ 1 ] );
         printf( "], " );
         rstr( t->just );
         printf( "),\n" );
      }
      printf( "        ],\n" );
      capture_start();
      for( i = 0; i < c->ntext; i++ ) {
         const struct text *t = c->texts + i;
         astText( pl, t->text, t->pos, t->up, t->just );
      }
      capture_end();
      printf( "    },\n" );
      if( !astOK ) {
         fprintf( stderr, "case %s failed with status %d\n", c->name, astStatus );
         return 1;
      }
      pl = astAnnul( pl );
   }
   printf( "];\n" );
   return 0;
}
