/* region_interval_remap_probe -- capture the public astMapRegion of an
 * Interval that is not equivalent to a Box, which simplifies the mapped
 * Interval and so re-defines it in the new Frame (interval.c Simplify, the
 * branch for an Interval with a missing limit): through a ZoomMap, a PermMap
 * swapping the axes, and a WinMap that reverses an axis, the last with one
 * axis excluded rather than included.
 *
 * Prints Rust source for crates/starlink-ast/tests/region_interval_remap_oracle/cases.rs:
 *
 *   ./region_interval_remap_probe > ../../crates/starlink-ast/tests/region_interval_remap_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static char dump[ 40000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

static const char *dumped( AstObject *obj ) {
   AstChannel *ch;
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   return dump;
}

/* One case: `(name, Interval dump, Mapping dump, mapped Region dump)`. The
   new Frame is a 2-D Frame with Domain NEW. */
static void emit( const char *name, AstRegion *reg, AstMapping *map ) {
   AstRegion *mapped;
   mapped = astMapRegion( reg, map, astFrame( 2, "Domain=NEW" ) );
   printf( "    (\"%s\",\n        ", name );
   str( dumped( (AstObject *) reg ) );
   printf( ",\n        " );
   str( dumped( (AstObject *) map ) );
   printf( ",\n        " );
   str( dumped( (AstObject *) mapped ) );
   printf( "),\n" );
}

int main( void ) {
   int status = 0;
   int perm[ 2 ] = { 2, 1 };
   double lb[ 2 ], ub[ 2 ];
   double ina[ 2 ] = { 0.0, 0.0 }, inb[ 2 ] = { 1.0, 1.0 };
   double outa[ 2 ] = { 10.0, 0.0 }, outb[ 2 ] = { 0.0, 3.0 };

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_interval_remap_probe.c. Do not edit.\n\n" );
   printf( "/// `(case, Interval dump, Mapping dump, the dump of astMapRegion's result)`.\n" );
   printf( "pub const CASES: &[(&str, &str, &str, &str)] = &[\n" );

   lb[ 0 ] = AST__BAD;
   lb[ 1 ] = 1.0;
   ub[ 0 ] = 5.0;
   ub[ 1 ] = AST__BAD;
   emit( "zoom", (AstRegion *) astInterval( astFrame( 2, " " ), lb, ub, NULL, " " ),
         (AstMapping *) astZoomMap( 2, 2.0, " " ) );

   ub[ 1 ] = 4.0;
   emit( "permuted", (AstRegion *) astInterval( astFrame( 2, " " ), lb, ub, NULL, " " ),
         (AstMapping *) astPermMap( 2, perm, 2, perm, NULL, " " ) );

   lb[ 0 ] = 0.6;
   lb[ 1 ] = AST__BAD;
   ub[ 0 ] = 0.2;
   ub[ 1 ] = 0.5;
   emit( "reversed_excluded",
         (AstRegion *) astInterval( astFrame( 2, " " ), lb, ub, NULL, " " ),
         (AstMapping *) astWinMap( 2, ina, inb, outa, outb, " " ) );

   printf( "];\n" );
   return status != 0;
}
