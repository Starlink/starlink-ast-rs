/* frame_attrs_probe -- capture every public attribute of a plain Frame as
 * the C library reports it, for each attribute set on its own, and the dump
 * of each such Frame.
 *
 * Prints Rust source for crates/starlink-ast/tests/frame_oracle/cases.rs:
 *
 *   ./frame_attrs_probe > ../../crates/starlink-ast/tests/frame_oracle/cases.rs
 *
 * Each case names an attribute setting string for astSet on a 2-axis Frame,
 * which the Rust test applies through the public BasicFrame API. A setting
 * starting "PERM:" is applied and the axes are then swapped with
 * astPermAxes.
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static const char *settings[] = {
   " ", "Title=My frame", "Domain=PIXEL", "Epoch=2010.5", "Epoch=B1950",
   "Epoch=J2000", "System=Cartesian", "AlignSystem=Cartesian", "Digits=4",
   "Digits(2)=10", "Direction(1)=0", "Format(1)=%6.2f", "Label(2)=Y axis",
   "Symbol(1)=x", "Unit(1)=km", "Top(1)=10", "Bottom(2)=-5", "MatchEnd=1",
   "MaxAxes=3", "MinAxes=1", "Permute=0", "PreserveAxes=1",
   "ObsLat=10:20:30", "ObsLon=-70:30:00", "ObsAlt=2000", "Dtai=37",
   "Dut1=0.2",
   "Title=T,Domain=D,Epoch=2020,Digits=5,Digits(1)=3,Direction(2)=0,"
   "Format(2)=%.3e,Label(1)=L,Symbol(2)=s,Unit(2)=m/s,Top(2)=4,"
   "Bottom(1)=-1,MatchEnd=1,MaxAxes=4,MinAxes=2,Permute=0,PreserveAxes=1,"
   "ObsLat=-30,ObsLon=120,ObsAlt=100,Dtai=36,Dut1=-0.1",
   "Domain=MY DOMAIN", "PERM: ", "PERM:Label(1)=A,Digits(2)=4,Top(1)=3",
   NULL
};

/* Attribute names, with 'n' for "one entry per axis", and value kinds:
   s = string, i = integer, d = double. "r" marks a read-only attribute,
   for which astTest is not asked. */
static const struct { const char *name; char kind; int per_axis; int ro; } attrs[] = {
   { "Title", 's', 0, 0 }, { "Domain", 's', 0, 0 }, { "Epoch", 'd', 0, 0 },
   { "System", 's', 0, 0 }, { "AlignSystem", 's', 0, 0 },
   { "Digits", 'i', 0, 0 }, { "Digits", 'i', 1, 0 },
   { "Direction", 'i', 1, 0 }, { "Format", 's', 1, 0 },
   { "Label", 's', 1, 0 }, { "Symbol", 's', 1, 0 }, { "Unit", 's', 1, 0 },
   { "Top", 'd', 1, 0 }, { "Bottom", 'd', 1, 0 },
   { "MatchEnd", 'i', 0, 0 }, { "MaxAxes", 'i', 0, 0 },
   { "MinAxes", 'i', 0, 0 }, { "Permute", 'i', 0, 0 },
   { "PreserveAxes", 'i', 0, 0 }, { "ObsLat", 's', 0, 0 },
   { "ObsLon", 's', 0, 0 }, { "ObsAlt", 'd', 0, 0 }, { "Dtai", 'd', 0, 0 },
   { "Dut1", 'd', 0, 0 }, { "Naxes", 'i', 0, 1 },
   { "NormUnit", 's', 1, 1 }, { "InternalUnit", 's', 1, 1 },
   { NULL, 0, 0, 0 }
};

/* Make the Frame a setting describes. */
static AstFrame *make( const char *setting ) {
   int perm[ 2 ] = { 2, 1 };
   int permute = !strncmp( setting, "PERM:", 5 );
   AstFrame *f = astFrame( 2, " " );
   astSet( f, "%s", permute ? setting + 5 : setting );
   if( permute ) astPermAxes( f, perm );
   return f;
}

static void lit( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void flit( double value ) {
   char buf[ 40 ];
   if( value == AST__BAD ) { fputs( "BAD", stdout ); return; }
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

static char dumpbuf[ 65536 ];
static void sink( const char *line ) {
   strncat( dumpbuf, line, sizeof( dumpbuf ) - strlen( dumpbuf ) - 2 );
   strcat( dumpbuf, "\n" );
}

int main( void ) {
   int status = 0;
   int s, a, axis;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/frame_attrs_probe.c against\n"
           "// the C library at the submodule pin. Do not edit.\n\n"
           "// Each value is printed with 17 digits so that it reads back exactly.\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "use starlink_ast::constants::BAD_VALUE as BAD;\n\n"
           "/// An attribute value as C reports it.\n"
           "#[derive(Debug, Clone, Copy, PartialEq)]\n"
           "pub enum V {\n    S(&'static str),\n    I(i32),\n    D(f64),\n}\n\n"
           "/// `(settings, attribute, axis (0 for none), value, astTest result)`;\n"
           "/// the test result is `None` for a read-only attribute.\n"
           "pub const VALUE_CASES: &[(&str, &str, usize, V, Option<bool>)] = &[\n" );

   for( s = 0; settings[ s ]; s++ ) {
      AstFrame *f = make( settings[ s ] );
      for( a = 0; attrs[ a ].name; a++ ) {
         int first = attrs[ a ].per_axis ? 1 : 0;
         int last = attrs[ a ].per_axis ? 2 : 0;
         for( axis = first; axis <= last; axis++ ) {
            char key[ 40 ];
            if( axis ) {
               snprintf( key, sizeof( key ), "%s(%d)", attrs[ a ].name, axis );
            } else {
               snprintf( key, sizeof( key ), "%s", attrs[ a ].name );
            }
            printf( "    (" ); lit( settings[ s ] ); printf( ", " );
            lit( attrs[ a ].name ); printf( ", %d, ", axis );
            if( attrs[ a ].kind == 's' ) {
               const char *v = astGetC( f, key );
               printf( "V::S(" ); lit( v ? v : "<NULL>" ); printf( ")" );
            } else if( attrs[ a ].kind == 'i' ) {
               printf( "V::I(%d)", astGetI( f, key ) );
            } else {
               printf( "V::D(" ); flit( astGetD( f, key ) ); printf( ")" );
            }
            if( attrs[ a ].ro ) {
               printf( ", None),\n" );
            } else {
               printf( ", Some(%s)),\n", astTest( f, key ) ? "true" : "false" );
            }
         }
      }
      f = astAnnul( f );
   }
   printf( "];\n\n" );

   printf( "/// `(settings, astWrite dump)`.\n"
           "pub const DUMP_CASES: &[(&str, &str)] = &[\n" );
   for( s = 0; settings[ s ]; s++ ) {
      AstFrame *f = make( settings[ s ] );
      AstChannel *ch = astChannel( NULL, sink, " " );
      dumpbuf[ 0 ] = '\0';
      astWrite( ch, f );
      ch = astAnnul( ch );
      f = astAnnul( f );
      printf( "    (\n        " ); lit( settings[ s ] );
      printf( ",\n        r#\"%s\"#,\n    ),\n", dumpbuf );
   }
   printf( "];\n" );

   return astOK ? 0 : 1;
}
