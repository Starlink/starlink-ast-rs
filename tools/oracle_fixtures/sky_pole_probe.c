/* sky_pole_probe -- capture the LONPOLE and LATPOLE that a FITS-WCS write
 * gives for celestial projections that wcsmap.c IsZenithal does and does
 * not count as zenithal (fitschan.c SkyPole): a zenithal projection writes
 * only the pole its WcsMap was given, and any other has the pole worked out
 * from its Mappings.
 *
 * Each case is a FITS-WCS header, read and written again; the values are
 * the written LONPOLE and LATPOLE, or None when the card is absent. A case
 * whose header C cannot read or write is printed with `false` as its last
 * field, and the port must fail it too.
 *
 * Prints Rust source for crates/ast-core/tests/sky_pole_oracle/cases.rs:
 *
 *   ./sky_pole_probe > ../../crates/ast-core/tests/sky_pole_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

/* Print a value as a Rust f64 literal, with the fewest digits that read
   back as the same value. */
static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

/* Print a string as a Rust string literal. */
static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

static void card( AstFitsChan *fc, const char *name ) {
   double v;
   astClear( fc, "Card" );
   if( astGetFitsF( fc, name, &v ) ) {
      printf( "Some(" );
      lit( v );
      printf( ")" );
   } else {
      printf( "None" );
   }
}

static void emit( const char *name, const char *proj, const char *extra ) {
   char header[ 2000 ], ct1[ 9 ], ct2[ 9 ];
   AstFitsChan *in, *out;
   AstObject *obj;
   int ok;
   astClearStatus;
   sprintf( ct1, "RA---%s", proj );
   sprintf( ct2, "DEC--%s", proj );
   sprintf( header,
            "NAXIS   = 2\n"
            "NAXIS1  = 100\n"
            "NAXIS2  = 100\n"
            "CRPIX1  = 50.0\n"
            "CRPIX2  = 50.0\n"
            "CRVAL1  = 30.0\n"
            "CRVAL2  = 40.0\n"
            "CDELT1  = -0.01\n"
            "CDELT2  = 0.01\n"
            "CTYPE1  = '%s'\n"
            "CTYPE2  = '%s'\n"
            "RADESYS = 'ICRS'\n"
            "%s", ct1, ct2, extra );

   in = astFitsChan( NULL, NULL, "Encoding=FITS-WCS" );
   {
      char *line = strtok( header, "\n" );
      for( ; line; line = strtok( NULL, "\n" ) ) astPutFits( in, line, 0 );
   }
   astClear( in, "Card" );
   obj = astRead( in );
   out = astFitsChan( NULL, NULL, "Encoding=FITS-WCS" );
   astWrite( out, obj );
   ok = astOK;
   astClearStatus;
   printf( "    (\"%s\", \"%s\", ", name, proj );
   str( extra );
   printf( ", " );
   if( ok ) {
      card( out, "LONPOLE" );
      printf( ", " );
      card( out, "LATPOLE" );
   } else {
      printf( "None, None" );
   }
   printf( ", %s),\n", ok ? "true" : "false" );
   if( obj ) obj = astAnnul( obj );
   in = astAnnul( in );
   out = astAnnul( out );
}

int main( void ) {
   int status = 0;
   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/sky_pole_probe.c. Do not edit.\n\n"
           "/// `(case, projection, extra header cards separated by newlines, the\n"
           "/// written LONPOLE, the written LATPOLE, whether C read and wrote it)`.\n"
           "pub type Case = (&'static str, &'static str, &'static str, Option<f64>, Option<f64>, bool);\n\n"
           "pub const CASES: &[Case] = &[\n" );
   emit( "tan_pole", "TAN", "LONPOLE = 170.0\n" );
   emit( "sin_zenithal_pole", "SIN", "LONPOLE = 170.0\n" );
   emit( "sin_slant_pole", "SIN", "PV2_1   = 0.1\nLONPOLE = 170.0\n" );
   emit( "azp_zenithal_pole", "AZP", "PV2_1   = 2.0\nLONPOLE = 170.0\n" );
   emit( "azp_tilted_pole", "AZP", "PV2_1   = 2.0\nPV2_2   = 10.0\nLONPOLE = 170.0\n" );
   emit( "szp_default_pole", "SZP", "LONPOLE = 170.0\n" );
   emit( "hpx_pole", "HPX", "LONPOLE = 170.0\n" );
   emit( "car_pole", "CAR", "LONPOLE = 170.0\n" );
   emit( "hpx_default", "HPX", "" );
   emit( "car_default", "CAR", "" );
   emit( "sin_slant_default", "SIN", "PV2_1   = 0.1\n" );
   emit( "azp_tilted_default", "AZP", "PV2_1   = 2.0\nPV2_2   = 10.0\n" );
   emit( "szp_default", "SZP", "" );
   emit( "sin_slant_latpole", "SIN", "PV2_1   = 0.1\nLATPOLE = 20.0\n" );
   printf( "];\n" );
   return status;
}
