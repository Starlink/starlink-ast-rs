/* flux_unit_system_probe -- capture FluxFrame behaviour when the System is
 * not set and follows from the Unit (fluxframe.c GetSystem): the Title, which
 * states the SpecVal in the density system's units, and a conversion to a
 * FluxFrame in FLXDN, which reads SpecVal in the same units
 * (fluxframe.c:1235 GetDensitySystem).
 *
 * Prints Rust source for crates/starlink-ast/tests/flux_unit_system_oracle/cases.rs:
 *
 *   ./flux_unit_system_probe > ../../crates/starlink-ast/tests/flux_unit_system_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void flit( double value ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

int main( void ) {
   int status = 0;
   double in[ 2 ] = { 1.0, 3.5 }, out[ 2 ];
   AstFluxFrame *a, *b;
   AstFrameSet *fs;
   astWatch( &status );

   a = astFluxFrame( 5000.0, NULL, "Unit=W/m^2/Angstrom" );
   b = astFluxFrame( 5.99584916e14, NULL, "System=FLXDN" );
   fs = astConvert( a, b, "" );
   astTran1( fs, 2, in, 1, out );

   printf( "// Generated by tools/oracle_fixtures/flux_unit_system_probe.c against\n"
           "// the C library at u/timj/norm-unit 5a2cac2a, past the submodule pin.\n"
           "// Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// The System C derives from the Unit.\n"
           "pub const SYSTEM: &str = \"%s\";\n\n"
           "/// The Title of the FluxFrame.\n"
           "pub const TITLE: &str = \"%s\";\n\n"
           "/// 1.0 and 3.5 converted to the FLXDN FluxFrame.\n"
           "pub const CONVERTED: [f64; 2] = [",
           astGetC( a, "System" ), astGetC( a, "Title" ) );
   flit( out[ 0 ] ); printf( ", " ); flit( out[ 1 ] ); printf( "];\n" );
   return 0;
}
