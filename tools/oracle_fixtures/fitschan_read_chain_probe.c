/* fitschan_read_chain_probe -- capture the FrameSet a FITS-WCS read gives
 * for headers whose simplified Mappings depend on how WcsMapFrm (fitschan.c)
 * builds the pixel to WCS chain before astSimplify:
 *
 *   ((((WcsIntWorld ; WcsCelestial) ; WcsSpectral) ; WcsOthers) ; tabmap)
 *
 * WcsIntWorld makes the CDELT scaling a diagonal MatrixMap, which is a unit
 * MatrixMap when every CDELT is equal to 1 within astEQUAL; WcsCelestial is a
 * UnitMap when there are no celestial axes; and WcsSpectral and WcsOthers
 * join one Mapping per axis in parallel, WcsOthers using LogWcs for a CTYPE
 * ending in "-LOG" (a UnitMap if CRVAL is zero) and LinearWcs otherwise.
 *
 * For each header: "! <status>" or "= none" if the read gives no FrameSet,
 * and otherwise its native dump.
 *
 * Prints Rust source for crates/starlink-ast/tests/fitschan_read_chain_oracle/cases.rs:
 *
 *   ./fitschan_read_chain_probe > ../../crates/starlink-ast/tests/fitschan_read_chain_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static char lines[ 2000 ][ 200 ];
static int nline;

static void sink( const char *line ) {
   strncpy( lines[ nline ], line, 199 );
   lines[ nline++ ][ 199 ] = 0;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void emit( const char *name, const char **header ) {
   AstChannel *ch;
   AstFitsChan *fc;
   AstObject *obj;
   int i;

   astBegin;
   printf( "    (\n        " );
   str( name );
   printf( ",\n        &[" );
   for( i = 0; header[ i ]; i++ ) {
      if( i ) printf( ", " );
      str( header[ i ] );
   }
   printf( "],\n        concat!(\n" );

   fc = astFitsChan( NULL, NULL, "Encoding=FITS-WCS" );
   for( i = 0; header[ i ]; i++ ) astPutFits( fc, header[ i ], 0 );
   astClear( fc, "Card" );
   obj = astRead( fc );
   if( !astOK ) {
      printf( "            \"! %d\\n\",\n", astStatus );
      astClearStatus;
   } else if( !obj ) {
      printf( "            \"= none\\n\",\n" );
   } else {
      nline = 0;
      ch = astChannel( NULL, sink, " " );
      astWrite( ch, obj );
      ch = astAnnul( ch );
      for( i = 0; i < nline; i++ ) {
         printf( "            " );
         {
            char buf[ 220 ];
            snprintf( buf, sizeof( buf ), "%s\n", lines[ i ] );
            putchar( '"' );
            for( char *p = buf; *p; p++ ) {
               if( *p == '"' || *p == '\\' ) putchar( '\\' );
               if( *p == '\n' ) {
                  printf( "\\n" );
               } else if( *p == '\t' ) {
                  printf( "\\t" );
               } else {
                  putchar( *p );
               }
            }
            putchar( '"' );
         }
         printf( ",\n" );
      }
   }
   printf( "        ),\n    ),\n" );
   astEnd;
}

int main( void ) {
   printf( "// Generated by tools/oracle_fixtures/fitschan_read_chain_probe.c; do not edit.\n" );
   printf( "pub const CASES: &[(&str, &[&str], &str)] = &[\n" );

/* CDELT values within astEQUAL of 1: a unit CDELT matrix. */
   {
      const char *h[] = { "NAXIS   = 2", "CRPIX1  = 1000", "CRPIX2  = 0",
         "CRVAL1  = 999.5", "CRVAL2  = -0.5", "CDELT1  = 0.99999999999999967",
         "CDELT2  = 1.0000000000000004", "CTYPE1  = 'p1'", "CTYPE2  = 'p2'", NULL };
      emit( "cdelt_near_unit", h );
   }

/* One CDELT far from 1 and one within astEQUAL of 1: a diagonal CDELT
   matrix, and a scale of exactly 1 once the per-axis shifts are merged. */
   {
      const char *h[] = { "NAXIS   = 3", "CRPIX1  = 1000", "CRPIX2  = 0", "CRPIX3  = 1",
         "CRVAL1  = 76.884615384615373", "CRVAL2  = -0.5", "CRVAL3  = 0.000244140625",
         "CDELT1  = 0.0769230769230769", "CDELT2  = 1.0000000000000004",
         "CDELT3  = 0.00048828125", "CTYPE1  = 'f1'", "CTYPE2  = 'f2'",
         "CTYPE3  = 'f3'", NULL };
      emit( "cdelt_mixed", h );
   }

/* A linear axis beside a spectral one. */
   {
      const char *h[] = { "NAXIS   = 2", "CRPIX1  = 1", "CRPIX2  = 1", "CRVAL1  = 1.0E9",
         "CRVAL2  = 7", "CDELT1  = 1.0E6", "CDELT2  = 1.0000000000000004",
         "CTYPE1  = 'FREQ'", "CTYPE2  = 'X'", NULL };
      emit( "spectral_and_linear", h );
   }

/* Non-spectral -LOG axes. */
   {
      const char *h[] = { "NAXIS   = 1", "CRPIX1  = 1", "CRVAL1  = 10", "CDELT1  = 2",
         "CTYPE1  = 'XXXX-LOG'", NULL };
      emit( "other_log", h );
   }
   {
      const char *h[] = { "NAXIS   = 1", "CRPIX1  = 1", "CRVAL1  = 0", "CDELT1  = 2",
         "CTYPE1  = 'XXXX-LOG'", NULL };
      emit( "other_log_crval_zero", h );
   }
   {
      const char *h[] = { "NAXIS   = 2", "CRPIX1  = 1", "CRPIX2  = 1", "CRVAL1  = 10",
         "CRVAL2  = 5", "CDELT1  = 2", "CDELT2  = 3", "CTYPE1  = 'XXXX-LOG'",
         "CTYPE2  = 'Y'", NULL };
      emit( "other_log_and_linear", h );
   }
   printf( "];\n" );
   return 0;
}
