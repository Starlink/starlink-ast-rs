/* region_interval_probe -- capture Interval membership, Bounded and mesh
 * (interval.c Transform, GetBounded, RegBaseMesh): a slice of zero width
 * on one axis, bounded (C hands it to the equivalent Box) and unbounded (C
 * separates the equal limits by the uncertainty), the unbounded one also
 * negated and open; an Interval in an ICRS SkyFrame whose RA range wraps
 * through 0 when tested by the equivalent Box; an Interval excluding every
 * axis; and the boundary mesh of a bounded and an unbounded Interval.
 *
 * Prints Rust source for crates/ast-core/tests/region_interval_oracle/cases.rs:
 *
 *   ./region_interval_probe > ../../crates/ast-core/tests/region_interval_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

/* One case: `(name, membership of each test point, Bounded)`. */
static void emit( const char *name, AstRegion *reg, int np, const double *x,
                  const double *y ) {
   double xo[ 10 ], yo[ 10 ];
   int i;
   astTran2( reg, np, x, y, 1, xo, yo );
   printf( "    (\"%s\", \"", name );
   for( i = 0; i < np; i++ ) putchar( xo[ i ] == AST__BAD ? '0' : '1' );
   printf( "\", %s),\n", astGetI( reg, "Bounded" ) ? "true" : "false" );
}

int main( void ) {
   int status = 0, npoint;
   AstFrame *f2;
   AstRegion *reg;
   double zx[] = { 1.5, 1.5, 1.5, 1.5 }, zy[] = { 5.0, 5.0 + 1.0E-12, 5.0 + 1.0E-6, 5.0 + 1.0E-3 };
   double sx[] = { 0.05, 6.3, 3.0 }, sy[] = { 0.2, 0.2, 0.2 };
   double ex[] = { 1.5, 5.0 }, ey[] = { 1.5, 5.0 };
   double mesh[ 2 * 1000 ];

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_interval_probe.c. Do not edit.\n\n"
           "/// The zero-width test points: x = 1.5, y just above 5.\n"
           "pub const ZERO_Y: [f64; 4] = [5.0, 5.0 + 1.0e-12, 5.0 + 1.0e-6, 5.0 + 1.0e-3];\n"
           "/// The sky test points.\n"
           "pub const SKY_X: [f64; 3] = [0.05, 6.3, 3.0];\n"
           "pub const SKY_Y: [f64; 3] = [0.2, 0.2, 0.2];\n"
           "/// The excluded-axes test points.\n"
           "pub const EXCLUDED_XY: [f64; 2] = [1.5, 5.0];\n\n"
           "/// `(case, membership of each test point, Bounded)`.\n"
           "pub const CASES: &[(&str, &str, bool)] = &[\n" );

   f2 = astFrame( 2, " " );
   {
      double l[] = { 1.0, 5.0 }, u[] = { 2.0, 5.0 };
      reg = (AstRegion *) astInterval( f2, l, u, NULL, " " );
      emit( "bounded_slice", reg, 4, zx, zy );
   }
   {
      double l[] = { 1.0, 5.0 }, u[] = { AST__BAD, 5.0 };
      reg = (AstRegion *) astInterval( f2, l, u, NULL, " " );
      emit( "unbounded_slice", reg, 4, zx, zy );
      reg = (AstRegion *) astInterval( f2, l, u, NULL, "Closed=0" );
      astNegate( reg );
      emit( "unbounded_slice_negated_open", reg, 4, zx, zy );
   }
   {
      double l[] = { 6.2, 0.1 }, u[] = { 6.4, 0.3 };
      reg = (AstRegion *) astInterval( astSkyFrame( "System=ICRS" ), l, u, NULL, " " );
      emit( "sky", reg, 3, sx, sy );
   }
   {
      double l[] = { 2.0, 2.0 }, u[] = { 1.0, 1.0 };
      reg = (AstRegion *) astInterval( f2, l, u, NULL, " " );
      emit( "all_axes_excluded", reg, 2, ex, ey );
   }
   printf( "];\n\n" );

   {
      double l[] = { 0.0, 0.0 }, u[] = { 1.0, 1.0 };
      reg = (AstRegion *) astInterval( f2, l, u, NULL, " " );
      astGetRegionMesh( reg, 1, 1000, 2, &npoint, mesh );
      printf( "/// The boundary mesh of the Interval [0, 1] x [0, 1]: the number of\n"
              "/// points, and its first and last points.\n"
              "pub const MESH: (usize, [f64; 4]) = (%d, [", npoint );
      lit( mesh[ 0 ] ); printf( ", " ); lit( mesh[ 1000 ] ); printf( ", " );
      lit( mesh[ npoint - 1 ] ); printf( ", " ); lit( mesh[ 1000 + npoint - 1 ] );
      printf( "]);\n" );
   }
   return status;
}
