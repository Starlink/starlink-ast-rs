/* fitschan_alt_epoch_probe -- capture where a FITS-WCS write takes MJD-OBS
 * and DATE-OBS from when the axis descriptions have different epochs.
 * SkySys (fitschan.c) stores the date of observation only for the primary
 * axis description: a header has a single MJD-OBS, which an alternate
 * description must not change, whether or not that alternate is written.
 *
 * Each case reads a celestial header with a primary (FK5) and an alternate
 * (galactic, "A") description, with or without MJD-OBS, then optionally
 * sets the Epoch of either Frame, and optionally remaps the alternate Frame
 * with a non-linear MathMap so that its description cannot be written. The
 * FrameSet is written to a FitsChan holding NAXIS1 and NAXIS2. For each:
 * the value astWrite returns and the cards written.
 *
 * Prints Rust source for crates/starlink-ast/tests/fitschan_alt_epoch_oracle/cases.rs:
 *
 *   ./fitschan_alt_epoch_probe > ../../crates/starlink-ast/tests/fitschan_alt_epoch_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static const char *header[] = { "NAXIS   = 2", "NAXIS1  = 100", "NAXIS2  = 100",
   "CRPIX1  = 50", "CRPIX2  = 50", "CRVAL1  = 10", "CRVAL2  = 20",
   "CDELT1  = -0.001", "CDELT2  = 0.001", "CTYPE1  = 'RA---TAN'",
   "CTYPE2  = 'DEC--TAN'", "RADESYS = 'FK5'", "EQUINOX = 2000.0",
   "CRPIX1A = 50", "CRPIX2A = 50", "CRVAL1A = 100", "CRVAL2A = 30",
   "CDELT1A = -0.001", "CDELT2A = 0.001", "CTYPE1A = 'GLON-TAN'",
   "CTYPE2A = 'GLAT-TAN'", NULL };

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

/* "mjdobs" is the MJD-OBS card to add to the header, or empty. "prim" and
   "alt" are MJD epochs to set on the primary and alternate Frames, or 0 to
   leave them as read. "fail" remaps the alternate Frame non-linearly. */
static void emit( const char *name, const char *mjdobs, double prim, double alt,
                  int fail ) {
   const char *fwd[ 2 ] = { "x=a+100*b*b", "y=b" };
   const char *inv[ 2 ] = { "a=x-100*y*y", "b=y" };
   AstFitsChan *fc, *out;
   AstFrameSet *fs;
   char card[ 81 ], epoch[ 40 ];
   int i, ret;

   fc = astFitsChan( NULL, NULL, " " );
   for( i = 0; header[ i ]; i++ ) astPutFits( fc, header[ i ], 0 );
   if( *mjdobs ) astPutFits( fc, mjdobs, 0 );
   astClear( fc, "Card" );
   fs = (AstFrameSet *) astRead( fc );

   /* Frame 2 is the primary description and Frame 3 the alternate. */
   if( prim != 0.0 ) {
      astSetI( fs, "Current", 2 );
      sprintf( epoch, "MJD %.1f", prim );
      astSetC( fs, "Epoch", epoch );
   }
   astSetI( fs, "Current", 3 );
   if( alt != 0.0 ) {
      sprintf( epoch, "MJD %.1f", alt );
      astSetC( fs, "Epoch", epoch );
   }
   if( fail ) astRemapFrame( fs, 3, astMathMap( 2, 2, 2, fwd, 2, inv, " " ) );
   astSetI( fs, "Current", 2 );

   out = astFitsChan( NULL, NULL, "Encoding=FITS-WCS" );
   astPutFits( out, "NAXIS1  = 100", 0 );
   astPutFits( out, "NAXIS2  = 100", 0 );
   ret = astWrite( out, fs );
   astClearStatus;

   printf( "    (\"%s\", ", name );
   str( mjdobs );
   printf( ", %.1f, %.1f, %s, %d, &[\n", prim, alt, fail ? "true" : "false", ret );
   astClear( out, "Card" );
   while( astFindFits( out, "%f", card, 1 ) ) {
      printf( "        " );
      str( card );
      printf( ",\n" );
   }
   printf( "    ]),\n" );
   out = astAnnul( out );
   fs = astAnnul( fs );
   fc = astAnnul( fc );
}

int main( void ) {
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/fitschan_alt_epoch_probe.c. Do not edit.\n\n" );
   printf( "/// `(name, the MJD-OBS card read or empty, the primary and alternate\n"
           "/// Epochs set (MJD, 0 for none), whether the alternate is remapped\n"
           "/// non-linearly, astWrite's value, the cards written)`.\n" );
   printf( "pub type Case = (&'static str, &'static str, f64, f64, bool, i32,\n"
           "    &'static [&'static str]);\n\n" );
   printf( "pub const CASES: &[Case] = &[\n" );
   emit( "no_dates", "", 0.0, 0.0, 0 );
   emit( "read_date", "MJD-OBS = 51000.0", 0.0, 0.0, 0 );
   emit( "alt_differs", "MJD-OBS = 51000.0", 0.0, 55000.0, 0 );
   emit( "alt_only", "", 0.0, 55000.0, 0 );
   emit( "primary_only", "", 52000.0, 0.0, 0 );
   emit( "both_set", "", 52000.0, 55000.0, 0 );
   emit( "alt_differs_fails", "MJD-OBS = 51000.0", 0.0, 55000.0, 1 );
   emit( "alt_only_fails", "", 0.0, 55000.0, 1 );
   emit( "both_set_fails", "", 52000.0, 55000.0, 1 );
   printf( "];\n" );
   return 0;
}
