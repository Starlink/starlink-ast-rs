/* report_probe -- capture what a Mapping with its Report attribute set
 * writes when astTran1 or astTran2 transforms points (mapping.c
 * ReportPoints), and how Report is dumped. A Mapping writes each value as
 * %.15g or <bad>; a FrameSet formats the input values with its base Frame
 * and the output values with its current Frame (the other way round for
 * the inverse); a Region formats both with its current Frame.
 *
 * C writes the report to standard output, which also carries the generated
 * source, so each report is printed inside a Rust raw string.
 *
 * Prints Rust source for crates/starlink-ast/tests/report_oracle/cases.rs:
 *
 *   ./report_probe > ../../crates/starlink-ast/tests/report_oracle/cases.rs
 */
#include <stdio.h>
#include "ast.h"

static void sink( const char *line ) {
   printf( "    \"" );
   for( ; *line; line++ ) {
      if( *line == '"' || *line == '\\' ) putchar( '\\' );
      putchar( *line );
   }
   printf( "\",\n" );
}

static void dump( const char *name, AstObject *obj ) {
   AstChannel *ch = astChannel( NULL, sink, " " );
   printf( "pub const %s: &[&str] = &[\n", name );
   astWrite( ch, obj );
   printf( "];\n" );
   ch = astAnnul( ch );
}

int main( void ) {
   const double x[ 3 ] = { 1.0, -2.5, AST__BAD }, y[ 3 ] = { 0.5, 3.0, 4.0 };
   double xo[ 3 ], yo[ 3 ];
   AstMapping *zoom, *shift;
   AstFrameSet *fs;
   AstRegion *circle;
   double centre[ 2 ] = { 0.0, 0.0 }, radius = 2.0, off[ 1 ] = { 1.25 };
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/report_probe.c. Do not edit.\n\n"
           "/// The x and y values transformed (`None` is AST__BAD).\n"
           "pub const X: [Option<f64>; 3] = [Some(1.0), Some(-2.5), None];\n"
           "pub const Y: [f64; 3] = [0.5, 3.0, 4.0];\n\n" );

   zoom = (AstMapping *) astZoomMap( 2, 2.5, "Report=1" );
   printf( "/// A ZoomMap of 2.5, forward then inverse (astTran2).\n"
           "pub const ZOOM: &str = r#\"" );
   astTran2( zoom, 3, x, y, 1, xo, yo );
   astTran2( zoom, 3, x, y, 0, xo, yo );
   printf( "\"#;\n\n" );

   shift = (AstMapping *) astShiftMap( 1, off, "Report=1" );
   printf( "/// A 1-D ShiftMap of 1.25 (astTran1).\n"
           "pub const SHIFT: &str = r#\"" );
   astTran1( shift, 3, x, 1, xo );
   printf( "\"#;\n\n" );

   fs = astFrameSet( astFrame( 2, " " ), "Report=1" );
   astAddFrame( fs, AST__BASE, astZoomMap( 2, 0.01, " " ), astSkyFrame( " " ) );
   printf( "/// A FrameSet from a plain Frame to a SkyFrame by a ZoomMap of 0.01,\n"
           "/// forward then inverse.\n"
           "pub const FRAMESET: &str = r#\"" );
   astTran2( fs, 3, x, y, 1, xo, yo );
   astTran2( fs, 3, x, y, 0, xo, yo );
   printf( "\"#;\n\n" );

   circle = (AstRegion *) astCircle( astFrame( 2, " " ), 1, centre, &radius, NULL, "Report=1" );
   printf( "/// A Circle of radius 2 about the origin.\n"
           "pub const CIRCLE: &str = r#\"" );
   astTran2( circle, 3, x, y, 1, xo, yo );
   printf( "\"#;\n\n" );

   dump( "ZOOM_DUMP", (AstObject *) zoom );
   astSetL( zoom, "Report", 0 );
   printf( "\n" );
   dump( "ZOOM_DUMP_OFF", (AstObject *) zoom );
   printf( "\n" );
   dump( "FRAMESET_DUMP", (AstObject *) fs );
   printf( "\n" );
   dump( "CIRCLE_DUMP", (AstObject *) circle );

   circle = astAnnul( circle );
   fs = astAnnul( fs );
   shift = astAnnul( shift );
   zoom = astAnnul( zoom );
   return 0;
}
