/* map_split_probe -- capture astMapSplit for each Mapping class that
 * overrides it, at a partial selection, a full permuted selection, an index
 * out of range, an index of 0, a repeated index and no index at all. The base MapSplit
 * (mapping.c) reports AST__AXIIN for an index out of range; the classes
 * that call it first (NormMap, MatrixMap, RateMap, TranMap, WcsMap) do the
 * same, and the others return no split. Each split is recorded by its
 * output indices and the dump of the split Mapping.
 *
 * Prints Rust source for crates/starlink-ast/tests/map_split_oracle/cases.rs:
 *
 *   ./map_split_probe > ../../crates/starlink-ast/tests/map_split_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"
#include "ast_err.h"

static char dump[ 20000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

/* Print a string as a Rust string literal. */
static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

/* Print one case: the Mapping's name, the 1-based inputs selected, and
   the outcome: Err(code name), None, or the outputs and the split
   Mapping's dump. */
static void emit( const char *name, AstMapping *map, int nin, const int *in ) {
   int out[ 20 ], i, ok, code;
   AstMapping *split = NULL;
   AstChannel *ch;
   astMapSplit( map, nin, in, out, &split );
   ok = astOK;
   code = astStatus;
   astClearStatus;
   printf( "    (\"%s\", &[", name );
   for( i = 0; i < nin; i++ ) printf( "%d, ", in[ i ] );
   printf( "], " );
   if( !ok ) {
      printf( "Outcome::Err(\"%s\")", code == AST__AXIIN ? "AXIIN" :
                                         code == AST__SELIN ? "SELIN" : "other" );
   } else if( !split ) {
      printf( "Outcome::None" );
   } else {
      printf( "Outcome::Split(&[" );
      for( i = 0; i < astGetI( split, "Nout" ); i++ ) printf( "%d, ", out[ i ] );
      printf( "], " );
      dump[ 0 ] = 0;
      ch = astChannel( NULL, sink, " " );
      astWrite( ch, split );
      ch = astAnnul( ch );
      str( dump );
      printf( ")" );
      split = astAnnul( split );
   }
   printf( "),\n" );
}

/* Every selection for one Mapping with "n" inputs. */
static void all( const char *name, AstMapping *map, int n ) {
   char buf[ 100 ];
   int partial[] = { 2 }, perm[ 3 ] = { 2, 1, 3 }, out_of_range[] = { 1, 4 };
   int zero[] = { 0 }, repeated[] = { 1, 1 };
   out_of_range[ 1 ] = n + 1;
   sprintf( buf, "%s_partial", name );
   emit( buf, map, 1, partial );
   sprintf( buf, "%s_full_permuted", name );
   emit( buf, map, n, perm );
   sprintf( buf, "%s_out_of_range", name );
   emit( buf, map, 2, out_of_range );
   sprintf( buf, "%s_zero", name );
   emit( buf, map, 1, zero );
   sprintf( buf, "%s_repeated", name );
   emit( buf, map, 2, repeated );
   sprintf( buf, "%s_empty", name );
   emit( buf, map, 0, repeated );
}

int main( void ) {
   int status = 0;
   double shift[] = { 1.0, 2.0, 3.0 };
   double ina[] = { 0.0, 0.0 }, inb[] = { 1.0, 1.0 };
   double outa[] = { 1.0, 2.0 }, outb[] = { 3.0, 6.0 };
   double mat[] = { 2.0, 1.0, 0.0, 3.0 };
   int inperm[] = { 2, 1, 3 }, outperm[] = { 2, 1, 3 };
   AstMapping *m;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/map_split_probe.c. Do not edit.\n\n"
           "/// What C's astMapSplit gives.\n"
           "#[derive(Debug)]\n"
           "pub enum Outcome {\n"
           "    /// An error, by its AST code name.\n"
           "    Err(&'static str),\n"
           "    /// No split.\n"
           "    None,\n"
           "    /// The 1-based outputs and the split Mapping's dump.\n"
           "    Split(&'static [usize], &'static str),\n"
           "}\n\n"
           "/// `(case, 1-based inputs selected, C's outcome)`.\n"
           "pub type Case = (&'static str, &'static [usize], Outcome);\n\n"
           "pub const CASES: &[Case] = &[\n" );

   all( "unitmap", (AstMapping *) astUnitMap( 3, " " ), 3 );

   m = (AstMapping *) astZoomMap( 3, 2.0, " " );
   astInvert( m );
   all( "zoommap_inverted", m, 3 );

   m = (AstMapping *) astShiftMap( 3, shift, " " );
   astInvert( m );
   all( "shiftmap_inverted", m, 3 );

   m = (AstMapping *) astWinMap( 2, ina, inb, outa, outb, " " );
   astInvert( m );
   all( "winmap_inverted", m, 2 );

   all( "permmap", (AstMapping *) astPermMap( 3, inperm, 3, outperm, NULL, " " ), 3 );

   m = (AstMapping *) astMatrixMap( 2, 2, 0, mat, " " );
   astInvert( m );
   all( "matrixmap_inverted", m, 2 );

   all( "normmap", (AstMapping *) astNormMap( astFrame( 3, " " ), " " ), 3 );

   all( "ratemap", (AstMapping *) astRateMap( astZoomMap( 2, 2.0, " " ), 1, 1, " " ), 2 );

   all( "tranmap", (AstMapping *) astTranMap( astZoomMap( 3, 2.0, " " ),
                                              astZoomMap( 3, 2.0, " " ), " " ), 3 );

   all( "wcsmap", (AstMapping *) astWcsMap( 3, AST__TAN, 1, 2, " " ), 3 );

   all( "cmpmap_parallel", (AstMapping *) astCmpMap( astZoomMap( 1, 2.0, " " ),
                                                     astShiftMap( 2, shift, " " ),
                                                     0, " " ), 3 );

   printf( "];\n" );
   return status;
}
