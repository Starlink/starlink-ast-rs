# Build hardening_probe.c once for each C hardening test and print, as the
# Rust source of crates/starlink-ast/tests/hardening_oracle/cases.rs, every
# dump the tests read with the C library's status and messages for each:
#
#   tools/oracle_fixtures/build_hardening_probe.sh \
#       > crates/starlink-ast/tests/hardening_oracle/cases.rs
#
# Uses the library built in $AST_REFERENCE/build (default
# reference/starlink-ast), and that checkout's ast_tester.  check_probes_fresh.sh
# runs it through its "ctests" recipe.
set -euo pipefail
unset CC CFLAGS CPPFLAGS LDFLAGS CXX
HERE=$(cd "$(dirname "$0")" && pwd)
REF=${AST_REFERENCE:-$HERE/../../reference/starlink-ast}
REF=$(cd "$REF" && pwd)
B=$REF/build
T=$REF/ast_tester
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
echo "// Generated by tools/oracle_fixtures/build_hardening_probe.sh from"
echo "// tools/oracle_fixtures/hardening_probe.c at reference/starlink-ast"
echo "// $(git -C "$REF" rev-parse --short=8 HEAD). Do not edit."
echo
echo "use super::Case;"
echo
echo "pub const CASES: &[Case] = &["
for t in testcorruptinput testloaderhardening testframeperm testframesetload testdssmap; do
   cc -w -DTEST_NAME="\"$t\"" -DTEST_SOURCE="\"$t.c\"" "$HERE/hardening_probe.c" \
      -I"$B" -I"$T" -I"$T/star_compat" -L"$B" -last -lm -Wl,-rpath,"$B" -o "$TMP/$t"
   # The cases come on descriptor 3 and the test's own output is dropped;
   # testdssmap reads its fixture from ast_tester.
   (cd "$T" && "$TMP/$t" 3>&1 >/dev/null 2>&1)
done
echo "];"
