/* attr_test_clear_probe -- capture what C's astTest reports and what C's
 * dump writes for Mapping attributes that are set to their default value
 * and for ones that are set and then cleared. A set attribute is written
 * whenever it is set, its default included, and a cleared one is written
 * commented, as its default, only when the class marks it "helpful".
 *
 * Each case is a Mapping, the attributes tested, the dump, and the dump of
 * the Mapping read back from it, which differs where a loader sets an
 * attribute the dump left unset. Prints Rust
 * source for crates/starlink-ast/tests/attr_test_clear_oracle/cases.rs:
 *
 *   ./attr_test_clear_probe > ../../crates/starlink-ast/tests/attr_test_clear_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

/* PermSplit is protected, so it has no public astSet/astTest route. */
extern void astSetPermSplit_( void *, int, int * );
extern void astClearPermSplit_( void *, int * );
extern int astTestPermSplit_( void *, int * );

static char dump[ 20000 ];
static const char *source;

static const char *next_line( void ) {
   static char line[ 400 ];
   const char *end;
   size_t n;
   if( !*source ) return NULL;
   end = strchr( source, '\n' );
   n = end - source;
   memcpy( line, source, n );
   line[ n ] = 0;
   source = end + 1;
   return line;
}

static int test( AstObject *obj, const char *attrib ) {
   int s = 0;
   if( !strcmp( attrib, "PermSplit" ) ) {
      return astTestPermSplit_( astMakePointer( obj ), &s );
   }
   return astTest( obj, attrib );
}

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

/* Print a string as a Rust string literal. */
static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

/* Print one case: the Mapping's dump and whether each of the
   comma-separated attributes in "attrs" is set. */
static void emit( const char *name, AstObject *obj, const char *attrs ) {
   char buf[ 200 ], first[ 20000 ], *a;
   AstChannel *ch;
   AstObject *back;
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   strcpy( first, dump );
   source = first;
   ch = astChannel( next_line, NULL, " " );
   back = astRead( ch );
   ch = astAnnul( ch );
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, back );
   ch = astAnnul( ch );
   back = astAnnul( back );
   printf( "    (\"%s\", &[", name );
   strcpy( buf, attrs );
   for( a = strtok( buf, "," ); a; a = strtok( NULL, "," ) ) {
      printf( "(\"%s\", %s), ", a, test( obj, a ) ? "true" : "false" );
   }
   printf( "], " );
   str( first );
   printf( ", " );
   str( dump );
   printf( "),\n" );
   obj = astAnnul( obj );
}

int main( void ) {
   int status = 0;
   double lut[] = { 0.0, 1.0, 4.0, 9.0, 16.0 };
   double pcf[] = { 1.0, 1, 1, 0,  1.0, 2, 0, 1 };
   double cen[] = { 1.0, 2.0 };
   double t[] = { 0.0, 1.0 }, cu[] = { 1.5 }, cv[] = { 2.5 };
   const char *fwd[] = { "y=x" }, *inv[] = { "x=y" };
   int perm[] = { 2, 1 };
   AstObject *obj, *cp;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/attr_test_clear_probe.c. Do not edit.\n\n"
           "/// `(case, [(attribute, C's astTest)], C's dump, C's dump of it read back)`.\n"
           "pub type Case = (&'static str, &'static [(&'static str, bool)], &'static str, &'static str);\n\n"
           "pub const CASES: &[Case] = &[\n" );

   obj = (AstObject *) astPermMap( 2, perm, 2, perm, NULL, " " );
   astSetPermSplit_( astMakePointer( obj ), 0, &status );
   emit( "permmap_split_default", obj, "PermSplit" );
   obj = (AstObject *) astPermMap( 2, perm, 2, perm, NULL, " " );
   astSetPermSplit_( astMakePointer( obj ), 1, &status );
   astClearPermSplit_( astMakePointer( obj ), &status );
   emit( "permmap_split_cleared", obj, "PermSplit" );

   obj = (AstObject *) astZoomMap( 2, 3.0, " " );
   astClear( obj, "Zoom" );
   emit( "zoommap_cleared", obj, "Zoom" );

   obj = (AstObject *) astLutMap( 5, lut, 0.0, 1.0, "LutInterp=0,LutEpsilon=1.0E-10" );
   cp = astCopy( obj );
   emit( "lutmap_default", obj, "LutInterp,LutEpsilon" );
   astClear( cp, "LutInterp,LutEpsilon" );
   obj = cp;
   emit( "lutmap_cleared", obj, "LutInterp,LutEpsilon" );

   obj = (AstObject *) astPolyMap( 2, 2, 2, pcf, 0, NULL, "NiterInverse=4,TolInverse=1.0E-6" );
   cp = astCopy( obj );
   emit( "polymap_default", obj, "NiterInverse,TolInverse" );
   astClear( cp, "NiterInverse,TolInverse" );
   obj = cp;
   emit( "polymap_cleared", obj, "NiterInverse,TolInverse" );

   obj = (AstObject *) astWcsMap( 2, AST__SIN, 1, 2, "PV2_1=0.1,PV2_2=0.2" );
   astClear( obj, "PV2_1" );
   emit( "wcsmap_pv_cleared", obj, "PV2_1,PV2_2" );

   obj = (AstObject *) astPcdMap( 1.0E-5, cen, " " );
   astClear( obj, "Disco,PcdCen(1)" );
   emit( "pcdmap_cleared", obj, "Disco,PcdCen(1),PcdCen(2)" );

   obj = (AstObject *) astGrismMap( "GrismNR=1.5,GrismM=2" );
   astClear( obj, "GrismNR,GrismM" );
   emit( "grismmap_cleared", obj, "GrismNR,GrismM" );

   obj = (AstObject *) astSplineMap( 1, 1, 1, 1, t, t, cu, cv,
                                     "OutUnit=0,InvNiter=6,InvTol=1.0E-6" );
   cp = astCopy( obj );
   emit( "splinemap_default", obj, "OutUnit,InvNiter,InvTol" );
   astClear( cp, "OutUnit,InvNiter,InvTol" );
   obj = cp;
   emit( "splinemap_cleared", obj, "OutUnit,InvNiter,InvTol" );

   obj = (AstObject *) astSphMap( "UnitRadius=0,PolarLong=1.0" );
   cp = astCopy( obj );
   emit( "sphmap_default", obj, "UnitRadius,PolarLong" );
   astClear( cp, "UnitRadius,PolarLong" );
   obj = cp;
   emit( "sphmap_cleared", obj, "UnitRadius,PolarLong" );

   obj = (AstObject *) astMathMap( 1, 1, 1, fwd, 1, inv, "SimpFI=0,SimpIF=0" );
   cp = astCopy( obj );
   emit( "mathmap_default", obj, "SimpFI,SimpIF" );
   astClear( cp, "SimpFI,SimpIF" );
   obj = cp;
   emit( "mathmap_cleared", obj, "SimpFI,SimpIF" );

   obj = (AstObject *) astZoomMap( 1, 2.0, "Invert=0" );
   emit( "invert_set_zero", obj, "Invert" );
   obj = (AstObject *) astZoomMap( 1, 2.0, " " );
   astInvert( obj );
   emit( "invert_once", obj, "Invert" );
   obj = (AstObject *) astZoomMap( 1, 2.0, "Invert=0" );
   astInvert( obj );
   astInvert( obj );
   emit( "invert_zero_inverted_twice", obj, "Invert" );
   obj = (AstObject *) astZoomMap( 1, 2.0, "Invert=1" );
   astClear( obj, "Invert" );
   emit( "invert_cleared", obj, "Invert" );

   printf( "];\n" );
   return status;
}
