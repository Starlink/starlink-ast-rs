/* sky_interleave_probe -- capture astFindFrame with a SkyFrame template
 * against a CmpFrame of two SkyFrames whose axes are interleaved. C's
 * SkyFrame Match takes the first SkyFrame axis, then searches the remaining
 * axes for one from the same SkyFrame, passing over axes of the other
 * (skyframe.c `Match`).
 *
 * Frame A is FK5 and frame B is Galactic, so the transformed point shows
 * which was matched. The template has MaxAxes=4 so that Frame Match
 * accepts the four-axis target. Each case gives the permutation applied to the
 * CmpFrame(A, B) and the template's output for the input point, or None.
 *
 * Prints Rust source for crates/ast-core/tests/sky_interleave_oracle/cases.rs:
 *
 *   ./sky_interleave_probe > ../../crates/ast-core/tests/sky_interleave_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

int main( void ) {
   int status = 0;
   int perms[][ 4 ] = { { 1, 2, 3, 4 }, { 1, 3, 2, 4 }, { 3, 1, 4, 2 },
                        { 1, 3, 4, 2 }, { 2, 3, 1, 4 }, { 3, 4, 1, 2 } };
   double in[ 4 ][ 1 ] = { { 0.1 }, { 0.2 }, { 0.3 }, { 0.4 } };
   double out[ 2 ][ 1 ];
   int i, j;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/sky_interleave_probe.c. Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// The input point, one value per CmpFrame axis.\n"
           "pub const POINT: [f64; 4] = [0.1, 0.2, 0.3, 0.4];\n\n"
           "/// `(permutation of CmpFrame(FK5, Galactic), output of an FK5 template\n"
           "/// with MaxAxes=4)`.\n"
           "pub const CASES: &[([usize; 4], Option<[f64; 2]>)] = &[\n" );

   for( i = 0; i < (int) ( sizeof( perms ) / sizeof( perms[ 0 ] ) ); i++ ) {
      AstFrame *a = (AstFrame *) astSkyFrame( "System=FK5" );
      AstFrame *b = (AstFrame *) astSkyFrame( "System=Galactic" );
      AstFrame *cmp = (AstFrame *) astCmpFrame( a, b, " " );
      AstFrame *t = (AstFrame *) astSkyFrame( "System=FK5,MaxAxes=4" );
      AstFrameSet *fs;
      astPermAxes( cmp, perms[ i ] );
      fs = astFindFrame( cmp, t, "" );
      printf( "    ([%d, %d, %d, %d], ", perms[ i ][ 0 ], perms[ i ][ 1 ],
              perms[ i ][ 2 ], perms[ i ][ 3 ] );
      if( !fs ) {
         printf( "None),\n" );
         continue;
      }
      astTranN( fs, 1, 4, 1, (const double *) in, 1, 2, 1, (double *) out );
      printf( "Some([" );
      for( j = 0; j < 2; j++ ) {
         num( out[ j ][ 0 ] );
         printf( j ? "" : ", " );
      }
      printf( "])),\n" );
   }
   printf( "];\n" );
   return 0;
}
