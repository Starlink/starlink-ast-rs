/* object_id_probe -- capture how Objects write and read ID, the Object
 * attribute every AST Object has (object.c). Dump writes it first in the
 * Object part of the description whenever it is set, even when blank;
 * astLoadObject reads it back; astCopy does not copy it.
 *
 * The cases are an object of each family with an ID; composites with an
 * ID; composites made from parts with IDs (the "_part_ids" cases), which
 * keep them where the constructor shares the part (astClone) and lose them
 * where it copies it (astCopy); copies; and simplified Mappings. Each is
 * dumped, read back and dumped again.
 *
 * Prints Rust source for crates/ast-core/tests/object_id_oracle/cases.rs:
 *
 *   ./object_id_probe > ../../crates/ast-core/tests/object_id_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern void astSetID_( void *, const char *, int * );

static char lines[ 400 ][ 200 ];
static int nline, iline;

static void sink( const char *line ) {
   strncpy( lines[ nline ], line, 199 );
   lines[ nline++ ][ 199 ] = 0;
}

static const char *source( void ) {
   return iline < nline ? lines[ iline++ ] : NULL;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      if( *s == '\t' ) {
         printf( "\\t" );
      } else {
         putchar( *s );
      }
   }
   putchar( '"' );
}

static void print_lines( void ) {
   int i;
   for( i = 0; i < nline; i++ ) {
      printf( "%s", i ? ", " : "" );
      str( lines[ i ] );
   }
}

/* Dump `obj`, then read it back and dump that: `(case, dump, read-back dump)`. */
static void dump( const char *name, void *obj ) {
   AstChannel *ch = astChannel( source, sink, " " );
   AstObject *back;
   nline = 0;
   astWrite( ch, obj );
   printf( "    (\"%s\", &[", name );
   print_lines();
   printf( "], &[" );
   iline = 0;
   back = astRead( ch );
   nline = 0;
   astWrite( ch, back );
   print_lines();
   printf( "]),\n" );
   back = astAnnul( back );
   ch = astAnnul( ch );
}

static AstFrame *frame( int naxes, const char *id ) {
   AstFrame *f = astFrame( naxes, " " );
   if( id ) astSetC( f, "ID", id );
   return f;
}

static AstZoomMap *zoom( double z, const char *id ) {
   AstZoomMap *m = astZoomMap( 1, z, " " );
   astSetC( m, "ID", id );
   return m;
}

static AstCircle *circle( const char *fid, const char *id ) {
   double c[ 2 ] = { 0.0, 0.0 }, r = 1.0;
   AstCircle *reg = astCircle( frame( 2, fid ), 1, c, &r, NULL, " " );
   if( id ) astSetC( reg, "ID", id );
   return reg;
}

int main( void ) {
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/object_id_probe.c. Do not edit.\n\n" );
   printf( "/// `(case, dump, dump of the object read back from it)`.\n" );
   printf( "pub const DUMPS: &[(&str, &[&str], &[&str])] = &[\n" );

   {
      AstZoomMap *m = zoom( 2.0, "zid" );
      astSetC( m, "Ident", "zident" );
      dump( "zoommap", m );
   }
   {
      AstZoomMap *m = astZoomMap( 1, 2.0, " " );
      astSetID_( astMakePointer( m ), "", &status );
      dump( "zoommap_blank", m );
   }
   dump( "frame", frame( 2, "fid" ) );
   {
      AstSkyFrame *f = astSkyFrame( "ID=sky" );
      dump( "skyframe", f );
   }
   {
      AstFrameSet *fs = astFrameSet( astFrame( 1, " " ), "ID=fs" );
      astAddFrame( fs, AST__BASE, astZoomMap( 1, 2.0, " " ), astFrame( 1, " " ) );
      dump( "frameset", fs );
      dump( "frameset_frame_id", astFrameSet( frame( 1, "base" ), "ID=fs" ) );
      fs = astFrameSet( frame( 1, "base" ), "ID=fs" );
      astAddFrame( fs, AST__BASE, zoom( 2.0, "map" ), frame( 1, "added" ) );
      dump( "frameset_part_ids", fs );
   }
   dump( "circle", circle( "cframe", "cid" ) );
   {
      AstKeyMap *km = astKeyMap( "ID=km" );
      astMapPut0A( km, "z", zoom( 2.0, "inner" ), NULL );
      dump( "keymap", km );
   }
   {
      AstCmpMap *m = astCmpMap( zoom( 2.0, "a" ), zoom( 3.0, "b" ), 1, "ID=c" );
      dump( "cmpmap", m );
      dump( "cmpmap_copy", astCopy( m ) );
      dump( "cmpmap_simplified", astSimplify( m ) );
   }
   {
      double lut[ 3 ] = { 0.0, 1.0, 4.0 };
      AstLutMap *l = astLutMap( 3, lut, 1.0, 1.0, "ID=l" );
      AstCmpMap *m = astCmpMap( zoom( 2.0, "a" ), l, 1, "ID=c" );
      dump( "cmpmap_unsimplifiable", astSimplify( m ) );
   }
   dump( "cmpframe", astCmpFrame( frame( 1, "a" ), frame( 1, "b" ), "ID=c" ) );
   dump( "tranmap", astTranMap( zoom( 2.0, "a" ), zoom( 3.0, "b" ), "ID=t" ) );
   {
      AstRegion *regs[ 1 ];
      regs[ 0 ] = (AstRegion *) circle( "sframe", "sreg" );
      dump( "selectormap_part_ids", astSelectorMap( 1, (void **) regs, -1.0, "ID=s" ) );
      regs[ 0 ] = (AstRegion *) circle( NULL, NULL );
      dump( "selectormap", astSelectorMap( 1, (void **) regs, -1.0, "ID=s" ) );
   }
   dump( "cmpregion", astCmpRegion( circle( NULL, NULL ), circle( NULL, NULL ),
                                    AST__AND, "ID=cr" ) );
   dump( "cmpregion_part_ids", astCmpRegion( circle( "f1", "r1" ), circle( "f2", "r2" ),
                                             AST__AND, "ID=cr" ) );
   {
      double lb = 0.0, ub = 1.0;
      AstInterval *iv = astInterval( frame( 1, "ivf" ), &lb, &ub, NULL, "ID=iv" );
      dump( "prism_part_ids", astPrism( circle( "pf", "pc" ), iv, "ID=p" ) );
      iv = astInterval( frame( 1, NULL ), &lb, &ub, NULL, " " );
      dump( "prism", astPrism( circle( NULL, NULL ), iv, "ID=p" ) );
   }
   dump( "normmap", astNormMap( frame( 2, "nf" ), "ID=n" ) );
   dump( "ratemap", astRateMap( zoom( 2.0, "rz" ), 1, 1, "ID=r" ) );
   {
      AstZoomMap *m = zoom( 2.0, "orig" );
      dump( "zoommap_copy", astCopy( m ) );
      dump( "zoommap_simplified", astSimplify( m ) );
   }
   dump( "channel", astChannel( NULL, NULL, "ID=ch" ) );
   dump( "fitschan", astFitsChan( NULL, NULL, "ID=fc" ) );

   printf( "];\n" );
   return 0;
}
