/* fixture_read_warnings_probe -- read each native fixture named on standard
 * input with a Channel, as the port's tests read them, and print the
 * warnings each read leaves (channel.c ClearValues: items no class loader
 * reads), with the status of each read. Only the fixtures for which C gives
 * a warning or an error are listed; the port's test requires no warning
 * and no error for the rest.
 *
 * Prints Rust source for
 * crates/starlink-ast/tests/fixture_read_warnings_oracle/cases.rs, run from
 * crates/starlink-ast/tests/fixtures:
 *
 *   find . -type f \( -name '*.map' -o -name '*.simp' -o -name '*.ast' \
 *        -o -name '*.native' \) | sort | \
 *     ../../../../tools/oracle_fixtures/fixture_read_warnings_probe 2>/dev/null \
 *     > ../fixture_read_warnings_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static FILE *fd;
static char line[ 10000 ];

static const char *source( void ) {
   size_t n;
   if( !fgets( line, sizeof( line ), fd ) ) return NULL;
   n = strlen( line );
   if( n && line[ n - 1 ] == '\n' ) line[ n - 1 ] = 0;
   return line;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

int main( void ) {
   AstChannel *ch;
   AstObject *obj;
   AstKeyMap *warn;
   char name[ 4096 ], key[ 20 ], out[ 100000 ];
   const char *msg;
   int status = 0, i, iread, st, any;
   size_t n;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/fixture_read_warnings_probe.c. Do not edit.\n\n" );
   printf( "/// A read: its status and the warnings it left.\n" );
   printf( "pub type Read = (i32, &'static [&'static str]);\n\n" );
   printf( "/// `(fixture, each read up to the end or an error)`.\n" );
   printf( "pub const CASES: &[(&str, &[Read])] = &[\n" );
   while( fgets( name, sizeof( name ), stdin ) ) {
      n = strlen( name );
      if( n && name[ n - 1 ] == '\n' ) name[ n - 1 ] = 0;
      fd = fopen( name, "r" );
      if( !fd ) continue;
      ch = astChannel( source, NULL, " " );
      out[ 0 ] = 0;
      any = 0;
      for( iread = 0; iread < 10; iread++ ) {
         obj = astRead( ch );
         st = astStatus;
         astClearStatus;
         warn = astWarnings( ch );
         if( !obj && !st && !warn ) break;
         {
            char buf[ 20000 ];
            int len = sprintf( buf, "(%d, &[", st );
            if( warn ) {
               for( i = 1; ; i++ ) {
                  sprintf( key, "Warning_%d", i );
                  if( !astMapGet0C( warn, key, &msg ) ) break;
                  len += sprintf( buf + len, "%s\"", i > 1 ? ", " : "" );
                  for( ; *msg; msg++ ) {
                     if( *msg == '"' || *msg == '\\' ) buf[ len++ ] = '\\';
                     buf[ len++ ] = *msg;
                  }
                  buf[ len++ ] = '"';
                  buf[ len ] = 0;
               }
               warn = astAnnul( warn );
               any = 1;
            }
            sprintf( buf + len, "]), " );
            strcat( out, buf );
         }
         if( st ) any = 1;
         if( obj ) obj = astAnnul( obj );
         if( st || !obj ) break;
      }
      if( any ) {
         printf( "    (" );
         str( name );
         printf( ", &[%s]),\n", out );
      }
      ch = astAnnul( ch );
      fclose( fd );
   }
   printf( "];\n" );
   return 0;
}
