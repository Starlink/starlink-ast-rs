/* allow_simplify_probe -- capture how a restricted simplification uses the
 * AllowSimplify flag. A CmpMap with RestrictedSimplify set nominates only
 * the components that have AllowSimplify set (cmpmap.c Simplify), and when a
 * nominated Mapping merges, the Mappings the merge creates take the flag if
 * every Mapping the merge consumed had it (mapping.c astMapMerge_), so they
 * can be nominated again on the next pass.
 *
 * The flags have no public setters, so each case is the dump of a series
 * CmpMap of ZoomMap(2, 2), ZoomMap(2, 3) and ShiftMap(1, 2) with "ReSimp = 1"
 * added to the outer CmpMap and "AlSimp = 1" to the chosen components,
 * read back and simplified.
 *
 * Prints Rust source for crates/ast-core/tests/allow_simplify_oracle/cases.rs:
 *
 *   ./allow_simplify_probe > ../../crates/ast-core/tests/allow_simplify_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static char *lines[ 200 ];
static int nlines;
static const char *text[ 220 ];
static int next_line;

static void collect( const char *line ) {
   lines[ nlines++ ] = strdup( line );
}

static const char *source( void ) {
   return text[ next_line ] ? text[ next_line++ ] : NULL;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void print_dump( const char *line ) {
   printf( "            " );
   str( line );
   printf( ",\n" );
}

/* The dump of the CmpMap with "ReSimp = 1" after the outer CmpMap's Nin
   and "AlSimp = 1" after the Nin of the leaf Mappings (the k'th Begin of a
   ZoomMap or ShiftMap, from 0) whose bit is set in "allowed"; then the dump
   of what astSimplify makes of it. */
static void emit( const char *name, AstMapping *map, int allowed ) {
   AstChannel *ch;
   AstMapping *in, *simp;
   int i, n = 0, leaf = -1, pending = 0;

   nlines = 0;
   ch = astChannel( NULL, collect, " " );
   astWrite( ch, map );
   ch = astAnnul( ch );
   for( i = 0; i < nlines; i++ ) {
      const char *l = lines[ i ] + strspn( lines[ i ], " " );
      text[ n++ ] = lines[ i ];
      if( !strncmp( l, "Begin ZoomMap", 13 ) || !strncmp( l, "Begin ShiftMap", 14 ) ) {
         leaf++;
         pending = ( allowed >> leaf ) & 1;
      } else if( !strncmp( l, "Nin", 3 ) ) {
         if( i == 1 ) text[ n++ ] = "ReSimp = 1";
         if( pending ) text[ n++ ] = "AlSimp = 1";
         pending = 0;
      }
   }
   text[ n ] = NULL;

   printf( "    (\n        \"%s\",\n        &[\n", name );
   for( i = 0; i < n; i++ ) print_dump( text[ i ] );
   printf( "        ],\n        &[\n" );

   next_line = 0;
   ch = astChannel( source, NULL, " " );
   in = astRead( ch );
   ch = astAnnul( ch );
   simp = astSimplify( in );
   ch = astChannel( NULL, print_dump, " " );
   astWrite( ch, simp );
   ch = astAnnul( ch );
   printf( "        ],\n    ),\n" );

   simp = astAnnul( simp );
   in = astAnnul( in );
   for( i = 0; i < nlines; i++ ) free( lines[ i ] );
}

int main( void ) {
   double shift[ 2 ] = { 1.0, 2.0 };
   AstMapping *map;
   int status = 0;
   astWatch( &status );

   map = (AstMapping *) astCmpMap(
            astCmpMap( astZoomMap( 2, 2.0, " " ), astZoomMap( 2, 3.0, " " ), 1, " " ),
            astShiftMap( 2, shift, " " ), 1, " " );

   printf( "// Generated by tools/oracle_fixtures/allow_simplify_probe.c. Do not edit.\n\n"
           "/// `(case, the CmpMap read, the dump of its simplification)`.\n"
           "pub type Case = (&'static str, &'static [&'static str], &'static [&'static str]);\n\n"
           "pub const CASES: &[Case] = &[\n" );
   emit( "zooms_allowed", map, 3 );
   emit( "first_zoom_allowed", map, 1 );
   emit( "second_zoom_allowed", map, 2 );
   emit( "shift_allowed", map, 4 );
   emit( "none_allowed", map, 0 );
   emit( "all_allowed", map, 7 );
   printf( "];\n" );

   map = astAnnul( map );
   return 0;
}
