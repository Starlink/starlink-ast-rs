/* region_disc_probe -- capture astGetRegionDisc (region.c GetRegionDisc)
 * for Regions whose boundary meshes the port already makes as C does: a
 * Cartesian Box, negated and not, an ICRS Circle and Polygon, a Cartesian
 * Circle and PointList, a NullRegion, an unbounded Interval (bad centre and radius)
 * and a 3-D Box (AST__INVAR); and an ICRS Ellipse, with its dump for the
 * port to read.
 *
 * Prints Rust source for crates/starlink-ast/tests/region_disc_oracle/cases.rs:
 *
 *   ./region_disc_probe > ../../crates/starlink-ast/tests/region_disc_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   if( v == AST__BAD ) {
      printf( "BAD_VALUE" );
      return;
   }
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

/* One case: `(name, Ok([cx, cy, radius]))`, or `Err(code)` for an error. */
static void disc( const char *name, AstRegion *reg, int *status ) {
   double centre[ 2 ] = { AST__BAD, AST__BAD }, radius = AST__BAD;
   astGetRegionDisc( reg, centre, &radius );
   printf( "    (\"%s\", ", name );
   if( !astOK ) {
      printf( "Err(\"%s\")", astStatus == AST__INVAR ? "Invar" :
              astStatus == AST__INTER ? "Inter" : "Other" );
      astClearStatus;
   } else {
      printf( "Ok([" );
      lit( centre[ 0 ] );
      printf( ", " );
      lit( centre[ 1 ] );
      printf( ", " );
      lit( radius );
      printf( "])" );
   }
   printf( "),\n" );
}

static char dump[ 20000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

int main( void ) {
   int status = 0;
   AstChannel *ch;
   AstFrame *f2 = NULL;
   AstRegion *reg, *sky_ellipse = NULL;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_disc_probe.c. Do not edit.\n\n"
           "use starlink_ast::constants::BAD_VALUE;\n\n"
           "/// `(case, Ok([centre x, centre y, radius]) or Err(the error code))`.\n"
           "pub const CASES: &[(&str, Result<[f64; 3], &str>)] = &[\n" );

   f2 = astFrame( 2, " " );
   {
      double l[] = { 0.0, 0.0 }, u[] = { 20.0, 10.0 };
      reg = (AstRegion *) astBox( f2, 1, l, u, NULL, " " );
      disc( "box", reg, &status );
      astNegate( reg );
      disc( "negated_box", reg, &status );
   }
   {
      double cen[] = { 1.0, 1.2 }, rad = 0.01;
      reg = (AstRegion *) astCircle( astSkyFrame( "System=ICRS" ), 1, cen, &rad, NULL, " " );
      disc( "sky_circle", reg, &status );
   }
   {
      double l[] = { 0.0, AST__BAD }, u[] = { AST__BAD, AST__BAD };
      reg = (AstRegion *) astInterval( f2, l, u, NULL, " " );
      disc( "half_plane", reg, &status );
   }
   {
      double l[] = { 0.0, 0.0 }, u[] = { 6.0, 8.0 };
      reg = (AstRegion *) astBox( f2, 1, l, u, NULL, " " );
      disc( "box_6_8", reg, &status );
   }
   {
      double cen[] = { 3.0, 4.0 }, rad = 7.0;
      reg = (AstRegion *) astCircle( f2, 1, cen, &rad, NULL, " " );
      disc( "circle_7", reg, &status );
   }
   {
      double pts[] = { 0.0, 3.0, 0.0, 0.0, 0.0, 4.0 };
      reg = (AstRegion *) astPointList( f2, 3, 2, 3, pts, NULL, " " );
      disc( "pointlist_3", reg, &status );
   }
   {
      double xy[] = { 0.0, 1.0, 1.0, 0.0,   0.2, 0.2, 0.8, 0.8 };
      reg = (AstRegion *) astPolygon( astSkyFrame( "System=ICRS" ), 4, 4, xy, NULL, " " );
      disc( "sky_polygon", reg, &status );
   }
   reg = (AstRegion *) astNullRegion( f2, NULL, " " );
   disc( "null_region", reg, &status );
   {
      double cen[] = { 2.0, 0.3 }, a[] = { 0.1, 0.05 }, ang = 0.0;
      reg = (AstRegion *) astEllipse( astSkyFrame( "System=ICRS" ), 1, cen, a, &ang, NULL, " " );
      disc( "sky_ellipse", reg, &status );
      sky_ellipse = reg;
   }
   {
      double l[] = { 0.0, 0.0, 0.0 }, u[] = { 1.0, 1.0, 1.0 };
      reg = (AstRegion *) astBox( astFrame( 3, " " ), 1, l, u, NULL, " " );
      disc( "three_d_box", reg, &status );
   }

   printf( "];\n\n/// C's dump of the sky_ellipse case, for the port to read.\n"
           "pub const SKY_ELLIPSE: &str = " );
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, sky_ellipse );
   str( dump );
   printf( ";\n" );
   return 0;
}
