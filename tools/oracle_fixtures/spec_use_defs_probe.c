/* spec_use_defs_probe -- capture what UseDefs=0 changes in a SpecFrame,
 * DSBSpecFrame and TimeFrame. A conversion that needs an attribute which has
 * not been set is refused with AST__NOVAL: the StdOfRest of both SpecFrames,
 * a RestFreq for a velocity system, the RefRA, RefDec, observer position or
 * Epoch for a change of rest frame (specframe.c MakeSpecMapping, SorConvert,
 * VerifyAttrs), the IF and DSBCentre for a change of sideband (dsbspecframe.c
 * GetLO), and the TimeScale and StdOfRest when picking axes (timeframe.c,
 * specframe.c SubFrame). A SpecFrame Title leaves out a RestFreq that has
 * not been set (specframe.c GetTitle).
 *
 * Prints Rust source for crates/starlink-ast/tests/spec_use_defs_oracle/cases.rs:
 *
 *   ./spec_use_defs_probe > ../../crates/starlink-ast/tests/spec_use_defs_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"
#include "ast_err.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

static AstFrame *make( const char *cls, const char *settings ) {
   AstFrame *f;
   if( !strcmp( cls, "SpecFrame" ) ) {
      f = (AstFrame *) astSpecFrame( " " );
   } else if( !strcmp( cls, "DSBSpecFrame" ) ) {
      f = (AstFrame *) astDSBSpecFrame( " " );
   } else {
      f = (AstFrame *) astTimeFrame( " " );
   }
   if( *settings ) astSet( f, settings, " " );
   return f;
}

static void outcome( AstFrameSet *fs, int nin ) {
   if( !astOK ) {
      printf( "Err(\"%s\")", astStatus == AST__NOVAL ? "Noval" : "other" );
      astClearStatus;
   } else if( !fs ) {
      printf( "Ok(None)" );
   } else {
      double in = 230.0, out;
      astTran1( fs, 1, &in, 1, &out );
      printf( "Ok(Some(" );
      num( out );
      printf( "))" );
   }
   (void) nin;
}

/* Find the template in the target, or pick the target's axis when the
   template settings are "pick". */
static void convert( const char *cls, const char *target, const char *template ) {
   AstFrame *t = make( cls, target );
   AstFrameSet *fs = NULL;
   printf( "    (\"%s\", ", cls );
   str( target );
   printf( ", " );
   str( template );
   printf( ", " );
   if( !strcmp( template, "pick" ) ) {
      int axis = 1;
      AstMapping *map;
      AstFrame *p = astPickAxes( t, 1, &axis, &map );
      if( astOK ) {
         fs = astFrameSet( t, " " );
         astAddFrame( fs, AST__BASE, map, p );
      }
   } else {
      fs = astFindFrame( t, make( cls, template ), "" );
   }
   outcome( fs, 1 );
   printf( "),\n" );
}

