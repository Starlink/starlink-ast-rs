/* region_equal_probe -- capture astEqual and astOverlap for pairs of
 * Regions that region.c Equal tells apart by more than their current
 * Frames: a Box whose Unit was changed adaptively (base Frame in m,
 * current in km, its points unchanged) against a Box in km with the same
 * points; Boxes whose points differ within and beyond pointset.c Equal's
 * default accuracy; and a Box against its negation.
 *
 * Prints Rust source for crates/ast-core/tests/region_equal_oracle/cases.rs:
 *
 *   ./region_equal_probe > ../../crates/ast-core/tests/region_equal_oracle/cases.rs
 */
#include <stdio.h>
#include "ast.h"

static AstRegion *box_in( AstFrame *f, double x1, double y1 ) {
   double l[] = { 0.0, 0.0 }, u[ 2 ];
   u[ 0 ] = x1;
   u[ 1 ] = y1;
   return (AstRegion *) astBox( f, 1, l, u, NULL, " " );
}

static void pair( const char *name, AstRegion *a, AstRegion *b ) {
   printf( "    (\"%s\", %s, %d),\n", name, astEqual( a, b ) ? "true" : "false",
           astOverlap( a, b ) );
}

int main( void ) {
   int status = 0;
   AstFrame *fm, *fkm;
   AstRegion *a;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_equal_probe.c. Do not edit.\n\n"
           "/// `(case, astEqual(a, b), astOverlap(a, b))`.\n"
           "pub const CASES: &[(&str, bool, i32)] = &[\n" );

   fm = astFrame( 2, "Unit(1)=m,Unit(2)=m" );
   astSetActiveUnit( fm, 1 );
   fkm = astFrame( 2, "Unit(1)=km,Unit(2)=m" );
   astSetActiveUnit( fkm, 1 );
   a = box_in( fm, 1.0, 1.0 );
   astSetC( a, "Unit(1)", "km" );
   pair( "remapped_against_plain", a, box_in( fkm, 1.0, 1.0 ) );

   pair( "points_within_accuracy", box_in( astFrame( 2, " " ), 1.0, 1.0 ),
         box_in( astFrame( 2, " " ), 1.0 + 1.0E-15, 1.0 ) );
   pair( "points_beyond_accuracy", box_in( astFrame( 2, " " ), 1.0, 1.0 ),
         box_in( astFrame( 2, " " ), 1.0 + 1.0E-9, 1.0 ) );

   a = box_in( astFrame( 2, " " ), 1.0, 1.0 );
   pair( "same", a, box_in( astFrame( 2, " " ), 1.0, 1.0 ) );
   a = box_in( astFrame( 2, " " ), 1.0, 1.0 );
   astNegate( a );
   pair( "negated", a, box_in( astFrame( 2, " " ), 1.0, 1.0 ) );

   printf( "];\n" );
   return status;
}
