/* skyframe_format_probe -- capture how the C library formats SkyFrame axis
 * values, which Unit, Format and NormUnit it reports for them, and how it
 * dumps a SkyFrame carrying those attributes.
 *
 * Prints Rust source for crates/ast-core/tests/skyframe_oracle/cases.rs:
 *
 *   ./skyframe_format_probe > ../../crates/ast-core/tests/skyframe_oracle/cases.rs
 *
 * Each case names a System and an attribute setting string for astSet, which
 * the Rust test applies through the public SkyFrame API.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static const char *systems[] = { "ICRS", "GALACTIC", NULL };

static const char *attrs[] = {
   " ", "Digits=3", "Digits=5", "Digits=9", "Digits=12",
   "Format(1)=hms.3", "Format(1)=bhms", "Format(1)=lhms.2",
   "Format(1)=+zdms", "Format(1)=dms.*", "Format(1)=hm.*", "Format(1)=d.3",
   "Format(1)=h", "Format(1)=m", "Format(1)=s.2", "Format(1)=tm",
   "Format(1)=ts.1", "Format(1)=%g", "Format(1)=%10.4f", "Format(1)=gdms",
   "Format(1)=zhms.12", "AsTime(1)=0", "AsTime(2)=1", "Format(2)=+dms.1",
   "Format(2)=zd.2", "Digits(1)=4", "Digits(2)=10,Format(2)=dms.*",
   "Unit(1)=deg", "Unit(1)=hh mm ss,Format(1)=bhms", "Unit(2)=s*(m/s)",
   NULL
};

static const double values[] = {
   0.0, 1.0, -1.0, 0.5, -0.5, 3.14159265358979, -3.14159265358979,
   6.28318530717958, 1e-7, -1e-7, 0.123456789, 4.0, -2.0,
   0.017453292519943295, 0.00029088820866572158
};

static const char *dumps[] = {
   "Format(1)=bhms", "Format(2)=+dms.2", "Digits=9", "Digits(2)=10",
   "Digits(1)=4,Format(1)=hms.*", "Unit(1)=deg", "Unit(2)=s*(m/s)",
   "AsTime(1)=0", "AsTime(2)=1", "System=Galactic,Digits=5",
   "System=Galactic,AsTime(1)=1", "Format(1)=%g,Unit(1)=rad",
   "Format(1)=lhms.2,Format(2)=ldms.1,Digits=10",
   "Label(1)=RA,Format(1)=bhms,Unit(1)=hh mm ss,Digits(1)=8,AsTime(1)=1",
   NULL
};

/* Print a Rust string literal. */
static void lit( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

/* Print a double as a Rust f64 literal that reads back exactly. */
static void flit( double value ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

/* Collect a dump in memory. */
static char dumpbuf[ 65536 ];
static void sink( const char *line ) {
   strncat( dumpbuf, line, sizeof( dumpbuf ) - strlen( dumpbuf ) - 2 );
   strcat( dumpbuf, "\n" );
}

static AstSkyFrame *make( const char *system, const char *attr ) {
   AstSkyFrame *sf = astSkyFrame( "System=%s", system );
   astSet( sf, "%s", attr );
   return sf;
}

int main( void ) {
   int status = 0;
   int s, a, ax;
   size_t v;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/skyframe_format_probe.c against\n"
           "// the C library at the submodule pin. Do not edit.\n\n"
           "// 3.14159265358979 is a test value, not an approximation of PI, and\n"
           "// each value is printed with 17 digits so that it reads back exactly.\n"
           "#![allow(clippy::approx_constant, clippy::excessive_precision)]\n\n" );

   printf( "/// `(system, attrs, axis, value, astFormat result)`.\n"
           "pub const FORMAT_CASES: &[(&str, &str, usize, f64, &str)] = &[\n" );
   for( s = 0; systems[ s ]; s++ ) {
      for( a = 0; attrs[ a ]; a++ ) {
         AstSkyFrame *sf = make( systems[ s ], attrs[ a ] );
         for( ax = 1; ax <= 2; ax++ ) {
            for( v = 0; v < sizeof( values ) / sizeof( values[ 0 ] ); v++ ) {
               const char *r = astFormat( sf, ax, values[ v ] );
               printf( "    (" ); lit( systems[ s ] ); printf( ", " );
               lit( attrs[ a ] ); printf( ", %d, ", ax ); flit( values[ v ] );
               printf( ", " );
               lit( r ? r : "<NULL>" ); printf( "),\n" );
            }
         }
         sf = astAnnul( sf );
      }
   }
   printf( "];\n\n" );

   printf( "/// `(system, attrs, axis, Format, Unit, NormUnit)`.\n"
           "pub const UNIT_CASES: &[(&str, &str, usize, &str, &str, &str)] = &[\n" );
   for( s = 0; systems[ s ]; s++ ) {
      for( a = 0; attrs[ a ]; a++ ) {
         AstSkyFrame *sf = make( systems[ s ], attrs[ a ] );
         for( ax = 1; ax <= 2; ax++ ) {
            char key[ 32 ], fmt[ 200 ], unit[ 200 ], norm[ 200 ];
            const char *r;
            snprintf( key, sizeof( key ), "Format(%d)", ax );
            r = astGetC( sf, key ); snprintf( fmt, sizeof( fmt ), "%s", r ? r : "<NULL>" );
            snprintf( key, sizeof( key ), "Unit(%d)", ax );
            r = astGetC( sf, key ); snprintf( unit, sizeof( unit ), "%s", r ? r : "<NULL>" );
            snprintf( key, sizeof( key ), "NormUnit(%d)", ax );
            r = astGetC( sf, key ); snprintf( norm, sizeof( norm ), "%s", r ? r : "<NULL>" );
            printf( "    (" ); lit( systems[ s ] ); printf( ", " ); lit( attrs[ a ] );
            printf( ", %d, ", ax ); lit( fmt ); printf( ", " ); lit( unit );
            printf( ", " ); lit( norm ); printf( "),\n" );
         }
         sf = astAnnul( sf );
      }
   }
   printf( "];\n\n" );

   printf( "/// `(attrs, astWrite dump)`, for an ICRS SkyFrame unless the\n"
           "/// settings name another System.\n"
           "pub const DUMP_CASES: &[(&str, &str)] = &[\n" );
   for( a = 0; dumps[ a ]; a++ ) {
      AstSkyFrame *sf = astSkyFrame( "%s", dumps[ a ] );
      AstChannel *ch = astChannel( NULL, sink, " " );
      dumpbuf[ 0 ] = '\0';
      astWrite( ch, sf );
      ch = astAnnul( ch );
      sf = astAnnul( sf );
      printf( "    (\n        " ); lit( dumps[ a ] );
      printf( ",\n        r#\"%s\"#,\n    ),\n", dumpbuf );
   }
   printf( "];\n" );

   return astOK ? 0 : 1;
}
