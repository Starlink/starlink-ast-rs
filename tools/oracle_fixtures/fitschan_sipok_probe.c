/* fitschan_sipok_probe -- capture how the SipOK attribute and the encoding
 * decide whether a FrameSet with SIP distortion is written with SIP
 * coefficients, with a linear approximation, or not at all.
 *
 * It reads crates/starlink-ast/tests/fixtures/wcsconv/inputs/sip.head with
 * SipReplace=0 (so the inverse coefficients are those of the header, not a
 * refit), then writes the FrameSet to a new FitsChan with each encoding and
 * SipOK unset, 0 and 1, recording astWrite's return value and every card,
 * as Rust source for
 * crates/starlink-ast/tests/fitschan_sipok_oracle/cases.rs:
 *
 *   ./fitschan_sipok_probe > ../../crates/starlink-ast/tests/fitschan_sipok_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void rust_str( const char *s ) {
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      if( *s == '\n' ) {
         fputs( "\\n", stdout );
      } else {
         putchar( *s );
      }
   }
}

int main( void ) {
   static const char *encs[] = { "FITS-WCS", "FITS-PC", "FITS-IRAF", "FITS-AIPS",
                                 "FITS-AIPS++", "FITS-CLASS", "DSS", NULL };
   static const char *sipok[] = { "unset", "0", "1", NULL };
   int status = 0;
   char line[ 200 ], card[ 81 ];
   AstFitsChan *in, *out;
   AstObject *obj;
   FILE *f;
   int e, k, n;

   astWatch( &status );
   in = astFitsChan( NULL, NULL, "SipReplace=0" );
   f = fopen( "../../crates/starlink-ast/tests/fixtures/wcsconv/inputs/sip.head", "r" );
   if( !f ) return 1;
   while( fgets( line, sizeof line, f ) ) {
      line[ strcspn( line, "\n" ) ] = 0;
      astPutFits( in, line, 0 );
   }
   fclose( f );
   astClear( in, "Card" );
   obj = astRead( in );
   if( !obj ) return 1;

   printf( "// Generated by tools/oracle_fixtures/fitschan_sipok_probe.c. Do not edit.\n\n" );
   printf( "/// `(encoding, SipOK, what astWrite returns and the cards it writes)`.\n" );
   printf( "pub const CASES: &[(&str, &str, &str)] = &[\n" );
   for( e = 0; encs[ e ]; e++ ) {
      for( k = 0; sipok[ k ]; k++ ) {
         out = astFitsChan( NULL, NULL, "Encoding=%s", encs[ e ] );
         if( strcmp( sipok[ k ], "unset" ) ) astSet( out, "SipOK=%s", sipok[ k ] );
         n = astWrite( out, obj );
         if( !astOK ) {
            astClearStatus;
            n = -1;
         }
         printf( "    (\"%s\", \"%s\", \"wrote %d\\n", encs[ e ], sipok[ k ], n );
         astClear( out, "Card" );
         while( astFindFits( out, "%f", card, 1 ) ) {
            rust_str( card );
            fputs( "\\n", stdout );
         }
         printf( "\"),\n" );
         out = astAnnul( out );
      }
   }
   printf( "];\n" );
   return status;
}
