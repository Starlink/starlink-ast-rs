/* ident_probe -- capture how Objects write and read Ident, the Object
 * attribute every AST Object has (object.c). Dump writes it in the Object
 * part of the description, ahead of an "IsA Object" line, whenever it is
 * set, even when blank; astLoadObject reads it back. A KeyMap, a Mapping,
 * a Frame and a Region each have a blank Ident set through the protected
 * astSetIdent, since astSet would store "Ident=" as a single space.
 *
 * Prints Rust source for crates/starlink-ast/tests/ident_oracle/cases.rs:
 *
 *   ./ident_probe > ../../crates/starlink-ast/tests/ident_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern void astSetIdent_( void *, const char *, int * );

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void sink( const char *line ) {
   printf( "    " );
   str( line );
   printf( ",\n" );
}

/* Print the Native dump of "obj" as a Rust array of lines. */
static void dump( const char *name, AstObject *obj ) {
   AstChannel *ch = astChannel( NULL, sink, " " );
   printf( "pub const %s: &[&str] = &[\n", name );
   astWrite( ch, obj );
   printf( "];\n\n" );
   ch = astAnnul( ch );
}

static const char **lines;
static int next_line;

static const char *source( void ) {
   return lines[ next_line ] ? lines[ next_line++ ] : NULL;
}

/* Read "text" and print the Ident of the KeyMap read, and of the KeyMap
   held in its entry "inner" if there is one, with whether each is set. */
static void read( const char *name, const char **text ) {
   AstChannel *ch;
   AstKeyMap *km;
   AstObject *inner = NULL;
   int i;

   lines = text;
   next_line = 0;
   ch = astChannel( source, NULL, " " );
   km = (AstKeyMap *) astRead( ch );
   ch = astAnnul( ch );
   printf( "    (\n        \"%s\",\n        &[\n", name );
   for( i = 0; text[ i ]; i++ ) {
      printf( "            " );
      str( text[ i ] );
      printf( ",\n" );
   }
   printf( "        ],\n        (" );
   str( astGetC( km, "Ident" ) );
   printf( ", %s),\n        ", astTest( km, "Ident" ) ? "true" : "false" );
   if( astMapGet0A( km, "inner", &inner ) ) {
      printf( "Some((" );
      str( astGetC( inner, "Ident" ) );
      printf( ", %s)),\n", astTest( inner, "Ident" ) ? "true" : "false" );
      inner = astAnnul( inner );
   } else {
      printf( "None,\n" );
   }
   printf( "    ),\n" );
   km = astAnnul( km );
}

int main( void ) {
   AstKeyMap *km, *inner;
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/ident_probe.c. Do not edit.\n\n" );

   /* A KeyMap with an Ident, holding another with an Ident of its own. */
   km = astKeyMap( " " );
   inner = astKeyMap( " " );
   astSetC( km, "Ident", "outer map" );
   astSetC( inner, "Ident", "inner map" );
   astMapPut0I( inner, "x", 7, NULL );
   astMapPut0A( km, "inner", inner, NULL );
   dump( "DUMP_IDENTS", (AstObject *) km );
   inner = astAnnul( inner );
   km = astAnnul( km );

   /* A blank Ident is set, and is written. */
   {
      AstObject *obj[ 4 ];
      const char *names[ 4 ] = { "DUMP_BLANK_KEYMAP", "DUMP_BLANK_ZOOMMAP",
                                 "DUMP_BLANK_FRAME", "DUMP_BLANK_FRAMESET" };
      obj[ 0 ] = (AstObject *) astKeyMap( " " );
      obj[ 1 ] = (AstObject *) astZoomMap( 1, 2.0, " " );
      obj[ 2 ] = (AstObject *) astFrame( 1, " " );
      obj[ 3 ] = (AstObject *) astFrameSet( astFrame( 1, " " ), " " );
      /* Adding a Frame sets Current, which is otherwise unset. */
      astAddFrame( (AstFrameSet *) obj[ 3 ], AST__BASE, astUnitMap( 1, " " ),
                   astFrame( 1, " " ) );
      for( int i = 0; i < 4; i++ ) {
         astSetIdent_( astMakePointer( obj[ i ] ), "", &status );
         dump( names[ i ], obj[ i ] );
         obj[ i ] = astAnnul( obj[ i ] );
      }
   }

   /* A KeyMap with no Ident writes no Object part. */
   km = astKeyMap( " " );
   astMapPut0I( km, "a", 1, NULL );
   dump( "DUMP_NO_IDENT", (AstObject *) km );
   km = astAnnul( km );

   printf( "/// `(name, Native text, (Ident, set), the inner KeyMap's (Ident, set))`.\n"
           "pub type ReadCase = (&'static str, &'static [&'static str], (&'static str, bool),\n"
           "                     Option<(&'static str, bool)>);\n\n"
           "pub const READS: &[ReadCase] = &[\n" );
   {
      const char *t[] = { "Begin KeyMap", "Ident = \"id\"", "IsA Object", "End KeyMap", NULL };
      read( "object_part", t );
   }
   {
      const char *t[] = { "Begin KeyMap", "Ident = \"\"", "IsA Object", "End KeyMap", NULL };
      read( "blank", t );
   }
   {
      const char *t[] = { "Begin KeyMap", "IsA Object", "Ident = \"id\"", "End KeyMap", NULL };
      read( "keymap_part", t );
   }
   {
      const char *t[] = { "Begin KeyMap", "Key1 = \"inner\"", "Typ1 = 4", "Val1 =",
                          "Begin KeyMap", "Ident = \"in\"", "IsA Object", "End KeyMap",
                          "End KeyMap", NULL };
      read( "nested", t );
   }
   printf( "];\n" );
   return 0;
}
