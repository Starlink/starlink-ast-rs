/* fixture_full_dump_probe -- read each native fixture named on standard
 * input with a Channel, as the port's tests read them, and write every
 * Object read with a second Channel whose Full is 1, so that every value a
 * class's Dump writes appears: set values, and unset ones as comments,
 * helpful or not (channel.c Use), with every IsA marker and a Frame's Axes
 * in full (frame.c Dump).
 *
 * With no argument, prints Rust source for
 * crates/starlink-ast/tests/fixture_full_dump_oracle/cases.rs, run from
 * crates/starlink-ast/tests/fixtures, giving for each fixture that reads
 * without error the FNV-1a 64-bit hash of the text written (each line
 * followed by a newline, the Objects one after another):
 *
 *   find . -type f \( -name '*.map' -o -name '*.simp' -o -name '*.ast' \
 *        -o -name '*.native' \) | sort | \
 *     ../../../../tools/oracle_fixtures/fixture_full_dump_probe 2>/dev/null \
 *     > ../fixture_full_dump_oracle/cases.rs
 *
 * With the argument "text", prints each fixture's name on a line starting
 * "== " followed by the text written, to compare by eye.
 *
 * The text is that C writes, less the lines `sink` describes.
 */
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include "ast.h"

static FILE *fd;
static char line[ 10000 ];
static uint64_t hash;
static int text;

static const char *source( void ) {
   size_t n;
   if( !fgets( line, sizeof( line ), fd ) ) return NULL;
   n = strlen( line );
   if( n && line[ n - 1 ] == '\n' ) line[ n - 1 ] = 0;
   return line;
}

static void add( const char *s ) {
   for( ; *s; s++ ) {
      hash ^= (unsigned char) *s;
      hash *= UINT64_C( 1099511628211 );
   }
}

/* The key of an unset value, or NULL for any other line. */
static const char *unset_key( const char *s, char *key ) {
   int n = 0;
   if( s[ 0 ] != '#' ) return NULL;
   if( sscanf( s, "# %31[A-Za-z0-9_] = %n", key, &n ) != 1 || !n ) return NULL;
   return key;
}

/* Lines that hold the state of the C process rather than of the Object
   are left out: the unset RefCnt and Nobj of the Object part (object.c
   Dump), counts of pointers and of Objects of the class, and the value of
   a MathMap's unset Seed (mathmap.c Dump), chosen at random when the
   MathMap is made, which is replaced by "<random>". */
static void sink( const char *s ) {
   char key[ 32 ], buf[ 1000 ];
   const char *eq;
   if( unset_key( s, key ) ) {
      if( !strcmp( key, "RefCnt" ) || !strcmp( key, "Nobj" ) ) return;
      if( !strcmp( key, "Seed" ) && strstr( s, "# Default random number seed used" ) ) {
         eq = strchr( s, '=' );
         sprintf( buf, "%.*s= <random> \t# Default random number seed used",
                  (int)( eq - s ), s );
         s = buf;
      }
   }
   add( s );
   add( "\n" );
   if( text ) printf( "%s\n", s );
}

int main( int argc, char **argv ) {
   AstChannel *ch, *out;
   AstObject *obj;
   char name[ 4096 ];
   int status = 0, iread, ok;
   size_t n;

   text = argc > 1 && !strcmp( argv[ 1 ], "text" );
   astWatch( &status );
   if( !text ) {
      printf( "// Generated by tools/oracle_fixtures/fixture_full_dump_probe.c. Do not edit.\n\n" );
      printf( "/// `(fixture, FNV-1a 64-bit hash of the Objects read written with Full = 1)`.\n" );
      printf( "pub const CASES: &[(&str, u64)] = &[\n" );
   }
   while( fgets( name, sizeof( name ), stdin ) ) {
      n = strlen( name );
      if( n && name[ n - 1 ] == '\n' ) name[ n - 1 ] = 0;
      fd = fopen( name, "r" );
      if( !fd ) continue;
      ch = astChannel( source, NULL, " " );
      out = astChannel( NULL, sink, "Full=1" );
      hash = UINT64_C( 14695981039346656037 );
      if( text ) printf( "== %s\n", name );
      ok = 1;
      for( iread = 0; iread < 10; iread++ ) {
         obj = astRead( ch );
         if( !astOK ) {
            astClearStatus;
            ok = 0;
            break;
         }
         if( !obj ) break;
         astWrite( out, obj );
         obj = astAnnul( obj );
         if( !astOK ) {
            astClearStatus;
            ok = 0;
            break;
         }
      }
      if( ok && iread > 0 && !text ) {
         printf( "    (\"%s\", 0x%016llx),\n", name, (unsigned long long) hash );
      }
      out = astAnnul( out );
      ch = astAnnul( ch );
      fclose( fd );
   }
   if( !text ) printf( "];\n" );
   return 0;
}
