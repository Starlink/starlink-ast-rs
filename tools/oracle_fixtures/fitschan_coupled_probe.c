/* fitschan_coupled_probe -- capture how a FITS-WCS write describes axes
 * that each depend on both pixel axes, so that IsMapLinear (fitschan.c)
 * cannot split the axis off the Mapping. It then holds the other output at
 * its value where astMapBox finds the tested output lowest, and widens the
 * output's bounds when they are equal.
 *
 * In OtherAxes the outcome of IsMapLinear shows only for an axis it finds
 * not linear, which LogAxis may then describe as -LOG, so the exponential
 * cases are the ones that test it.
 *
 * Each FrameSet maps a 2-D GRID Frame to a 2-D Frame with a MathMap, and is
 * written to a FitsChan holding NAXIS1 and NAXIS2. For each: the value
 * astWrite returns and the cards written. For each Mapping and image size,
 * also the astMapBox results over the image for each output, which
 * IsMapLinear uses.
 *
 * Prints Rust source for crates/ast-core/tests/fitschan_coupled_oracle/cases.rs:
 *
 *   ./fitschan_coupled_probe > ../../crates/ast-core/tests/fitschan_coupled_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

/* A double as the shortest Rust f64 literal that reads back to the same
   value. */
static void dbl( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec <= 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   if( !strpbrk( buf, ".en" ) ) strcat( buf, ".0" );
   printf( "%s, ", buf );
}

static void emit( const char *name, const char *fwd1, const char *fwd2,
                  const char *inv1, const char *inv2, int nx, int ny ) {
   const char *fwd[ 2 ], *inv[ 2 ];
   AstFrameSet *fs;
   AstMapping *map;
   AstFitsChan *fc;
   char card[ 81 ];
   double lbnd[ 2 ], ubnd[ 2 ], lo, hi, xl[ 2 ], xu[ 2 ];
   int ret, iout;

   fwd[ 0 ] = fwd1;
   fwd[ 1 ] = fwd2;
   inv[ 0 ] = inv1;
   inv[ 1 ] = inv2;
   map = (AstMapping *) astMathMap( 2, 2, 2, fwd, 2, inv, " " );

   printf( "    (\"%s\", [", name );
   str( fwd1 );
   printf( ", " );
   str( fwd2 );
   printf( "], [" );
   str( inv1 );
   printf( ", " );
   str( inv2 );
   printf( "], %d, %d,\n     [", nx, ny );

   /* The pixel box IsMapLinear is given: 1 to NAXISi. */
   lbnd[ 0 ] = lbnd[ 1 ] = 1.0;
   ubnd[ 0 ] = nx;
   ubnd[ 1 ] = ny;
   for( iout = 1; iout <= 2; iout++ ) {
      astMapBox( map, lbnd, ubnd, 1, iout, &lo, &hi, xl, xu );
      if( !astOK ) {
         astClearStatus;
         printf( "None, " );
      } else {
         printf( "Some([" );
         dbl( lo );
         dbl( hi );
         dbl( xl[ 0 ] );
         dbl( xl[ 1 ] );
         dbl( xu[ 0 ] );
         dbl( xu[ 1 ] );
         printf( "]), " );
      }
   }
   printf( "],\n" );

   fs = astFrameSet( astFrame( 2, "Domain=GRID" ), " " );
   astAddFrame( fs, AST__BASE, map, astFrame( 2, "Domain=X" ) );
   fc = astFitsChan( NULL, NULL, "Encoding=FITS-WCS" );
   sprintf( card, "NAXIS1  = %d", nx );
   astPutFits( fc, card, 0 );
   sprintf( card, "NAXIS2  = %d", ny );
   astPutFits( fc, card, 0 );
   ret = astWrite( fc, fs );
   astClearStatus;

   printf( "     %d, &[\n", ret );
   astClear( fc, "Card" );
   while( astFindFits( fc, "%f", card, 1 ) ) {
      printf( "        " );
      str( card );
      printf( ",\n" );
   }
   printf( "    ]),\n" );
   fc = astAnnul( fc );
   fs = astAnnul( fs );
   map = astAnnul( map );
}

/* "x = a + b, y = b + k*a*a" with its inverse. How far the second output
   is from linear depends on the value the first is held at. */
static void quad( const char *name, const char *k, int nx, int ny ) {
   char f2[ 100 ], i1[ 200 ], i2[ 200 ];
   sprintf( f2, "y=b+%s*a*a", k );
   sprintf( i1, "a=(1-sqrt(1-4*%s*(x-y)))/(2*%s)", k, k );
   sprintf( i2, "b=x-(1-sqrt(1-4*%s*(x-y)))/(2*%s)", k, k );
   emit( name, "x=a+b", f2, i1, i2, nx, ny );
}

/* "x = 2*exp(k*(a + 0.5*b)), y = b" with its inverse: not linear, but its
   logarithm is. */
static void expo( const char *name, const char *k, int nx, int ny ) {
   char f1[ 100 ], i1[ 100 ];
   sprintf( f1, "x=2*exp(%s*(a+0.5*b))", k );
   sprintf( i1, "a=log(x/2)/%s-0.5*y", k );
   emit( name, f1, "y=b", i1, "b=y", nx, ny );
}

int main( void ) {
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/fitschan_coupled_probe.c. Do not edit.\n\n" );
   printf( "/// `(name, forward functions, inverse functions, NAXIS1, NAXIS2,\n"
           "/// astMapBox over the image for each output as `[lbnd, ubnd, xl, xu]`\n"
           "/// (None if it fails), astWrite's value, the cards written)`.\n" );
   printf( "pub type Case = (&'static str, [&'static str; 2], [&'static str; 2], i32, i32,\n"
           "    [Option<[f64; 6]>; 2], i32, &'static [&'static str]);\n\n" );
   printf( "pub const CASES: &[Case] = &[\n" );
   emit( "rotation", "x=a+0.5*b", "y=b-0.25*a", "a=(x-0.5*y)/1.125",
         "b=(y+0.25*x)/1.125", 100, 200 );
   emit( "rotation_1x1", "x=a+0.5*b", "y=b-0.25*a", "a=(x-0.5*y)/1.125",
         "b=(y+0.25*x)/1.125", 1, 1 );
   emit( "rotation_1x50", "x=a+0.5*b", "y=b-0.25*a", "a=(x-0.5*y)/1.125",
         "b=(y+0.25*x)/1.125", 1, 50 );
   quad( "quad_1e-9", "1e-9", 100, 100 );
   quad( "quad_1e-8", "1e-8", 100, 100 );
   quad( "quad_1e-7", "1e-7", 100, 100 );
   quad( "quad_1e-6", "1e-6", 100, 100 );
   quad( "quad_1e-4", "1e-4", 100, 100 );
   quad( "quad_1e-6_wide", "1e-6", 1000, 10 );
   quad( "quad_1e-6_1x1", "1e-6", 1, 1 );
   emit( "shear_sq", "x=a+1e-6*b*b", "y=b", "a=x-1e-6*y*y", "b=y", 100, 100 );
   emit( "shear_sq_1e-4", "x=a+1e-4*b*b", "y=b", "a=x-1e-4*y*y", "b=y", 100, 100 );
   emit( "scaled", "x=a*(1+1e-3*b)", "y=b", "a=x/(1+1e-3*y)", "b=y", 100, 100 );
   emit( "scaled_1x1", "x=a*(1+1e-3*b)", "y=b", "a=x/(1+1e-3*y)", "b=y", 1, 1 );
   emit( "near_zero_1x1", "x=a-1", "y=b-1+1e-3*(a-1)", "a=x+1", "b=y+1-1e-3*x", 1, 1 );
   expo( "exp_1e-2", "0.01", 100, 100 );
   expo( "exp_1e-4", "1e-4", 100, 100 );
   expo( "exp_1e-5", "1e-5", 100, 100 );
   expo( "exp_1e-6", "1e-6", 100, 100 );
   expo( "exp_1e-2_1x1", "0.01", 1, 1 );
   expo( "exp_1e-2_1x50", "0.01", 1, 50 );
   expo( "exp_1_1x1", "1", 1, 1 );
   expo( "exp_1e-4_1x1", "1e-4", 1, 1 );
   printf( "];\n" );
   return 0;
}
