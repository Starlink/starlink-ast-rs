/* cmp_match_end_probe -- capture astFindFrame with a CmpFrame template of
 * two one-axis Frames against a four-axis Frame, varying the MatchEnd and
 * MaxAxes of the template and of its first component, and the MinAxes and
 * PreserveAxes of the component, which make its result keep more axes than
 * it has. Those extra axes are placed by the component's MatchEnd. C's CmpFrame
 * PartMatch gives an unset component the template's MatchEnd only while
 * matching it, then lays the result out with each component's own MatchEnd
 * (cmpframe.c:6856, :6936).
 *
 * Prints Rust source for crates/starlink-ast/tests/cmp_match_end_oracle/cases.rs:
 *
 *   ./cmp_match_end_probe > ../../crates/starlink-ast/tests/cmp_match_end_oracle/cases.rs
 */
#include <stdio.h>
#include "ast.h"

int main( void ) {
   int status = 0;
   const char *cmps[] = { "MaxAxes=4", "MaxAxes=4,MatchEnd=1", NULL };
   const char *c1s[] = { "MaxAxes=2", "MaxAxes=2,MatchEnd=1", "MaxAxes=3",
                         "MaxAxes=3,MatchEnd=0", "MaxAxes=3,MatchEnd=1",
                         "MaxAxes=3,PreserveAxes=1", "MaxAxes=3,PreserveAxes=1,MatchEnd=0",
                         "MaxAxes=3,PreserveAxes=1,MatchEnd=1",
                         "MinAxes=2,MaxAxes=2,PreserveAxes=1",
                         "MinAxes=2,MaxAxes=2,PreserveAxes=1,MatchEnd=0",
                         "MinAxes=2,MaxAxes=2,PreserveAxes=1,MatchEnd=1", NULL };
   int i, j, k;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/cmp_match_end_probe.c. Do not edit.\n\n"
           "/// `(CmpFrame settings, first component settings, labels of the result\n"
           "/// axes and their values for the input (1, 2, 3, 4), or None)`. The\n"
           "/// target axes are labelled A to D.\n"
           "pub type Case = (&'static str, &'static str, Option<&'static [(&'static str, f64)]>);\n\n"
           "pub const CASES: &[Case] = &[\n" );
   for( i = 0; cmps[ i ]; i++ ) {
      for( j = 0; c1s[ j ]; j++ ) {
         AstFrame *target = astFrame( 4, "Label(1)=A,Label(2)=B,Label(3)=C,Label(4)=D" );
         AstFrame *t = (AstFrame *) astCmpFrame( astFrame( 1, "%s", c1s[ j ] ),
                                                 astFrame( 1, " " ), "%s", cmps[ i ] );
         AstFrameSet *fs = astFindFrame( target, t, "" );
         printf( "    (\"%s\", \"%s\", ", cmps[ i ], c1s[ j ] );
         if( !fs ) {
            printf( "None),\n" );
            continue;
         }
         {
            AstFrame *r = astGetFrame( fs, AST__CURRENT );
            int n = astGetI( r, "Naxes" );
            double in[ 4 ][ 1 ] = { { 1 }, { 2 }, { 3 }, { 4 } }, out[ 4 ][ 1 ];
            astTranN( fs, 1, 4, 1, (const double *) in, 1, n, 1, (double *) out );
            printf( "Some(&[" );
            for( k = 1; k <= n; k++ ) {
               char key[ 20 ];
               sprintf( key, "Label(%d)", k );
               printf( "%s(\"%s\", %.1f)", k > 1 ? ", " : "", astGetC( r, key ),
                       out[ k - 1 ][ 0 ] );
            }
            printf( "])),\n" );
         }
      }
   }
   printf( "];\n" );
   return 0;
}
