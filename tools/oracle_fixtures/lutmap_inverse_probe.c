/* lutmap_inverse_probe -- capture the inverse transformation of LutMaps
 * whose tables have bad entries, flat runs, and either direction, with
 * linear and nearest-neighbour interpolation (lutmap.c Transform). The
 * inputs are each good table value, the midpoints between them, and values
 * beyond both ends of the table.
 *
 * Prints Rust source for crates/starlink-ast/tests/lutmap_inverse_oracle/cases.rs:
 *
 *   ./lutmap_inverse_probe > ../../crates/starlink-ast/tests/lutmap_inverse_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

#define BAD AST__BAD

/* Print a value as a Rust f64 literal, with the fewest digits that read
   back as the same value. */
static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void emit( const char *name, int nlut, const double *lut, double start,
                  double inc ) {
   AstLutMap *map;
   double in[ 64 ], out[ 64 ], lo, hi, prev;
   int i, n = 0, near, have_prev = 0;

   lo = hi = BAD;
   for( i = 0; i < nlut; i++ ) {
      if( lut[ i ] == BAD ) continue;
      if( lo == BAD || lut[ i ] < lo ) lo = lut[ i ];
      if( hi == BAD || lut[ i ] > hi ) hi = lut[ i ];
      if( have_prev ) in[ n++ ] = 0.5*( prev + lut[ i ] );
      in[ n++ ] = lut[ i ];
      prev = lut[ i ];
      have_prev = 1;
   }
   in[ n++ ] = lo - 1.5;
   in[ n++ ] = hi + 2.0;
   in[ n++ ] = BAD;

   for( near = 0; near < 2; near++ ) {
      map = astLutMap( nlut, lut, start, inc, "LutInterp=%d", near );
      astTran1( map, n, in, 0, out );
      printf( "    (\n        \"%s_%s\",\n        &[", name, near ? "nearest" : "linear" );
      for( i = 0; i < nlut; i++ ) {
         if( i ) printf( ", " );
         lit( lut[ i ] );
      }
      printf( "],\n        " );
      lit( start );
      printf( ",\n        " );
      lit( inc );
      printf( ",\n        %s,\n        &[\n", near ? "true" : "false" );
      for( i = 0; i < n; i++ ) {
         printf( "            (" );
         lit( in[ i ] );
         printf( ", " );
         lit( out[ i ] );
         printf( "),\n" );
      }
      printf( "        ],\n    ),\n" );
      map = astAnnul( map );
   }
}

int main( void ) {
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/lutmap_inverse_probe.c. Do not edit.\n\n"
           "/// `(case, table, start, increment, nearest-neighbour, (input, C output) pairs)`.\n"
           "pub type Case = (\n"
           "    &'static str,\n"
           "    &'static [f64],\n"
           "    f64,\n"
           "    f64,\n"
           "    bool,\n"
           "    &'static [(f64, f64)],\n"
           ");\n\n"
           "pub const CASES: &[Case] = &[\n" );

   { double t[] = { 1, BAD, 3 }; emit( "one_bad", 3, t, 1.0, 1.0 ); }
   { double t[] = { 1, 2, 4, 8 }; emit( "increasing", 4, t, 1.0, 1.0 ); }
   { double t[] = { 8, 4, 2, 1 }; emit( "decreasing", 4, t, 1.0, 1.0 ); }
   { double t[] = { 0, BAD, 2, 3, BAD, BAD, 6, 7 }; emit( "increasing_bad_runs", 8, t, 0.0, 2.0 ); }
   { double t[] = { 7, BAD, 5, 4, BAD, 2 }; emit( "decreasing_bad", 6, t, -3.0, 0.5 ); }
   { double t[] = { 1, 2, 2, 3 }; emit( "flat", 4, t, 0.0, 1.0 ); }
   { double t[] = { 1, BAD, 2, 2, 3 }; emit( "flat_after_bad", 5, t, 0.0, 1.0 ); }
   { double t[] = { BAD, 1, 2, 4, BAD }; emit( "bad_ends", 5, t, 0.0, 1.0 ); }
   { double t[] = { 1, 3, 6, BAD, 10 }; emit( "negative_increment", 5, t, 10.0, -0.5 ); }
   { double t[] = { 1, 1.5, 4 }; emit( "uneven", 3, t, 2.0, 3.0 ); }

   printf( "];\n" );
   return status;
}
