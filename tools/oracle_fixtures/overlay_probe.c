/* overlay_probe -- capture the attributes of the Frames that astFindFrame
 * and astPickAxes produce, which come from C's astOverlay (frame.c:8513 and
 * each class's Overlay): the target is overlaid onto the result first, then
 * the template, each by its own class's Overlay.
 *
 * For each case it prints the result Frame's Title, Domain, Digits, whether
 * Epoch is set and its value (as a TDB MJD), and the Label and Unit of axis
 * 1, or "None" when no Frame is found.
 *
 * Prints Rust source for crates/ast-core/tests/overlay_oracle/cases.rs:
 *
 *   ./overlay_probe > ../../crates/ast-core/tests/overlay_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern double astGetEpoch_( void *, int * );

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void emit( const char *name, AstFrame *f ) {
   int status = 0;
   printf( "    (\"%s\", ", name );
   if( !f ) {
      printf( "None),\n" );
      return;
   }
   printf( "Some((" );
   str( astGetC( f, "Title" ) ); printf( ", " );
   str( astGetC( f, "Domain" ) ); printf( ", " );
   {
      char buf[ 40 ];
      snprintf( buf, sizeof( buf ), "%.17g",
                astGetEpoch_( astMakePointer( f ), &status ) );
      if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
      printf( "%d, %s, %s, ", astGetI( f, "Digits" ),
              astTest( f, "Epoch" ) ? "true" : "false", buf );
   }
   str( astGetC( f, "Label(1)" ) ); printf( ", " );
   str( astGetC( f, "Unit(1)" ) );
   printf( "))),\n" );
}

/* The current Frame of the FrameSet astFindFrame returns, or NULL. */
static AstFrame *found( AstFrame *target, AstFrame *template ) {
   AstFrameSet *fs = astFindFrame( target, template, "" );
   return fs ? astGetFrame( fs, AST__CURRENT ) : NULL;
}

int main( void ) {
   int status = 0;
   int pick1[] = { 1 };
   int pick21[] = { 2, 1 };
   AstFrame *f, *t;
   AstMapping *map;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/overlay_probe.c against\n"
           "// the C library at u/timj/norm-unit 5a2cac2a, past the submodule pin.\n"
           "// Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// `(Title, Domain, Digits, TestEpoch, Epoch as TDB MJD, Label(1), Unit(1))`.\n"
           "pub type Attrs = (&'static str, &'static str, i32, bool, f64, &'static str, &'static str);\n\n"
           "pub const CASES: &[(&str, Option<Attrs>)] = &[\n" );

   /* A plain Frame's attributes reach the axes picked from it. */
   f = astFrame( 2, "Title=Picked,Domain=PIX,Digits=3,Epoch=1990.0,"
                    "Label(1)=X,Label(2)=Y,Unit(1)=m" );
   emit( "frame_pick", astPickAxes( f, 1, pick21, &map ) );

   /* A SkyFrame target and a plain Frame template in the SKY Domain. */
   f = (AstFrame *) astSkyFrame( "System=FK5" );
   t = astFrame( 2, "Domain=SKY,Title=Hello,Digits=9" );
   emit( "sky_target_frame_template", found( f, t ) );

   /* A SkyFrame target with Epoch, Title and Digits, picked to one axis. */
   f = (AstFrame *) astSkyFrame( "System=FK5,Epoch=1990.0,Title=Sky,Digits=5" );
   emit( "sky_pick_one", astPickAxes( f, 1, pick1, &map ) );

   /* A FluxFrame target and a plain Frame template in its Domain. */
   f = (AstFrame *) astFluxFrame( 1.4e9, NULL, "System=FLXDN" );
   t = astFrame( 1, "Domain=FLUX,Title=TT,Label(1)=LL,Epoch=2010.0,Digits=9" );
   emit( "flux_target_frame_template", found( f, t ) );

   /* A SpecFrame target and a plain Frame template in its Domain. */
   f = (AstFrame *) astSpecFrame( "System=FREQ,Unit=GHz" );
   t = astFrame( 1, "Domain=SPECTRUM,Title=Spec,Label(1)=Nu,Digits=8" );
   emit( "spec_target_frame_template", found( f, t ) );

   /* A TimeFrame target and a plain Frame template in its Domain. */
   f = (AstFrame *) astTimeFrame( "System=MJD" );
   t = astFrame( 1, "Domain=TIME,Title=When,Label(1)=T,Digits=11" );
   emit( "time_target_frame_template", found( f, t ) );

   /* A TimeFrame template that changes the System: C clears the result's
      Title, Label and Symbol first. */
   f = (AstFrame *) astTimeFrame( "System=MJD,Label(1)=Mine,Title=Mine" );
   t = (AstFrame *) astTimeFrame( "System=JD" );
   emit( "time_system_change", found( f, t ) );

   /* A SpecFrame template that changes the System. */
   f = (AstFrame *) astSpecFrame( "System=FREQ,Label(1)=Mine,Title=Mine" );
   t = (AstFrame *) astSpecFrame( "System=WAVE" );
   emit( "spec_system_change", found( f, t ) );

   /* A CmpFrame template whose SpecFrame component has a Title and Label,
      against a two-axis plain Frame. */
   f = astFrame( 2, "Domain=SPECTRUM-" );
   t = (AstFrame *) astCmpFrame( astSpecFrame( "Title=CmpSpec,Label(1)=Freq" ),
                                 astFrame( 1, " " ), " " );
   emit( "cmp_template_plain_target", found( f, t ) );

   printf( "];\n" );
   return 0;
}
