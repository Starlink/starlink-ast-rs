/* lsst_probe -- capture the LSST FrameSet's transforms (fixtures/wcsconv/
 * inputs/lsst.ast) for test_lsst_oracle.rs: the forward transform of ten
 * pixel positions, through the FrameSet as read and through astSimplify's
 * result, and the inverse transform of those forward outputs through each.
 * The inverse runs PolyMap's iterative inverse, which stops at TolInv, so the
 * two inverses need not agree with each other or with the pixel positions.
 *
 *   ./lsst_probe [lsst.ast] > ../../crates/starlink-ast/tests/lsst_oracle/cases.rs
 */
#include "ast.h"
#include <stdio.h>
#include <stdlib.h>

#define NPTS 10

static void print_pairs( const char *doc, const char *name, const double *x,
                         const double *y ) {
   int i;
   printf( "%s", doc );
   printf( "pub const %s: [(f64, f64); NPTS] = [\n", name );
   for( i = 0; i < NPTS; i++ ) printf( "    (%.17g, %.17g),\n", x[ i ], y[ i ] );
   printf( "];\n" );
}

int main( int argc, char **argv ) {
   const char *path = argc > 1 ? argv[ 1 ] :
      "../../crates/starlink-ast/tests/fixtures/wcsconv/inputs/lsst.ast";
   static char text[ 1 << 20 ];
   double x[ NPTS ], y[ NPTS ], fx[ NPTS ], fy[ NPTS ], sx[ NPTS ], sy[ NPTS ];
   double ix[ NPTS ], iy[ NPTS ], six[ NPTS ], siy[ NPTS ];
   int status = 0, i, same = 1;
   size_t n;
   FILE *fd;
   AstMapping *map, *simp;

   fd = fopen( path, "r" );
   if( !fd ) {
      fprintf( stderr, "lsst_probe: cannot open %s\n", path );
      return 1;
   }
   n = fread( text, 1, sizeof text - 1, fd );
   fclose( fd );
   text[ n ] = '\0';

   astWatch( &status );
   map = (AstMapping *) astFromString( text );
   simp = astSimplify( map );

   for( i = 0; i < NPTS; i++ ) {
      x[ i ] = 100.0 + i*0.01;
      y[ i ] = 200.0 + i*0.005;
   }
   astTran2( map, NPTS, x, y, 1, fx, fy );
   astTran2( simp, NPTS, x, y, 1, sx, sy );
   astTran2( map, NPTS, fx, fy, 0, ix, iy );
   astTran2( simp, NPTS, fx, fy, 0, six, siy );
   if( !astOK ) {
      fprintf( stderr, "lsst_probe: AST error\n" );
      return 1;
   }
   for( i = 0; i < NPTS; i++ ) {
      if( fx[ i ] != sx[ i ] || fy[ i ] != sy[ i ] ) same = 0;
   }
   if( !same ) {
      fprintf( stderr, "lsst_probe: the simplified forward transform differs\n" );
      return 1;
   }

   printf( "// Generated by tools/oracle_fixtures/lsst_probe.c. Do not edit.\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// The number of pixel positions, (100 + i*0.01, 200 + i*0.005).\n"
           "pub const NPTS: usize = %d;\n\n", NPTS );
   print_pairs( "/// The forward transform of each position, the same bits through the\n"
                "/// FrameSet as read and through its simplified form.\n",
                "C_FORWARD", fx, fy );
   printf( "\n" );
   print_pairs( "/// The inverse transform of `C_FORWARD` through the FrameSet as read.\n",
                "C_INVERSE_OF_FORWARD", ix, iy );
   printf( "\n" );
   print_pairs( "/// The inverse transform of `C_FORWARD` through the simplified form.\n",
                "C_SIMPLIFIED_INVERSE_OF_FORWARD", six, siy );
   return 0;
}
