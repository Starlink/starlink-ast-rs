/* sky_plain_axis_probe -- capture how a SkyFrame behaves when it holds plain
 * Axis objects, as astLoadFrame gives it for a description with no Ax<n>
 * objects (frame.c:15227). The SkyFrame's own methods still answer Label,
 * Symbol, Direction, Top and Bottom, but Format, Unit, formatting and
 * unformatting go to the plain Axis. Setting AsTime on an axis replaces its
 * plain Axis with a SkyAxis carrying the same attributes (skyframe.c
 * SetAsTime).
 *
 * Prints Rust source for crates/starlink-ast/tests/sky_plain_axis_oracle/cases.rs:
 *
 *   ./sky_plain_axis_probe > ../../crates/starlink-ast/tests/sky_plain_axis_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static const char *text[] = { "Begin SkyFrame", "Naxes = 2", "Lbl1 = \"Lon\"",
                              "Dig1 = 3", "IsA Frame", "End SkyFrame", NULL };
static int next_line;

static const char *source( void ) {
   return text[ next_line ] ? text[ next_line++ ] : NULL;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void sink( const char *line ) {
   printf( "    " );
   str( line );
   printf( ",\n" );
}

/* Print, for each axis, its Format, Unit, a value formatted, and what
   "1.5" unformats to with the number of characters read. */
static void axes( const char *name, AstFrame *f ) {
   char key[ 20 ];
   double value;
   int axis, nc;

   printf( "    (\n        \"%s\",\n        [\n", name );
   for( axis = 1; axis <= 2; axis++ ) {
      printf( "            (" );
      sprintf( key, "Format(%d)", axis );
      str( astGetC( f, key ) );
      printf( ", " );
      sprintf( key, "Unit(%d)", axis );
      str( astGetC( f, key ) );
      printf( ", " );
      str( astFormat( f, axis, 1.2345 ) );
      nc = astUnformat( f, axis, "1.5", &value );
      printf( ", (%.17g, %d)),\n", value, nc );
   }
   printf( "        ],\n    ),\n" );
}

int main( void ) {
   AstChannel *ch;
   AstFrame *f, *picked;
   int status = 0, pick = 2;
   astWatch( &status );

   ch = astChannel( source, NULL, " " );
   f = astRead( ch );
   ch = astAnnul( ch );

   printf( "// Generated by tools/oracle_fixtures/sky_plain_axis_probe.c. Do not edit.\n\n"
           "// C's values, which may happen to equal a named constant.\n"
           "#![allow(clippy::approx_constant)]\n\n"
           "/// The description read, a SkyFrame with no Ax objects.\n"
           "pub const TEXT: &[&str] = &[\n" );
   for( int i = 0; text[ i ]; i++ ) sink( text[ i ] );
   printf( "];\n\n"
           "/// Per axis: Format, Unit, 1.2345 formatted, and \"1.5\" unformatted\n"
           "/// with the characters read.\n"
           "pub type Axis = (&'static str, &'static str, &'static str, (f64, usize));\n\n"
           "/// `(step, the two axes)`.\n"
           "pub const STEPS: &[(&str, [Axis; 2])] = &[\n" );
   axes( "loaded", f );
   astSetI( f, "AsTime(1)", 1 );
   axes( "as_time_set", f );
   printf( "];\n\n" );

   printf( "/// The dump after AsTime(1) is set: a SkyAxis on axis 1, a plain Axis\n"
           "/// on axis 2.\n"
           "pub const DUMP: &[&str] = &[\n" );
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, f );
   ch = astAnnul( ch );
   printf( "];\n\n" );

   printf( "/// The Frame picked from axis 2, as its dump.\n"
           "pub const PICKED_2: &[&str] = &[\n" );
   picked = astPickAxes( f, 1, &pick, NULL );
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, picked );
   ch = astAnnul( ch );
   printf( "];\n" );

   picked = astAnnul( picked );
   f = astAnnul( f );
   return 0;
}
