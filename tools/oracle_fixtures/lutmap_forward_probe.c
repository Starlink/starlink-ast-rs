/* lutmap_forward_probe -- capture the forward transformation of LutMaps,
 * bit for bit, at inputs that exercise the interpolation (lutmap.c
 * Transform): between nodes with an increment that is not a power of two,
 * on the last node beside a bad entry, beyond either end, and at exactly
 * half an increment below the start for nearest-neighbour interpolation.
 *
 * Prints Rust source for crates/ast-core/tests/lutmap_forward_oracle/cases.rs:
 *
 *   ./lutmap_forward_probe > ../../crates/ast-core/tests/lutmap_forward_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   if( v == AST__BAD ) {
      printf( "BAD_VALUE" );
      return;
   }
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void list( int n, const double *v ) {
   int i;
   printf( "&[" );
   for( i = 0; i < n; i++ ) {
      lit( v[ i ] );
      printf( ", " );
   }
   printf( "]" );
}

static void emit( const char *name, int nlut, const double *lut, double start,
                  double inc, int nearest, int nin, const double *in ) {
   double out[ 20 ];
   char opts[ 40 ];
   AstLutMap *lm;
   sprintf( opts, "LutInterp=%d", nearest );
   lm = astLutMap( nlut, lut, start, inc, opts );
   astTran1( lm, nin, in, 1, out );
   printf( "    (\"%s\", ", name );
   list( nlut, lut );
   printf( ", " );
   lit( start );
   printf( ", " );
   lit( inc );
   printf( ", %s, ", nearest ? "true" : "false" );
   list( nin, in );
   printf( ", " );
   list( nin, out );
   printf( "),\n" );
   lm = astAnnul( lm );
}

int main( void ) {
   int status = 0;
   double smooth[] = { 0.1, 0.7, 2.9, 3.3, 8.15 };
   double between[] = { 1.05, 1.17, 1.31, 1.44, 1.59, 1.9, 2.21, 2.2 };
   double outside[] = { -3.0, 0.4, 2.3, 9.0 };
   double gap[] = { 1.0, AST__BAD, 3.0 };
   double gap_in[] = { 1.0, 2.0, 3.0, 3.5 };
   double near_in[] = { 0.85, 1.0, 1.15, 1.45, 2.2, 2.35, 2.36 };
   double halves[] = { 0.5, 1.5, 2.5, 5.5 };

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/lutmap_forward_probe.c. Do not edit.\n\n"
           "use ast_core::constants::BAD_VALUE;\n\n"
           "/// `(case, table, start, increment, nearest-neighbour, inputs, C's outputs)`.\n"
           "pub type Case = (&'static str, &'static [f64], f64, f64, bool, &'static [f64], &'static [f64]);\n\n"
           "pub const CASES: &[Case] = &[\n" );
   emit( "linear_between_nodes", 5, smooth, 1.0, 0.3, 0, 8, between );
   emit( "linear_beyond_ends", 5, smooth, 1.0, 0.3, 0, 4, outside );
   emit( "linear_last_node_beside_bad", 3, gap, 1.0, 1.0, 0, 4, gap_in );
   emit( "nearest_half_increments", 5, smooth, 1.0, 0.3, 1, 7, near_in );
   emit( "nearest_last_node_beside_bad", 3, gap, 1.0, 1.0, 1, 4, gap_in );
   emit( "nearest_exact_half_increments", 5, smooth, 1.0, 1.0, 1, 4, halves );
   printf( "];\n" );
   return status;
}
