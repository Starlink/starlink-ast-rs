/* fitschan_alt_naxes_probe -- capture how a FITS-WCS write describes axis
 * descriptions with different numbers of axes. WcsFromStore (fitschan.c)
 * bounds its per-axis loops, for each version, by WCSAXES if the version
 * has one, and otherwise by the highest CRPIX index stored for it.
 *
 * Each FrameSet has a 3-D GRID Frame, a primary Frame and an alternate
 * Frame (Ident "A"), joined to the GRID Frame by PermMaps that drop or add
 * axes, and is written with NAXIS = 3. For each: the value astWrite
 * returns and the cards written.
 *
 * Prints Rust source for crates/starlink-ast/tests/fitschan_alt_naxes_oracle/cases.rs:
 *
 *   ./fitschan_alt_naxes_probe > ../../crates/starlink-ast/tests/fitschan_alt_naxes_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

/* A Mapping from 3 pixel axes to "nout" axes: a PermMap (whose public
   constructor takes 1-based axis indices) passing the axes
   they share and giving any extra output the value 5, followed by a
   ShiftMap adding "shift" to each output. */
static AstMapping *map_to( int nout, double shift ) {
   int inperm[ 3 ], outperm[ 10 ], i;
   double con = 5.0, sh[ 10 ];
   for( i = 0; i < 3; i++ ) inperm[ i ] = ( i < nout ) ? i + 1 : -1;
   for( i = 0; i < nout; i++ ) outperm[ i ] = ( i < 3 ) ? i + 1 : -1;
   for( i = 0; i < nout; i++ ) sh[ i ] = shift + i;
   return (AstMapping *) astCmpMap( astPermMap( 3, inperm, nout, outperm, &con, " " ),
                                    astShiftMap( nout, sh, " " ), 1, " " );
}

static void emit( const char *name, int nprim, int nalt ) {
   AstFrameSet *fs;
   AstFrame *alt;
   AstFitsChan *fc;
   char card[ 81 ];
   int ret;

   fs = astFrameSet( astFrame( 3, "Domain=GRID" ), " " );
   astAddFrame( fs, AST__BASE, map_to( nprim, 10.0 ), astFrame( nprim, "Domain=PRI" ) );
   alt = astFrame( nalt, "Domain=ALT,Ident=A" );
   astAddFrame( fs, AST__BASE, map_to( nalt, 100.0 ), alt );
   astSetI( fs, "Current", 2 );

   fc = astFitsChan( NULL, NULL, "Encoding=FITS-WCS" );
   astPutFits( fc, "NAXIS   = 3", 0 );
   ret = astWrite( fc, fs );
   astClearStatus;

   printf( "    (\"%s\", %d, %d, %d, &[\n", name, nprim, nalt, ret );
   astClear( fc, "Card" );
   while( astFindFits( fc, "%f", card, 1 ) ) {
      printf( "        " );
      str( card );
      printf( ",\n" );
   }
   printf( "    ]),\n" );
   fc = astAnnul( fc );
   fs = astAnnul( fs );
}

int main( void ) {
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/fitschan_alt_naxes_probe.c. Do not edit.\n\n" );
   printf( "/// `(name, primary axes, alternate axes, astWrite's value, the cards\n"
           "/// written)`.\n" );
   printf( "pub type Case = (&'static str, usize, usize, i32, &'static [&'static str]);\n\n" );
   printf( "pub const CASES: &[Case] = &[\n" );
   emit( "same", 3, 3 );
   emit( "alt_fewer", 3, 2 );
   emit( "alt_one", 3, 1 );
   emit( "alt_more", 3, 4 );
   emit( "primary_fewer", 2, 3 );
   emit( "primary_more", 4, 3 );
   printf( "];\n" );
   return 0;
}
