/* flux_badun_probe -- capture where C reports a FluxFrame Unit that fits no
 * flux system. GetSystem takes an unset System from a set Unit and raises
 * AST__BADUN when no system's default units can be converted to it
 * (fluxframe.c GetSystem). SetUnit stores the Unit and then reads the
 * System, clearing a set System that the Unit does not fit (fluxframe.c
 * SetUnit). The Title, Label, Symbol and Unit defaults read the System.
 *
 * Each case starts from a FluxFrame with SpecVal 1.4E9 Hz and the given
 * System setting, sets Unit(1), and then reads each attribute, printing
 * its value or the error.
 *
 * Prints Rust source for crates/starlink-ast/tests/flux_badun_oracle/cases.rs:
 *
 *   ./flux_badun_probe > ../../crates/starlink-ast/tests/flux_badun_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"
#include "ast_err.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

/* Print Ok("value") or Err("code") for the last call, clearing the status. */
static void result( const char *value ) {
   if( astOK ) {
      printf( "Ok(" );
      str( value ? value : "" );
      printf( ")" );
   } else {
      printf( "Err(\"%s\")", astStatus == AST__BADUN ? "Badun" : "other" );
      astClearStatus;
   }
}

int main( void ) {
   int status = 0;
   const char *systems[] = { "", "System=FLXDN", NULL };
   const char *units[] = { "Jy", "W/m^2/Hz/arcsec**2", "m", NULL };
   const char *attrs[] = { "System", "Title", "Label(1)", "Symbol(1)", "Unit(1)", NULL };
   int i, j, k;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/flux_badun_probe.c. Do not edit.\n\n"
           "/// The attributes read after setting the Unit.\n"
           "pub const ATTRS: [&str; 5] = [\"System\", \"Title\", \"Label(1)\", \"Symbol(1)\", \"Unit(1)\"];\n\n"
           "/// `(System setting, Unit, result of setting the Unit, then of reading\n"
           "/// each of ATTRS)`, each `Ok(value)` or `Err(error)`.\n"
           "pub type Case = (&'static str, &'static str, Result<&'static str, &'static str>,\n"
           "                 [Result<&'static str, &'static str>; 5]);\n\n"
           "pub const CASES: &[Case] = &[\n" );
   for( i = 0; systems[ i ]; i++ ) {
      for( j = 0; units[ j ]; j++ ) {
         AstFrame *f = (AstFrame *) astFluxFrame( 1.4e9, NULL, "%s", systems[ i ] );
         printf( "    (\"%s\", \"%s\", ", systems[ i ], units[ j ] );
         astSetC( f, "Unit(1)", units[ j ] );
         result( "" );
         printf( ", [" );
         for( k = 0; attrs[ k ]; k++ ) {
            const char *v = astGetC( f, attrs[ k ] );
            if( k ) printf( ", " );
            result( v );
         }
         printf( "]),\n" );
      }
   }
   printf( "];\n" );
   return 0;
}
