/* spec_origin_sor_probe -- capture how a SpecOrigin and AlignSpecOffset take
 * part in a change of StdOfRest. SetStdOfRest re-expresses a set SpecOrigin
 * in the new rest frame by converting with astConvert on the Frame itself,
 * AlignSpecOffset included, and raises AST__ATSER when the result is bad
 * (specframe.c OriginStdOfRest). With AlignSpecOffset set on both Frames,
 * MakeSpecMapping takes the result's zero point from the target origin
 * transformed through the conversion (specframe.c:2953). That has no value
 * in a wavelength system when no SpecOrigin is set, and the result's own
 * origin is used instead since upstream 65bd5b6e, which the corpus needs.
 *
 * Each case builds an LSRK SpecFrame or DSBSpecFrame in the given System
 * and Unit, with the listed settings, then (a) sets StdOfRest=HELIO on a
 * copy, printing its SpecOrigin or the error, and (b) converts the original
 * to a copy whose StdOfRest is HELIO, printing the converted value, or None
 * when no conversion is found, or the error.
 *
 * Prints Rust source for crates/ast-core/tests/spec_origin_sor_oracle/cases.rs:
 *
 *   ./spec_origin_sor_probe > ../../crates/ast-core/tests/spec_origin_sor_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"
#include "ast_err.h"

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

static const char *err_name( void ) {
   return astStatus == AST__ATSER ? "Atser" : "other";
}

int main( void ) {
   int status = 0;
   const char *classes[] = { "SpecFrame", "DSBSpecFrame", NULL };
   const char *systems[] = { "System=WAVE,Unit=Angstrom", "System=FREQ,Unit=GHz", NULL };
   const double values[] = { 13000000.0, 230.0 };
   const double origins[] = { 12990000.0, 229.0 };
   int c, s, off, org;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/spec_origin_sor_probe.c. Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// `(class, System settings, AlignSpecOffset, SpecOrigin or None, value\n"
           "/// converted, SpecOrigin after StdOfRest=HELIO or the error, converted\n"
           "/// value or None or the error)`.\n"
           "pub type Case = (&'static str, &'static str, bool, Option<f64>, f64,\n"
           "                 Result<Option<f64>, &'static str>, Result<Option<f64>, &'static str>);\n\n"
           "pub const CASES: &[Case] = &[\n" );
   for( c = 0; classes[ c ]; c++ ) {
      for( s = 0; systems[ s ]; s++ ) {
         for( off = 0; off < 2; off++ ) {
            for( org = 0; org < 2; org++ ) {
               AstFrame *f, *g, *h;
               AstFrameSet *fs;
               double out;
               /* AST takes a substituted %s as one attribute value, so the
                  settings are assembled first and passed as the format. */
               char opts[ 200 ];
               if( c ) {
                  sprintf( opts, "%s,StdOfRest=LSRK,Epoch=2005.0,IF=4,SideBand=LSB,"
                           "AlignSideBand=1", systems[ s ] );
                  f = (AstFrame *) astDSBSpecFrame( opts, " " );
               } else {
                  sprintf( opts, "%s,StdOfRest=LSRK,Epoch=2005.0", systems[ s ] );
                  f = (AstFrame *) astSpecFrame( opts, " " );
               }
               astSetRefPos( f, NULL, 2.6, 0.35 );
               if( c ) astSetD( f, "DSBCentre", values[ s ] );
               astSetI( f, "AlignSpecOffset", off );
               if( org ) astSetD( f, "SpecOrigin", origins[ s ] );

               printf( "    (\"%s\", \"%s\", %s, ", classes[ c ], systems[ s ],
                       off ? "true" : "false" );
               if( org ) {
                  printf( "Some(" ); num( origins[ s ] ); printf( ")" );
               } else {
                  printf( "None" );
               }
               printf( ", " ); num( values[ s ] ); printf( ", " );

               g = astCopy( f );
               astSet( g, "StdOfRest=HELIO" );
               if( !astOK ) {
                  printf( "Err(\"%s\")", err_name() );
                  astClearStatus;
               } else if( astTest( g, "SpecOrigin" ) ) {
                  printf( "Ok(Some(" ); num( astGetD( g, "SpecOrigin" ) ); printf( "))" );
               } else {
                  printf( "Ok(None)" );
               }
               printf( ", " );

               h = astCopy( f );
               astClear( h, "SpecOrigin" );
               astSet( h, "StdOfRest=HELIO" );
               if( org ) astSetD( h, "SpecOrigin", origins[ s ] );
               fs = astConvert( f, h, "" );
               if( !astOK ) {
                  printf( "Err(\"%s\")", err_name() );
                  astClearStatus;
               } else if( !fs ) {
                  printf( "Ok(None)" );
               } else {
                  astTran1( fs, 1, &values[ s ], 1, &out );
                  printf( "Ok(Some(" ); num( out ); printf( "))" );
               }
               printf( "),\n" );
            }
         }
      }
   }
   printf( "];\n" );
   return 0;
}
