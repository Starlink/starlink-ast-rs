/* axis_format_probe -- capture astFormat on a plain Frame axis for a corpus
 * of Format strings and values. C's AxisFormat (axis.c:637) rewrites the
 * Format with ParseAxisFormat, which removes the AST "&" log flag and
 * replaces a ".*" precision with Digits, and then hands the result to
 * sprintf with the value, cast to int for an integer conversion.
 *
 * Every Format here has at most one conversion, whose argument type matches
 * what AxisFormat passes. Values outside the int range are left out for an
 * integer conversion, where the cast is undefined, as are values between
 * -1 and 1 for a log integer conversion, and so are %c values
 * whose byte is not ASCII, which a Rust String cannot hold as one byte.
 *
 * Prints Rust source for crates/starlink-ast/tests/axis_format_oracle/cases.rs:
 *
 *   ./axis_format_probe > ../../crates/starlink-ast/tests/axis_format_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) {
         putchar( '\\' );
         putchar( *s );
      } else if( (unsigned char) *s < 0x20 || *s == 0x7f ) {
         printf( "\\u{%x}", (unsigned char) *s );
      } else {
         putchar( *s );
      }
   }
   putchar( '"' );
}

/* Whether formatting "v" with "fmt" is defined: an integer conversion
   casts the value to int, which is undefined outside its range. */
static int defined( const char *fmt, double v ) {
   const char *c = strrchr( fmt, '%' );
   for( ; c && *c; c++ ) {
      if( strchr( "diuoxXc", *c ) ) {
         if( v >= 2147483648.0 || v <= -2147483649.0 ) return 0;
         /* A log format takes log10 of the value cast to int, which is
            -inf for 0 < |v| < 1, and casting that back to int is
            undefined. */
         if( strchr( fmt, '&' ) && v != 0.0 && v > -1.0 && v < 1.0 ) return 0;
         if( *c == 'c' && (unsigned char) (int) v >= 0x80 ) return 0;
         return 1;
      }
      if( strchr( "eEfFgG", *c ) ) return 1;
   }
   return 1;
}

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".en" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

int main( void ) {
   int status = 0;
   const char *formats[] = {
      "%g", "%G", "%e", "%E", "%f", "%F", "%.0f", "%#.0f", "%.0e", "%#.0e",
      "%#G", "%#.3g", "%.3g", "%8.3f", "%-8.3f|", "%08.2f", "%-+8.2f|",
      "%+08.2f", "% 08.2f", "%+e", "% e", "%12.4E", "%-12.4e|",
      "%d", "%i", "%5d", "%-5d|", "%05d", "%+d", "% d", "%.3d", "%u",
      "%x", "%X", "%#x", "%o", "%#o", "%8.4x", "%c",
      "%&G", "%+&G", "% &G", "%&.3f", "%&d", "%-&8.2f|",
      "%.1f deg", "x=%g", "%.*f", "%10.*e", "%.*G", "100%%", "%g%%",
      "abc", "%1.7G", "%1.15G", NULL
   };
   double values[] = { 0.0, -0.0, 1.0, -1.0, 2.5, 0.5, -3.7, 65.0, 1000.0,
                       1234.5678, -0.000123456, 1.0e-5, 1.0e20, 123456789.0,
                       -98765.4321 };
   int nval = (int) ( sizeof( values ) / sizeof( values[ 0 ] ) );
   int i, j;
   AstFrame *f;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/axis_format_probe.c. Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// The Digits set on the Frame, which a `.*` precision takes.\n"
           "pub const DIGITS: i32 = 5;\n\n"
           "/// `(Format, value, astFormat result)`.\n"
           "pub const CASES: &[(&str, f64, &str)] = &[\n" );

   f = astFrame( 1, "Digits=5" );
   for( i = 0; formats[ i ]; i++ ) {
      astSetC( f, "Format(1)", formats[ i ] );
      for( j = 0; j < nval; j++ ) {
         if( !defined( formats[ i ], values[ j ] ) ) continue;
         const char *r = astFormat( f, 1, values[ j ] );
         printf( "    (" );
         str( formats[ i ] );
         printf( ", " );
         num( values[ j ] );
         printf( ", " );
         str( r ? r : "<null>" );
         printf( "),\n" );
      }
   }
   printf( "];\n" );
   return 0;
}
