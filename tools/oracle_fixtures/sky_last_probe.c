/* sky_last_probe -- capture AZEL conversions whose LAST C serves from its
 * caches: the LAST each SkyFrame keeps and extrapolates for Epoch changes
 * under 0.4 day (skyframe.c GetLAST), and the table of LAST values shared by
 * every SkyFrame, which interpolates between cached epochs less than 0.4 day
 * apart (GetCachedLAST, SetCachedLAST). The steps run in one process, in
 * order, so each sees the caches the earlier steps left.
 *
 * Epoch, ObsLat and ObsLon are set through the protected setters, which
 * take an MJD and radians, rather than through astSet, which would read
 * the observer position as a formatted angle.
 *
 * Prints Rust source for crates/starlink-ast/tests/sky_last_oracle/cases.rs:
 *
 *   ./sky_last_probe > ../../crates/starlink-ast/tests/sky_last_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern void astSetEpoch_( void *, double, int * );
extern void astSetObsLat_( void *, double, int * );
extern void astSetObsLon_( void *, double, int * );

static int status = 0;

static const double xin[ 3 ] = { 1.0, 4.2, 5.9 };
static const double yin[ 3 ] = { 0.5, -0.9, 1.3 };

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".en" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

/* Convert "from" to "to" and print the three points transformed. */
static void step( const char *name, AstSkyFrame *from, AstSkyFrame *to ) {
   AstFrameSet *fs;
   double xout[ 3 ], yout[ 3 ];
   int i;

   fs = astConvert( from, to, "" );
   astTran2( fs, 3, xin, yin, 1, xout, yout );
   fs = astAnnul( fs );
   printf( "    (\"%s\", [", name );
   for( i = 0; i < 3; i++ ) {
      printf( "[" );
      num( xout[ i ] );
      printf( ", " );
      num( yout[ i ] );
      printf( "]%s", i < 2 ? ", " : "" );
   }
   printf( "]),\n" );
}

static void set_epoch( AstSkyFrame *f, double mjd ) {
   astSetEpoch_( astMakePointer( f ), mjd, &status );
}

static void set_obslon( AstSkyFrame *f, double lon ) {
   astSetObsLon_( astMakePointer( f ), lon, &status );
}

static AstSkyFrame *sky( const char *system, double epoch, double obslon ) {
   AstSkyFrame *f = astSkyFrame( " " );
   astSetC( f, "System", system );
   set_epoch( f, epoch );
   astSetObsLat_( astMakePointer( f ), 0.3459, &status );
   set_obslon( f, obslon );
   return f;
}

int main( void ) {
   AstSkyFrame *azel, *icrs, *a, *b, *copy;
   const double e0 = 55300.25, lon = -2.7135;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/sky_last_probe.c. Do not edit.\n\n"
           "// Each value is printed with 17 digits so that it reads back exactly.\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "/// The points every step transforms.\n"
           "pub const POINTS: [[f64; 2]; 3] = [[1.0, 0.5], [4.2, -0.9], [5.9, 1.3]];\n\n"
           "/// The first Epoch (MJD) and the observer longitude (radians).\n"
           "pub const E0: f64 = 55300.25;\n"
           "pub const LON: f64 = -2.7135;\n\n"
           "/// `(step, transformed points)`, in the order the probe runs them.\n"
           "pub const STEPS: &[(&str, [[f64; 2]; 3])] = &[\n" );

   /* One pair of SkyFrames whose Epoch moves, as a pipeline moves it per
      time slice. */
   azel = sky( "AZEL", 0.0, lon );
   icrs = sky( "ICRS", 0.0, lon );
   set_epoch( azel, e0 );
   set_epoch( icrs, e0 );
   step( "pair_e0", azel, icrs );
   set_epoch( azel, e0 + 0.1 );
   set_epoch( icrs, e0 + 0.1 );
   step( "pair_plus_0.1", azel, icrs );
   set_epoch( azel, e0 + 0.5 );
   set_epoch( icrs, e0 + 0.5 );
   step( "pair_plus_0.5", azel, icrs );
   set_epoch( azel, e0 + 0.45 );
   set_epoch( icrs, e0 + 0.45 );
   step( "pair_plus_0.45", azel, icrs );
   step( "pair_reverse", icrs, azel );

   /* New SkyFrames, which start with no LAST of their own and so draw on
      the shared table. */
   a = sky( "AZEL", 0.0, lon );
   b = sky( "ICRS", 0.0, lon );
   set_epoch( a, e0 + 0.25 );
   set_epoch( b, e0 + 0.25 );
   step( "fresh_plus_0.25", a, b );
   set_epoch( a, e0 );
   set_epoch( b, e0 );
   step( "fresh_e0", a, b );
   a = astAnnul( a );
   b = astAnnul( b );

   /* Another observer longitude has a table of its own. */
   a = sky( "AZEL", 0.0, lon + 0.5 );
   b = sky( "ICRS", 0.0, lon + 0.5 );
   set_epoch( a, e0 + 0.25 );
   set_epoch( b, e0 + 0.25 );
   step( "other_lon_plus_0.25", a, b );
   a = astAnnul( a );
   b = astAnnul( b );

   /* A conversion with no AZEL frame still computes and caches LAST. */
   a = sky( "FK5", 0.0, lon );
   b = sky( "ICRS", 0.0, lon );
   set_epoch( a, e0 + 2.0 );
   set_epoch( b, e0 + 2.3 );
   step( "fk5_plus_2", a, b );
   a = astAnnul( a );
   b = astAnnul( b );
   a = sky( "AZEL", 0.0, lon );
   b = sky( "ICRS", 0.0, lon );
   set_epoch( a, e0 + 2.1 );
   set_epoch( b, e0 + 2.1 );
   step( "azel_after_fk5", a, b );
   a = astAnnul( a );
   b = astAnnul( b );

   /* A copy keeps the LAST of the SkyFrame it was copied from. */
   copy = astCopy( azel );
   set_epoch( copy, e0 + 0.6 );
   step( "copy_plus_0.6", copy, icrs );
   copy = astAnnul( copy );

   /* Changing the observer discards a SkyFrame's own LAST. */
   set_obslon( azel, lon + 0.5 );
   set_obslon( icrs, lon + 0.5 );
   set_epoch( azel, e0 + 0.35 );
   set_epoch( icrs, e0 + 0.35 );
   step( "pair_new_lon_plus_0.35", azel, icrs );

   printf( "];\n" );
   azel = astAnnul( azel );
   icrs = astAnnul( icrs );
   return 0;
}
