/* region_attrib_probe -- capture the dumps of Regions after a Frame
 * attribute is set or cleared through them (region.c SetAttrib and
 * ClearAttrib): through the FrameSet, remapping the Region, when it is
 * Adaptive, and otherwise through RegSetAttrib/RegClearAttrib, which make
 * the change to the current Frame, the base Frame (on the base-Frame axis
 * the current-Frame axis is connected to) and the uncertainty, and which
 * CmpRegion and Prism extend to their components. Also whether the point
 * (0.5, 0.5) is inside the Box, whose axes are in metres before Unit(1) is
 * set to km. The "permuted_box" case is the Box before Label(1) is set in
 * "label_after_permaxes".
 *
 * Prints Rust source for crates/starlink-ast/tests/region_attrib_oracle/cases.rs:
 *
 *   ./region_attrib_probe > ../../crates/starlink-ast/tests/region_attrib_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static char dump[ 20000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

static void emit( const char *name, AstObject *obj, int inside ) {
   AstChannel *ch;
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   printf( "    (\"%s\", %d, ", name, inside );
   str( dump );
   printf( "),\n" );
}

/* Whether (0.5, 0.5) is inside a 2-D Region: 1, 0, or -1 when not 2-D. */
static int inside( AstRegion *reg ) {
   double x = 0.5, y = 0.5, xo, yo;
   if( astGetI( reg, "Naxes" ) != 2 ) return -1;
   astTran2( reg, 1, &x, &y, 1, &xo, &yo );
   return xo != AST__BAD;
}

/* The unit square in a Frame with axes in metres and ActiveUnit set. */
static AstRegion *metre_box( void ) {
   double l[] = { 0.0, 0.0 }, u[] = { 1.0, 1.0 };
   AstFrame *f = astFrame( 2, "Unit(1)=m,Unit(2)=m" );
   astSetActiveUnit( f, 1 );
   return (AstRegion *) astBox( f, 1, l, u, NULL, " " );
}

static AstRegion *unit_box( double x0, double y0, double x1, double y1, AstRegion *unc ) {
   double l[ 2 ], u[ 2 ];
   l[ 0 ] = x0; l[ 1 ] = y0; u[ 0 ] = x1; u[ 1 ] = y1;
   return (AstRegion *) astBox( astFrame( 2, " " ), 1, l, u, unc, " " );
}

int main( void ) {
   int status = 0;
   AstRegion *reg;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_attrib_probe.c. Do not edit.\n\n"
           "/// `(case, whether (0.5, 0.5) is inside (-1 if not 2-D), C's dump)`.\n"
           "pub const CASES: &[(&str, i32, &str)] = &[\n" );

   reg = metre_box();
   astSetI( reg, "Adaptive", 1 );
   astSetC( reg, "Unit(1)", "km" );
   emit( "unit_km_adaptive", (AstObject *) reg, inside( reg ) );

   reg = metre_box();
   astSetI( reg, "Adaptive", 0 );
   astSetC( reg, "Unit(1)", "km" );
   emit( "unit_km_not_adaptive", (AstObject *) reg, inside( reg ) );

   reg = metre_box();
   astSetI( reg, "Adaptive", 0 );
   astSetC( reg, "Unit(1)", "km" );
   astClear( reg, "Unit(1)" );
   emit( "unit_cleared_not_adaptive", (AstObject *) reg, inside( reg ) );

   /* A Box whose current-Frame axes are permuted, so Label(1) of the
      current Frame is Label(2) of the base Frame. */
   {
      int perm[] = { 2, 1 };
      reg = unit_box( 0.0, 0.0, 1.0, 2.0, NULL );
      astPermAxes( reg, perm );
      emit( "permuted_box", (AstObject *) reg, inside( reg ) );
      astSetI( reg, "Adaptive", 0 );
      astSetC( reg, "Label(1)", "Swapped" );
      emit( "label_after_permaxes", (AstObject *) reg, inside( reg ) );
   }

   /* A Box with an explicit uncertainty. */
   reg = unit_box( 0.0, 0.0, 1.0, 1.0, unit_box( 0.0, 0.0, 0.01, 0.01, NULL ) );
   astSetI( reg, "Adaptive", 0 );
   astSetC( reg, "Label(2)", "Second" );
   astSetC( reg, "Title", "Titled" );
   emit( "label_and_title_with_uncertainty", (AstObject *) reg, inside( reg ) );

   /* A CmpRegion and a Prism pass the change on to their components. */
   reg = (AstRegion *) astCmpRegion( unit_box( 0.0, 0.0, 1.0, 1.0, NULL ),
                                     unit_box( 0.5, 0.5, 2.0, 2.0, NULL ),
                                     AST__OR, " " );
   astSetI( reg, "Adaptive", 0 );
   astSetC( reg, "Label(1)", "Joined" );
   emit( "label_cmpregion", (AstObject *) reg, inside( reg ) );

   {
      double zl[] = { 0.0 }, zu[] = { 1.0 };
      reg = (AstRegion *) astPrism( unit_box( 0.0, 0.0, 1.0, 1.0, NULL ),
                                    astInterval( astFrame( 1, " " ), zl, zu, NULL, " " ),
                                    " " );
      astSetI( reg, "Adaptive", 0 );
      astSetC( reg, "Label(3)", "Height" );
      astSetC( reg, "Symbol(1)", "X" );
      emit( "labels_prism", (AstObject *) reg, inside( reg ) );
   }

   printf( "];\n" );
   return status;
}
