/* sky_convert_probe -- capture the Mapping astConvert finds between two
 * SkyFrames (skyframe.c Match, SubFrame, MakeSkyMapping), for every pair of
 * celestial coordinate systems, under a range of alignment systems, with
 * the two Frames differing in Epoch, Equinox and observer position.
 *
 * Each case transforms three points with the connecting Mapping and prints
 * the results, or "None" when astConvert finds no conversion.
 *
 * Epoch, Equinox, ObsLat and ObsLon are set through the protected setters,
 * which take the stored values (MJD, radians) directly, so the Rust test
 * sets exactly the same values.
 *
 * Prints Rust source for crates/starlink-ast/tests/sky_convert_oracle/cases.rs:
 *
 *   ./sky_convert_probe > ../../crates/starlink-ast/tests/sky_convert_oracle/cases.rs
 */
#include <float.h>
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern void astSetEpoch_( void *, double, int * );
extern void astSetEquinox_( void *, double, int * );
extern void astSetObsLat_( void *, double, int * );
extern void astSetObsLon_( void *, double, int * );

static const char *systems[] = {
   "ICRS", "FK4", "FK4-NO-E", "FK5", "J2000", "GAPPT", "ECLIPTIC",
   "HELIOECLIPTIC", "GALACTIC", "SUPERGALACTIC", "AZEL", "UNKNOWN"
};
#define NSYS ( (int) ( sizeof( systems ) / sizeof( systems[ 0 ] ) ) )

/* Alignment systems set on the template (the "to" Frame); NULL leaves
   AlignSystem unset (ICRS). */
static const char *aligns[] = {
   NULL, "FK4", "FK4-NO-E", "FK5", "J2000", "GAPPT", "ECLIPTIC",
   "HELIOECLIPTIC", "GALACTIC", "AZEL"
};
#define NALIGN ( (int) ( sizeof( aligns ) / sizeof( aligns[ 0 ] ) ) )

/* Frame properties: { epoch MJD, equinox MJD, obslat rad, obslon rad }.
   Configuration 0 differs in everything; configuration 1 shares the
   epoch and observer and differs only in equinox. */
static const double from_props[ 2 ][ 4 ] = {
   { 55300.25, 42413.5, 0.3459, -2.7135 },
   { 51544.5, 42413.5, 0.3459, -2.7135 },
};
static const double to_props[ 2 ][ 4 ] = {
   { 49900.75, 62502.0, -0.5013, 1.2345 },
   { 51544.5, 62502.0, 0.3459, -2.7135 },
};

static const double points[ 3 ][ 2 ] = {
   { 1.0, 0.5 }, { 4.2, -0.9 }, { 5.9, 1.3 }
};

static void flit( double value ) {
   char buf[ 40 ];
   if( value == AST__BAD ) { fputs( "BAD", stdout ); return; }
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

static AstSkyFrame *make( const char *sys, const double props[ 4 ] ) {
   int status = 0;
   AstSkyFrame *f = astSkyFrame( " " );
   astSetC( f, "System", sys );
   astSetEpoch_( astMakePointer( f ), props[ 0 ], &status );
   astSetEquinox_( astMakePointer( f ), props[ 1 ], &status );
   astSetObsLat_( astMakePointer( f ), props[ 2 ], &status );
   astSetObsLon_( astMakePointer( f ), props[ 3 ], &status );
   return f;
}

static void props_lit( const double p[ 4 ] ) {
   printf( "[" );
   for( int i = 0; i < 4; i++ ) { if( i ) printf( ", " ); flit( p[ i ] ); }
   printf( "]" );
}

int main( void ) {
   int status = 0, c, a, i, j, k;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/sky_convert_probe.c against\n"
           "// the C library at u/timj/norm-unit 5a2cac2a, past the submodule pin.\n"
           "// Do not edit.\n\n"
           "// Each value is printed with 17 digits so that it reads back exactly.\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "#[allow(unused_imports)]\n"
           "use starlink_ast::constants::BAD_VALUE as BAD;\n\n"
           "/// `[epoch MJD, equinox MJD, obslat rad, obslon rad]` of the source\n"
           "/// (\"from\") Frame, per configuration.\n"
           "pub const FROM_PROPS: [[f64; 4]; 2] = [" );
   props_lit( from_props[ 0 ] ); printf( ", " ); props_lit( from_props[ 1 ] );
   printf( "];\n\n/// The same for the destination (\"to\") Frame.\n"
           "pub const TO_PROPS: [[f64; 4]; 2] = [" );
   props_lit( to_props[ 0 ] ); printf( ", " ); props_lit( to_props[ 1 ] );
   printf( "];\n\n/// The points transformed by every case.\n"
           "pub const POINTS: [[f64; 2]; 3] = [" );
   for( i = 0; i < 3; i++ ) {
      if( i ) printf( ", " );
      printf( "[" ); flit( points[ i ][ 0 ] ); printf( ", " );
      flit( points[ i ][ 1 ] ); printf( "]" );
   }
   printf( "];\n\n"
           "/// `(configuration, from System, to System, to AlignSystem, transformed\n"
           "/// points)`; `None` when astConvert finds no conversion.\n"
           "pub type ConvertCase = (usize, &'static str, &'static str, Option<&'static str>,\n"
           "                        Option<[[f64; 2]; 3]>);\n\n"
           "pub const CASES: &[ConvertCase] = &[\n" );

   for( c = 0; c < 2; c++ ) {
      for( a = 0; a < NALIGN; a++ ) {
         if( c == 1 && a > 0 ) break;
         for( i = 0; i < NSYS; i++ ) {
            for( j = 0; j < NSYS; j++ ) {
               AstSkyFrame *from, *to;
               AstFrameSet *fs;
               from = make( systems[ i ], from_props[ c ] );
               to = make( systems[ j ], to_props[ c ] );
               if( aligns[ a ] ) astSetC( to, "AlignSystem", aligns[ a ] );
               fs = astConvert( from, to, "" );
               if( !astOK ) {
                  fprintf( stderr, "error: %d %s %s %s\n", c, systems[ i ],
                           systems[ j ], aligns[ a ] ? aligns[ a ] : "-" );
                  return 1;
               }
               printf( "    (%d, \"%s\", \"%s\", ", c, systems[ i ], systems[ j ] );
               if( aligns[ a ] ) printf( "Some(\"%s\"), ", aligns[ a ] );
               else printf( "None, " );
               if( !fs ) {
                  printf( "None),\n" );
               } else {
                  double xin[ 3 ], yin[ 3 ], xout[ 3 ], yout[ 3 ];
                  for( k = 0; k < 3; k++ ) {
                     xin[ k ] = points[ k ][ 0 ];
                     yin[ k ] = points[ k ][ 1 ];
                  }
                  astTran2( fs, 3, xin, yin, 1, xout, yout );
                  printf( "Some([" );
                  for( k = 0; k < 3; k++ ) {
                     if( k ) printf( ", " );
                     printf( "[" ); flit( xout[ k ] ); printf( ", " );
                     flit( yout[ k ] ); printf( "]" );
                  }
                  printf( "])),\n" );
                  fs = astAnnul( fs );
               }
               from = astAnnul( from );
               to = astAnnul( to );
            }
         }
      }
   }
   printf( "];\n" );
   return 0;
}
