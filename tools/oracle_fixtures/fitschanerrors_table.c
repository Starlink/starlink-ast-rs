/* fitschanerrors_table -- print the bad-header table of testfitschanerrors.c
 * as Rust source, so the Rust port runs exactly C's cases.
 *
 * The C test is included with its main() renamed, so its table is the one
 * source of truth. Strings are escaped for an ordinary Rust string literal;
 * a non-printing character becomes a \x escape. Error statuses are printed
 * as the ErrorCode variants the Rust port names them by.
 *
 * Built and run from the reference library's build directory:
 *
 *   cc -I. ../../../tools/oracle_fixtures/fitschanerrors_table.c \
 *      -o fitschanerrors_table -L. -last -lm -Wl,-rpath,$PWD
 *   ./fitschanerrors_table \
 *      > ../../../crates/starlink-ast/tests/fitschanerrors_oracle/cases.rs
 */
#define main testfitschanerrors_main
#include "../../reference/starlink-ast/ast_tester/testfitschanerrors.c"
#undef main

static void rust_string( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      unsigned char c = (unsigned char) *s;
      if( c == '"' || c == '\\' ) {
         printf( "\\%c", c );
      } else if( c == '\n' ) {
         printf( "\\n" );
      } else if( c < 0x20 || c >= 0x7f ) {
         printf( "\\x%02x", c );
      } else {
         putchar( c );
      }
   }
   putchar( '"' );
}

static void option_string( const char *s ) {
   if( s ) {
      printf( "Some(" );
      rust_string( s );
      printf( ")" );
   } else {
      printf( "None" );
   }
}

static const char *error_name( int status ) {
   switch( status ) {
      case 0: return "None";
      case AST__RDERR: return "Some(ErrorCode::Rderr)";
      case AST__BDFTS: return "Some(ErrorCode::Bdfts)";
      case AST__BADAT: return "Some(ErrorCode::Badat)";
      case AST__NOWRT: return "Some(ErrorCode::Nowrt)";
   }
   fprintf( stderr, "unmapped error status %d\n", status );
   exit( 1 );
}

int main( void ) {
   size_t i;
   printf( "// Generated by tools/oracle_fixtures/fitschanerrors_table.c from the\n"
           "// table in reference/starlink-ast/ast_tester/testfitschanerrors.c.\n\n"
           "use super::BadHeaderTest;\n"
           "use starlink_ast::error::ErrorCode;\n\n"
           "pub(super) const CASES: &[BadHeaderTest] = &[\n" );
   for( i = 0; i < NTESTS; i++ ) {
      const BadHeaderTest *t = &bad_headers[ i ];
      printf( "    BadHeaderTest {\n        name: " );
      rust_string( t->name );
      printf( ",\n        cards: " );
      rust_string( t->cards );
      printf( ",\n        warn_cat: " );
      option_string( t->warn_cat );
      printf( ",\n        expect_error: %s,\n        expect_text: ",
              error_name( t->expect_error ) );
      option_string( t->expect_text );
      printf( ",\n        skip_read: %s,\n        attrs: ",
              t->skip_read ? "true" : "false" );
      option_string( t->attrs );
      printf( ",\n        write_enc: " );
      option_string( t->write_enc );
      printf( ",\n    },\n" );
   }
   printf( "];\n" );
   return 0;
}
