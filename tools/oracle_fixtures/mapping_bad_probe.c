/* mapping_bad_probe -- capture how NormMaps, ShiftMaps and MatrixMaps
 * treat bad values: a NormMap normalises every point, so a SkyFrame still
 * wraps the longitude of a point whose latitude is bad (normmap.c
 * Transform); a bad shift makes its axis bad (shiftmap.c Transform); and a
 * MatrixMap ignores a bad input where its element is zero in a full matrix
 * but not in a diagonal one, and a bad element makes its output bad
 * (matrixmap.c Transform).
 *
 * The port takes a NaN input to be a bad value (CLAUDE.md), where C tests
 * inputs against AST__BAD only, so a NaN input meets a zero MatrixMap
 * element as 0*NaN. The points list NaN where the port is given NaN, and C
 * is given AST__BAD there, so each case checks the port's NaN against C's
 * bad value.
 *
 * Each case is the dump C wrote, input points with a bad or NaN value on
 * one axis at a time, and the forward and inverse transformations of them
 * (the inverse only when the Mapping has one). AST_REPLACE_NAN is set to 1,
 * so C turns NaN outputs into AST__BAD (pointset.c ReplaceNaN), as the
 * port always does.
 *
 * Prints Rust source for crates/starlink-ast/tests/mapping_bad_oracle/cases.rs:
 *
 *   ./mapping_bad_probe > ../../crates/starlink-ast/tests/mapping_bad_oracle/cases.rs
 */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

#define BAD AST__BAD
#define NP 7

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void print_dump( const char *line ) {
   printf( "            " );
   str( line );
   printf( ",\n" );
}

/* Print a value as a Rust f64 expression, with the fewest digits that read
   back as the same value. */
static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   if( isnan( v ) ) {
      printf( "f64::NAN" );
      return;
   }
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

/* Print an array of values between "open" and "close". */
static void values( const char *open, int n, const double *v,
                    const char *close ) {
   int i;
   printf( "        %s", open );
   for( i = 0; i < n; i++ ) {
      if( i ) printf( ", " );
      lit( v[ i ] );
   }
   printf( "%s,\n", close );
}

/* Transform "npoint" points given point by point. */
static void tran( AstMapping *map, int forward, int npoint, const double *in,
                  double *out ) {
   double in_t[ 64 ], out_t[ 64 ];
   int i, k, nin, nout;
   nin = astGetI( map, forward ? "Nin" : "Nout" );
   nout = astGetI( map, forward ? "Nout" : "Nin" );
   for( i = 0; i < npoint; i++ ) {
      for( k = 0; k < nin; k++ ) {
         in_t[ k*npoint + i ] = isnan( in[ i*nin + k ] ) ? BAD : in[ i*nin + k ];
      }
   }
   astTranN( map, npoint, nin, npoint, in_t, forward, nout, npoint, out_t );
   for( i = 0; i < npoint; i++ ) {
      for( k = 0; k < nout; k++ ) out[ i*nout + k ] = out_t[ k*npoint + i ];
   }
}

/* Emit a case. "in" holds NP points, each with as many values as the
   Mapping has inputs, used in both directions. */
static void emit( const char *name, AstMapping *map, const double *in ) {
   AstChannel *ch;
   double out[ 64 ];
   int nin = astGetI( map, "Nin" ), nout = astGetI( map, "Nout" );

   printf( "    (\n        \"%s\",\n        &[\n", name );
   ch = astChannel( NULL, print_dump, " " );
   astWrite( ch, map );
   ch = astAnnul( ch );
   printf( "        ],\n" );
   values( "&[", NP*nin, in, "]" );
   tran( map, 1, NP, in, out );
   values( "&[", NP*nout, out, "]" );
   if( astGetI( map, "TranInverse" ) ) {
      tran( map, 0, NP, in, out );
      values( "Some(&[", NP*nin, out, "])" );
   } else {
      printf( "        None,\n" );
   }
   printf( "    ),\n" );
   map = astAnnul( map );
}

int main( void ) {
   double nan = strtod( "nan", NULL );
   double in2[] = { 7.0, BAD, BAD, 0.3, -1.0, 2.0, 7.0, nan, nan, 0.2,
                    3.0, 0.1, BAD, BAD };
   double in3[] = { 7.0, BAD, 5.0, BAD, 0.3, 5.0, -1.0, 2.0, BAD, 7.0, nan, 1.0,
                    nan, 0.2, 2.0, 3.0, 0.1, nan, BAD, BAD, BAD };
   int status = 0;
   setenv( "AST_REPLACE_NAN", "1", 1 );
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/mapping_bad_probe.c. Do not edit.\n\n"
           "/// `(case, the dump, input points, forward outputs, inverse outputs\n"
           "/// of the same inputs when there is an inverse)`, the points given\n"
           "/// point by point.\n"
           "pub type Case = (\n"
           "    &'static str,\n"
           "    &'static [&'static str],\n"
           "    &'static [f64],\n"
           "    &'static [f64],\n"
           "    Option<&'static [f64]>,\n"
           ");\n\n"
           "pub const CASES: &[Case] = &[\n" );

   emit( "normmap_skyframe",
         (AstMapping *) astNormMap( astSkyFrame( " " ), " " ), in2 );
   emit( "normmap_cmpframe",
         (AstMapping *) astNormMap( astCmpFrame( astSkyFrame( " " ),
                                                 astFrame( 1, " " ), " " ),
                                    " " ), in3 );
   {
      double shift[] = { BAD, 1.5 };
      emit( "shiftmap_bad_shift", (AstMapping *) astShiftMap( 2, shift, " " ), in2 );
   }
   {
      double diag[] = { 0.0, 2.0 };
      emit( "matrixmap_diagonal_zero", (AstMapping *) astMatrixMap( 2, 2, 1, diag, " " ),
            in2 );
   }
   {
      double diag[] = { BAD, 2.0 };
      emit( "matrixmap_diagonal_bad", (AstMapping *) astMatrixMap( 2, 2, 1, diag, " " ),
            in2 );
   }
   {
      double m[] = { 1.0, 0.5, 0.0, 2.0 };
      emit( "matrixmap_full_zero", (AstMapping *) astMatrixMap( 2, 2, 0, m, " " ), in2 );
   }
   {
      double m[] = { 1.0, BAD, 0.0, 2.0 };
      emit( "matrixmap_full_bad", (AstMapping *) astMatrixMap( 2, 2, 0, m, " " ), in2 );
   }

   printf( "];\n" );
   return status;
}
