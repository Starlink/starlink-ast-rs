/* region_box_probe -- capture which test points a Box contains (box.c
 * Transform): a Box in an ICRS SkyFrame whose corner wraps through RA 0,
 * whose extent C takes as the axis distance from centre to corner (Cache);
 * and a Box of zero width on one axis, un-negated, negated and open, and
 * negated and closed, where Transform widens the limits to the width of
 * the uncertainty only when Negated and Closed differ. Also the sky Box's
 * bounding box, and the boundary meshes (box.c RegBaseMesh) of a flat 2-D
 * Box, one whose axes have different units, a sky Box, a 3-D Box and a
 * single-point Box, which needs box.c from 4785102b or later.
 *
 * The zero-width cases need box.c from d0853dcd or later, before which the
 * widening depended on whether the limits had been cached first.
 *
 * Prints Rust source for crates/starlink-ast/tests/region_box_oracle/cases.rs:
 *
 *   ./region_box_probe > ../../crates/starlink-ast/tests/region_box_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

/* One case: `(name, membership of each test point as '1' or '0')`. */
static void emit( const char *name, AstRegion *reg, int np, const double *x,
                  const double *y ) {
   double xo[ 10 ], yo[ 10 ];
   int i;
   astTran2( reg, np, x, y, 1, xo, yo );
   printf( "    (\"%s\", \"", name );
   for( i = 0; i < np; i++ ) putchar( xo[ i ] == AST__BAD ? '0' : '1' );
   printf( "\"),\n" );
}

/* One mesh case, the current-Frame mesh (astGetRegionMesh) point by point. */
static void mesh( const char *name, AstRegion *reg ) {
   static double m[ 3 * 4000 ];
   int np, nax, ip, ic;
   nax = astGetI( reg, "Naxes" );
   astGetRegionMesh( reg, 1, 4000, nax, &np, m );
   printf( "    (\"%s\", &[", name );
   for( ip = 0; ip < np; ip++ ) {
      for( ic = 0; ic < nax; ic++ ) {
         lit( m[ ic*4000 + ip ] );
         printf( ", " );
      }
   }
   printf( "]),\n" );
}

int main( void ) {
   int status = 0, i;
   AstRegion *reg;
   double skyx[] = { 3.0, 6.28, 0.02, 6.0 }, skyy[] = { 0.5, 0.51, 0.51, 0.51 };
   double zx[] = { 1.5, 1.5, 1.5, 1.5 }, zy[] = { 5.0, 5.0 + 1.0E-12, 5.0 + 1.0E-6, 5.0 + 1.0E-3 };
   double lb[ 2 ], ub[ 2 ];

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_box_probe.c. Do not edit.\n\n"
           "/// The sky test points.\n"
           "pub const SKY_X: [f64; 4] = [3.0, 6.28, 0.02, 6.0];\n"
           "pub const SKY_Y: [f64; 4] = [0.5, 0.51, 0.51, 0.51];\n"
           "/// The zero-width test points: x = 1.5, y just above 5.\n"
           "pub const ZERO_Y: [f64; 4] = [5.0, 5.0 + 1.0e-12, 5.0 + 1.0e-6, 5.0 + 1.0e-3];\n\n"
           "/// `(case, membership of each test point)`.\n"
           "pub const CASES: &[(&str, &str)] = &[\n" );
   {
      double cen[] = { 6.27, 0.5 }, cor[] = { 0.037, 0.52 };
      reg = (AstRegion *) astBox( astSkyFrame( "System=ICRS" ), 0, cen, cor, NULL, " " );
      emit( "sky_box", reg, 4, skyx, skyy );
      astGetRegionBounds( reg, lb, ub );
   }
   {
      double l[] = { 1.0, 5.0 }, u[] = { 2.0, 5.0 };
      AstFrame *f = astFrame( 2, " " );
      reg = (AstRegion *) astBox( f, 1, l, u, NULL, " " );
      emit( "zero_width", reg, 4, zx, zy );
      reg = (AstRegion *) astBox( f, 1, l, u, NULL, "Closed=0" );
      astNegate( reg );
      emit( "zero_width_negated_open", reg, 4, zx, zy );
      reg = (AstRegion *) astBox( f, 1, l, u, NULL, " " );
      astNegate( reg );
      emit( "zero_width_negated_closed", reg, 4, zx, zy );
   }
   printf( "];\n\n/// `(case, the boundary mesh: the points in turn, each axis in turn)`.\n"
           "pub const MESHES: &[(&str, &[f64])] = &[\n" );
   {
      double l[] = { 0.0, 0.0 }, u[] = { 3.0, 1.0 };
      mesh( "flat", (AstRegion *) astBox( astFrame( 2, " " ), 1, l, u, NULL, " " ) );
      mesh( "mixed_units", (AstRegion *) astBox( astFrame( 2, "Unit(1)=Hz,Unit(2)=m" ),
                                                 1, l, u, NULL, " " ) );
   }
   {
      double l[] = { 1.0, 0.2 }, u[] = { 1.3, 0.4 };
      mesh( "sky", (AstRegion *) astBox( astSkyFrame( "System=ICRS" ), 1, l, u, NULL, " " ) );
   }
   {
      double l[] = { 0.0, 0.0, 0.0 }, u[] = { 1.0, 2.0, 3.0 };
      mesh( "three_d", (AstRegion *) astBox( astFrame( 3, " " ), 1, l, u, NULL, " " ) );
   }
   {
      double l[] = { 1.0, 3.0 }, u[] = { 1.0, 3.0 };
      mesh( "single_point", (AstRegion *) astBox( astFrame( 2, " " ), 1, l, u, NULL, " " ) );
   }
   printf( "];\n\n/// The sky Box's bounding box: lower, then upper.\n"
           "pub const SKY_BOUNDS: [f64; 4] = [" );
   for( i = 0; i < 2; i++ ) { lit( lb[ i ] ); printf( ", " ); }
   lit( ub[ 0 ] ); printf( ", " ); lit( ub[ 1 ] );
   printf( "];\n" );
   return status;
}
