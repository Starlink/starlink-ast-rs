/* frameset_variants_probe -- capture the dumps of FrameSets whose current
 * Frame has variants (astAddVariant), for a current Frame of each kind:
 * a Frame, a SkyFrame, a SpecFrame and a CmpFrame, and a Frame with Digits
 * set, whose value the FrameSet's own Frame part shows, unset, through its
 * astGetDigits (frameset.c GetDigits). frame.c Dump writes the
 * variants FrameSet as "Vrnts", last in the Frame class's part, so for a
 * subclass of Frame it comes before the "IsA Frame" marker. For each, the
 * dump, the dump of what is read back from it, and the dump written with
 * Full set to 1, less the lines holding the state of the C process rather
 * than of the Object: the unset RefCnt and Nobj of each Object part
 * (object.c Dump). It needs frameset.c as fixed upstream at 5ac21af5.
 *
 * Prints Rust source for crates/starlink-ast/tests/frameset_variants_oracle/cases.rs:
 *
 *   ./frameset_variants_probe > ../../crates/starlink-ast/tests/frameset_variants_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static char dump[ 200000 ];
static int full;

static void sink( const char *line ) {
   char key[ 32 ];
   if( full && sscanf( line, "# %31[A-Za-z] = ", key ) == 1 &&
       ( !strcmp( key, "RefCnt" ) || !strcmp( key, "Nobj" ) ) ) return;
   strcat( dump, line );
   strcat( dump, "\n" );
}

static char reload_buf[ 200000 ];
static const char *next_line;

static const char *source( void ) {
   static char line[ 4000 ];
   const char *nl;
   size_t n;
   if( !next_line || !*next_line ) return NULL;
   nl = strchr( next_line, '\n' );
   n = nl ? (size_t)( nl - next_line ) : strlen( next_line );
   memcpy( line, next_line, n );
   line[ n ] = 0;
   next_line = nl ? nl + 1 : next_line + n;
   return line;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

/* Dump `obj` with Full set to `f`. */
static const char *dumped( AstObject *obj, int f ) {
   AstChannel *ch;
   dump[ 0 ] = 0;
   full = f;
   ch = astChannel( NULL, sink, "Full=%d", f );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   return dump;
}

/* `(case, dump, dump read back, dump with Full = 1)`. */
static void emit( const char *name, AstFrame *current ) {
   AstFrameSet *fs;
   AstChannel *ch;
   AstObject *back;

   fs = astFrameSet( astFrame( astGetI( current, "Naxes" ), "Domain=PIX" ), " " );
   astAddFrame( fs, AST__BASE, astUnitMap( astGetI( current, "Naxes" ), " " ),
                current );
   astAddVariant( fs, astZoomMap( astGetI( current, "Naxes" ), 2.0, " " ), "Two" );

   printf( "    (\"%s\",\n        ", name );
   str( dumped( (AstObject *) fs, 0 ) );
   strcpy( reload_buf, dump );
   next_line = reload_buf;
   ch = astChannel( source, NULL, " " );
   back = astRead( ch );
   ch = astAnnul( ch );
   printf( ",\n        " );
   str( dumped( back, 0 ) );
   printf( ",\n        " );
   str( dumped( (AstObject *) fs, 1 ) );
   printf( "),\n" );
}

int main( void ) {
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/frameset_variants_probe.c. Do not edit.\n\n" );
   printf( "/// `(case, dump, dump of the FrameSet read back, dump written with Full = 1\n" );
   printf( "/// less the unset RefCnt and Nobj)`.\n" );
   printf( "pub const CASES: &[(&str, &str, &str, &str)] = &[\n" );
   emit( "frame", astFrame( 2, "Domain=CUR" ) );
   emit( "skyframe", (AstFrame *) astSkyFrame( "Domain=SKY" ) );
   emit( "specframe", (AstFrame *) astSpecFrame( "Domain=SPEC" ) );
   emit( "cmpframe", (AstFrame *) astCmpFrame( astFrame( 1, "Domain=A" ),
                                              astFrame( 1, "Domain=B" ), " " ) );
   emit( "frame_digits", astFrame( 2, "Domain=CUR,Digits=4" ) );
   printf( "];\n" );
   return status;
}
