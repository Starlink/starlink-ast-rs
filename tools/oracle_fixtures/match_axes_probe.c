/* match_axes_probe -- capture what astMatchAxes( frm1, frm2, axes ) returns
 * for every pair from a fixed list of Frames, so that each class's
 * MatchAxesX (frame.c, skyframe.c, cmpframe.c, frameset.c, region.c) is
 * exercised as frm2 against each kind of frm1.
 *
 * Prints Rust source for crates/ast-core/tests/match_axes_oracle/cases.rs:
 *
 *   ./match_axes_probe > ../../crates/ast-core/tests/match_axes_oracle/cases.rs
 */
#include <stdio.h>
#include "ast.h"

#define NFRAME 13

/* The Frames, by index; frame() in crates/ast-core/tests/test_match_axes.rs
   builds the same list. */
static AstFrame *make( int i ) {
   int perm2[ 2 ] = { 2, 1 };
   int perm3[ 3 ] = { 3, 2, 1 };
   int perm3b[ 3 ] = { 2, 3, 1 };
   double centre[ 2 ] = { 0.0, 0.0 }, radius[ 1 ] = { 0.1 };
   AstFrame *f = NULL;
   AstFrameSet *fs;
   switch( i ) {
   case 0: f = (AstFrame *) astSkyFrame( " " ); break;
   case 1: f = (AstFrame *) astSkyFrame( " " ); astPermAxes( f, perm2 ); break;
   case 2: f = (AstFrame *) astSpecFrame( " " ); break;
   case 3: f = astFrame( 1, " " ); break;
   case 4: f = (AstFrame *) astCmpFrame( astSkyFrame( " " ), astSpecFrame( " " ), " " ); break;
   case 5: f = (AstFrame *) astCmpFrame( astSkyFrame( " " ), astSpecFrame( " " ), " " );
           astPermAxes( f, perm3 ); break;
   case 6: f = (AstFrame *) astCmpFrame( astSpecFrame( " " ), astSkyFrame( " " ), " " ); break;
   case 7: f = (AstFrame *) astCmpFrame( astFrame( 1, " " ), astSkyFrame( " " ), " " );
           astPermAxes( f, perm3b ); break;
   case 8: fs = astFrameSet( astFrame( 2, " " ), " " );
           astAddFrame( fs, AST__BASE, astUnitMap( 2, " " ), astSkyFrame( " " ) );
           f = (AstFrame *) fs; break;
   case 9: fs = astFrameSet( astFrame( 3, " " ), " " );
           astAddFrame( fs, AST__BASE, astUnitMap( 3, " " ),
                        astCmpFrame( astSpecFrame( " " ), astSkyFrame( " " ), " " ) );
           f = (AstFrame *) fs; break;
   case 10: f = (AstFrame *) astCircle( astSkyFrame( " " ), 1, centre, radius, NULL, " " ); break;
   case 11: f = (AstFrame *) astCmpFrame( astCmpFrame( astSpecFrame( " " ), astSkyFrame( " " ), " " ),
                                          astFrame( 1, " " ), " " ); break;
   case 12: f = (AstFrame *) astTimeFrame( " " ); break;
   }
   return f;
}

int main( void ) {
   int status_value = 0, *status = &status_value;
   int i, j, k, axes[ 10 ];
   astWatch( status );
   printf( "// Generated by tools/oracle_fixtures/match_axes_probe.c against\n"
           "// the C library at the submodule pin. Do not edit.\n\n"
           "/// `(frm1, frm2, axes)` from astMatchAxes( frm1, frm2, axes ), with\n"
           "/// the Frames numbered as `frame` builds them.\n"
           "pub const CASES: &[(usize, usize, &[i32])] = &[\n" );
   for( i = 0; i < NFRAME; i++ ) {
      for( j = 0; j < NFRAME; j++ ) {
         astBegin;
         AstFrame *f1 = make( i ), *f2 = make( j );
         int n = astGetI( f2, "Naxes" );
         astMatchAxes( f1, f2, axes );
         if( !astOK ) {
            fprintf( stderr, "error for %d %d\n", i, j );
            astClearStatus;
         } else {
            printf( "    (%d, %d, &[", i, j );
            for( k = 0; k < n; k++ ) printf( k ? ", %d" : "%d", axes[ k ] );
            printf( "]),\n" );
         }
         astEnd;
      }
   }
   printf( "];\n" );
   return 0;
}
