/* frame_api_probe -- capture three small Frame-class functions:
 * astCurrentTime (timeframe.c), which converts the clock reading, whole
 * UTC seconds since 1970, to a TimeFrame's axis; astGetRefPos
 * (specframe.c), which gives a SpecFrame's reference position in a
 * supplied SkyFrame; and astGetDensitySystem and astGetDensityUnit
 * (fluxframe.c), the spectral system and unit a flux is a density in.
 *
 * astCurrentTime reads the clock, so the probe records the second it read,
 * repeating the calls until the clock did not tick during them.
 *
 * Prints Rust source for crates/starlink-ast/tests/frame_api_oracle/cases.rs:
 *
 *   ./frame_api_probe > ../../crates/starlink-ast/tests/frame_api_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include <time.h>
#include "ast.h"

extern int astGetDensitySystem_( void *, int * );
extern const char *astGetDensityUnit_( void *, int * );

#define NTIME 4

static const char *time_attrs[ NTIME ] = {
   " ", "System=JEPOCH,TimeScale=TDB",
   "System=MJD,TimeScale=UTC,TimeOrigin=60000,Unit(1)=h", "System=BEPOCH,TimeScale=TT" };

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".en" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

int main( void ) {
   AstTimeFrame *tf[ NTIME ];
   AstSpecFrame *sf;
   AstSkyFrame *gal, *fk4;
   AstFluxFrame *ff;
   double value[ NTIME ], lon, lat;
   time_t t0, t1;
   int i, status = 0, perm[ 2 ] = { 2, 1 };
   astWatch( &status );

   for( i = 0; i < NTIME; i++ ) tf[ i ] = astTimeFrame( time_attrs[ i ] );
   do {
      t0 = time( NULL );
      for( i = 0; i < NTIME; i++ ) value[ i ] = astCurrentTime( tf[ i ] );
      t1 = time( NULL );
   } while( t0 != t1 );

   printf( "// Generated by tools/oracle_fixtures/frame_api_probe.c. Do not edit.\n\n"
           "// Each value is printed with 17 digits so that it reads back exactly.\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "/// The clock reading, UTC seconds since 1970, the times were taken at.\n"
           "pub const SYSTIME: f64 = " );
   num( difftime( t0, (time_t) 0 ) );
   printf( ";\n\n/// `(TimeFrame attributes, astCurrentTime)`.\n"
           "pub const TIMES: &[(&str, f64)] = &[\n" );
   for( i = 0; i < NTIME; i++ ) {
      printf( "    (\"%s\", ", time_attrs[ i ] );
      num( value[ i ] );
      printf( "),\n" );
      tf[ i ] = astAnnul( tf[ i ] );
   }
   printf( "];\n\n" );

   /* A SpecFrame with its reference position at RA 1.0, Dec 0.3 radians
      (FK5 J2000), asked for it in galactic coordinates and in FK4 B1950
      with its axes swapped. */
   sf = astSpecFrame( " " );
   astSetRefPos( sf, NULL, 1.0, 0.3 );
   gal = astSkyFrame( "System=Galactic" );
   fk4 = astSkyFrame( "System=FK4,Equinox=B1950" );
   astPermAxes( fk4, perm );
   printf( "/// `(SkyFrame, astGetRefPos)` for a reference position of (1.0, 0.3).\n"
           "pub const REF_POS: &[(&str, [f64; 2])] = &[\n" );
   astGetRefPos( sf, NULL, &lon, &lat );
   printf( "    (\"none\", [" ); num( lon ); printf( ", " ); num( lat ); printf( "]),\n" );
   astGetRefPos( sf, gal, &lon, &lat );
   printf( "    (\"galactic\", [" ); num( lon ); printf( ", " ); num( lat ); printf( "]),\n" );
   astGetRefPos( sf, fk4, &lon, &lat );
   printf( "    (\"fk4_swapped\", [" ); num( lon ); printf( ", " ); num( lat ); printf( "]),\n" );
   printf( "];\n\n" );

   /* FluxFrames: a System set, and a System that follows from the Unit. */
   printf( "/// `(FluxFrame attributes, density system, density unit)`.\n"
           "pub const DENSITY: &[(&str, &str, &str)] = &[\n" );
   {
      const char *attrs[] = { "System=FLXDN", "System=SFCBRW", "Unit=W/m^2/Angstrom", NULL };
      for( i = 0; attrs[ i ]; i++ ) {
         int code;
         ff = astFluxFrame( 0.0, NULL, attrs[ i ] );
         code = astGetDensitySystem_( astMakePointer( ff ), &status );
         printf( "    (\"%s\", \"%s\", \"%s\"),\n", attrs[ i ],
                 code == 1 ? "FREQ" : code == 4 ? "WAVE" : "?",
                 astGetDensityUnit_( astMakePointer( ff ), &status ) );
         ff = astAnnul( ff );
      }
   }
   printf( "];\n" );

   fk4 = astAnnul( fk4 );
   gal = astAnnul( gal );
   sf = astAnnul( sf );
   return 0;
}
