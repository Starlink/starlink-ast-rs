/* intramap_probe -- capture the dumps and transformations of IntraMaps
 * (intramap.c): one applying a registered doubling function with an
 * IntraFlag, the same inverted, and one whose function has no forward
 * transformation (AST__NOFWD), which C passes to the base Mapping, so its
 * dump says the forward transformation is not defined.
 *
 * Prints Rust source for crates/ast-core/tests/intramap_oracle/cases.rs:
 *
 *   ./intramap_probe > ../../crates/ast-core/tests/intramap_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static char dump[ 4000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

/* Forward: y = 2x; inverse: x = y/2. */
static void Double( AstMapping *map, int npoint, int ncoord_in,
                    const double *ptr_in[], int forward, int ncoord_out,
                    double *ptr_out[] ) {
   int i;
   (void) map;
   (void) ncoord_in;
   (void) ncoord_out;
   for( i = 0; i < npoint; i++ ) {
      ptr_out[ 0 ][ i ] = ( ptr_in[ 0 ][ i ] == AST__BAD ) ? AST__BAD :
                          ( forward ? 2.0*ptr_in[ 0 ][ i ] : 0.5*ptr_in[ 0 ][ i ] );
   }
}

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   if( v == AST__BAD ) {
      printf( "BAD_VALUE" );
      return;
   }
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void emit_dump( const char *name, AstObject *obj ) {
   AstChannel *ch;
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   printf( "    (\"%s\", ", name );
   str( dump );
   printf( "),\n" );
}

int main( void ) {
   int status = 0;
   double in[] = { 1.5, -2.0, AST__BAD }, fwd[ 3 ], inv[ 3 ];
   AstMapping *dbl, *nofwd;
   int i;

   astWatch( &status );
   astIntraReg( "double", 1, 1, Double, AST__SIMPFI | AST__SIMPIF,
                "Double the value", "AST test suite", "starlink-ast" );
   astIntraReg( "nofwd", 1, 1, Double, AST__NOFWD,
                "No forward transformation", "AST test suite", "starlink-ast" );

   dbl = (AstMapping *) astIntraMap( "double", 1, 1, "IntraFlag=v1" );
   nofwd = (AstMapping *) astIntraMap( "nofwd", 1, 1, " " );
   astTran1( dbl, 3, in, 1, fwd );
   astTran1( dbl, 3, in, 0, inv );

   printf( "// Generated by tools/oracle_fixtures/intramap_probe.c. Do not edit.\n\n"
           "use ast_core::constants::BAD_VALUE;\n\n"
           "/// `(case, C's dump)`.\n"
           "pub const DUMPS: &[(&str, &str)] = &[\n" );
   emit_dump( "double_with_flag", (AstObject *) dbl );
   astInvert( dbl );
   emit_dump( "double_inverted", (AstObject *) dbl );
   emit_dump( "nofwd", (AstObject *) nofwd );
   printf( "];\n\n/// The inputs and C's forward and inverse results through \"double\".\n"
           "pub const INPUT: [f64; 3] = [1.5, -2.0, BAD_VALUE];\n"
           "pub const FORWARD: [f64; 3] = [" );
   for( i = 0; i < 3; i++ ) {
      lit( fwd[ i ] );
      printf( ", " );
   }
   printf( "];\npub const INVERSE: [f64; 3] = [" );
   for( i = 0; i < 3; i++ ) {
      lit( inv[ i ] );
      printf( ", " );
   }
   printf( "];\n" );
   return status;
}
