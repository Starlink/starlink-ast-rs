/* specflux_primary_probe -- capture what a SpecFluxFrame inherits from
 * CmpFrame: its System is "Compound" (cmpframe.c GetSystem), and
 * PrimaryFrame descends into its SpecFrame and FluxFrame, so a SpecFrame
 * template finds the spectral axis of a SpecFluxFrame, alone or inside a
 * CmpFrame (cmpframe.c PrimaryFrame).
 *
 * Prints Rust source for crates/starlink-ast/tests/specflux_primary_oracle/cases.rs:
 *
 *   ./specflux_primary_probe > ../../crates/starlink-ast/tests/specflux_primary_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void found( const char *name, AstFrame *target, AstFrame *template,
                   int nin, double *in ) {
   AstFrameSet *fs = astFindFrame( target, template, "" );
   double out;
   char buf[ 40 ];
   printf( "    (\"%s\", ", name );
   if( !fs ) {
      printf( "None),\n" );
      return;
   }
   astTranN( fs, 1, nin, 1, in, 1, 1, 1, &out );
   snprintf( buf, sizeof( buf ), "%.17g", out );
   if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
   printf( "Some(%s)),\n", buf );
}

int main( void ) {
   int status = 0;
   double in[ 3 ] = { 1.4, 3.0, 7.0 };
   AstFrame *sp, *fl, *sff, *cmp;
   astWatch( &status );

   sp = (AstFrame *) astSpecFrame( "System=FREQ,Unit=GHz" );
   fl = (AstFrame *) astFluxFrame( 1.4e9, NULL, "System=FLXDN" );
   sff = (AstFrame *) astSpecFluxFrame( sp, fl, " " );
   cmp = (AstFrame *) astCmpFrame( sff, astFrame( 1, " " ), " " );

   printf( "// Generated by tools/oracle_fixtures/specflux_primary_probe.c. Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// The System of the SpecFluxFrame.\n"
           "pub const SYSTEM: &str = \"%s\";\n\n"
           "/// The point transformed, one value per target axis.\n"
           "pub const POINT: [f64; 3] = [1.4, 3.0, 7.0];\n\n"
           "/// `(case, the template's value for POINT, or None)`.\n"
           "pub const CASES: &[(&str, Option<f64>)] = &[\n",
           astGetC( sff, "System" ) );

   found( "spec_in_specflux", sff,
          (AstFrame *) astSpecFrame( "MaxAxes=2,System=WAVE,Unit=nm" ), 2, in );
   found( "spec_in_cmp", cmp,
          (AstFrame *) astSpecFrame( "MaxAxes=3,System=WAVE,Unit=nm" ), 3, in );
   found( "flux_in_specflux", sff,
          (AstFrame *) astFluxFrame( 1.4e9, NULL, "MaxAxes=2,System=FLXDN,Unit=mJy" ), 2, in );
   found( "flux_in_cmp", cmp,
          (AstFrame *) astFluxFrame( 1.4e9, NULL, "MaxAxes=3,System=FLXDN,Unit=mJy" ), 3, in );
   printf( "];\n" );
   return 0;
}
