/* spec_convert_probe -- capture the Mapping astConvert finds between two
 * SpecFrames (specframe.c Match, SubFrame, MakeSpecMapping), and between
 * DSBSpecFrames (dsbspecframe.c Match, SubFrame), for every pair of
 * spectral systems.
 *
 * Configurations:
 *   0  neither Frame has a RestFreq, both heliocentric (the 1.0E14 Hz
 *      RestFreq default is what relates a velocity to a frequency);
 *   1  different RestFreqs, the source frame LSRK and the destination
 *      barycentric, with a reference position, epoch and observer.
 * plus named cases for the units checks and for DSBSpecFrames.
 *
 * Values that are not exactly representable in the attribute's units are
 * avoided, so the Rust test can set the same values through typed setters.
 *
 * Prints Rust source for crates/starlink-ast/tests/spec_convert_oracle/cases.rs:
 *
 *   ./spec_convert_probe > ../../crates/starlink-ast/tests/spec_convert_oracle/cases.rs
 */
#include <float.h>
#include <stdio.h>
#include <string.h>
#include "ast.h"

#define REF_RA 1.0471975511965976
#define REF_DEC 0.52359877559829882

static const char *systems[] = {
   "FREQ", "ENER", "WAVN", "WAVE", "AWAV", "VRAD", "VOPT", "ZOPT", "BETA", "VELO"
};
#define NSYS ( (int) ( sizeof( systems ) / sizeof( systems[ 0 ] ) ) )

/* Points in the source Frame's default units, per source system. */
static const double points[ NSYS ][ 2 ] = {
   { 230.0, 345.0 },               /* FREQ GHz */
   { 1.0e-22, 2.0e-22 },           /* ENER J */
   { 7.5, 11.5 },                  /* WAVN 1/m */
   { 0.0013, 0.0009 },             /* WAVE m (default unit Angstrom? see below) */
   { 0.0013, 0.0009 },             /* AWAV */
   { 50.0, -120.0 },               /* VRAD km/s */
   { 50.0, -120.0 },               /* VOPT km/s */
   { 0.001, 0.25 },                /* ZOPT */
   { 0.001, 0.25 },                /* BETA */
   { 50.0, -120.0 },               /* VELO km/s */
};

static void flit( double value ) {
   char buf[ 40 ];
   if( value == AST__BAD ) { fputs( "BAD", stdout ); return; }
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

/* Convert, transform the two points of the source system, print the case. */
static void emit( const char *label, AstFrame *from, AstFrame *to, const double in[ 2 ] ) {
   double out[ 2 ];
   AstFrameSet *fs = astConvert( from, to, "" );
   printf( "    (\"%s\", ", label );
   if( !astOK ) {
      astClearStatus;
      printf( "Err(())),\n" );
   } else if( !fs ) {
      printf( "Ok(None)),\n" );
   } else {
      astTran1( fs, 2, in, 1, out );
      printf( "Ok(Some([" ); flit( out[ 0 ] ); printf( ", " ); flit( out[ 1 ] );
      printf( "]))),\n" );
      fs = astAnnul( fs );
   }
}

static AstSpecFrame *config( int c, const char *sys, int is_to ) {
   AstSpecFrame *f = astSpecFrame( "System=%s", sys );
   if( c == 1 ) {
      astSet( f, "RestFreq=%s,StdOfRest=%s,Epoch=2010.0", is_to ? "345.5" : "230.5",
              is_to ? "Bary" : "LSRK" );
      astSetRefPos( f, NULL, REF_RA, REF_DEC );
   }
   return f;
}

int main( void ) {
   int status = 0, c, i, j;
   char label[ 80 ];
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/spec_convert_probe.c against\n"
           "// the C library at u/timj/norm-unit 5a2cac2a, past the submodule pin.\n"
           "// Do not edit.\n\n"
           "// Each value is printed with 17 digits so that it reads back exactly.\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "#[allow(unused_imports)]\n"
           "use starlink_ast::constants::BAD_VALUE as BAD;\n\n"
           "/// The source systems, in the order the points are indexed.\n"
           "pub const SYSTEMS: [&str; %d] = [", NSYS );
   for( i = 0; i < NSYS; i++ ) printf( "%s\"%s\"", i ? ", " : "", systems[ i ] );
   printf( "];\n\n/// Two points per source system, in its default units.\n"
           "pub const POINTS: [[f64; 2]; %d] = [\n", NSYS );
   for( i = 0; i < NSYS; i++ ) {
      printf( "    [" ); flit( points[ i ][ 0 ] ); printf( ", " ); flit( points[ i ][ 1 ] );
      printf( "],\n" );
   }
   printf( "];\n\n"
           "/// `(case, result)`: the case is `c<config>:<from>:<to>` for the\n"
           "/// System grid, or a name for the named cases. The result is the\n"
           "/// two transformed points, `Ok(None)` when no conversion exists, or\n"
           "/// `Err(())` when C reports an error.\n"
           "pub type SpecCase = (&'static str, Result<Option<[f64; 2]>, ()>);\n\n"
           "pub const CASES: &[SpecCase] = &[\n" );

   for( c = 0; c < 2; c++ ) {
      for( i = 0; i < NSYS; i++ ) {
         for( j = 0; j < NSYS; j++ ) {
            AstSpecFrame *from = config( c, systems[ i ], 0 );
            AstSpecFrame *to = config( c, systems[ j ], 1 );
            snprintf( label, sizeof( label ), "c%d:%s:%s", c, systems[ i ], systems[ j ] );
            emit( label, (AstFrame *) from, (AstFrame *) to, points[ i ] );
            from = astAnnul( from );
            to = astAnnul( to );
         }
      }
   }

   /* Units: a frequency axis in Jy cannot be related to Hz, so two such
      Frames match only because no spectral conversion is needed and the
      units agree; with different units C reports the error. The
      constructor rejects such a Unit, so it is set afterwards. */
   {
      AstSpecFrame *a = astSpecFrame( "System=FREQ" );
      AstSpecFrame *b = astSpecFrame( "System=FREQ" );
      AstSpecFrame *d = astSpecFrame( "System=FREQ" );
      astSetC( a, "Unit", "Jy" );
      astSetC( b, "Unit", "Jy" );
      astSetC( d, "Unit", "W" );
      if( !astOK ) {
         fprintf( stderr, "setting a non-frequency Unit failed\n" );
         return 1;
      }
      emit( "units_same_bad", (AstFrame *) a, (AstFrame *) b, points[ 0 ] );
      emit( "units_different_bad", (AstFrame *) a, (AstFrame *) d, points[ 0 ] );
   }

   /* DSBSpecFrames: a DSBSpecFrame template is a SpecFrame in C, so its
      System, StdOfRest and Unit are overlaid and used for alignment. */
   {
      /* A "%s" in an options string is substituted as one value, so the
         common settings are applied separately. */
      const char *base = "System=FREQ,Unit=GHz,RestFreq=230.5,DSBCentre=230.0,IF=4.0";
      AstDSBSpecFrame *a = astDSBSpecFrame( "SideBand=LSB" );
      AstDSBSpecFrame *v = astDSBSpecFrame( "SideBand=LSB" );
      AstDSBSpecFrame *u = astDSBSpecFrame( "SideBand=USB" );
      AstDSBSpecFrame *ua = astDSBSpecFrame( "SideBand=USB,AlignSideBand=1" );
      AstDSBSpecFrame *aa = astDSBSpecFrame( "SideBand=LSB,AlignSideBand=1" );
      AstDSBSpecFrame *all[] = { a, v, u, ua, aa };
      for( i = 0; i < 5; i++ ) astSet( all[ i ], base, " " );
      AstSpecFrame *s = astSpecFrame( "System=VRAD,RestFreq=230.5" );
      astSet( v, "System=VRAD" );
      emit( "dsb_freq_to_vrad", (AstFrame *) a, (AstFrame *) v, points[ 0 ] );
      emit( "dsb_lsb_to_usb", (AstFrame *) a, (AstFrame *) u, points[ 0 ] );
      emit( "dsb_lsb_to_usb_aligned", (AstFrame *) aa, (AstFrame *) ua, points[ 0 ] );
      emit( "dsb_to_spec_vrad", (AstFrame *) a, (AstFrame *) s, points[ 0 ] );
      emit( "spec_vrad_to_dsb", (AstFrame *) s, (AstFrame *) a, points[ 5 ] );

      /* A DSBSpecFrame template found in a (sky, DSBSpecFrame) cube. The
         case transforms two cube positions to the template's VRAD axis. */
      {
         AstCmpFrame *cube = astCmpFrame( astSkyFrame( " " ), a, " " );
         AstDSBSpecFrame *t = astCopy( v );
         AstFrameSet *fs;
         double in[ 6 ] = { 1.0, 2.0, 0.5, 0.6, 230.0, 345.0 }, out[ 2 ];
         astSet( t, "MaxAxes=3" );
         fs = astFindFrame( cube, t, "" );
         printf( "    (\"dsb_found_in_cube\", " );
         if( !fs ) {
            printf( "Ok(None)),\n" );
         } else {
            astTranN( fs, 2, 3, 2, in, 1, 1, 2, out );
            printf( "Ok(Some([" ); flit( out[ 0 ] ); printf( ", " ); flit( out[ 1 ] );
            printf( "]))),\n" );
         }
      }
   }

   printf( "];\n" );
   return 0;
}
