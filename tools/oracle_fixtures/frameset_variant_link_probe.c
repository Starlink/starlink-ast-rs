/* frameset_variant_link_probe -- capture the dumps of a FrameSet after a
 * variant is added to, and then removed from, a Frame whose node's Mapping
 * is used in its inverse direction (Inv2 = 1). The FrameSet joins Frame
 * GRID to the current Frame B of a FrameSet A -> B by a ZoomMap of 2, so
 * astAddFrame re-roots A -> B at B and reverses the link to A. The link
 * from A to B is a ShiftMap of 10 ("shift") or a MathMap y = x + 10
 * ("mathmap"); the current Frame is A (Frame 2, the reversed link) or B
 * (Frame 3); the variant Mapping is a UnitMap, a ShiftMap of 5 or a ZoomMap
 * of 3. SetVariant replaces the Mapping of the current Frame's node with
 * that Mapping, used as its link flag says, followed by the change of
 * variant, simplified, and records the Invert of the result as the link
 * flag. For each, the dump after astAddVariant, the transformations of 3
 * from Frame 1 to Frames 2 and 3, then the same after the Variant is set
 * back to the Frame's Domain.
 *
 * Prints Rust source for
 * crates/ast-core/tests/frameset_variant_link_oracle/cases.rs:
 *
 *   ./frameset_variant_link_probe > ../../crates/ast-core/tests/frameset_variant_link_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static char dump[ 200000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

static const char *dumped( AstObject *obj ) {
   AstChannel *ch;
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   return dump;
}

/* `v` as a Rust f64 literal. */
static void num( double v ) {
   char buf[ 40 ];
   sprintf( buf, "%.17g", v );
   if( !strpbrk( buf, ".en" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

/* The transformations of 3 from Frame 1 to Frames 2 and 3. */
static void tran( AstFrameSet *fs ) {
   double in = 3.0, out2, out3;
   AstMapping *map;
   map = astGetMapping( fs, 1, 2 );
   astTran1( map, 1, &in, 1, &out2 );
   map = astAnnul( map );
   map = astGetMapping( fs, 1, 3 );
   astTran1( map, 1, &in, 1, &out3 );
   map = astAnnul( map );
   printf( "[" );
   num( out2 );
   printf( ", " );
   num( out3 );
   printf( "]" );
}

static void emit( const char *link, int current, const char *variant ) {
   AstFrameSet *outer, *inner;
   AstMapping *ab, *vmap;
   const char *fwd[] = { "y=x+10" };
   const char *inv[] = { "x=y-10" };
   const double shift = 10.0, vshift = 5.0;
   char domain[ 80 ];

   astBegin;
   outer = astFrameSet( astFrame( 1, "Domain=GRID" ), " " );
   inner = astFrameSet( astFrame( 1, "Domain=A" ), " " );
   if( !strcmp( link, "shift" ) ) {
      ab = (AstMapping *) astShiftMap( 1, &shift, " " );
   } else {
      ab = (AstMapping *) astMathMap( 1, 1, 1, fwd, 1, inv, " " );
   }
   astAddFrame( inner, AST__BASE, ab, astFrame( 1, "Domain=B" ) );
   astAddFrame( outer, AST__BASE, astZoomMap( 1, 2.0, " " ), inner );
   astSetI( outer, "Current", current );

   if( !strcmp( variant, "unit" ) ) {
      vmap = (AstMapping *) astUnitMap( 1, " " );
   } else if( !strcmp( variant, "shift" ) ) {
      vmap = (AstMapping *) astShiftMap( 1, &vshift, " " );
   } else {
      vmap = (AstMapping *) astZoomMap( 1, 3.0, " " );
   }
   astAddVariant( outer, vmap, "V2" );

   printf( "    (\"%s_cur%d_%s\", %d, \"%s\", \"%s\",\n        ", link, current,
           variant, current, link, variant );
   str( dumped( (AstObject *) outer ) );
   printf( ",\n        " );
   tran( outer );
   printf( ",\n        " );

   strcpy( domain, astGetC( outer, "Domain" ) );
   astSetC( outer, "Variant", domain );
   str( dumped( (AstObject *) outer ) );
   printf( ",\n        " );
   tran( outer );
   printf( "),\n" );
   astEnd;
}

int main( void ) {
   int status = 0;
   const char *links[] = { "shift", "mathmap" };
   const char *variants[] = { "unit", "shift", "zoom" };
   int i, j, current;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/frameset_variant_link_probe.c. Do not edit.\n\n" );
   printf( "/// `(case, current Frame, A to B link, variant Mapping, dump after adding\n" );
   printf( "/// the variant, Frame 1 to 2 and 1 to 3 of 3, dump after selecting the\n" );
   printf( "/// Frame's own variant again, Frame 1 to 2 and 1 to 3 of 3)`.\n" );
   printf( "#[allow(clippy::type_complexity)]\n" );
   printf( "pub const CASES: &[(&str, usize, &str, &str, &str, [f64; 2], &str, [f64; 2])] = &[\n" );
   for( i = 0; i < 2; i++ ) {
      for( current = 2; current <= 3; current++ ) {
         for( j = 0; j < 3; j++ ) emit( links[ i ], current, variants[ j ] );
      }
   }
   printf( "];\n" );
   return status;
}
