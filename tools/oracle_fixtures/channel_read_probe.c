/* channel_read_probe -- capture how a Channel reads Objects from its
 * source (channel.c Read, GetNextData, InputTextItem and ClearValues): one
 * Object per astRead, the next starting where the last stopped; with Skip
 * set, anything before a "Begin" ignored, and without it an error; the
 * error for input that ends inside an Object; and the warnings for items
 * no class reads, which Strict makes errors.
 *
 * Each case reads its text up to four times, clearing the error status
 * after a read that fails, and prints for each read the class of the
 * Object read (or "" for none), the status, and the warnings the read left
 * in the Channel.
 *
 * Prints Rust source for crates/ast-core/tests/channel_read_oracle/cases.rs:
 *
 *   ./channel_read_probe 2>/dev/null > ../../crates/ast-core/tests/channel_read_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static const char **lines;
static int next_line;

static const char *source( void ) {
   return lines[ next_line ] ? lines[ next_line++ ] : NULL;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

/* Read `text` with a Channel made with `options`. */
static void read( const char *name, const char *options, const char **text ) {
   AstChannel *ch;
   AstObject *obj;
   AstKeyMap *warn;
   char key[ 20 ];
   const char *msg;
   int i, iread, st;

   lines = text;
   next_line = 0;
   ch = astChannel( source, NULL, "%s", options );
   printf( "    (\n        \"%s\",\n        \"%s\",\n        &[", name, options );
   for( i = 0; text[ i ]; i++ ) {
      printf( "%s", i ? ", " : "" );
      str( text[ i ] );
   }
   printf( "],\n        &[\n" );
   for( iread = 0; iread < 4; iread++ ) {
      obj = astRead( ch );
      st = astStatus;
      astClearStatus;
      printf( "            (" );
      str( obj ? astGetC( obj, "Class" ) : "" );
      printf( ", %d, &[", st );
      warn = astWarnings( ch );
      if( warn ) {
         for( i = 1; ; i++ ) {
            sprintf( key, "Warning_%d", i );
            if( !astMapGet0C( warn, key, &msg ) ) break;
            printf( "%s", i > 1 ? ", " : "" );
            str( msg );
         }
         warn = astAnnul( warn );
      }
      printf( "]),\n" );
      if( obj ) obj = astAnnul( obj );
   }
   printf( "        ],\n    ),\n" );
   ch = astAnnul( ch );
}

