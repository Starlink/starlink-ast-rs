/* region_bounded_probe -- capture whether Regions are bounded, and their
 * bounding boxes, where those depend on a class's own GetBounded or
 * RegBaseBox: a PointList, which inherits region.c GetBounded, so a negated
 * PointList is unbounded unless its Frame is a SkyFrame; a Prism, which
 * prism.c GetBounded tests with both components negated when it is negated;
 * an Interval excluding a range on each axis, whose interval.c RegBaseBox
 * returns its limits as stored; and a sky PointList either side of RA 0,
 * whose pointlist.c RegBaseBox measures from the first point with
 * astAxDistance, and whose default uncertainty is built from that box.
 *
 * Prints Rust source for crates/starlink-ast/tests/region_bounded_oracle/cases.rs:
 *
 *   ./region_bounded_probe > ../../crates/starlink-ast/tests/region_bounded_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

extern int astGetBounded_( void *, int * );

static int bounded( void *id ) {
   int s = 0;
   return astGetBounded_( astMakePointer( id ), &s );
}

static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void flag( const char *name, void *reg ) {
   printf( "pub const %s: bool = %s;\n", name, bounded( reg ) ? "true" : "false" );
}

static void bounds( const char *name, AstRegion *reg, int nax ) {
   double lb[ 3 ], ub[ 3 ];
   int i;
   astGetRegionBounds( reg, lb, ub );
   printf( "pub const %s: [[f64; %d]; 2] = [[", name, nax );
   for( i = 0; i < nax; i++ ) { lit( lb[ i ] ); printf( ", " ); }
   printf( "], [" );
   for( i = 0; i < nax; i++ ) { lit( ub[ i ] ); printf( ", " ); }
   printf( "]];\n" );
}

int main( void ) {
   int status = 0;
   AstRegion *reg;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_bounded_probe.c. Do not edit.\n\n" );
   {
      double pts[] = { 0.0, 1.0, 3.0, 0.0, 2.0, 1.0 };
      reg = (AstRegion *) astPointList( astFrame( 2, " " ), 3, 2, 3, pts, NULL, " " );
      printf( "/// The PointList (0, 0), (1, 2), (3, 1), as made and negated.\n" );
      flag( "POINTLIST", reg );
      astNegate( reg );
      flag( "POINTLIST_NEGATED", reg );
      reg = (AstRegion *) astPointList( astSkyFrame( " " ), 3, 2, 3, pts, NULL, " " );
      astNegate( reg );
      printf( "/// The same points in a SkyFrame, negated.\n" );
      flag( "SKY_POINTLIST_NEGATED", reg );
   }
   {
      double l[] = { 0.0, 0.0 }, u[] = { 1.0, 1.0 }, l1 = 0.0, u1 = 1.0;
      reg = (AstRegion *) astPrism( astBox( astFrame( 2, " " ), 1, l, u, NULL, " " ),
                                    astInterval( astFrame( 1, " " ), &l1, &u1, NULL, " " ),
                                    " " );
      printf( "/// The Prism of the Box [0,1]x[0,1] and the Interval [0,1], as made\n"
              "/// and negated.\n" );
      flag( "PRISM", reg );
      astNegate( reg );
      flag( "PRISM_NEGATED", reg );
   }
   {
      double l[] = { 3.0, 4.0 }, u[] = { 1.0, 2.0 };
      reg = (AstRegion *) astInterval( astFrame( 2, " " ), l, u, NULL, " " );
      printf( "/// The bounds of the Interval excluding (1, 3) and (2, 4).\n" );
      bounds( "EXCLUDED_BOUNDS", reg, 2 );
   }
   {
      double pts[] = { 0.01, 6.27, 6.2, 0.1, 0.2, 0.15 };
      reg = (AstRegion *) astPointList( astSkyFrame( " " ), 3, 2, 3, pts, NULL, " " );
      printf( "/// The bounds of the sky PointList (0.01, 0.1), (6.27, 0.2), (6.2, 0.15),\n"
              "/// and of its default uncertainty.\n" );
      bounds( "SKY_BOUNDS", reg, 2 );
      bounds( "SKY_UNC_BOUNDS", astGetUnc( reg, 1 ), 2 );
   }
   return status;
}
