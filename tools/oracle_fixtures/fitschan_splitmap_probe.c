/* fitschan_splitmap_probe -- capture the FITS-WCS headers C writes for
 * FrameSets whose pixel->sky Mapping holds no WcsMap, which fitschan.c
 * SplitMap gives one: a linear Mapping is given a CAR projection, with
 * its longitude origin moved to the pixel origin, and one giving constant
 * celestial values the WcsMap of a TAN header with those values at its
 * reference point. For each, the value astWrite returns and the cards.
 *
 * Prints Rust source for crates/starlink-ast/tests/fitschan_splitmap_oracle/cases.rs:
 *
 *   ./fitschan_splitmap_probe > ../../crates/starlink-ast/tests/fitschan_splitmap_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void emit( const char *name, AstFrame *sky, AstMapping *map ) {
   AstFitsChan *fc;
   AstFrameSet *fs;
   char card[ 81 ];
   int ret;

   fs = astFrameSet( astFrame( astGetI( map, "Nin" ), "Domain=GRID" ), " " );
   astAddFrame( fs, AST__BASE, map, sky );
   fc = astFitsChan( NULL, NULL, "Encoding=FITS-WCS" );
   ret = astWrite( fc, fs );
   astClearStatus;
   printf( "    (\"%s\", %d, &[\n", name, ret );
   astClear( fc, "Card" );
   while( astFindFits( fc, "%f", card, 1 ) ) printf( "        \"%s\",\n", card );
   printf( "    ]),\n" );
}

int main( void ) {
   int status = 0, outperm[ 2 ] = { -1, -2 }, inperm[ 2 ] = { 0, 0 };
   double zoom[ 9 ] = { -0.001, 0.0, 0.0, 0.0, 0.002, 0.0, 0.0, 0.0, 3.0 };
   double diag[ 2 ] = { -0.001, 0.002 };
   double shift[ 3 ] = { 0.2, 0.3, 4.0 }, con[ 2 ] = { 0.5, -0.25 };
   AstMapping *lin2, *lin3;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/fitschan_splitmap_probe.c. Do not edit.\n\n" );
   printf( "/// `(case, astWrite's value, the cards written)`.\n" );
   printf( "pub const CASES: &[(&str, i32, &[&str])] = &[\n" );

   lin2 = (AstMapping *) astCmpMap( astMatrixMap( 2, 2, 1, diag, " " ),
                                    astShiftMap( 2, shift, " " ), 1, " " );
   emit( "linear", (AstFrame *) astSkyFrame( " " ), lin2 );

   lin3 = (AstMapping *) astCmpMap( astMatrixMap( 3, 3, 0, zoom, " " ),
                                    astShiftMap( 3, shift, " " ), 1, " " );
   emit( "linear_3d", (AstFrame *) astCmpFrame( astSkyFrame( " " ),
                                                astFrame( 1, "Domain=X" ), " " ),
         lin3 );

   emit( "constant", (AstFrame *) astSkyFrame( " " ),
         (AstMapping *) astPermMap( 2, inperm, 2, outperm, con, " " ) );

   printf( "];\n" );
   return 0;
}
