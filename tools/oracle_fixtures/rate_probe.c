/* rate_probe -- capture the rates of change that classes delegating to a
 * component's astRate give: a RateMap at every point, bad inputs included
 * (ratemap.c Transform), a TranMap through its forward component in the
 * orientation it records (tranmap.c Rate), and a SwitchMap through the
 * chosen route, bad with no forward selector (switchmap.c Rate). A RateMap
 * read from a dump whose recorded orientation ("Inv") differs from its
 * Mapping's Invert asks the rate in the recorded orientation.
 *
 * Prints Rust source for crates/starlink-ast/tests/rate_oracle/cases.rs:
 *
 *   ./rate_probe > ../../crates/starlink-ast/tests/rate_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

/* Print a value as a Rust f64 literal, with the fewest digits that read
   back as the same value, or BAD_VALUE. */
static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   if( v == AST__BAD ) {
      printf( "BAD_VALUE" );
      return;
   }
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static char text[ 4000 ];
static const char *source;

static void sink( const char *line ) {
   /* Drop the encapsulated Mapping's Invert card, keeping the RateMap's
      record ("Inv") of the orientation it had when the RateMap was made. */
   if( strstr( line, " Invert = 1" ) ) return;
   strcat( text, line );
   strcat( text, "\n" );
}

static const char *next_line( void ) {
   static char line[ 400 ];
   const char *end;
   size_t n;
   if( !*source ) return NULL;
   end = strchr( source, '\n' );
   n = end - source;
   memcpy( line, source, n );
   line[ n ] = 0;
   source = end + 1;
   return line;
}

static void emit( const char *name, double v ) {
   printf( "    (\"%s\", ", name );
   lit( v );
   printf( "),\n" );
}

/* The output of a 1-input RateMap at "x" (the rate it gives). */
static double ratemap_at( AstMapping *map, int nin, double *at ) {
   double out;
   AstRateMap *rm = astRateMap( map, 1, 1, " " );
   astTranN( rm, 1, nin, 1, at, 1, 1, 1, &out );
   rm = astAnnul( rm );
   return out;
}

/* A one-dimensional SwitchMap whose routes are WinMaps from [0,10] to
   [0,100] and from [20,30] to [200,300], with a forward selector over the
   input intervals and, if "inverse" is set, an inverse selector over the
   output intervals, which the SwitchMap applies in its inverse direction. */
static AstSwitchMap *switchmap( int inverse ) {
   AstFrame *f = astFrame( 1, " " );
   double l1[] = { 0.0 }, u1[] = { 10.0 }, l2[] = { 20.0 }, u2[] = { 30.0 };
   double ol1[] = { 0.0 }, ou1[] = { 100.0 }, ol2[] = { 200.0 }, ou2[] = { 300.0 };
   AstRegion *in[ 2 ], *out[ 2 ];
   AstMapping *routes[ 2 ];
   AstSelectorMap *fsel, *isel = NULL;
   in[ 0 ] = (AstRegion *) astBox( f, 1, l1, u1, NULL, " " );
   in[ 1 ] = (AstRegion *) astBox( f, 1, l2, u2, NULL, " " );
   fsel = astSelectorMap( 2, (void **) in, AST__BAD, " " );
   if( inverse ) {
      out[ 0 ] = (AstRegion *) astBox( f, 1, ol1, ou1, NULL, " " );
      out[ 1 ] = (AstRegion *) astBox( f, 1, ol2, ou2, NULL, " " );
      isel = astSelectorMap( 2, (void **) out, AST__BAD, " " );
      astInvert( isel );
   }
   routes[ 0 ] = (AstMapping *) astWinMap( 1, l1, u1, ol1, ou1, " " );
   routes[ 1 ] = (AstMapping *) astWinMap( 1, l2, u2, ol2, ou2, " " );
   return astSwitchMap( fsel, isel, 2, (void **) routes, " " );
}

int main( void ) {
   int status = 0;
   double at1, at2[ 2 ];
   AstTranMap *tm;
   AstSwitchMap *sm;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/rate_probe.c. Do not edit.\n\n"
           "use starlink_ast::constants::BAD_VALUE;\n\n"
           "/// `(case, C's rate)`.\n"
           "pub const CASES: &[(&str, f64)] = &[\n" );

   at1 = AST__BAD;
   emit( "ratemap_zoommap_bad_input",
         ratemap_at( (AstMapping *) astZoomMap( 1, 3.0, " " ), 1, &at1 ) );
   at2[ 0 ] = 1.0;
   at2[ 1 ] = AST__BAD;
   emit( "ratemap_unitmap_bad_other_axis",
         ratemap_at( (AstMapping *) astUnitMap( 2, " " ), 2, at2 ) );

   {
      AstZoomMap *zm = astZoomMap( 1, 2.0, " " );
      AstChannel *ch;
      AstMapping *rm;
      double out;
      astInvert( zm );
      text[ 0 ] = 0;
      ch = astChannel( NULL, sink, " " );
      astWrite( ch, astRateMap( zm, 1, 1, " " ) );
      ch = astAnnul( ch );
      source = text;
      ch = astChannel( next_line, NULL, " " );
      rm = astRead( ch );
      at1 = 1.0;
      astTran1( rm, 1, &at1, 1, &out );
      emit( "ratemap_recorded_orientation", out );
      if( !strstr( text, "Inv = 1" ) ) {
         fprintf( stderr, "the RateMap dump does not record Inv = 1\n" );
         return 1;
      }
   }

   tm = astTranMap( astZoomMap( 1, 2.0, " " ), astZoomMap( 1, 3.0, " " ), " " );
   at1 = 1.0;
   emit( "tranmap_forward", astRate( tm, &at1, 1, 1 ) );
   astInvert( tm );
   emit( "tranmap_inverted", astRate( tm, &at1, 1, 1 ) );

   sm = switchmap( 0 );
   at1 = 5.0;
   emit( "switchmap_forward", astRate( sm, &at1, 1, 1 ) );
   astInvert( sm );
   at1 = 50.0;
   emit( "switchmap_inverted_no_selector", astRate( sm, &at1, 1, 1 ) );
   sm = astAnnul( sm );
   sm = switchmap( 1 );
   astInvert( sm );
   emit( "switchmap_inverted_route", astRate( sm, &at1, 1, 1 ) );

   printf( "];\n" );
   return status;
}
