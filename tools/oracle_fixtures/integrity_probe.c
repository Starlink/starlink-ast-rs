/* integrity_probe -- capture how a FrameSet keeps its integrity when an
 * attribute of its current Frame is changed through the FrameSet
 * (frameset.c RecordIntegrity / RestoreIntegrity), for every Frame class.
 *
 * Each case builds a FrameSet whose base Frame is a plain Frame joined to
 * the current Frame by a UnitMap, sets one or more attributes through the
 * FrameSet with astSetC, and transforms a few points from the base to the
 * current Frame. A case where C cannot keep the integrity records the error
 * instead (AST__ILOST).
 *
 * Values that C parses from a formatted string (SkyRef) are read back and
 * printed so the Rust test sets exactly the same values.
 *
 * Prints Rust source for crates/starlink-ast/tests/integrity_oracle/cases.rs:
 *
 *   ./integrity_probe > ../../crates/starlink-ast/tests/integrity_oracle/cases.rs
 */
#include <float.h>
#include <stdio.h>
#include <string.h>
#include "ast.h"
#include "ast_err.h"

/* RefRA and RefDec of the SpecFrame cases, radians (FK5 J2000). */
#define REF_RA 1.0471975511965976
#define REF_DEC 0.52359877559829882

static void flit( double value ) {
   char buf[ 40 ];
   if( value == AST__BAD ) { fputs( "BAD", stdout ); return; }
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

/* Join "current" to a plain base Frame with a UnitMap, apply the settings
   (a NULL-terminated list of astSet strings) through the FrameSet, and
   print the case. */
static void run( const char *name, AstFrame *current, const char **settings,
                 int npoint, const double *in ) {
   int status_value, i, j, naxes;
   double out[ 3 * 8 ];
   AstFrameSet *fs;

   naxes = astGetI( current, "Naxes" );
   fs = astFrameSet( astFrame( naxes, " " ), " " );
   astAddFrame( fs, AST__BASE, astUnitMap( naxes, " " ), current );

   for( i = 0; settings[ i ] && astOK; i++ ) {
      char name[ 40 ];
      const char *eq = strchr( settings[ i ], '=' );
      snprintf( name, sizeof( name ), "%.*s", (int) ( eq - settings[ i ] ), settings[ i ] );
      astSetC( fs, name, eq + 1 );
   }

   printf( "    (\"%s\", ", name );
   if( !astOK ) {
      status_value = astStatus;
      astClearStatus;
      printf( "Err(\"%s\")),\n", status_value == AST__ILOST ? "ILOST" : "OTHER" );
   } else {
      astTranN( fs, npoint, naxes, npoint, in, 1, naxes, npoint, out );
      printf( "Ok(&[" );
      for( j = 0; j < npoint; j++ ) {
         if( j ) printf( ", " );
         printf( "&[" );
         for( i = 0; i < naxes; i++ ) {
            if( i ) printf( ", " );
            flit( out[ i * npoint + j ] );
         }
         printf( "]" );
      }
      printf( "])),\n" );
   }
   fs = astAnnul( fs );
}

int main( void ) {
   int status = 0;
   astWatch( &status );

   /* Points are stored axis by axis, as astTranN takes them. */
   static const double p2[] = { 1.0, 4.2, 0.5, -0.9 };
   static const double p3[] = { 1.0, 4.2, 0.5, -0.9, 1.0, 2.0 };
   static const double pspec[] = { 230.0, 345.0 };
   static const double ptime[] = { 0.25, 1.75 };
   static const double pflux[] = { 1.0e-26, 3.0e-26 };
   static const double pspecflux[] = { 1.0, 2.0, 1.0e-26, 3.0e-26 };
   static const double pmetre[] = { 1000.0, 5.0 };

   const char *s_unit_jy[] = { "Unit(1)=Jy", NULL };
   const char *s_sfcbr[] = { "System=SFCBR", NULL };
   const char *s_unit2_jy[] = { "Unit(2)=Jy", NULL };
   const char *s_unit1_mhz[] = { "Unit(1)=MHz", NULL };
   const char *s_unit_km[] = { "Unit(1)=km", NULL };
   const char *s_eq2050[] = { "Equinox=J2050", NULL };
   const char *s_ep2010[] = { "Epoch=2010.0", NULL };
   const char *s_fk5[] = { "System=FK5", NULL };
   const char *s_gal[] = { "System=GALACTIC", NULL };
   const char *s_skyref[] = { "SkyRef=4:00:00,30:00:00",
                              "SkyRefIs=Origin", NULL };
   const char *s_title[] = { "Title=Renamed", NULL };
   const char *s_vrad[] = { "System=VRAD", NULL };
   const char *s_lsrk[] = { "StdOfRest=LSRK", NULL };
   const char *s_srcvel[] = { "SourceVel=100.0", NULL };
   const char *s_jd[] = { "System=JD", NULL };
   const char *s_utc[] = { "TimeScale=UTC", NULL };
   const char *s_origin[] = { "TimeOrigin=55000.0", NULL };
   const char *s_usb[] = { "SideBand=USB", NULL };

   int perm[ 2 ] = { 2, 1 };
   AstFrame *f;
   AstSkyFrame *sky;
   AstSpecFrame *spec;

   printf( "// Generated by tools/oracle_fixtures/integrity_probe.c against\n"
           "// the C library at u/timj/norm-unit 5a2cac2a, past the submodule pin.\n"
           "// Do not edit.\n\n"
           "// Each value is printed with 17 digits so that it reads back exactly.\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "#[allow(unused_imports)]\n"
           "use starlink_ast::constants::BAD_VALUE as BAD;\n\n" );

   /* The SkyRef values C parses from the strings in s_skyref. */
   sky = astSkyFrame( "System=ICRS" );
   astSetC( sky, "SkyRef", "4:00:00,30:00:00" );
   printf( "/// SkyRef(1) and SkyRef(2), in radians, from \"4:00:00\" and \"30:00:00\".\n"
           "pub const SKYREF: [f64; 2] = [" );
   flit( astGetD( sky, "SkyRef(1)" ) ); printf( ", " );
   flit( astGetD( sky, "SkyRef(2)" ) ); printf( "];\n\n" );
   sky = astAnnul( sky );

   printf( "/// `(case, points transformed from the base to the current Frame, or\n"
           "/// the error C reports)`, each point one coordinate per axis.\n"
           "pub type IntegrityCase = (&'static str, Result<&'static [&'static [f64]], &'static str>);\n\n"
           "pub const CASES: &[IntegrityCase] = &[\n" );

   run( "flux_unit_jy", (AstFrame *) astFluxFrame( 1.4e9, NULL, "System=FLXDN" ),
        s_unit_jy, 2, pflux );
   run( "flux_system_sfcbr", (AstFrame *) astFluxFrame( 1.4e9, NULL, "System=FLXDN" ),
        s_sfcbr, 2, pflux );
   run( "specflux_unit2_jy",
        (AstFrame *) astSpecFluxFrame( astSpecFrame( "System=FREQ,Unit=GHz" ),
                                       astFluxFrame( AST__BAD, NULL, "System=FLXDN" ), " " ),
        s_unit2_jy, 2, pspecflux );
   run( "specflux_unit1_mhz",
        (AstFrame *) astSpecFluxFrame( astSpecFrame( "System=FREQ,Unit=GHz" ),
                                       astFluxFrame( AST__BAD, NULL, "System=FLXDN" ), " " ),
        s_unit1_mhz, 2, pspecflux );

   f = astFrame( 1, "Unit(1)=m" );
   astSetActiveUnit( f, 1 );
   run( "frame_activeunit_km", f, s_unit_km, 2, pmetre );
   run( "frame_title", astFrame( 2, " " ), s_title, 2, p2 );

   run( "sky_fk5_equinox", (AstFrame *) astSkyFrame( "System=FK5" ), s_eq2050, 2, p2 );
   run( "sky_gappt_epoch", (AstFrame *) astSkyFrame( "System=GAPPT" ), s_ep2010, 2, p2 );
   run( "sky_fk4_to_fk5", (AstFrame *) astSkyFrame( "System=FK4" ), s_fk5, 2, p2 );
   run( "sky_icrs_to_galactic", (AstFrame *) astSkyFrame( "System=ICRS" ), s_gal, 2, p2 );
   run( "sky_skyref_origin", (AstFrame *) astSkyFrame( "System=ICRS" ), s_skyref, 2, p2 );
   sky = astSkyFrame( "System=ICRS,AlignOffset=1,SkyRefIs=Origin" );
   astSetC( sky, "SkyRef", "4:00:00,30:00:00" );
   run( "sky_alignoffset_galactic", (AstFrame *) sky, s_gal, 2, p2 );
   run( "sky_unknown_title", (AstFrame *) astSkyFrame( "System=UNKNOWN" ), s_title, 2, p2 );
   sky = astSkyFrame( "System=ICRS" );
   astPermAxes( sky, perm );
   run( "sky_permuted_galactic", (AstFrame *) sky, s_gal, 2, p2 );

   run( "cmp_sky_spec_equinox",
        (AstFrame *) astCmpFrame( astSkyFrame( "System=FK5" ),
                                  astSpecFrame( "System=FREQ,Unit=GHz" ), " " ),
        s_eq2050, 2, p3 );
   run( "cmp_sky_spec_galactic",
        (AstFrame *) astCmpFrame( astSkyFrame( "System=FK5" ),
                                  astSpecFrame( "System=FREQ,Unit=GHz" ), " " ),
        s_gal, 2, p3 );

   run( "spec_vrad",
        (AstFrame *) astSpecFrame( "System=FREQ,Unit=GHz,RestFreq=230.538" ),
        s_vrad, 2, pspec );
   spec = astSpecFrame( "System=FREQ,Unit=GHz,Epoch=2010.0" );
   astSetRefPos( spec, NULL, REF_RA, REF_DEC );
   run( "spec_lsrk", (AstFrame *) spec, s_lsrk, 2, pspec );
   spec = astSpecFrame( "System=FREQ,Unit=GHz,StdOfRest=Source" );
   astSetRefPos( spec, NULL, REF_RA, REF_DEC );
   run( "spec_sourcevel", (AstFrame *) spec, s_srcvel, 2, pspec );

   run( "time_jd", (AstFrame *) astTimeFrame( "System=MJD,TimeScale=TAI" ), s_jd, 2, ptime );
   run( "time_utc", (AstFrame *) astTimeFrame( "System=MJD,TimeScale=TAI" ), s_utc, 2, ptime );
   run( "time_origin", (AstFrame *) astTimeFrame( "System=MJD,TimeScale=TAI" ),
        s_origin, 2, ptime );

   spec = (AstSpecFrame *) astDSBSpecFrame( "System=FREQ,Unit=GHz,DSBCentre=230.0,"
                                            "IF=4.0,SideBand=LSB" );
   run( "dsb_usb", (AstFrame *) spec, s_usb, 2, pspec );

   printf( "];\n" );
   return 0;
}
