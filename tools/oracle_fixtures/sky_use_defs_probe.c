/* sky_use_defs_probe -- capture what UseDefs=0 changes in a SkyFrame. The
 * default Title leaves out an Equinox or Epoch that has not been set
 * (skyframe.c GetTitle), and MakeSkyMapping refuses a conversion step that
 * needs an Equinox, Epoch or observer position that is not set, in the
 * input SkyFrame for the steps to the alignment system and in the output
 * SkyFrame for the steps from it (skyframe.c VerifyMSMAttrs, AST__NOVAL).
 * Picking axes from a SkyFrame is exempt (skyframe.c SubFrame).
 *
 * Each title case prints the default Title. Each conversion case finds the
 * template in the target and prints the converted point, None when no
 * conversion is found, or the error.
 *
 * Prints Rust source for crates/starlink-ast/tests/sky_use_defs_oracle/cases.rs:
 *
 *   ./sky_use_defs_probe > ../../crates/starlink-ast/tests/sky_use_defs_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"
#include "ast_err.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

static void title( const char *settings ) {
   AstFrame *f = (AstFrame *) astSkyFrame( "%s", " " );
   astSet( f, settings, " " );
   printf( "    (" );
   str( settings );
   printf( ", " );
   str( astGetC( f, "Title" ) );
   printf( "),\n" );
}

static void convert( const char *target, const char *template ) {
   AstFrame *t = (AstFrame *) astSkyFrame( "%s", " " );
   AstFrame *p = (AstFrame *) astSkyFrame( "%s", " " );
   AstFrameSet *fs;
   astSet( t, target, " " );
   astSet( p, template, " " );
   fs = astFindFrame( t, p, "" );
   printf( "    (" );
   str( target );
   printf( ", " );
   str( template );
   printf( ", " );
   if( !astOK ) {
      printf( "Err(\"%s\")", astStatus == AST__NOVAL ? "Noval" : "other" );
      astClearStatus;
   } else if( !fs ) {
      printf( "Ok(None)" );
   } else {
      double x = 1.0, y = 0.5, xo, yo;
      astTran2( fs, 1, &x, &y, 1, &xo, &yo );
      printf( "Ok(Some([" );
      num( xo );
      printf( ", " );
      num( yo );
      printf( "]))" );
   }
   printf( "),\n" );
}

int main( void ) {
   int status = 0;
   const char *systems[] = { "FK4", "FK4-NO-E", "FK5", "J2000", "GAPPT", "ECLIPTIC",
                             "HELIOECLIPTIC", "GALACTIC", "ICRS", "AZEL", NULL };
   const char *extras[] = { "", ",Equinox=J2010", ",Epoch=2010.0",
                            ",ObsLon=60,ObsLat=30,Epoch=2010.0", NULL };
   char a[ 200 ], b[ 200 ];
   int i, j, k;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/sky_use_defs_probe.c. Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// `(settings, default Title)`.\n"
           "pub const TITLES: &[(&str, &str)] = &[\n" );
   for( i = 0; systems[ i ]; i++ ) {
      for( k = 0; k < 3; k++ ) {
         sprintf( a, "System=%s,UseDefs=0%s", systems[ i ], extras[ k ] );
         title( a );
      }
      sprintf( a, "System=%s,UseDefs=1", systems[ i ] );
      title( a );
   }
   printf( "];\n\n"
           "/// `(target settings, template settings, the point (1, 0.5) converted\n"
           "/// or None, or the error)`.\n"
           "pub type Case = (&'static str, &'static str, Result<Option<[f64; 2]>, &'static str>);\n\n"
           "pub const CONVERSIONS: &[Case] = &[\n" );
   for( i = 0; systems[ i ]; i++ ) {
      for( k = 0; extras[ k ]; k++ ) {
         /* The target alone has UseDefs=0, then the template alone. */
         sprintf( a, "System=%s,UseDefs=0%s", systems[ i ], extras[ k ] );
         convert( a, "System=GALACTIC" );
         sprintf( a, "System=GALACTIC" );
         sprintf( b, "System=%s,UseDefs=0%s", systems[ i ], extras[ k ] );
         convert( a, b );
      }
   }
   for( i = 0; systems[ i ]; i++ ) {
      for( j = 0; systems[ j ]; j++ ) {
         if( i == j ) continue;
         sprintf( a, "System=%s,UseDefs=0", systems[ i ] );
         sprintf( b, "System=%s", systems[ j ] );
         convert( a, b );
      }
   }
   printf( "];\n" );
   return 0;
}
