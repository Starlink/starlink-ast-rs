/* wcsmap_pv_probe -- capture the projection parameter values C's astGetPV
 * gives (wcsmap.c GetPV): the defaults of unset latitude parameters, the
 * longitude parameters 0 to 2, which default to 0 and the native longitude
 * and latitude of the reference point except for TPN, a bad value for an
 * unset parameter without a default, and AST__AXIIN for an invalid axis or
 * parameter index.
 *
 * Prints Rust source for crates/starlink-ast/tests/wcsmap_pv_oracle/cases.rs:
 *
 *   ./wcsmap_pv_probe > ../../crates/starlink-ast/tests/wcsmap_pv_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

/* Print a value as a Rust f64 literal, with the fewest digits that read
   back as the same value. */
static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

/* One case: a WcsMap of "type" with the "settings", and the value of
   PV<axis>_<m>, or None when astGetPV reports an error. */
static void emit( const char *name, int type, const char *code, const char *settings,
                  int axis, int m ) {
   int status = 0, *old = astWatch( &status );
   char attr[ 20 ];
   AstWcsMap *map = astWcsMap( 2, type, 1, 2, "%s", settings );
   double v;
   sprintf( attr, "PV%d_%d", axis, m );
   v = astGetD( map, attr );
   printf( "    (\"%s\", \"%s\", \"%s\", %d, %d, ", name, code, settings, axis, m );
   if( status ) {
      printf( "None),\n" );
   } else {
      printf( "Some(" );
      lit( v );
      printf( ")),\n" );
   }
   astClearStatus;
   map = astAnnul( map );
   astWatch( old );
}

int main( void ) {
   printf( "// Generated by tools/oracle_fixtures/wcsmap_pv_probe.c. Do not edit.\n\n"
           "/// `(case, WcsMap projection type, settings, axis, parameter,\n"
           "/// astGetPV's value or None for an error)`.\n"
           "pub type Case = (&'static str, &'static str, &'static str, usize, usize, Option<f64>);\n\n"
           "pub const CASES: &[Case] = &[\n" );
   emit( "tan_lon_0", AST__TAN, "TAN", " ", 1, 0 );
   emit( "tan_lon_1", AST__TAN, "TAN", " ", 1, 1 );
   emit( "tan_lon_2", AST__TAN, "TAN", " ", 1, 2 );
   emit( "tan_lon_3", AST__TAN, "TAN", " ", 1, 3 );
   emit( "tan_lat_0", AST__TAN, "TAN", " ", 2, 0 );
   emit( "tan_lat_1_invalid", AST__TAN, "TAN", " ", 2, 1 );
   emit( "tan_axis_3_invalid", AST__TAN, "TAN", " ", 3, 0 );
   emit( "tan_lon_set", AST__TAN, "TAN", "PV1_1=10", 1, 1 );
   emit( "szp_lat_3", AST__SZP, "SZP", " ", 2, 3 );
   emit( "air_lat_1", AST__AIR, "AIR", " ", 2, 1 );
   emit( "cyp_lat_2", AST__CYP, "CYP", " ", 2, 2 );
   emit( "hpx_lat_1", AST__HPX, "HPX", " ", 2, 1 );
   emit( "hpx_lat_2", AST__HPX, "HPX", " ", 2, 2 );
   emit( "cop_lat_1_unset", AST__COP, "COP", " ", 2, 1 );
   emit( "cop_lat_1", AST__COP, "COP", "PV2_1=45", 2, 1 );
   emit( "cop_lon_2", AST__COP, "COP", "PV2_1=45", 1, 2 );
   emit( "zea_lon_2", AST__ZEA, "ZEA", " ", 1, 2 );
   emit( "car_lon_2", AST__CAR, "CAR", " ", 1, 2 );
   emit( "tpn_lon_1", AST__TPN, "TPN", " ", 1, 1 );
   emit( "tpn_lat_1", AST__TPN, "TPN", " ", 2, 1 );
   printf( "];\n" );
   return 0;
}
