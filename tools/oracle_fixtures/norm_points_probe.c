/* norm_points_probe -- capture astNormPoints, which normalises a set of
 * points through the Frame's astNormalPoints method (frame.c), and the
 * boundary mesh astGetRegionMesh returns, which it normalises in the same
 * way (region.c GetRegionMesh). A SkyFrame normalises each point and, when
 * asked for contiguous values, keeps the longitudes on one side of the
 * widest gap between them (skyframe.c NormalPoints). A CmpFrame hands each
 * component its own axes, and a FrameSet its current Frame.
 *
 * Prints Rust source for crates/starlink-ast/tests/norm_points_oracle/cases.rs:
 *
 *   ./norm_points_probe > ../../crates/starlink-ast/tests/norm_points_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

#define D2R ( 3.14159265358979323846 / 180.0 )
#define NPOINT 6

/* Longitude and latitude of each point, in degrees: a group crossing zero
   longitude, one given a turn out, and a latitude past the pole. */
static const double lon[ NPOINT ] = { 350.0, 355.0, 5.0, 10.0, 365.0, 2.0 };
static const double lat[ NPOINT ] = { 0.0, 10.0, -10.0, 20.0, 30.0, 100.0 };

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".en" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

/* Normalise the points with "frame", whose first two axes are given the
   longitude and latitude in the order "lon_axis" says, and any third axis
   the value 7.5, and print the result as rows. */
static void norm( const char *name, AstFrame *frame, int ncoord, int lon_axis, int contig ) {
   double in[ 3 ][ NPOINT ], out[ 3 ][ NPOINT ];
   int i, c;

   for( i = 0; i < NPOINT; i++ ) {
      in[ lon_axis ][ i ] = lon[ i ] * D2R;
      in[ 1 - lon_axis ][ i ] = lat[ i ] * D2R;
      in[ 2 ][ i ] = 7.5;
   }
   astNormPoints( frame, NPOINT, ncoord, NPOINT, (const double *) in, contig, ncoord,
                  NPOINT, (double *) out );
   printf( "    (\"%s\", &[", name );
   for( i = 0; i < NPOINT; i++ ) {
      printf( "&[" );
      for( c = 0; c < ncoord; c++ ) {
         num( out[ c ][ i ] );
         printf( "%s", c < ncoord - 1 ? ", " : "" );
      }
      printf( "]%s", i < NPOINT - 1 ? ", " : "" );
   }
   printf( "]),\n" );
}

int main( void ) {
   AstFrame *sky, *swapped, *plain, *cmp;
   AstFrameSet *fs;
   AstRegion *circle;
   double centre[ 2 ] = { 0.0, 0.0 }, radius = 5.0 * D2R;
   double mesh[ 2 ][ 400 ];
   int perm[ 2 ] = { 2, 1 };
   int i, npoint, status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/norm_points_probe.c. Do not edit.\n\n"
           "// Each value is printed with 17 digits so that it reads back exactly.\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "/// Longitude and latitude of each point, in degrees.\n"
           "pub const LON: [f64; %d] = [350.0, 355.0, 5.0, 10.0, 365.0, 2.0];\n"
           "pub const LAT: [f64; %d] = [0.0, 10.0, -10.0, 20.0, 30.0, 100.0];\n\n"
           "/// `(case, the normalised points)`.\n"
           "pub const CASES: &[(&str, &[&[f64]])] = &[\n", NPOINT, NPOINT );

   sky = (AstFrame *) astSkyFrame( " " );
   norm( "sky", sky, 2, 0, 0 );
   norm( "sky_contig", sky, 2, 0, 1 );

   swapped = astCopy( sky );
   astPermAxes( swapped, perm );
   norm( "sky_swapped_contig", swapped, 2, 1, 1 );

   plain = astFrame( 1, " " );
   cmp = (AstFrame *) astCmpFrame( sky, plain, " " );
   norm( "cmpframe_contig", cmp, 3, 0, 1 );

   fs = astFrameSet( sky, " " );
   norm( "frameset_contig", (AstFrame *) fs, 2, 0, 1 );
   printf( "];\n\n" );

   /* The boundary mesh of a circle of radius 5 degrees about (0,0). */
   circle = (AstRegion *) astCircle( sky, 1, centre, &radius, NULL, " " );
   astGetRegionMesh( circle, 1, 400, 2, &npoint, (double *) mesh );
   printf( "/// The boundary mesh of a Circle of radius 5 degrees about (0,0).\n"
           "pub const CIRCLE_MESH: &[[f64; 2]] = &[\n" );
   for( i = 0; i < npoint; i++ ) {
      printf( "    [" );
      num( mesh[ 0 ][ i ] );
      printf( ", " );
      num( mesh[ 1 ][ i ] );
      printf( "],\n" );
   }
   printf( "];\n" );

   circle = astAnnul( circle );
   fs = astAnnul( fs );
   cmp = astAnnul( cmp );
   plain = astAnnul( plain );
   swapped = astAnnul( swapped );
   sky = astAnnul( sky );
   return 0;
}
