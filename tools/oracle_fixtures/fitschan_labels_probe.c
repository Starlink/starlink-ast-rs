/* fitschan_labels_probe -- capture the axis Labels a FITS-WCS read gives.
 * WcsOthers (fitschan.c) labels each axis no other function claims with its
 * CNAME, else with the comment of its CTYPE card, else with its CTYPE
 * value. It uses the comments only when more than one axis is left to it,
 * each has a comment, and no comment repeats an earlier one, comparing each
 * comment with those at the positions of the earlier such axes counted from
 * zero; WcsFcRead stores the comment of every CTYPE card it reads.
 *
 * For each header: "! <status>" or "= none" if the read gives no FrameSet,
 * and otherwise, for each Frame, its Domain and then the Label of each axis.
 *
 * Prints Rust source for crates/starlink-ast/tests/fitschan_labels_oracle/cases.rs:
 *
 *   ./fitschan_labels_probe > ../../crates/starlink-ast/tests/fitschan_labels_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void emit( const char *name, const char **header ) {
   AstFitsChan *fc;
   AstFrameSet *fs;
   AstFrame *frm;
   char attr[ 40 ];
   int i, iax;

   astBegin;
   printf( "    (\n        " );
   str( name );
   printf( ",\n        &[" );
   for( i = 0; header[ i ]; i++ ) {
      if( i ) printf( ", " );
      str( header[ i ] );
   }
   printf( "],\n        concat!(\n" );

   fc = astFitsChan( NULL, NULL, "Encoding=FITS-WCS" );
   for( i = 0; header[ i ]; i++ ) astPutFits( fc, header[ i ], 0 );
   astClear( fc, "Card" );
   fs = astRead( fc );
   if( !astOK ) {
      printf( "            \"! %d\\n\",\n", astStatus );
      astClearStatus;
   } else if( !fs ) {
      printf( "            \"= none\\n\",\n" );
   } else {
      for( i = 1; i <= astGetI( fs, "Nframe" ); i++ ) {
         frm = astGetFrame( fs, i );
         printf( "            " );
         printf( "\"= frame %d ", i );
         printf( "%s\\n\",\n", astGetC( frm, "Domain" ) );
         for( iax = 1; iax <= astGetI( frm, "Naxes" ); iax++ ) {
            sprintf( attr, "Label(%d)", iax );
            printf( "            \"| " );
            {
               const char *l = astGetC( frm, attr );
               for( ; *l; l++ ) {
                  if( *l == '"' || *l == '\\' ) putchar( '\\' );
                  putchar( *l );
               }
            }
            printf( "\\n\",\n" );
         }
      }
   }
   printf( "        ),\n    ),\n" );
   astEnd;
}

