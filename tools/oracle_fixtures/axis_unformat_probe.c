/* axis_unformat_probe -- capture astUnformat on a plain Frame axis for a
 * corpus of strings. C's AxisUnformat (axis.c:1335) reads the value with
 * sscanf "%lf %n", counting trailing white space, and otherwise accepts the
 * "<bad>" token.
 *
 * Captured on macOS, whose scanf takes the longest prefix strtod accepts.
 * Where an exponent marker or "0x" has no digits after it, or a word is a
 * partial "infinity" or "nan(...)", the C standard makes the input item the
 * whole prefix and the conversion fails; libraries differ there. Those
 * cases are marked "libc-dependent" in the generated file, and the port
 * follows strtod for them.
 *
 * Prints Rust source for crates/starlink-ast/tests/axis_unformat_oracle/cases.rs:
 *
 *   ./axis_unformat_probe > ../../crates/starlink-ast/tests/axis_unformat_oracle/cases.rs
 */
#include <math.h>
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\t' ) {
         printf( "\\t" );
      } else if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

static void num( double v ) {
   char buf[ 40 ];
   if( isnan( v ) ) {
      printf( "f64::NAN" );
   } else if( isinf( v ) ) {
      printf( v > 0 ? "f64::INFINITY" : "f64::NEG_INFINITY" );
   } else {
      snprintf( buf, sizeof( buf ), "%.17g", v );
      if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
      printf( "%s", buf );
   }
}

int main( void ) {
   int status = 0;
   const char *portable[] = {
      "0x10", "0X1.8p3", "-0x.8", "0x1p-1074", "0x1.p9", "0x1.fffffffffffff8p0",
      "0x1.0000000000000800000000001p0", "0x.0000000000001p-1022", "1e5x", "1.5e3",
      " 12 ", "12abc", "  -7  x", "inf", "-Infinity", "infx", "nan", "NaN(123)",
      "+.5", ".", "-", "+", "1e400", "-1e400", "1e-400", "<bad>", " < B a D > x",
      "<bad", "1.2.3", "  ", "", "1,5", "4.9e-324", "2.4703282292062327e-324",
      "2.4703282292062328e-324", "e5", "1.e2", "-0", "-0.0e7", "\t3\n", NULL
   };
   const char *libc_dependent[] = {
      "0x", "0xg", "0x.p9", "1e+x", "1e", "1e-", "1e+", "infin", "nan(", "nan(1", NULL
   };
   const char **lists[] = { portable, libc_dependent };
   AstFrame *f;
   int i, l;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/axis_unformat_probe.c on macOS.\n"
           "// Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// `(string, characters read, value)`, for the strings every C library\n"
           "/// reads alike, then the libc-dependent ones.\n"
           "pub const CASES: &[(&str, usize, f64)] = &[\n" );

   f = astFrame( 1, " " );
   for( l = 0; l < 2; l++ ) {
      if( l == 1 ) printf( "    // libc-dependent: see the probe.\n" );
      for( i = 0; lists[ l ][ i ]; i++ ) {
         double v = AST__BAD;
         int n = astUnformat( f, 1, lists[ l ][ i ], &v );
         printf( "    (" );
         str( lists[ l ][ i ] );
         printf( ", %d, ", n );
         num( v );
         printf( "),\n" );
      }
   }
   printf( "];\n" );
   return 0;
}
