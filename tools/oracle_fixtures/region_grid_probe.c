/* region_grid_probe -- capture the interior grids astGetRegionMesh returns
 * (surface unset) and the boundary mesh of a Prism. A Box makes its grid
 * with its base Frame's astFrameGrid (box.c RegBaseGrid); any other Region
 * keeps the points of a covering Box's grid that it contains, remaking the
 * grid up to three times to bring the count near MeshSize (region.c
 * RegBaseGrid). A Prism's boundary is built from its components' meshes and
 * grids (prism.c RegBaseMesh).
 *
 * Needs the CmpFrame FrameGrid fix (db5199d7 on u/timj/norm-unit).
 *
 * Prints Rust source for crates/ast-core/tests/region_grid_oracle/cases.rs:
 *
 *   ./region_grid_probe > ../../crates/ast-core/tests/region_grid_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

#define D2R ( 3.14159265358979323846 / 180.0 )
#define MAXPT 2000

static double mesh[ 3 ][ MAXPT ];

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".en" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

/* Print the mesh (surface set) or grid (surface unset) of "reg" as a
   constant named "name". */
static void emit( const char *name, AstRegion *reg, int surface ) {
   static int first = 1;
   int i, c, np = 0, nc = astGetI( reg, "Naxes" );
   astGetRegionMesh( reg, surface, MAXPT, 3, &np, (double *) mesh );
   printf( "%spub const %s: &[&[f64]] = &[\n", first ? "" : "\n", name );
   first = 0;
   for( i = 0; i < np; i++ ) {
      printf( "    &[" );
      for( c = 0; c < nc; c++ ) {
         num( mesh[ c ][ i ] );
         printf( "%s", c < nc - 1 ? ", " : "" );
      }
      printf( "],\n" );
   }
   printf( "];\n" );
}

int main( void ) {
   AstFrame *f1, *f2, *sky;
   AstRegion *reg, *circ, *intv;
   double lo[ 3 ] = { 0.0, 0.0, 0.0 }, hi[ 3 ] = { 1.0, 2.0, 3.0 };
   double centre[ 2 ] = { 0.0, 0.0 }, radius = 1.0;
   double poly[ 8 ];
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/region_grid_probe.c. Do not edit.\n\n"
           "// Each value is printed with 17 digits so that it reads back exactly.\n"
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n" );

   /* A Box on a 2-D Frame. */
   f2 = astFrame( 2, " " );
   reg = (AstRegion *) astBox( f2, 1, lo, hi, NULL, "MeshSize=12" );
   emit( "BOX_PLAIN", reg, 0 );
   reg = astAnnul( reg );

   /* A Box on a CmpFrame of two 1-D Frames. */
   reg = (AstRegion *) astBox( astCmpFrame( astFrame( 1, " " ), astFrame( 1, " " ), " " ),
                               1, lo, hi, NULL, "MeshSize=12" );
   emit( "BOX_CMP", reg, 0 );
   reg = astAnnul( reg );

   /* A Box on a CmpFrame of a SkyFrame and a 1-D Frame. */
   {
      double slo[ 3 ] = { -0.2, -0.1, 0.0 }, shi[ 3 ] = { 0.2, 0.1, 3.0 };
      reg = (AstRegion *) astBox( astCmpFrame( astSkyFrame( " " ), astFrame( 1, " " ), " " ),
                                  1, slo, shi, NULL, "MeshSize=60" );
      emit( "BOX_SKY_CMP", reg, 0 );
      reg = astAnnul( reg );
   }

   /* A Circle of radius 1 on a 2-D Frame. */
   circ = (AstRegion *) astCircle( f2, 1, centre, &radius, NULL, "MeshSize=40" );
   emit( "CIRCLE_PLAIN", circ, 0 );

   /* A Circle of radius 5 degrees about (0,0) on a SkyFrame. */
   sky = (AstFrame *) astSkyFrame( " " );
   radius = 5.0 * D2R;
   reg = (AstRegion *) astCircle( sky, 1, centre, &radius, NULL, "MeshSize=50" );
   emit( "CIRCLE_SKY", reg, 0 );
   reg = astAnnul( reg );

   /* A Polygon on a SkyFrame, a quadrilateral about RA 30 degrees, its
      vertices in the order that makes it the small region in C's (STC)
      convention. */
   poly[ 0 ] = 25.0 * D2R; poly[ 1 ] = 25.0 * D2R; poly[ 2 ] = 35.0 * D2R; poly[ 3 ] = 35.0 * D2R;
   poly[ 4 ] = -5.0 * D2R; poly[ 5 ] = 5.0 * D2R; poly[ 6 ] = 5.0 * D2R; poly[ 7 ] = -5.0 * D2R;
   reg = (AstRegion *) astPolygon( sky, 4, 4, poly, NULL, "MeshSize=40" );
   emit( "POLYGON_SKY", reg, 0 );
   reg = astAnnul( reg );

   /* A Prism: the plain Circle extruded along an Interval on a 1-D Frame. */
   f1 = astFrame( 1, " " );
   {
      double ilo[ 1 ] = { 0.0 }, ihi[ 1 ] = { 3.0 };
      intv = (AstRegion *) astInterval( f1, ilo, ihi, NULL, " " );
   }
   reg = (AstRegion *) astPrism( circ, intv, "MeshSize=60" );
   emit( "PRISM_MESH", reg, 1 );
   emit( "PRISM_GRID", reg, 0 );
   reg = astAnnul( reg );

   intv = astAnnul( intv );
   circ = astAnnul( circ );
   f1 = astAnnul( f1 );
   sky = astAnnul( sky );
   f2 = astAnnul( f2 );
   return 0;
}
