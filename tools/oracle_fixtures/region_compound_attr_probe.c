/* region_compound_attr_probe -- capture how a CmpRegion and a Prism share
 * Closed, MeshSize and FillFactor with their components: setting or
 * clearing Closed or MeshSize on either sets or clears it on both components
 * too (cmpregion.c and prism.c MAKE_SET, MAKE_CLEAR); astInitCmpRegion
 * copies the first component's set MeshSize and Closed onto the CmpRegion,
 * and so onto both components; and the default FillFactor is the first
 * component's for a CmpRegion (cmpregion.c GetFillFactor) and the product
 * of the components' for a Prism (prism.c GetFillFactor).
 *
 * Prints Rust source for
 * crates/starlink-ast/tests/region_compound_attr_oracle/cases.rs:
 *
 *   ./region_compound_attr_probe > ../../crates/starlink-ast/tests/region_compound_attr_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static char dump[ 40000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

/* Print the shortest literal that reads back as `v`. */
static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void emit( const char *name, AstObject *obj ) {
   AstChannel *ch;
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   printf( "pub const %s: &str = ", name );
   str( dump );
   printf( ";\n" );
}

int main( void ) {
   int status = 0;
   AstRegion *b1, *b2, *iv, *cmp, *prism;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_compound_attr_probe.c. Do not edit.\n\n" );
   {
      double l1[] = { 0.0, 0.0 }, u1[] = { 2.0, 2.0 }, l2[] = { 1.0, 1.0 }, u2[] = { 3.0, 3.0 };
      b1 = (AstRegion *) astBox( astFrame( 2, " " ), 1, l1, u1, NULL, "MeshSize=50,Closed=0,FillFactor=0.5" );
      b2 = (AstRegion *) astBox( astFrame( 2, " " ), 1, l2, u2, NULL, " " );
      cmp = (AstRegion *) astCmpRegion( b1, b2, AST__OR, " " );
      printf( "/// The OR of the Box [0,2]x[0,2], with MeshSize 50, Closed 0 and\n"
              "/// FillFactor 0.5, and the Box [1,3]x[1,3], as made.\n" );
      emit( "CMP_MADE", (AstObject *) cmp );
      printf( "/// Its FillFactor, unset on the CmpRegion.\n" );
      printf( "pub const CMP_FILL: f64 = " );
   lit( astGetD( cmp, "FillFactor" ) );
   printf( ";\n" );
      astSetI( cmp, "MeshSize", 30 );
      astSetI( cmp, "Closed", 1 );
      printf( "/// After setting MeshSize 30 and Closed 1 on it.\n" );
      emit( "CMP_SET", (AstObject *) cmp );
      astClear( cmp, "MeshSize,Closed" );
      printf( "/// After clearing both.\n" );
      emit( "CMP_CLEARED", (AstObject *) cmp );
   }
   {
      double l[] = { 0.0, 0.0 }, u[] = { 1.0, 1.0 }, l1 = 0.0, u1 = 1.0;
      b1 = (AstRegion *) astBox( astFrame( 2, " " ), 1, l, u, NULL, "FillFactor=0.5" );
      iv = (AstRegion *) astInterval( astFrame( 1, " " ), &l1, &u1, NULL, "FillFactor=0.4" );
      prism = (AstRegion *) astPrism( b1, iv, " " );
      printf( "/// The Prism of the Box [0,1]x[0,1], FillFactor 0.5, and the Interval\n"
              "/// [0,1], FillFactor 0.4: its FillFactor, unset on the Prism.\n" );
      printf( "pub const PRISM_FILL: f64 = " );
   lit( astGetD( prism, "FillFactor" ) );
   printf( ";\n" );
      astSetI( prism, "MeshSize", 30 );
      astSetI( prism, "Closed", 0 );
      printf( "/// After setting MeshSize 30 and Closed 0 on it.\n" );
      emit( "PRISM_SET", (AstObject *) prism );
      astClear( prism, "MeshSize,Closed" );
      printf( "/// After clearing both.\n" );
      emit( "PRISM_CLEARED", (AstObject *) prism );
   }
   return status;
}
