/* equal_probe -- capture astEqual for Mappings whose Equal takes account of
 * the Invert flag in class-specific ways: a WinMap (winmap.c Equal compares
 * the stored terms first, then the applied ones), a SelectorMap (number of
 * inputs, Regions and bad value, not the Invert flag) and a TranMap read
 * from a dump whose recorded component orientation (InvA) differs from the
 * component's Invert (tranmap.c Equal restores the recorded orientation);
 * and WcsMaps whose projection parameters are set, unset or cleared.
 *
 * Prints Rust source for crates/starlink-ast/tests/equal_oracle/cases.rs:
 *
 *   ./equal_probe > ../../crates/starlink-ast/tests/equal_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static char text[ 8000 ];
static const char *source;
static const char *drop;

/* Keep each dump line except those containing "drop". */
static void sink( const char *line ) {
   if( drop && strstr( line, drop ) ) {
      drop = NULL;
      return;
   }
   strcat( text, line );
   strcat( text, "\n" );
}

static const char *next_line( void ) {
   static char line[ 400 ];
   const char *end;
   size_t n;
   if( !*source ) return NULL;
   end = strchr( source, '\n' );
   n = end - source;
   memcpy( line, source, n );
   line[ n ] = 0;
   source = end + 1;
   return line;
}

/* Write "obj" without the first dump line containing "without", and read it
   back. */
static AstObject *reread( AstObject *obj, const char *without ) {
   AstChannel *ch;
   AstObject *back;
   text[ 0 ] = 0;
   drop = without;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   source = text;
   ch = astChannel( next_line, NULL, " " );
   back = astRead( ch );
   ch = astAnnul( ch );
   return back;
}

static void emit( const char *name, AstObject *a, AstObject *b ) {
   printf( "    (\"%s\", %s),\n", name, astEqual( a, b ) ? "true" : "false" );
}

int main( void ) {
   int status = 0;
   double zero[] = { 0.0 }, one[] = { 1.0 }, mone[] = { -1.0 }, two[] = { 2.0 };
   double three[] = { 3.0 }, half[] = { 0.5 }, mhalf[] = { -0.5 };
   double c1[] = { 0.0, 0.0 }, c2[] = { 5.0, 5.0 }, r[] = { 1.0 };
   AstObject *a, *b;
   AstRegion *regs[ 2 ];
   AstFrame *frm;
   AstZoomMap *z2;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/equal_probe.c. Do not edit.\n\n"
           "/// `(case, C's astEqual)`.\n"
           "pub const CASES: &[(&str, bool)] = &[\n" );

   /* x -> -x is its own inverse. */
   a = (AstObject *) astWinMap( 1, zero, one, zero, mone, " " );
   b = astCopy( a );
   astInvert( b );
   emit( "winmap_self_inverse_vs_inverted_copy", a, b );

   /* x -> 2x + 1, and the inverse of x -> 0.5x - 0.5. */
   a = (AstObject *) astWinMap( 1, zero, one, one, three, " " );
   b = (AstObject *) astWinMap( 1, zero, two, mhalf, half, " " );
   astInvert( b );
   emit( "winmap_inverse_of_its_inverse", a, b );

   frm = astFrame( 2, " " );
   regs[ 0 ] = (AstRegion *) astCircle( frm, 1, c1, r, NULL, " " );
   regs[ 1 ] = (AstRegion *) astCircle( frm, 1, c2, r, NULL, " " );
   a = (AstObject *) astSelectorMap( 1, (void **) regs, AST__BAD, " " );
   b = (AstObject *) astSelectorMap( 2, (void **) regs, AST__BAD, " " );
   emit( "selectormap_one_region_vs_two", a, b );
   b = astCopy( a );
   astInvert( b );
   emit( "selectormap_vs_inverted_copy", a, b );
   {
      AstFrame *f1 = astFrame( 1, " " );
      double lo[] = { 0.0 }, hi[] = { 1.0 };
      AstRegion *r1[ 1 ];
      r1[ 0 ] = (AstRegion *) astBox( f1, 1, lo, hi, NULL, " " );
      a = (AstObject *) astSelectorMap( 1, (void **) r1, AST__BAD, " " );
      b = astCopy( a );
      astInvert( b );
      emit( "selectormap_1d_vs_inverted_copy", a, b );
   }

   /* WcsMaps compare each projection parameter, an unset one differing
      from one set to zero (wcsmap.c Equal, fixed upstream in 47826767). */
   {
      AstObject *plain = (AstObject *) astWcsMap( 2, AST__SIN, 1, 2, " " );
      a = (AstObject *) astWcsMap( 2, AST__SIN, 1, 2, "PV2_1=0.5" );
      emit( "wcsmap_pv_vs_none", a, plain );
      b = (AstObject *) astWcsMap( 2, AST__SIN, 1, 2, "PV2_1=0.0" );
      emit( "wcsmap_zero_pv_vs_none", b, plain );
      b = (AstObject *) astWcsMap( 2, AST__SIN, 1, 2, "PV2_1=0.5,PV2_2=1.0" );
      astClear( b, "PV2_2" );
      emit( "wcsmap_pv_vs_pv_with_one_cleared", a, b );
      b = (AstObject *) astWcsMap( 2, AST__SIN, 1, 2, "PV2_1=0.5" );
      emit( "wcsmap_same_pv", a, b );
   }

   /* A TranMap whose first component was inverted when it was made, read
      back without that component's Invert card. */
   z2 = astZoomMap( 1, 2.0, " " );
   astInvert( z2 );
   a = (AstObject *) astTranMap( z2, astZoomMap( 1, 0.5, " " ), " " );
   b = reread( a, " Invert = 1" );
   if( !strstr( text, "InvA = 1" ) ) {
      fprintf( stderr, "the TranMap dump does not record InvA = 1\n" );
      return 1;
   }
   emit( "tranmap_vs_reread_without_component_invert", a, b );

   printf( "];\n" );
   return status;
}
