/* use_defs_probe -- capture the UseDefs attribute of Frames: its default of
 * 1, the default a CmpFrame takes from its first component and a FrameSet
 * from its current Frame (cmpframe.c, frameset.c GetUseDefs), and the
 * UseDfs item a dump writes when it is set (object.c Dump).
 *
 * Prints Rust source for crates/starlink-ast/tests/use_defs_oracle/cases.rs:
 *
 *   ./use_defs_probe > ../../crates/starlink-ast/tests/use_defs_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static char dump[ 20000 ];
static int dumplen;

static void sink( const char *line ) {
   dumplen += sprintf( dump + dumplen, "%s\n", line );
}

static void emit( const char *name, AstObject *o ) {
   AstChannel *ch = astChannel( NULL, sink, "Comment=1" );
   dumplen = 0;
   dump[ 0 ] = 0;
   astWrite( ch, o );
   printf( "    (\"%s\", %s, %s, r#\"%s\"#),\n", name,
           astGetI( o, "UseDefs" ) ? "true" : "false",
           astTest( o, "UseDefs" ) ? "true" : "false", dump );
}

int main( void ) {
   int status = 0;
   AstFrame *f, *g;
   AstFrameSet *fs;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/use_defs_probe.c. Do not edit.\n\n"
           "/// `(case, UseDefs, whether it is set, the dump)`.\n"
           "pub const CASES: &[(&str, bool, bool, &str)] = &[\n" );

   emit( "frame_default", (AstObject *) astFrame( 1, " " ) );
   emit( "frame_off", (AstObject *) astFrame( 1, "UseDefs=0" ) );
   emit( "frame_off_ident", (AstObject *) astFrame( 1, "UseDefs=0,Ident=Me" ) );
   emit( "spec_off", (AstObject *) astSpecFrame( "UseDefs=0" ) );
   emit( "sky_on", (AstObject *) astSkyFrame( "UseDefs=1" ) );
   emit( "time_off", (AstObject *) astTimeFrame( "UseDefs=0" ) );

   f = (AstFrame *) astSkyFrame( "UseDefs=0" );
   emit( "cmp_from_first", (AstObject *) astCmpFrame( f, astFrame( 1, " " ), " " ) );
   emit( "cmp_second_ignored",
         (AstObject *) astCmpFrame( astFrame( 1, " " ), astSkyFrame( "UseDefs=0" ), " " ) );

   g = astFrame( 2, "UseDefs=0" );
   fs = astFrameSet( astFrame( 2, " " ), " " );
   astAddFrame( fs, AST__BASE, astUnitMap( 2, " " ), g );
   emit( "frameset_from_current", (AstObject *) fs );
   astSetI( fs, "UseDefs", 1 );
   emit( "frameset_own", (AstObject *) fs );

   printf( "];\n" );
   return 0;
}
