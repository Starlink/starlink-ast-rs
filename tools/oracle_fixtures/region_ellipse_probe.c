/* region_ellipse_probe -- capture Ellipse membership (ellipse.c Transform,
 * with its axes from CalcPars): an Ellipse given by its centre, the end of
 * its primary axis and another point on it (form 0), whose second point is
 * not the end of the secondary axis, and an Ellipse in an ICRS SkyFrame
 * tested over a grid, where the components along and across the primary
 * axis are measured on the sky; and a Cartesian Ellipse given by its centre,
 * axis half-lengths and angle (form 1). Each Ellipse is dumped, for the port
 * to read, and for the port's EllipseBuilder, which takes form 1's
 * arguments, to reproduce.
 *
 * Prints Rust source for crates/ast-core/tests/region_ellipse_oracle/cases.rs:
 *
 *   ./region_ellipse_probe > ../../crates/ast-core/tests/region_ellipse_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

#define NX 61
#define NY 51

static char dump[ 20000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

/* One case: `(name, C's dump, membership of each test point)`. */
static void emit( const char *name, AstRegion *reg, int np, const double *x,
                  const double *y ) {
   static double xo[ NX*NY ], yo[ NX*NY ];
   AstChannel *ch;
   int i;
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, reg );
   ch = astAnnul( ch );
   astTran2( reg, np, x, y, 1, xo, yo );
   printf( "    (\"%s\", ", name );
   str( dump );
   printf( ", \"" );
   for( i = 0; i < np; i++ ) putchar( xo[ i ] == AST__BAD ? '0' : '1' );
   printf( "\"),\n" );
}

int main( void ) {
   int status = 0, i, j;
   static double gx[ NX*NY ], gy[ NX*NY ];

   astWatch( &status );
   for( j = 0; j < NY; j++ ) {
      for( i = 0; i < NX; i++ ) {
         gx[ j*NX + i ] = 0.7 + 0.01*i;
         gy[ j*NX + i ] = 0.65 + 0.006*j;
      }
   }
   printf( "// Generated by tools/oracle_fixtures/region_ellipse_probe.c. Do not edit.\n\n"
           "/// The form-1 test points.\n"
           "pub const FORM1_X: [f64; 4] = [1.0, 1.6, 2.9, 1.0];\n"
           "pub const FORM1_Y: [f64; 4] = [2.0, 3.9, 2.0, 3.1];\n"
           "/// The form-0 test points.\n"
           "pub const FORM0_X: [f64; 4] = [0.0, 0.0, 1.9, 1.0];\n"
           "pub const FORM0_Y: [f64; 4] = [1.2, 0.95, 0.1, 0.9];\n"
           "/// The sky test grid: x = 0.7 + 0.01*i (i < %d), y = 0.65 + 0.006*j\n"
           "/// (j < %d), i varying fastest.\n"
           "pub const GRID: (usize, usize) = (%d, %d);\n\n"
           "/// `(case, C's dump, membership of each test point)`.\n"
           "pub const CASES: &[(&str, &str, &str)] = &[\n", NX, NY, NX, NY );
   {
      double c[] = { 0.0, 0.0 }, p1[] = { 2.0, 0.0 }, p2[] = { 1.0, 0.866 };
      double x[] = { 0.0, 0.0, 1.9, 1.0 }, y[] = { 1.2, 0.95, 0.1, 0.9 };
      emit( "form0", (AstRegion *) astEllipse( astFrame( 2, " " ), 0, c, p1, p2, NULL, " " ),
            4, x, y );
   }
   {
      double c[] = { 1.0, 0.8 }, a[] = { 0.2, 0.1 }, ang = 0.3;
      emit( "sky", (AstRegion *) astEllipse( astSkyFrame( "System=ICRS" ), 1, c, a, &ang,
                                            NULL, " " ), NX*NY, gx, gy );
   }
   {
      double c[] = { 1.0, 2.0 }, a[] = { 2.0, 1.0 }, ang = 0.3;
      double x[] = { 1.0, 1.6, 2.9, 1.0 }, y[] = { 2.0, 3.9, 2.0, 3.1 };
      emit( "form1", (AstRegion *) astEllipse( astFrame( 2, " " ), 1, c, a, &ang, NULL, " " ),
            4, x, y );
   }
   printf( "];\n" );
   return status;
}
