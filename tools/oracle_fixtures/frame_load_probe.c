/* frame_load_probe -- capture what astRead makes of hand-written Native
 * Frame descriptions: the per-axis items Lbl<n>, Sym<n>, Uni<n>, Fmt<n>,
 * Dig<n>, Dir<n>, Top<n> and Bot<n> that astLoadFrame applies to the Axis
 * object it has read (frame.c:15226), a Frame with no axes, and an
 * unrecognised System or AlignSystem (AST__ATTIN, frame.c:15392).
 *
 * Prints Rust source for crates/ast-core/tests/frame_load_oracle/cases.rs:
 *
 *   ./frame_load_probe > ../../crates/ast-core/tests/frame_load_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"
#include "ast_err.h"

static const char **lines;
static int next_line;

static const char *source( void ) {
   return lines[ next_line ] ? lines[ next_line++ ] : NULL;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

static void attr( AstObject *o, const char *name, int axis, int quote ) {
   char key[ 40 ];
   sprintf( key, "%s(%d)", name, axis );
   putchar( '(' );
   if( quote ) {
      str( astGetC( o, key ) );
   } else if( !strcmp( name, "Direction" ) ) {
      printf( "%s", astGetI( o, key ) ? "true" : "false" );
   } else if( !strcmp( name, "Digits" ) ) {
      printf( "%d", astGetI( o, key ) );
   } else {
      num( astGetD( o, key ) );
   }
   printf( ", %s), ", astTest( o, key ) ? "true" : "false" );
}

static void emit( const char *name, const char **text ) {
   AstChannel *ch;
   AstObject *o;
   int i, n;

   printf( "    (\n        \"%s\",\n        &[\n", name );
   for( i = 0; text[ i ]; i++ ) {
      printf( "            " );
      str( text[ i ] );
      printf( ",\n" );
   }
   printf( "        ],\n" );

   lines = text;
   next_line = 0;
   ch = astChannel( source, NULL, " " );
   o = astRead( ch );
   if( !astOK ) {
      printf( "        Err(%s),\n    ),\n",
              astStatus == AST__ATTIN ? "\"Attin\"" : "\"other\"" );
      astClearStatus;
      return;
   }
   n = astGetI( o, "Naxes" );
   printf( "        Ok(&[\n" );
   for( i = 1; i <= n; i++ ) {
      printf( "            (" );
      attr( o, "Label", i, 1 );
      attr( o, "Symbol", i, 1 );
      attr( o, "Unit", i, 1 );
      attr( o, "Format", i, 1 );
      attr( o, "Digits", i, 0 );
      attr( o, "Direction", i, 0 );
      attr( o, "Top", i, 0 );
      attr( o, "Bottom", i, 0 );
      printf( "),\n" );
   }
   printf( "        ]),\n    ),\n" );
}

