/* fitschan_spec_unit_probe -- capture how a FITS-WCS write describes a
 * spectral axis, for SpectralAxes (fitschan.c): the default reference value
 * is the middle of the spectral range when the size of the spectral pixel
 * axis is known and its first pixel otherwise, and a spectral Unit that is
 * not linearly related to the default Unit is cleared first.
 *
 * Each case reads a frequency cube, optionally sets the Unit of its
 * spectral axis, and writes it to a FitsChan holding the given NAXIS cards.
 * For each: the value astWrite returns and the cards written.
 *
 * Prints Rust source for crates/ast-core/tests/fitschan_spec_unit_oracle/cases.rs:
 *
 *   ./fitschan_spec_unit_probe > ../../crates/ast-core/tests/fitschan_spec_unit_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static const char *header[] = { "NAXIS   = 3", "CRPIX1  = 5", "CRPIX2  = 5",
   "CRPIX3  = 10", "CRVAL1  = 10", "CRVAL2  = 20", "CRVAL3  = 1.4E9",
   "CDELT1  = -0.001", "CDELT2  = 0.001", "CDELT3  = 1.0E6",
   "CTYPE1  = 'RA---TAN'", "CTYPE2  = 'DEC--TAN'", "CTYPE3  = 'FREQ'",
   "CUNIT3  = 'Hz'", "SPECSYS = 'LSRK'", "RESTFRQ = 1.420405752E9",
   "RADESYS = 'FK5'", "EQUINOX = 2000.0", NULL };

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

/* "dims" is a '~'-separated list of cards, or empty. */
static void emit( const char *name, const char *unit, const char *dims ) {
   AstFitsChan *fc, *out;
   AstObject *fs;
   char card[ 81 ], buf[ 400 ], *p;
   int i, ret;

   fc = astFitsChan( NULL, NULL, " " );
   for( i = 0; header[ i ]; i++ ) astPutFits( fc, header[ i ], 0 );
   astClear( fc, "Card" );
   fs = astRead( fc );
   if( *unit ) astSetC( fs, "Unit(3)", unit );

   out = astFitsChan( NULL, NULL, "Encoding=FITS-WCS" );
   strcpy( buf, dims );
   for( p = strtok( buf, "~" ); p; p = strtok( NULL, "~" ) ) astPutFits( out, p, 0 );
   ret = astWrite( out, fs );
   astClearStatus;

   printf( "    (\"%s\", ", name );
   str( unit );
   printf( ", " );
   str( dims );
   printf( ", %d, &[\n", ret );
   astClear( out, "Card" );
   while( astFindFits( out, "%f", card, 1 ) ) {
      printf( "        " );
      str( card );
      printf( ",\n" );
   }
   printf( "    ]),\n" );
   out = astAnnul( out );
   fs = astAnnul( fs );
   fc = astAnnul( fc );
}

int main( void ) {
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/fitschan_spec_unit_probe.c. Do not edit.\n\n" );
   printf( "/// `(name, spectral Unit set or empty, the NAXIS cards ('~'-separated),\n"
           "/// astWrite's value, the cards written)`.\n" );
   printf( "pub type Case = (&'static str, &'static str, &'static str, i32,\n"
           "    &'static [&'static str]);\n\n" );
   printf( "pub const CASES: &[Case] = &[\n" );
   emit( "all_dims", "", "NAXIS1  = 10~NAXIS2  = 10~NAXIS3  = 20" );
   emit( "spectral_dim_only", "", "NAXIS3  = 20" );
   emit( "spatial_dims_only", "", "NAXIS1  = 10~NAXIS2  = 10" );
   emit( "no_dims", "", "" );
   emit( "unit_mhz", "MHz", "NAXIS1  = 10~NAXIS2  = 10~NAXIS3  = 20" );
   emit( "unit_log", "log(Hz)", "NAXIS1  = 10~NAXIS2  = 10~NAXIS3  = 20" );
   emit( "unit_log_no_dims", "log(Hz)", "" );
   printf( "];\n" );
   return 0;
}
