/* section_load_probe -- capture what astRead makes of hand-written Native
 * descriptions that place an item in the part of the description belonging
 * to a class other than the one that reads it. Each loader reads its items
 * through astReadClassData (channel.c), which gives it only the items
 * between the previous "IsA" and its own "IsA <class>" (or the "End" line
 * for the object's own class), so a misplaced item is ignored. Each case
 * that misplaces an item has a companion placing it where its class reads
 * it.
 *
 * Prints Rust source for crates/starlink-ast/tests/section_load_oracle/cases.rs:
 *
 *   ./section_load_probe > ../../crates/starlink-ast/tests/section_load_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

static const char **lines;
static int next_line;

static const char *source( void ) {
   return lines[ next_line ] ? lines[ next_line++ ] : NULL;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void num( double v ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", v );
   if( !strpbrk( buf, ".e" ) ) strcat( buf, ".0" );
   printf( "%s", buf );
}

/* Each attribute is named with a one-character prefix giving how to read
   it: 'S' a string, 'I' an integer, 'D' a double, 'Y' a year (Epoch,
   Equinox). */
static void emit( const char *name, const char **text, const char **attrs ) {
   AstChannel *ch;
   AstObject *o;
   int i;

   printf( "    (\n        \"%s\",\n        &[\n", name );
   for( i = 0; text[ i ]; i++ ) {
      printf( "            " );
      str( text[ i ] );
      printf( ",\n" );
   }
   printf( "        ],\n        &[\n" );

   lines = text;
   next_line = 0;
   ch = astChannel( source, NULL, " " );
   o = astRead( ch );
   if( !astOK || !o ) {
      fprintf( stderr, "%s: astRead failed\n", name );
      astClearStatus;
      return;
   }
   for( i = 0; attrs[ i ]; i++ ) {
      const char *a = attrs[ i ] + 1;
      printf( "            (\"%s\", ", a );
      switch( attrs[ i ][ 0 ] ) {
      case 'S':
         printf( "V::S(" );
         str( astGetC( o, a ) );
         break;
      case 'I':
         printf( "V::I(%d", astGetI( o, a ) );
         break;
      case 'D':
         printf( "V::D(" );
         num( astGetD( o, a ) );
         break;
      default:
         printf( "V::Y(" );
         num( astGetD( o, a ) );
      }
      printf( "), %s),\n", astTest( o, a ) ? "true" : "false" );
   }
   printf( "        ],\n    ),\n" );
   o = astAnnul( o );
   ch = astAnnul( ch );
}

#define FRM( n ) "Begin Frame", "Naxes = " #n, "End Frame"

static char *dumped[ 200 ];
static int ndumped;

static void sink( const char *line ) {
   dumped[ ndumped++ ] = strdup( line );
}

/* Dump "obj" with astWrite and emit the dump with the lines "extra"
   inserted before the first line that starts with "marker", ignoring
   leading spaces, or after the "Begin" line if "marker" is NULL. With
   "extra" NULL, the "marker" line is removed instead. */
static void emit_dump( const char *name, AstObject *obj, const char *marker,
                       const char **extra, const char **attrs ) {
   const char *text[ 220 ];
   AstChannel *ch;
   int i, n = 0, done = 0;

   ndumped = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   for( i = 0; i < ndumped; i++ ) {
      const char *l = dumped[ i ] + strspn( dumped[ i ], " " );
      if( !done && marker && !strncmp( l, marker, strlen( marker ) ) ) {
         done = 1;
         if( !extra ) continue;
         for( int j = 0; extra[ j ]; j++ ) text[ n++ ] = extra[ j ];
      }
      text[ n++ ] = dumped[ i ];
      if( !done && !marker ) {
         for( int j = 0; extra[ j ]; j++ ) text[ n++ ] = extra[ j ];
         done = 1;
      }
   }
   if( !done ) {
      fprintf( stderr, "%s: no line starts with %s\n", name, marker );
      exit( 1 );
   }
   text[ n ] = NULL;
   emit( name, text, attrs );
   for( i = 0; i < ndumped; i++ ) free( dumped[ i ] );
}

