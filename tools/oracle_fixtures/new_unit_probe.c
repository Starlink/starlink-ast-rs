/* new_unit_probe -- capture what setting or clearing an axis Unit does to
 * the Label, Symbol and Format of that axis (frame.c SetUnit, ClearUnit and
 * NewUnit): with ActiveUnit set, a set Label and Symbol are rewritten for the
 * new Unit and a set Format is cleared when the Unit changes; trailing
 * spaces are dropped from the Unit.
 *
 * Prints Rust source for crates/starlink-ast/tests/new_unit_oracle/cases.rs:
 *
 *   ./new_unit_probe > ../../crates/starlink-ast/tests/new_unit_oracle/cases.rs
 */
#include <stdio.h>
#include "ast.h"

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) { if( *s == '"' || *s == '\\' ) putchar( '\\' ); putchar( *s ); }
   putchar( '"' );
}

static void emit( const char *name, AstFrame *f ) {
   printf( "    (\"%s\", ", name );
   str( astGetC( f, "Label(1)" ) ); printf( ", " );
   str( astGetC( f, "Symbol(1)" ) ); printf( ", " );
   printf( "%s, ", astTest( f, "Format(1)" ) ? "true" : "false" );
   str( astGetC( f, "Unit(1)" ) ); printf( "),\n" );
}

static AstFrame *frame( int active ) {
   AstFrame *f = astFrame( 1, "Label(1)=Dist,Symbol(1)=d,Format(1)=%%.2f,Unit(1)=m" );
   astSetActiveUnit( f, active );
   return f;
}

int main( void ) {
   int status = 0;
   AstFrame *f;
   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/new_unit_probe.c against\n"
           "// the C library at u/timj/norm-unit 5a2cac2a, past the submodule pin.\n"
           "// Do not edit.\n\n"
           "/// `(case, Label(1), Symbol(1), TestFormat(1), Unit(1))` afterwards.\n"
           "pub const CASES: &[(&str, &str, &str, bool, &str)] = &[\n" );

   f = frame( 1 ); astSet( f, "Unit(1)=log(m)" ); emit( "active_log", f );
   f = frame( 1 ); astSet( f, "Unit(1)=km" ); emit( "active_km", f );
   f = frame( 1 ); astSet( f, "Unit(1)=m" ); emit( "active_same", f );
   f = frame( 0 ); astSet( f, "Unit(1)=log(m)" ); emit( "inactive_log", f );
   f = frame( 1 ); astClear( f, "Unit(1)" ); emit( "active_clear", f );
   f = frame( 1 ); astSetC( f, "Unit(1)", "km   " ); emit( "active_trailing_spaces", f );

   f = (AstFrame *) astSpecFrame( "System=FREQ,Label(1)=Nu,Symbol(1)=n,Format(1)=%%.3f" );
   astSet( f, "Unit(1)=log(Hz)" ); emit( "spec_log", f );
   f = (AstFrame *) astSpecFrame( "System=FREQ,Label(1)=Nu,Format(1)=%%.3f" );
   astSet( f, "Unit(1)=MHz" ); emit( "spec_mhz", f );
   f = (AstFrame *) astTimeFrame( "System=MJD,Label(1)=When,Format(1)=%%.3f" );
   astSet( f, "Unit(1)=s" ); emit( "time_s", f );

   printf( "];\n" );
   return 0;
}
