/* region_overlap_probe -- capture astOverlap codes for pairs of Regions
 * that exercise the per-class dispatch of region.c Overlap/OverlapX: an
 * Interval unbounded along one axis against Boxes that miss, cross and lie
 * inside it (the generic OverlapX falls back to Interval's BndBaseMesh),
 * Regions whose Frames cannot be converted (code 0), NullRegions
 * (nullregion.c Overlap/OverlapX), and Prisms (prism.c Overlap/OverlapX),
 * including one inside a rotated Box, which prism.c compares through the
 * inherited OverlapX. Each pair is compared in both orders.
 *
 * The Prism cases need prism.c from 0516a13d or later, which passes the
 * Regions to that OverlapX in the right order.
 *
 * Prints Rust source for crates/starlink-ast/tests/region_overlap_oracle/cases.rs:
 *
 *   ./region_overlap_probe > ../../crates/starlink-ast/tests/region_overlap_oracle/cases.rs
 */
#include <math.h>
#include <stdio.h>
#include "ast.h"

static void pair( const char *name, AstRegion *a, AstRegion *b ) {
   int ab = astOverlap( a, b );
   int ba = astOverlap( b, a );
   printf( "    (\"%s\", %d, %d),\n", name, ab, ba );
}

int main( void ) {
   int status = 0;
   AstFrame *f, *fa, *fb;
   AstRegion *iv, *bx, *a, *b, *nr;
   double ivl[] = { 0.0, AST__BAD }, ivu[] = { AST__BAD, AST__BAD };

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_overlap_probe.c. Do not edit.\n\n"
           "/// `(case, astOverlap(a, b), astOverlap(b, a))`.\n"
           "pub const CASES: &[(&str, i32, i32)] = &[\n" );

   /* An Interval x >= 0, unbounded on every other side. */
   f = astFrame( 2, " " );
   iv = (AstRegion *) astInterval( f, ivl, ivu, NULL, " " );
   {
      double l[] = { -10.0, -1.0 }, u[] = { -9.0, 1.0 };
      bx = (AstRegion *) astBox( f, 1, l, u, NULL, " " );
      pair( "box_beside_half_plane", bx, iv );
   }
   {
      double l[] = { -1.0, -1.0 }, u[] = { 1.0, 1.0 };
      bx = (AstRegion *) astBox( f, 1, l, u, NULL, " " );
      pair( "box_across_half_plane_edge", bx, iv );
   }
   {
      double l[] = { 5.0, -1.0 }, u[] = { 6.0, 1.0 };
      bx = (AstRegion *) astBox( f, 1, l, u, NULL, " " );
      pair( "box_inside_half_plane", bx, iv );
   }

   /* Boxes in Frames with different Domains cannot be compared. */
   fa = astFrame( 2, "Domain=AAA" );
   fb = astFrame( 2, "Domain=BBB" );
   {
      double l[] = { 0.0, 0.0 }, u[] = { 1.0, 1.0 };
      a = (AstRegion *) astBox( fa, 1, l, u, NULL, " " );
      b = (AstRegion *) astBox( fb, 1, l, u, NULL, " " );
      pair( "different_domains", a, b );
   }

   /* NullRegions, empty and (negated) infinite, against a Box. */
   {
      double l[] = { 0.0, 0.0 }, u[] = { 1.0, 1.0 };
      bx = (AstRegion *) astBox( f, 1, l, u, NULL, " " );
      nr = (AstRegion *) astNullRegion( f, NULL, " " );
      pair( "box_and_null_region", bx, nr );
      astNegate( nr );
      pair( "box_and_negated_null_region", bx, nr );
   }

   /* A Prism: the unit Circle extruded over z in [0, 1]. */
   {
      AstFrame *f1 = astFrame( 1, " " ), *f2 = astFrame( 2, " " ), *f3 = astFrame( 3, " " );
      double c[] = { 0.0, 0.0 }, r = 1.0, zl[] = { 0.0 }, zu[] = { 1.0 };
      double rot = 0.5, m[ 9 ];
      double l[] = { -5.0, -5.0, -5.0 }, u[] = { 5.0, 5.0, 5.0 };
      double hl[] = { 0.0, -5.0, -5.0 };
      AstRegion *prism = (AstRegion *) astPrism(
         astCircle( f2, 1, c, &r, NULL, " " ),
         astInterval( f1, zl, zu, NULL, " " ), " " );
      AstRegion *big = (AstRegion *) astBox( f3, 1, l, u, NULL, " " );
      m[ 0 ] = cos( rot ); m[ 1 ] = 0.0; m[ 2 ] = -sin( rot );
      m[ 3 ] = 0.0;        m[ 4 ] = 1.0; m[ 5 ] = 0.0;
      m[ 6 ] = sin( rot ); m[ 7 ] = 0.0; m[ 8 ] = cos( rot );
      pair( "prism_in_box", prism, big );
      pair( "prism_in_rotated_box", prism,
            astMapRegion( big, astMatrixMap( 3, 3, 0, m, " " ), f3 ) );
      pair( "prism_across_box", prism, (AstRegion *) astBox( f3, 1, hl, u, NULL, " " ) );
      astNegate( prism );
      pair( "negated_prism_and_box", prism, big );
   }

   printf( "];\n" );
   return status;
}
