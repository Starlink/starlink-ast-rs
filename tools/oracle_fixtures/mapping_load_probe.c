/* mapping_load_probe -- capture how Mappings whose dumps leave values out
 * are read back: a PermMap constant or a diagonal MatrixMap element that is
 * bad is written unset and reads back as bad (permmap.c, matrixmap.c Dump
 * and Load), and a WcsMap dump written before the PVi_m keys holds the
 * projection parameters as ProjP<m> (wcsmap.c Load).
 *
 * Each case is the dump read, the dump of what astRead makes of it, and the
 * forward transformation of some points by it.
 *
 * Prints Rust source for crates/starlink-ast/tests/mapping_load_oracle/cases.rs:
 *
 *   ./mapping_load_probe > ../../crates/starlink-ast/tests/mapping_load_oracle/cases.rs
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ast.h"

#define BAD AST__BAD

static char *lines[ 100 ];
static int nlines;
static int next_line;

static void collect( const char *line ) {
   lines[ nlines++ ] = strdup( line );
}

static const char *source( void ) {
   return next_line < nlines ? lines[ next_line++ ] : NULL;
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '"' || *s == '\\' ) putchar( '\\' );
      putchar( *s );
   }
   putchar( '"' );
}

static void print_dump( const char *line ) {
   printf( "            " );
   str( line );
   printf( ",\n" );
}

/* Print a value as a Rust f64 literal, with the fewest digits that read
   back as the same value. */
static void lit( double v ) {
   char buf[ 40 ];
   int prec;
   for( prec = 1; prec < 17; prec++ ) {
      sprintf( buf, "%.*g", prec, v );
      if( strtod( buf, NULL ) == v ) break;
   }
   sprintf( buf, "%.*g", prec, v );
   printf( "%s%s", buf, strpbrk( buf, ".e" ) ? "" : ".0" );
}

static void values( int n, const double *v ) {
   int i;
   printf( "        &[" );
   for( i = 0; i < n; i++ ) {
      if( i ) printf( ", " );
      lit( v[ i ] );
   }
   printf( "],\n" );
}

/* Emit the case for the dump held in "lines". The points are given
   point by point, "nin" values each. */
static void emit( const char *name, int npoint, const double *in ) {
   AstChannel *ch;
   AstMapping *map;
   double in_t[ 64 ], out_t[ 64 ], out[ 64 ];
   int i, k, nin, nout;

   printf( "    (\n        \"%s\",\n        &[\n", name );
   for( i = 0; i < nlines; i++ ) print_dump( lines[ i ] );
   printf( "        ],\n        &[\n" );

   next_line = 0;
   ch = astChannel( source, NULL, " " );
   map = astRead( ch );
   ch = astAnnul( ch );

   ch = astChannel( NULL, print_dump, " " );
   astWrite( ch, map );
   ch = astAnnul( ch );
   printf( "        ],\n" );

   nin = astGetI( map, "Nin" );
   nout = astGetI( map, "Nout" );
   for( i = 0; i < npoint; i++ ) {
      for( k = 0; k < nin; k++ ) in_t[ k*npoint + i ] = in[ i*nin + k ];
   }
   astTranN( map, npoint, nin, npoint, in_t, 1, nout, npoint, out_t );
   for( i = 0; i < npoint; i++ ) {
      for( k = 0; k < nout; k++ ) out[ i*nout + k ] = out_t[ k*npoint + i ];
   }
   values( npoint*nin, in );
   values( npoint*nout, out );
   printf( "    ),\n" );

   map = astAnnul( map );
   for( i = 0; i < nlines; i++ ) free( lines[ i ] );
   nlines = 0;
}

/* Emit the case for the dump of "obj". */
static void emit_object( const char *name, AstObject *obj, int npoint,
                         const double *in ) {
   AstChannel *ch = astChannel( NULL, collect, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   emit( name, npoint, in );
}

/* Emit the case for the dump given as text. */
static void emit_text( const char *name, const char **text, int npoint,
                       const double *in ) {
   for( ; *text; text++ ) collect( *text );
   emit( name, npoint, in );
}

int main( void ) {
   AstObject *obj;
   int status = 0;
   astWatch( &status );

   printf( "// Generated by tools/oracle_fixtures/mapping_load_probe.c. Do not edit.\n\n"
           "/// `(case, the dump read, the dump of what C reads from it, input points,\n"
           "/// forward outputs)`, the points given point by point.\n"
           "pub type Case = (\n"
           "    &'static str,\n"
           "    &'static [&'static str],\n"
           "    &'static [&'static str],\n"
           "    &'static [f64],\n"
           "    &'static [f64],\n"
           ");\n\n"
           "pub const CASES: &[Case] = &[\n" );

   {
      int inperm[] = { 1 }, outperm[] = { 1, -1 };
      double con[] = { BAD }, in[] = { 5.0, BAD };
      obj = (AstObject *) astPermMap( 1, inperm, 2, outperm, con, " " );
      emit_object( "permmap_bad_constant", obj, 2, in );
      obj = astAnnul( obj );
   }
   {
      int inperm[] = { 1 }, outperm[] = { 1, -2 };
      double con[] = { 5.0, BAD, 7.0 }, in[] = { 3.0 };
      obj = (AstObject *) astPermMap( 1, inperm, 2, outperm, con, " " );
      emit_object( "permmap_bad_constant_among_others", obj, 1, in );
      obj = astAnnul( obj );
   }
   {
      int inperm[] = { 1 }, outperm[] = { 1, -1 };
      double con[] = { 5.0, 6.0 }, in[] = { 3.0 };
      obj = (AstObject *) astPermMap( 1, inperm, 2, outperm, con, " " );
      emit_object( "permmap_unreferenced_constant", obj, 1, in );
      obj = astAnnul( obj );
   }
   {
      double diag[] = { 2.0, BAD }, in[] = { 1.0, 1.0, -3.0, 4.0 };
      obj = (AstObject *) astMatrixMap( 2, 2, 1, diag, " " );
      emit_object( "matrixmap_diagonal_bad", obj, 2, in );
      obj = astAnnul( obj );
   }
   {
      double diag[] = { BAD, 3.0, 0.5 }, in[] = { 1.0, 2.0, 3.0 };
      obj = (AstObject *) astMatrixMap( 3, 3, 1, diag, " " );
      emit_object( "matrixmap_diagonal_bad_first", obj, 1, in );
      obj = astAnnul( obj );
   }
   {
      const char *text[] = { " Begin WcsMap", "    Nin = 2", " IsA Mapping",
                             "    Type = \"COP\"", "    ProjP1 = 45",
                             " End WcsMap", NULL };
      double in[] = { 0.1, 0.2, -0.3, 0.6 };
      emit_text( "wcsmap_legacy_projp", text, 2, in );
   }
   {
      const char *text[] = { " Begin WcsMap", "    Nin = 2", " IsA Mapping",
                             "    Type = \"COP\"", "    ProjP1 = 45",
                             "    PV2_1 = 30", " End WcsMap", NULL };
      double in[] = { 0.1, 0.2, -0.3, 0.6 };
      emit_text( "wcsmap_pv_overrides_projp", text, 2, in );
   }
   {
      const char *text[] = { " Begin WcsMap", "    Nin = 3", " IsA Mapping",
                             "    Type = \"ZPN\"", "    WcsAx1 = 3",
                             "    WcsAx2 = 1", "    ProjP0 = 0.05",
                             "    ProjP1 = 1", "    ProjP3 = -0.1",
                             " End WcsMap", NULL };
      double in[] = { 0.4, 7.0, 0.1, 0.9, -2.0, -0.2 };
      emit_text( "wcsmap_legacy_projp_permuted_axes", text, 2, in );
   }

   printf( "];\n" );
   return status;
}
