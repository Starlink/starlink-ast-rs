/* specflux_cmp_probe -- capture the SpecFluxFrame methods C inherits from
 * CmpFrame (specfluxframe.c Match, SubFrame): picking one axis of a
 * SpecFluxFrame, and matching a SpecFluxFrame template against a CmpFrame
 * of a SpecFrame and a FluxFrame.
 *
 * Prints Rust source for crates/ast-core/tests/specflux_cmp_oracle/cases.rs:
 *
 *   ./specflux_cmp_probe > ../../crates/ast-core/tests/specflux_cmp_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void flit( double value ) {
   char buf[ 40 ];
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

static AstSpecFluxFrame *sff( void ) {
   return astSpecFluxFrame( astSpecFrame( "System=FREQ,Unit=GHz" ),
                            astFluxFrame( 1.4e9, NULL, "System=FLXDN" ), " " );
}

int main( void ) {
   int status = 0, i, perm[ 2 ] = { 2, 1 }, one[ 1 ] = { 1 }, two[ 1 ] = { 2 };
   AstMapping *map;
   AstFrame *f;
   AstSpecFluxFrame *s;
   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/specflux_cmp_probe.c against\n"
           "// the C library at u/timj/norm-unit 5a2cac2a, past the submodule pin.\n"
           "// Do not edit.\n\n"
           "#![allow(clippy::excessive_precision)]\n\n"
           "/// `(swapped, picked axis, class, Label(1), Unit(1))`.\n"
           "pub const PICKS: &[(bool, usize, &str, &str, &str)] = &[\n" );
   for( i = 0; i < 2; i++ ) {
      int ax;
      for( ax = 1; ax <= 2; ax++ ) {
         s = sff();
         if( i ) astPermAxes( s, perm );
         f = astPickAxes( s, 1, ax == 1 ? one : two, &map );
         printf( "    (%s, %d, \"%s\", \"%s\", \"%s\"),\n", i ? "true" : "false", ax,
                 astGetC( f, "Class" ), astGetC( f, "Label(1)" ), astGetC( f, "Unit(1)" ) );
      }
   }
   printf( "];\n\n" );
   {
      AstCmpFrame *target = astCmpFrame( astSpecFrame( "System=FREQ,Unit=GHz" ),
                                         astFluxFrame( 1.4e9, NULL, "System=FLXDN" ), " " );
      AstSpecFluxFrame *t = astSpecFluxFrame( astSpecFrame( "System=FREQ,Unit=MHz" ),
                                              astFluxFrame( 1.4e9, NULL, "System=FLXDN" ), " " );
      AstFrameSet *fs = astFindFrame( target, t, "" );
      double in[ 2 ] = { 1.4, 1.0e-26 }, out[ 2 ];
      printf( "/// The class of the Frame found for a SpecFluxFrame template in a\n"
              "/// CmpFrame(SpecFrame, FluxFrame), and (1.4 GHz, 1e-26) converted to it.\n" );
      if( fs ) {
         astTranN( fs, 1, 2, 1, in, 1, 2, 1, out );
         printf( "pub const FOUND: Option<(&str, [f64; 2])> = Some((\"%s\", [",
                 astGetC( astGetFrame( fs, AST__CURRENT ), "Class" ) );
         flit( out[ 0 ] ); printf( ", " ); flit( out[ 1 ] ); printf( "]));\n" );
      } else {
         printf( "pub const FOUND: Option<(&str, [f64; 2])> = None;\n" );
      }
   }
   return 0;
}
