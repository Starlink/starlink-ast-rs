/* convert_frameset_probe -- capture astConvert between a SkyFrame and a
 * FrameSet whose current Frame is GRID and whose base Frame is an ICRS
 * SkyFrame, each way round. C dispatches astConvertX on the class of the
 * target: to a FrameSet, frameset.c searches all its Frames; from a
 * FrameSet to a plain Frame, frame.c's driver tries the FrameSet as the
 * template, whose Match searches its Frames. For each direction, whether a
 * route is found, the Domain of the result's current Frame, and two points
 * transformed each way.
 *
 * Prints Rust source for crates/ast-core/tests/convert_frameset_oracle/cases.rs:
 *
 *   ./convert_frameset_probe > ../../crates/ast-core/tests/convert_frameset_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void num( double v ) {
   char buf[ 40 ];
   sprintf( buf, "%.17g", v );
   printf( "%s%s", buf, strpbrk( buf, ".en" ) ? "" : ".0" );
}

/* `(found, current Domain, forward of [[x, y]; 2], inverse of [[x, y]; 2])`. */
static void emit( const char *name, AstFrameSet *cvt ) {
   double x[ 2 ] = { 1.0, 2.5 }, y[ 2 ] = { 0.5, -0.3 }, xo[ 2 ], yo[ 2 ];
   int i, dir;
   printf( "pub const %s: Case = (%s, \"%s\", [", name, cvt ? "true" : "false",
           cvt ? astGetC( cvt, "Domain" ) : "" );
   for( dir = 1; dir >= 0; dir-- ) {
      if( cvt ) {
         astTran2( cvt, 2, x, y, dir, xo, yo );
      } else {
         xo[ 0 ] = xo[ 1 ] = yo[ 0 ] = yo[ 1 ] = 0.0;
      }
      printf( "[" );
      for( i = 0; i < 2; i++ ) {
         printf( "[" );
         num( xo[ i ] );
         printf( ", " );
         num( yo[ i ] );
         printf( "]%s", i ? "" : ", " );
      }
      printf( "]%s", dir ? ", " : "" );
   }
   printf( "]);\n" );
}

int main( void ) {
   int status = 0;
   AstFrameSet *fs;

   astWatch( &status );
   fs = astFrameSet( astSkyFrame( "System=ICRS" ), " " );
   astAddFrame( fs, AST__BASE, astZoomMap( 2, 0.5, " " ),
                astFrame( 2, "Domain=GRID" ) );

   printf( "// Generated by tools/oracle_fixtures/convert_frameset_probe.c. Do not edit.\n\n" );
   printf( "/// `(route found, Domain of its current Frame, [forward, inverse] of the\n" );
   printf( "/// points (1, 0.5) and (2.5, -0.3))`.\n" );
   printf( "pub type Case = (bool, &'static str, [[[f64; 2]; 2]; 2]);\n" );
   emit( "FRAME_TO_FRAMESET",
         astConvert( astSkyFrame( "System=Galactic" ), fs, "" ) );
   emit( "FRAMESET_TO_FRAME",
         astConvert( fs, astSkyFrame( "System=Galactic" ), "" ) );
   return 0;
}
