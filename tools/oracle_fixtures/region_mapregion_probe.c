/* region_mapregion_probe -- capture astMapRegion, protected and public: the
 * protected form (region.c MapRegion) given an Interval whose defining
 * points include a BAD limit and a Mapping that drops an axis, where C
 * reduces the Region's axes only when it has flags saying which old axes
 * give good values, which it has only when the points are all good; and the
 * public form (region.c astMapRegionId_), which simplifies what the
 * protected form returns, given a Box and a PermMap that swaps its axes.
 * Also astSimplify of the PermMap the first case uses, whose inperm C
 * stores as it was given (permmap.c MapMerge and NullPerm). And the dump of
 * a Circle mapped by the protected form through a ZoomMap of 2 then one of
 * 0.5, whose base->current Mapping simplifies to a UnitMap, so the dump
 * (region.c Dump, which tests astRegMapping) writes only its Frame.
 *
 * Prints Rust source for crates/ast-core/tests/region_mapregion_oracle/cases.rs:
 *
 *   ./region_mapregion_probe > ../../crates/ast-core/tests/region_mapregion_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern void *astMapRegion_( void *, void *, void *, int * );
extern AstObject *astMakeId_( AstObject *, int * );

static char dump[ 40000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

static void emit( const char *name, AstObject *obj ) {
   AstChannel *ch;
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   printf( "pub const %s: &str = ", name );
   str( dump );
   printf( ";\n" );
}

int main( void ) {
   int status = 0, s = 0;
   AstRegion *reg;
   AstFrame *frm;
   AstMapping *pm;
   void *p;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_mapregion_probe.c. Do not edit.\n\n" );
   {
      double l[] = { 0.0, 0.0, 0.0 }, u[] = { 1.0, 1.0, AST__BAD };
      int outperm[] = { 1, 2 }, inperm[] = { 1, 2, 0 };
      reg = (AstRegion *) astInterval( astFrame( 3, " " ), l, u, NULL, " " );
      pm = (AstMapping *) astPermMap( 3, inperm, 2, outperm, NULL, " " );
      frm = astFrame( 2, " " );
      p = astMapRegion_( astMakePointer( reg ), astMakePointer( pm ),
                         astMakePointer( frm ), &s );
      printf( "/// The Interval [0,1]x[0,1]x[0,BAD] through a PermMap dropping its\n"
              "/// third axis, mapped by the protected astMapRegion.\n" );
      emit( "DROP_UNBOUNDED", astMakeId_( p, &s ) );
      printf( "/// astSimplify of that PermMap, inperm (1, 2, 0) and outperm (1, 2).\n" );
      emit( "PERMMAP_SIMPLIFIED", (AstObject *) astSimplify( astPermMap( 3, inperm, 2, outperm, NULL, " " ) ) );
   }
   {
      double l[] = { 0.0, 1.0 }, u[] = { 2.0, 4.0 };
      int perm[] = { 2, 1 };
      reg = (AstRegion *) astBox( astFrame( 2, " " ), 1, l, u, NULL, " " );
      pm = (AstMapping *) astPermMap( 2, perm, 2, perm, NULL, " " );
      printf( "/// The Box [0,2]x[1,4] through a PermMap swapping its axes, mapped by\n"
              "/// the public astMapRegion.\n" );
      emit( "SWAPPED_PUBLIC", (AstObject *) astMapRegion( reg, pm, astFrame( 2, " " ) ) );
   }
   {
      double c[] = { 1.0, 0.5 }, r = 0.1;
      AstRegion *circ = (AstRegion *) astCircle( astFrame( 2, "Domain=FOO" ), 1, c, &r, NULL, " " );
      void *cm = astCmpMap( astZoomMap( 2, 2.0, " " ), astZoomMap( 2, 0.5, " " ), 1, " " );
      void *p = astMapRegion_( astMakePointer( circ ), astMakePointer( cm ),
                               astMakePointer( astFrame( 2, "Domain=BAR" ) ), &s );
      printf( "/// A Circle in Domain FOO through a ZoomMap of 2 then one of 0.5 into\n"
              "/// Domain BAR, by the protected form.\n" );
      emit( "IDENTITY_CHAIN", astMakeId_( p, &s ) );
   }
   return status + s;
}
