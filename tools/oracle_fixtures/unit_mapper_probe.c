/* unit_mapper_probe -- capture the scale factors AST derives from unit
 * strings, and how it combines them when it simplifies a chain of
 * ZoomMaps.
 *
 * Three tables:
 *
 * - UNIT_CASES: the Mapping astUnitMapper builds between two unit strings
 *   (unit.c astUnitMapper_), as seen through astConvert between two
 *   one-axis Frames that have ActiveUnit set (frame.c SubFrame calls
 *   astUnitMapper for each axis).
 *
 * - SPEC_CASES: astConvert between two SpecFrames in the same System but
 *   different Units. specframe.c MakeSpecMapping sandwiches the SpecMap
 *   between two astUnitMapper ZoomMaps, and frame.c ConvertX joins the
 *   result to the inverse of the "to" Frame's mapping to itself, so the
 *   simplified Mapping comes from zoommap.c MapMerge combining forward and
 *   inverted ZoomMaps.
 *
 * - ZOOM_CASES: astSimplify of a series CmpMap of two or three ZoomMaps,
 *   each possibly inverted (zoommap.c MapMerge).
 *
 * Each Mapping is applied to a fixed set of values in both directions, so
 * the scale factor is compared bit-for-bit without depending on the
 * Mapping class.
 *
 * Prints Rust source for crates/starlink-ast/tests/unit_mapper_oracle/cases.rs:
 *
 *   ./unit_mapper_probe > ../../crates/starlink-ast/tests/unit_mapper_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include "ast.h"

static void flit( double value ) {
   char buf[ 40 ];
   if( value == AST__BAD ) { fputs( "BAD", stdout ); return; }
   snprintf( buf, sizeof( buf ), "%.17g", value );
   fputs( buf, stdout );
   if( !strpbrk( buf, ".en" ) ) fputs( ".0", stdout );
}

#define NVAL 4
static const double values[ NVAL ] = { 1.0, 2.5, 1.0e9, -3.75e-4 };

