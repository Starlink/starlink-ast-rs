/* region_moc_text_probe -- capture the MOC string, JSON and data forms of
 * a Moc (moc.c): MOCs read from string and JSON text with astAddMocString
 * (each combination mode, negated, with MaxOrder given, found from the
 * text or already set, degrading cells above it, an empty JSON MOC, and
 * text with tabs, newlines and spaces), and from NUNIQ data with
 * astAddMocData (4 and 8 byte values, degraded, negated); for each, its
 * MaxOrder, MocLength, string and JSON forms (astGetMocString), MocType
 * and data (astGetMocData). Also the JSON and string forms of an empty
 * Moc with and without MaxOrder; the pieces astGetMocText passes to its
 * sink with a small buffer, and the status when it is shorter than a value;
 * the FITS header astGetMocHeader gives; and the status for malformed
 * text and data. It needs moc.c as fixed upstream in 7beab7b1 and
 * 7d06331e.
 *
 * Prints Rust source for crates/starlink-ast/tests/region_moc_text_oracle/cases.rs:
 *
 *   ./region_moc_text_probe > ../../crates/starlink-ast/tests/region_moc_text_oracle/cases.rs
 */
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "ast.h"

extern void astGetMocText_( AstMoc *, int, size_t,
                            void (*)( void *, size_t, const char *, int * ),
                            void *, const char *, int * );

static void str( const char *s, size_t n ) {
   size_t i;
   putchar( '"' );
   for( i = 0; i < n && s[ i ]; i++ ) {
      if( s[ i ] == '\n' ) {
         printf( "\\n" );
      } else if( s[ i ] == '\t' ) {
         printf( "\\t" );
      } else {
         if( s[ i ] == '"' || s[ i ] == '\\' ) putchar( '\\' );
         putchar( s[ i ] );
      }
   }
   putchar( '"' );
}

static void form( AstMoc *moc, int json ) {
   static char buf[ 100000 ];
   size_t size = 0;
   astGetMocString( moc, json, sizeof( buf ), buf, &size );
   str( buf, size );
}

/* `(name, MaxOrder, MocLength, string form, JSON form, MocType, data)`. */
static void emit( const char *name, AstMoc *moc ) {
   int i, n, type;
   static char data[ 800000 ];
   printf( "    (\"%s\", %d, %d, ", name, astGetI( moc, "MaxOrder" ),
           n = astGetI( moc, "MocLength" ) );
   form( moc, 0 );
   printf( ", " );
   form( moc, 1 );
   type = astGetI( moc, "MocType" );
   astGetMocData( moc, sizeof( data ), data );
   printf( ", %d, &[", type );
   for( i = 0; i < n; i++ ) {
      printf( "%lld%s", type == 4 ? (long long) ((int *) data)[ i ]
                                  : (long long) ((int64_t *) data)[ i ],
              i < n - 1 ? ", " : "" );
   }
   printf( "]),\n" );
}

static AstMoc *ordered( int maxorder ) {
   AstMoc *moc = astMoc( " " );
   if( maxorder >= 0 ) astSetI( moc, "MaxOrder", maxorder );
   return moc;
}

static AstMoc *text( int maxorder, int cmode, int negate, int mxord,
                     const char *t, AstMoc *base ) {
   AstMoc *moc;
   int json;
   moc = base ? astCopy( base ) : ordered( maxorder );
   astAddMocString( moc, cmode, negate, mxord, strlen( t ), t, &json );
   return moc;
}

static void sink( void *data, size_t nc, const char *buf, int *status ) {
   printf( "%s", *(int *) data ? ", " : "" );
   str( buf, nc );
   *(int *) data = 1;
}

static void discard( void *data, size_t nc, const char *buf, int *status ) {
}

int main( void ) {
   int status = 0, json, i, started;
   AstMoc *low, *high, *m;
   AstFitsChan *fc;
   char card[ 81 ];
   static int idata[ 10000 ];
   static int64_t kdata[ 10000 ];

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_moc_text_probe.c. Do not edit.\n\n" );

   low = astMoc( " " );
   astAddCell( low, AST__OR, 2, 37 );
   astAddCell( low, AST__OR, 1, 3 );
   astAddCell( low, AST__OR, 2, 100 );
   astAddCell( low, AST__XOR, 1, 25 );
   astAddCell( low, AST__OR, 0, 7 );
   high = astMoc( " " );
   astAddCell( high, AST__OR, 15, 1234567890 );
   astAddCell( high, AST__OR, 10, 5 );
   astAddCell( high, AST__OR, 3, 700 );

   printf( "/// `(case, MaxOrder, MocLength, string form, JSON form, MocType, data)`.\n" );
   printf( "pub type Case = (&'static str, i32, i32, &'static str, &'static str, i32,\n" );
   printf( "    &'static [i64]);\n" );
   printf( "pub const CASES: &[Case] = &[\n" );
   emit( "low", low );
   emit( "high", high );
   emit( "string", text( -1, AST__OR, 0, -1, "3/1-5,9 4/100-103 5/", NULL ) );
   emit( "string_degraded", text( -1, AST__OR, 0, 4, "2/3 6/1000-1010,2000", NULL ) );
   emit( "json", text( -1, AST__OR, 0, -1,
                       "{\"1\":[1,2,4], \"3\":[ 100 , 101 ],\"5\":[]}", NULL ) );
   emit( "json_empty", text( 3, AST__OR, 0, -1, "{}", NULL ) );
   emit( "json_spaced", text( -1, AST__OR, 0, -1,
                              " {\n \"2\" : [ 7 ,8 ],\n\t\"4\":[1]\n}\n", NULL ) );
   emit( "negated", text( 3, AST__OR, 1, -1, "2/5-10", NULL ) );
   emit( "and", text( -1, AST__AND, 0, -1, "1/0-20", low ) );
   emit( "xor", text( -1, AST__XOR, 0, -1, "1/0-20 2/150", low ) );
   emit( "whitespace", text( -1, AST__OR, 0, -1, "  1/3\t\n2/40-45, 47", NULL ) );
   emit( "maxorder_set", text( 2, AST__OR, 0, 5, "4/1000 1/7", NULL ) );
   emit( "low_text", text( -1, AST__OR, 0, -1,
                           "{\"0\":[7],\"1\":[3,25],\"2\":[37,100]}", NULL ) );

   astGetMocData( low, sizeof( idata ), idata );
   m = ordered( -1 );
   astAddMocData( m, AST__OR, 0, -1, astGetI( low, "MocLength" ), 4, idata );
   emit( "data_4", m );
   astGetMocData( high, sizeof( kdata ), kdata );
   m = ordered( -1 );
   astAddMocData( m, AST__OR, 0, -1, astGetI( high, "MocLength" ), 8, kdata );
   emit( "data_8", m );
   m = ordered( -1 );
   astAddMocData( m, AST__OR, 0, 2, astGetI( high, "MocLength" ), 8, kdata );
   emit( "data_degraded", m );
   m = astCopy( low );
   astAddMocData( m, AST__XOR, 1, -1, astGetI( low, "MocLength" ), 4, idata );
   emit( "data_negated_xor", m );
   m = astCopy( low );
   astAddMocData( m, AST__AND, 0, -1, 0, 4, idata );
   emit( "data_and_empty", m );
   printf( "];\n\n" );

   printf( "/// The string and JSON forms of an empty Moc without and with MaxOrder 4.\n" );
   printf( "pub const EMPTY: [&str; 4] = [" );
   form( ordered( -1 ), 0 );
   printf( ", " );
   form( ordered( -1 ), 1 );
   printf( ", " );
   form( ordered( 4 ), 0 );
   printf( ", " );
   form( ordered( 4 ), 1 );
   printf( "];\n\n" );

   printf( "/// The pieces astGetMocText passes to its sink for the high Moc with a\n" );
   printf( "/// buffer of 16 bytes, in string and JSON form, and the status after.\n" );
   for( json = 0; json < 2; json++ ) {
      started = 0;
      printf( "pub const PIECES_%s: (&[&str], i32) = (&[", json ? "JSON" : "STRING" );
      astGetMocText_( astMakePointer( high ), json, 16, sink, &started, "probe",
                      &status );
      printf( "], %d);\n", status );
      astClearStatus;
   }
   started = 0;
   printf( "/// The status when the buffer is 3 bytes, shorter than a value.\n" );
   printf( "pub const SMALL_BUFFER: i32 = " );
   astGetMocText_( astMakePointer( high ), 0, 3, discard, NULL, "probe",
                   &status );
   printf( "%d;\n\n", status );
   astClearStatus;

   printf( "/// The cards of astGetMocHeader for the low and high Mocs.\n" );
   for( i = 0; i < 2; i++ ) {
      printf( "pub const HEADER_%s: &[&str] = &[", i ? "HIGH" : "LOW" );
      fc = astGetMocHeader( i ? high : low );
      astClear( fc, "Card" );
      started = 0;
      while( astFindFits( fc, "%f", card, 1 ) ) {
         printf( "%s", started ? ", " : "" );
         str( card, 80 );
         started = 1;
      }
      printf( "];\n" );
   }
   printf( "\n" );

   printf( "/// The status of reading each malformed text into a copy of the low Moc,\n" );
   printf( "/// and whether the copy was left as it was.\n" );
   printf( "pub const BAD_TEXT: &[(&str, i32, bool)] = &[\n" );
   {
      const char *bad[] = { "", " ", "x", "5", "5 6", "3/10-5", "3/5-2 4",
                            "4294967301/1", "28/1", "0/12", "{\"0\":[12]}",
                            "3/18446744073709551621", "{\"1\":[3]", "{\"1\":[3],}",
                            "{\"1\" [3]}", "{\"1\":3}", "{\"1\":[3}", "{\"1\":[3]} x",
                            "{\"x\":[3]}", "{\"28\":[3]}", "3/4a", NULL };
      for( i = 0; bad[ i ]; i++ ) {
         m = astCopy( low );
         astAddMocString( m, AST__OR, 0, -1, strlen( bad[ i ] ), bad[ i ], &json );
         printf( "    (" );
         str( bad[ i ], strlen( bad[ i ] ) );
         printf( ", %d, ", status );
         astClearStatus;
         printf( "%s),\n", astEqual( m, low ) ? "true" : "false" );
      }
   }
   printf( "];\n\n" );

   printf( "/// The status of adding NUNIQ data holding 0, 4 byte and 8 byte.\n" );
   {
      int ibad[ 2 ] = { 20, 0 };
      int64_t kbad[ 2 ] = { 20, -5 };
      m = ordered( 5 );
      astAddMocData( m, AST__OR, 0, -1, 2, 4, ibad );
      printf( "pub const BAD_DATA_4: i32 = %d;\n", status );
      astClearStatus;
      astAddMocData( m, AST__OR, 0, -1, 2, 8, kbad );
      printf( "pub const BAD_DATA_8: i32 = %d;\n", status );
      astClearStatus;
      printf( "pub const BAD_DATA_LENGTH: i32 = %d;\n", astGetI( m, "MocLength" ) );
   }
   return 0;
}
