/* region_showmesh_probe -- capture astShowMesh (region.c ShowMesh): the
 * table of current-Frame boundary mesh points it writes to standard output,
 * with and without a title, unformatted (C's "%g") and formatted by the axis
 * Format, for a Cartesian Circle, a sky Box straddling RA 0 (whose mesh is
 * normalised as one contiguous group), a Polygon whose axes have their own
 * Format, a Box whose values need "%g"'s exponent form, and a Circle whose
 * base->current Mapping is a ZoomMap.
 *
 * Prints Rust source for crates/starlink-ast/tests/region_showmesh_oracle/cases.rs:
 *
 *   ./region_showmesh_probe > ../../crates/starlink-ast/tests/region_showmesh_oracle/cases.rs
 */
#include <stdio.h>
#include <string.h>
#include <unistd.h>
#include "ast.h"

static char dump[ 40000 ];
static char table[ 40000 ];

static void sink( const char *line ) {
   strcat( dump, line );
   strcat( dump, "\n" );
}

static void str( const char *s ) {
   putchar( '"' );
   for( ; *s; s++ ) {
      if( *s == '\n' ) {
         printf( "\\n" );
      } else if( *s == '\t' ) {
         printf( "\\t" );
      } else {
         if( *s == '"' || *s == '\\' ) putchar( '\\' );
         putchar( *s );
      }
   }
   putchar( '"' );
}

static const char *dumped( AstObject *obj ) {
   AstChannel *ch;
   dump[ 0 ] = 0;
   ch = astChannel( NULL, sink, " " );
   astWrite( ch, obj );
   ch = astAnnul( ch );
   return dump;
}

/* Run astShowMesh with standard output sent to a temporary file, and read
   back what it wrote. */
static const char *shown( AstRegion *reg, int format, const char *ttl ) {
   FILE *tmp = tmpfile();
   int saved;
   size_t n;
   fflush( stdout );
   saved = dup( 1 );
   dup2( fileno( tmp ), 1 );
   astShowMesh( reg, format, ttl );
   fflush( stdout );
   dup2( saved, 1 );
   close( saved );
   rewind( tmp );
   n = fread( table, 1, sizeof( table ) - 1, tmp );
   table[ n ] = 0;
   fclose( tmp );
   return table;
}

/* One case: `(name, dump, format, title, table)`. */
static void emit( const char *name, AstRegion *reg, int format,
                  const char *ttl ) {
   printf( "    (\"%s\",\n        ", name );
   str( dumped( (AstObject *) reg ) );
   printf( ",\n        %s, ", format ? "true" : "false" );
   if( ttl ) {
      printf( "Some(" );
      str( ttl );
      printf( ")" );
   } else {
      printf( "None" );
   }
   printf( ",\n        " );
   str( shown( reg, format, ttl ) );
   printf( "),\n" );
}

int main( void ) {
   int status = 0;
   double c[ 2 ], r, lb[ 2 ], ub[ 2 ];
   double tri[ 6 ] = { 0.0, 4.0, 1.0, 0.0, 0.0, 3.0 };
   AstFrame *f;
   AstFrameSet *fs;
   AstRegion *reg;

   astWatch( &status );
   printf( "// Generated by tools/oracle_fixtures/region_showmesh_probe.c. Do not edit.\n\n" );
   printf( "/// `(case, Region dump, format, title, the table astShowMesh writes)`.\n" );
   printf( "pub const CASES: &[(&str, &str, bool, Option<&str>, &str)] = &[\n" );

   c[ 0 ] = 1.0;
   c[ 1 ] = 2.0;
   r = 0.5;
   reg = (AstRegion *) astCircle( astFrame( 2, " " ), 1, c, &r, NULL,
                                  "MeshSize=8" );
   emit( "circle_titled", reg, 0, "Circle mesh" );
   emit( "circle_formatted", reg, 1, NULL );

   c[ 0 ] = 0.0;
   c[ 1 ] = 0.5;
   lb[ 0 ] = 0.02;
   lb[ 1 ] = 0.52;
   reg = (AstRegion *) astBox( astSkyFrame( " " ), 0, c, lb, NULL,
                               "MeshSize=12" );
   emit( "sky_box_wrap", reg, 1, NULL );
   emit( "sky_box_wrap_plain", reg, 0, "Sky" );

   f = astFrame( 2, "Format(1)=%%.3f,Format(2)=%%8.2e" );
   reg = (AstRegion *) astPolygon( f, 3, 3, tri, NULL, "MeshSize=6" );
   emit( "polygon_formats", reg, 1, "" );

   lb[ 0 ] = 1.5e7;
   lb[ 1 ] = 1.0e-5;
   ub[ 0 ] = 1.5000002e7;
   ub[ 1 ] = 3.0e-5;
   reg = (AstRegion *) astBox( astFrame( 2, " " ), 1, lb, ub, NULL,
                               "MeshSize=8" );
   emit( "box_g_values", reg, 0, NULL );

   fs = astFrameSet( astFrame( 2, " " ), " " );
   astAddFrame( fs, AST__BASE, astZoomMap( 2, 3.0, " " ),
                astFrame( 2, "Domain=ZOOMED" ) );
   c[ 0 ] = 1.0;
   c[ 1 ] = 1.0;
   r = 0.25;
   reg = (AstRegion *) astCircle( fs, 1, c, &r, NULL, "MeshSize=8" );
   emit( "zoomed_circle", reg, 0, NULL );

   printf( "];\n" );
   return status != 0;
}
