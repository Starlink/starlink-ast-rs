//! NormMaps, ShiftMaps and MatrixMaps treat bad values as C does: a NormMap
//! normalizes every point, so a SkyFrame wraps the longitude of a point whose
//! latitude is bad (normmap.c `Transform`); a bad shift makes its axis bad
//! (shiftmap.c `Transform`); and a MatrixMap ignores a bad input where a full
//! matrix's element is zero, but not a diagonal one's, and a bad element makes
//! its output bad (matrixmap.c `Transform`). Each case's forward and inverse
//! transformations equal C's bit for bit, through both the bad-value path and
//! the NaN protocol, which carries bad values as NaN.
//!
//! `mapping_bad_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/mapping_bad_probe.c`.

// Generated; formatted by its generator rather than rustfmt.
#[rustfmt::skip]
#[path = "mapping_bad_oracle/cases.rs"]
mod cases;

use starlink_ast::coords::PointSet;
use starlink_ast::from_native_string;

fn text(lines: &[&str]) -> String {
    let mut s = lines.join("\n");
    s.push('\n');
    s
}

fn points(values: &[f64], n: usize) -> PointSet {
    PointSet::from_rows(values.chunks(n).map(<[f64]>::to_vec).collect::<Vec<_>>())
}

fn flat(pts: &PointSet) -> Vec<f64> {
    (0..pts.npoint())
        .flat_map(|i| pts.point(i).to_vec())
        .collect()
}

fn same(got: &[f64], want: &[f64]) -> bool {
    got.iter()
        .map(|v| v.to_bits())
        .eq(want.iter().map(|v| v.to_bits()))
}

#[test]
fn bad_values_match_the_c_library() {
    let mut failures = Vec::new();
    for &(name, dump, input, forward, inverse) in cases::CASES {
        let obj = from_native_string(&text(dump)).unwrap();
        let map = obj.as_mapping().expect("a Mapping");
        let mut dirs = vec![(true, map.nin(), forward)];
        if let Some(inverse) = inverse {
            dirs.push((false, map.nout(), inverse));
        }
        for (dir, n, want) in dirs {
            let got = flat(&map.transform(&points(input, n), dir).unwrap());
            if !same(&got, want) {
                failures.push(format!("{name} forward={dir}: {got:?}\n  C gives {want:?}"));
            }

            // The NaN protocol runs the classes' NaN paths, giving NaN for
            // bad inside and BAD at its boundary.
            let got = flat(&map.transform_nan_protocol(&points(input, n), dir).unwrap());
            if !same(&got, want) {
                failures.push(format!(
                    "{name} NaN protocol forward={dir}: {got:?}\n  C gives {want:?}"
                ));
            }
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}
