//! How a FITS-WCS write describes axis descriptions with different numbers
//! of axes, against C: `WcsFromStore` (fitschan.c) bounds its per-axis
//! loops, for each version, by WCSAXES if the version has one, and otherwise
//! by the highest CRPIX index stored for it.
//!
//! Each FrameSet has a 3-D GRID Frame, a primary Frame and an alternate
//! Frame (Ident "A"), joined to the GRID Frame by PermMaps that drop or add
//! axes, and is written with NAXIS = 3. Compared with C: the value the write
//! returns and the cards written. `fitschan_alt_naxes_oracle/cases.rs` is
//! generated by `tools/oracle_fixtures/fitschan_alt_naxes_probe.c`.

#[rustfmt::skip]
#[path = "fitschan_alt_naxes_oracle/cases.rs"]
mod cases;

use starlink_ast::frames::{BasicFrameBuilder, FrameRef, FrameSet};
use starlink_ast::mappings::{CmpMap, Composition, PermMap, ShiftMap};
use starlink_ast::{AnyObject, Channel, Encoding, FitsChan};

/// The probe's Mapping from 3 pixel axes to `nout` axes: a PermMap passing
/// the axes they share and giving any extra output the value 5, then a
/// ShiftMap adding `shift + i` to output `i`.
fn map_to(nout: usize, shift: f64) -> CmpMap {
    let inperm: Vec<i64> = (0..3)
        .map(|i| if i < nout { i as i64 + 1 } else { -1 })
        .collect();
    let outperm: Vec<i64> = (0..nout)
        .map(|i| if i < 3 { i as i64 + 1 } else { -1 })
        .collect();
    let perm = PermMap::new(&inperm, &outperm, &[5.0]).unwrap();
    let shift = ShiftMap::new((0..nout).map(|i| shift + i as f64).collect::<Vec<_>>());
    CmpMap::new(Box::new(perm), Box::new(shift), Composition::Series).unwrap()
}

/// The value the write returns and the cards written.
fn written(nprim: usize, nalt: usize) -> (i32, Vec<String>) {
    let grid = BasicFrameBuilder::new(3).domain("GRID").build().unwrap();
    let prim = BasicFrameBuilder::new(nprim).domain("PRI").build().unwrap();
    let mut alt = BasicFrameBuilder::new(nalt).domain("ALT").build().unwrap();
    alt.set_ident("A");
    let mut fs = FrameSet::new(Box::new(grid));
    fs.add_frame(
        FrameRef::Base,
        Box::new(map_to(nprim, 10.0)),
        Box::new(prim),
    )
    .unwrap();
    fs.add_frame(FrameRef::Base, Box::new(map_to(nalt, 100.0)), Box::new(alt))
        .unwrap();
    fs.set_current(FrameRef::Index(2)).unwrap();

    let mut fc = FitsChan::new().unwrap();
    fc.set_encoding(Encoding::FitsWcs);
    fc.put_fits("NAXIS   = 3", false).unwrap();
    let ret = fc.write(&AnyObject::FrameSet(fs)).map_or(0, |n| n as i32);
    fc.clear_card().unwrap();
    let mut cards = Vec::new();
    while let Some(card) = fc.find_fits("%f", true).unwrap() {
        cards.push(card);
    }
    (ret, cards)
}

#[test]
fn versions_match_c() {
    let mut failed = Vec::new();
    for &(name, nprim, nalt, ret, cards) in cases::CASES {
        let got = written(nprim, nalt);
        let want = (ret, cards.iter().map(|c| c.to_string()).collect::<Vec<_>>());
        if got != want {
            failed.push(format!("{name}:\n--- rust\n{got:#?}\n--- C\n{want:#?}"));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n"));
}
