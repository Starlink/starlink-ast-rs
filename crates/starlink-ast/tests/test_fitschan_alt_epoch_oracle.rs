//! Where a FITS-WCS write takes MJD-OBS and DATE-OBS from when the axis
//! descriptions have different epochs, against C: `SkySys` (fitschan.c)
//! stores the date of observation only for the primary axis description. A
//! header has a single MJD-OBS, which an alternate description must not
//! change, whether or not that alternate is written.
//!
//! Each case reads a celestial header with a primary (FK5) and an alternate
//! (galactic, "A") description, with or without MJD-OBS, then optionally
//! sets the Epoch of either Frame, and optionally remaps the alternate Frame
//! with a non-linear MathMap so that its description cannot be written. The
//! FrameSet is written with NAXIS1 and NAXIS2 set. Compared with C: the
//! value the write returns and the cards written.
//! `fitschan_alt_epoch_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/fitschan_alt_epoch_probe.c`.

#[rustfmt::skip]
#[path = "fitschan_alt_epoch_oracle/cases.rs"]
mod cases;

use starlink_ast::frames::{Frame, FrameRef};
use starlink_ast::mappings::MathMap;
use starlink_ast::{AnyObject, Channel, Encoding, FitsChan};

const HEADER: &[&str] = &[
    "NAXIS   = 2",
    "NAXIS1  = 100",
    "NAXIS2  = 100",
    "CRPIX1  = 50",
    "CRPIX2  = 50",
    "CRVAL1  = 10",
    "CRVAL2  = 20",
    "CDELT1  = -0.001",
    "CDELT2  = 0.001",
    "CTYPE1  = 'RA---TAN'",
    "CTYPE2  = 'DEC--TAN'",
    "RADESYS = 'FK5'",
    "EQUINOX = 2000.0",
    "CRPIX1A = 50",
    "CRPIX2A = 50",
    "CRVAL1A = 100",
    "CRVAL2A = 30",
    "CDELT1A = -0.001",
    "CDELT2A = 0.001",
    "CTYPE1A = 'GLON-TAN'",
    "CTYPE2A = 'GLAT-TAN'",
];

/// The value the write returns and the cards written. `prim` and `alt` are
/// the MJD epochs set on the primary and alternate Frames, or 0 for none.
fn written(mjdobs: &str, prim: f64, alt: f64, fail: bool) -> (i32, Vec<String>) {
    let mut fc = FitsChan::new().unwrap();
    for card in HEADER {
        fc.put_fits(card, false).unwrap();
    }
    if !mjdobs.is_empty() {
        fc.put_fits(mjdobs, false).unwrap();
    }
    fc.clear_card().unwrap();
    let Some(AnyObject::FrameSet(mut fs)) = fc.read().unwrap() else {
        panic!("the header does not read as a FrameSet");
    };

    // Frame 2 is the primary description and Frame 3 the alternate.
    if prim != 0.0 {
        fs.set_current(FrameRef::Index(2)).unwrap();
        fs.set_epoch_mjd(prim).unwrap();
    }
    fs.set_current(FrameRef::Index(3)).unwrap();
    if alt != 0.0 {
        fs.set_epoch_mjd(alt).unwrap();
    }
    if fail {
        let map = MathMap::new(2, 2, &["x=a+100*b*b", "y=b"], &["a=x-100*y*y", "b=y"]).unwrap();
        fs.remap_frame(FrameRef::Index(3), Box::new(map)).unwrap();
    }
    fs.set_current(FrameRef::Index(2)).unwrap();

    let mut out = FitsChan::new().unwrap();
    out.set_encoding(Encoding::FitsWcs);
    out.put_fits("NAXIS1  = 100", false).unwrap();
    out.put_fits("NAXIS2  = 100", false).unwrap();
    let ret = out.write(&AnyObject::FrameSet(fs)).map_or(0, |n| n as i32);
    out.clear_card().unwrap();
    let mut cards = Vec::new();
    while let Some(card) = out.find_fits("%f", true).unwrap() {
        cards.push(card);
    }
    (ret, cards)
}

#[test]
fn dates_match_c() {
    let mut failed = Vec::new();
    for &(name, mjdobs, prim, alt, fail, ret, cards) in cases::CASES {
        let got = written(mjdobs, prim, alt, fail);
        let want = (ret, cards.iter().map(|c| c.to_string()).collect::<Vec<_>>());
        if got != want {
            failed.push(format!("{name}:\n--- rust\n{got:#?}\n--- C\n{want:#?}"));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n"));
}
