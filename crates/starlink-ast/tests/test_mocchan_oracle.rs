//! `MocChan` against C's MocChan (mocchan.c): the lines written for Mocs in
//! string and JSON form at several `MocLineLen` values, including lengths
//! too short for a value; the Moc read from text split across lines, JSON,
//! blank lines, no text and malformed text, with the `MocFormat` left
//! behind; a read after a failed one; and the attribute defaults.
//!
//! When a line length is too short, C reports the error and passes no more
//! lines to the sink; the port returns the error after the same lines.
//!
//! `mocchan_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/mocchan_probe.c`, which needs the C library as
//! fixed upstream at `7ef81c01`.

// Generated; formatted by its generator rather than rustfmt.
#[rustfmt::skip]
#[path = "mocchan_oracle/cases.rs"]
mod cases;

use starlink_ast::mappings::ZoomMap;
use starlink_ast::regions::{CmpOperator, Moc};
use starlink_ast::{AnyObject, Channel, MocChan, MocFormat, Sink, Source};
use std::sync::{Arc, Mutex};

fn low() -> Moc {
    let mut m = Moc::new();
    m.add_cell(CmpOperator::Or, 2, 37).unwrap();
    m.add_cell(CmpOperator::Or, 1, 3).unwrap();
    m.add_cell(CmpOperator::Or, 2, 100).unwrap();
    m.add_cell(CmpOperator::Xor, 1, 25).unwrap();
    m.add_cell(CmpOperator::Or, 0, 7).unwrap();
    m
}

fn high() -> Moc {
    let mut m = Moc::new();
    m.add_cell(CmpOperator::Or, 15, 1234567890).unwrap();
    m.add_cell(CmpOperator::Or, 10, 5).unwrap();
    m.add_cell(CmpOperator::Or, 3, 700).unwrap();
    m.add_cell(CmpOperator::Or, 3, 702).unwrap();
    m.add_cell(CmpOperator::Or, 8, 99999).unwrap();
    m
}

fn format(name: &str) -> MocFormat {
    match name {
        "STRING" => MocFormat::String,
        "JSON" => MocFormat::Json,
        "UNKNOWN" | "" => MocFormat::Unknown,
        _ => panic!("no MocFormat {name}"),
    }
}

/// A sink that keeps each line, shared so the test can see it.
#[derive(Clone, Default)]
struct Lines(Arc<Mutex<Vec<String>>>);

impl Sink for Lines {
    fn write_line(&mut self, line: &str) {
        self.0.lock().unwrap().push(line.to_string());
    }
}

/// A source that gives the lines as they are, blank ones included.
struct Given(std::vec::IntoIter<String>);

impl Given {
    fn new(lines: &[&str]) -> Box<Self> {
        Box::new(Given(
            lines
                .iter()
                .map(|l| l.to_string())
                .collect::<Vec<_>>()
                .into_iter(),
        ))
    }
}

impl Source for Given {
    fn read_line(&mut self) -> Option<String> {
        self.0.next()
    }
}

#[test]
fn writes_match_c() {
    for &(name, map, fmt, linelen, lines, ret, status) in cases::WRITES {
        let obj = match map {
            "low" => AnyObject::Moc(low()),
            "high" => AnyObject::Moc(high()),
            "zoommap" => AnyObject::ZoomMap(ZoomMap::new(2, 2.0).unwrap()),
            _ => panic!("no object {map}"),
        };
        let mut ch = MocChan::new();
        let sink = Lines::default();
        ch.set_sink(Box::new(sink.clone()));
        if !fmt.is_empty() {
            ch.set_moc_format(format(fmt));
        }
        if linelen > -100 {
            ch.set_moc_line_len(linelen);
        }
        let result = ch.write(&obj);
        assert_eq!(*sink.0.lock().unwrap(), lines, "{name}: lines");
        match result {
            Ok(n) => {
                assert_eq!(n as i32, ret, "{name}: returned value");
                assert_eq!(status, 0, "{name}: C reported an error");
            }
            Err(e) => assert_eq!(e.code() as i32, status, "{name}: status"),
        }
    }
}

#[test]
fn reads_match_c() {
    for &(name, lines, before, read, maxorder, string, after, status) in cases::READS {
        let mut ch = MocChan::new();
        ch.set_source(Given::new(lines));
        if !before.is_empty() {
            ch.set_moc_format(format(before));
        }
        match ch.read() {
            Ok(Some(AnyObject::Moc(moc))) => {
                assert!(read, "{name}: C read no Moc");
                assert_eq!(moc.max_order(), maxorder, "{name}: MaxOrder");
                assert_eq!(moc.get_moc_string(false).unwrap(), string, "{name}");
                assert_eq!(status, 0, "{name}: C reported an error");
            }
            Ok(other) => panic!("{name}: read {other:?}"),
            Err(e) => {
                assert!(!read, "{name}: {e}");
                assert_eq!(e.code() as i32, status, "{name}: status");
            }
        }
        assert_eq!(ch.moc_format(), format(after), "{name}: MocFormat after");
    }
}

#[test]
fn read_after_a_failed_read_continues_with_the_next_line() {
    let (status, string) = cases::RETRY;
    let mut ch = MocChan::new();
    ch.set_source(Given::new(&["2/7 x", "3/1"]));
    assert_eq!(ch.read().unwrap_err().code() as i32, status);
    let Some(AnyObject::Moc(moc)) = ch.read().unwrap() else {
        panic!("expected a Moc");
    };
    assert_eq!(moc.get_moc_string(false).unwrap(), string);
}

#[test]
fn attributes_match_c() {
    let (
        default_len,
        negative_len,
        len_set,
        cleared_len,
        default_fmt,
        json,
        json_set,
        unknown,
        unknown_set,
    ) = cases::ATTRS;
    let mut ch = MocChan::new();
    assert_eq!(ch.moc_line_len(), default_len);
    ch.set_moc_line_len(-5);
    assert_eq!(ch.moc_line_len(), negative_len);
    assert_eq!(ch.test_moc_line_len(), len_set);
    ch.clear_moc_line_len();
    assert_eq!(ch.moc_line_len(), cleared_len);
    assert_eq!(ch.moc_format(), format(default_fmt));
    ch.set_moc_format(MocFormat::Json);
    assert_eq!(ch.moc_format(), format(json));
    assert_eq!(ch.test_moc_format(), json_set);
    ch.set_moc_format(MocFormat::Unknown);
    assert_eq!(ch.moc_format(), format(unknown));
    assert_eq!(ch.test_moc_format(), unknown_set);
}
