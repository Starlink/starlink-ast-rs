//! How many pixel and WCS axes a FITS-WCS read gives, against C: the pixel
//! axes are counted from the highest CRPIX index in the primary or any
//! alternate axis description (fitschan.c `FitsToStore`), whatever NAXIS
//! says; each axis description has WCSAXES WCS axes, or as many as there are
//! pixel axes; a description with a different number of axes is joined to
//! the pixel Frame by a PermMap (`AddFrame`); and a header with no CRPIX
//! gives nothing (`MakeFitsFrameSet`).
//!
//! For each header, compared with C: whether the read gives a FrameSet,
//! nothing or an error, Ncard after the read, the names of the cards left,
//! which shows where a warning was written, the number of axes of each
//! Frame, and the current Frame's position for pixel (2, 3, 4, ...).
//! `fitschan_axis_count_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/fitschan_axis_count_probe.c`.

#[rustfmt::skip]
#[allow(clippy::excessive_precision)]
#[path = "fitschan_axis_count_oracle/cases.rs"]
mod cases;

use starlink_ast::coords::PointSet;
use starlink_ast::frames::FrameRef;
use starlink_ast::mappings::Mapping;
use starlink_ast::{AnyObject, Channel, FitsChan};

/// What the port gives for `header`, in the form of a case's last five
/// fields.
fn read(header: &[&str]) -> (&'static str, i32, Vec<String>, Vec<i32>, Vec<f64>) {
    let mut fc = FitsChan::new().unwrap();
    for card in header {
        fc.put_fits(card, false).unwrap();
    }
    fc.clear_card().unwrap();
    let result = fc.read();
    let ncard = fc.ncard().unwrap() as i32;
    fc.clear_card().unwrap();
    let mut names = Vec::new();
    while let Some(card) = fc.find_fits("%f", true).unwrap() {
        names.push(card[..8].trim_end().to_string());
    }
    match result {
        Err(_) => ("error", ncard, names, vec![], vec![]),
        Ok(None) => ("none", ncard, names, vec![], vec![]),
        Ok(Some(AnyObject::FrameSet(fs))) => {
            let naxes = (1..=fs.nframe())
                .map(|i| fs.frame(FrameRef::Index(i)).unwrap().naxes() as i32)
                .collect();
            let point: Vec<f64> = (0..fs.nin()).map(|i| i as f64 + 2.0).collect();
            let out = fs.transform(&PointSet::from_rows([point]), true).unwrap();
            ("frameset", ncard, names, naxes, out.point(0).to_vec())
        }
        Ok(Some(_)) => panic!("read gave an Object that is not a FrameSet"),
    }
}

#[test]
fn axis_counts_match_c() {
    let mut failed = Vec::new();
    for &(name, header, result, ncard, names, naxes, point) in cases::CASES {
        let got = read(header);
        let names = names.iter().map(|n| n.to_string()).collect();
        let want = (result, ncard, names, naxes.to_vec(), point.to_vec());
        if got != want {
            failed.push(format!("{name}:\n  rust {got:?}\n  C    {want:?}"));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n"));
}
