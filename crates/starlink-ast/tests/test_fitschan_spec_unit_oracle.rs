//! How a FITS-WCS write describes a spectral axis, against C's
//! `SpectralAxes` (fitschan.c): the default reference value is the middle of
//! the spectral range when the size of the spectral pixel axis is known and
//! its first pixel otherwise, and a spectral Unit that is not linearly
//! related to the default Unit is cleared first.
//!
//! Each case reads a frequency cube, optionally sets the Unit of its
//! spectral axis, and writes it to a FitsChan holding the given NAXIS cards.
//! Compared with C: the value the write returns and the cards written.
//! `fitschan_spec_unit_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/fitschan_spec_unit_probe.c`.

#[rustfmt::skip]
#[path = "fitschan_spec_unit_oracle/cases.rs"]
mod cases;

use starlink_ast::frames::Frame;
use starlink_ast::{AnyObject, Channel, Encoding, FitsChan};

const HEADER: &[&str] = &[
    "NAXIS   = 3",
    "CRPIX1  = 5",
    "CRPIX2  = 5",
    "CRPIX3  = 10",
    "CRVAL1  = 10",
    "CRVAL2  = 20",
    "CRVAL3  = 1.4E9",
    "CDELT1  = -0.001",
    "CDELT2  = 0.001",
    "CDELT3  = 1.0E6",
    "CTYPE1  = 'RA---TAN'",
    "CTYPE2  = 'DEC--TAN'",
    "CTYPE3  = 'FREQ'",
    "CUNIT3  = 'Hz'",
    "SPECSYS = 'LSRK'",
    "RESTFRQ = 1.420405752E9",
    "RADESYS = 'FK5'",
    "EQUINOX = 2000.0",
];

/// The value the write returns and the cards written.
fn written(unit: &str, dims: &str) -> (i32, Vec<String>) {
    let mut fc = FitsChan::new().unwrap();
    for card in HEADER {
        fc.put_fits(card, false).unwrap();
    }
    fc.clear_card().unwrap();
    let Some(AnyObject::FrameSet(mut fs)) = fc.read().unwrap() else {
        panic!("the header gave no FrameSet");
    };
    if !unit.is_empty() {
        fs.set_unit(3, unit).unwrap();
    }
    let mut out = FitsChan::new().unwrap();
    out.set_encoding(Encoding::FitsWcs);
    for card in dims.split('~').filter(|c| !c.is_empty()) {
        out.put_fits(card, false).unwrap();
    }
    let ret = out.write(&AnyObject::FrameSet(fs)).map_or(0, |n| n as i32);
    out.clear_card().unwrap();
    let mut cards = Vec::new();
    while let Some(card) = out.find_fits("%f", true).unwrap() {
        cards.push(card);
    }
    (ret, cards)
}

#[test]
fn spectral_axes_match_c() {
    let mut failed = Vec::new();
    for &(name, unit, dims, ret, cards) in cases::CASES {
        let got = written(unit, dims);
        let want = (ret, cards.iter().map(|c| c.to_string()).collect::<Vec<_>>());
        if got != want {
            failed.push(format!("{name}:\n--- rust\n{got:#?}\n--- C\n{want:#?}"));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n"));
}
