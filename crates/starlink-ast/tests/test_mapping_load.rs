//! Mappings whose dumps leave values out read back as C's do: a PermMap
//! constant or a diagonal MatrixMap element that is bad is written unset and
//! reads back as bad (permmap.c, matrixmap.c Dump and Load), and the
//! `ProjP<m>` keys of an older WcsMap dump are the latitude axis's projection
//! parameters (wcsmap.c Load). Each case's re-dump must equal C's, and its
//! forward transformation must equal C's bit for bit. The PermMaps C dumped
//! are also built here, and their dumps must equal C's: C writes only the
//! constants the permutations refer to.
//!
//! `mapping_load_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/mapping_load_probe.c`.

use crate::common::native_dump;
// Generated; formatted by its generator rather than rustfmt.
#[rustfmt::skip]
#[path = "mapping_load_oracle/cases.rs"]
mod cases;

use starlink_ast::constants::BAD_VALUE;
use starlink_ast::coords::PointSet;
use starlink_ast::mappings::PermMap;
use starlink_ast::{AnyObject, from_native_string};

fn text(lines: &[&str]) -> String {
    let mut s = lines.join("\n");
    s.push('\n');
    s
}

#[test]
fn loads_match_the_c_library() {
    let mut failures = Vec::new();
    for &(name, dump, redump, input, want) in cases::CASES {
        let obj = from_native_string(&text(dump)).unwrap();
        let got = native_dump(&obj).unwrap();
        if got != text(redump) {
            failures.push(format!(
                "{name} re-dump:\n{got}\nC gives:\n{}",
                text(redump)
            ));
        }

        let map = obj.as_mapping().expect("a Mapping");
        let rows: Vec<Vec<f64>> = input.chunks(map.nin()).map(<[f64]>::to_vec).collect();
        let out = map.transform(&PointSet::from_rows(rows), true).unwrap();
        let got: Vec<f64> = (0..out.npoint())
            .flat_map(|i| out.point(i).to_vec())
            .collect();
        if !crate::common::c_values_eq(&got, want) {
            failures.push(format!("{name} forward: {got:?}, C gives {want:?}"));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

#[test]
fn permmap_dumps_match_the_c_library() {
    let built = [
        (
            "permmap_bad_constant",
            PermMap::new(&[1], &[1, -1], &[BAD_VALUE]),
        ),
        (
            "permmap_bad_constant_among_others",
            PermMap::new(&[1], &[1, -2], &[5.0, BAD_VALUE, 7.0]),
        ),
        (
            "permmap_unreferenced_constant",
            PermMap::new(&[1], &[1, -1], &[5.0, 6.0]),
        ),
    ];
    let mut failures = Vec::new();
    for (name, map) in built {
        let &(_, dump, ..) = cases::CASES.iter().find(|c| c.0 == name).expect("a case");
        let got = native_dump(&AnyObject::PermMap(map.unwrap())).unwrap();
        if got != text(dump) {
            failures.push(format!("{name}:\n{got}\nC gives:\n{}", text(dump)));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

/// A DssMap dump missing a plate parameter, PPO3, PPO6 or one of the first
/// 13 plate solution coefficients on an axis is an AST__RDERR error, as C's
/// loader reports; a later coefficient defaults to 0 (dssmap.c Load).
#[test]
#[cfg_attr(ast_dist_tier = "cutdown", ignore = "fixture not distributed")]
fn a_dssmap_dump_needs_its_plate_solution() {
    let dump = std::fs::read_to_string(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/tests/fixtures/serialisation/c_dssmap.ast"
    ))
    .unwrap();
    let without = |key: &str| -> String {
        dump.lines()
            .filter(|l| !l.trim_start().starts_with(&format!("{key} =")))
            .map(|l| format!("{l}\n"))
            .collect()
    };
    assert!(from_native_string(&dump).is_ok());
    for key in ["PltRA", "YPixSz", "PPO3", "PPO6", "AMDX1", "AMDY13"] {
        let err = from_native_string(&without(key)).unwrap_err();
        assert_eq!(err.code(), starlink_ast::error::ErrorCode::Rderr, "{key}");
    }
    for key in ["PPO1", "AMDX14", "AMDY19"] {
        assert!(from_native_string(&without(key)).is_ok(), "{key}");
    }
}
