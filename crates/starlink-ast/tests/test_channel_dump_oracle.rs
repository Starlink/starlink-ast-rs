//! Channel, MocChan and FitsChan dumps against C's (channel.c, mocchan.c and
//! fitschan.c `Dump` and loaders): every attribute unset, each set, values
//! the setters change, and an Ident; FitsChans holding a card of each type,
//! cards used by a read, and a retained card; each dump read back and dumped
//! again; and hand-written dumps holding values the setters change, a
//! lower-case MocEnc and an unknown one, missing FitsChan card items, a
//! legacy deletion flag, and unknown card types, encodings and AltAxes
//! values. Each case is also written with Full = 1, which writes every unset
//! value, less C's unset `RefCnt` and `Nobj`, counts of pointers to the
//! Object and of Objects of its class, which the port does not have.
//!
//! `channel_dump_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/channel_dump_probe.c`, which needs the C library
//! as fixed upstream at `228a0310` and with the reversed MocEnc names
//! explained at `f5fdca61`, and fitschan.c as fixed at `c16f9b11`.

use crate::common::native_dump;
// Generated; formatted by its generator rather than rustfmt.
#[rustfmt::skip]
#[path = "channel_dump_oracle/cases.rs"]
mod cases;

use starlink_ast::{
    AltAxes, AnyObject, Channel, Encoding, FitsChan, MocChan, MocFormat, NativeChannel,
};
use starlink_ast::{StringSource, from_native_string};

fn channel(f: impl FnOnce(&mut NativeChannel)) -> AnyObject {
    let mut ch = NativeChannel::new();
    f(&mut ch);
    AnyObject::NativeChannel(Box::new(ch))
}

fn mocchan(f: impl FnOnce(&mut MocChan)) -> AnyObject {
    let mut ch = MocChan::new();
    f(&mut ch);
    AnyObject::MocChan(Box::new(ch))
}

/// The object each case of the probe makes.
fn object(name: &str) -> AnyObject {
    match name {
        "channel" => channel(|_| {}),
        "channel_set" => channel(|ch| {
            let c = ch.config_mut();
            c.set_comment(false);
            c.set_full(1);
            c.set_indent(5);
            c.set_report_level(2);
            c.set_skip(true);
            c.set_strict(true);
        }),
        "channel_set_defaults" => channel(|ch| {
            let c = ch.config_mut();
            c.set_comment(true);
            c.set_full(0);
            c.set_indent(3);
            c.set_report_level(1);
            c.set_skip(false);
            c.set_strict(false);
        }),
        "channel_clamped" => channel(|ch| {
            let c = ch.config_mut();
            c.set_comment(true);
            c.set_full(5);
            c.set_indent(-2);
        }),
        "channel_full_negative" => channel(|ch| ch.config_mut().set_full(-4)),
        "mocchan" => mocchan(|_| {}),
        "mocchan_string" => mocchan(|ch| {
            ch.set_moc_format(MocFormat::String);
            ch.set_moc_line_len(40);
        }),
        "mocchan_json" => mocchan(|ch| {
            ch.set_moc_format(MocFormat::Json);
            ch.set_moc_line_len(-3);
            ch.config_mut().set_indent(2);
            ch.config_mut().set_strict(true);
        }),
        "mocchan_ident" => mocchan(|ch| ch.set_ident("hello")),
        "fitschan" => fitschan(|_| {}),
        "fitschan_cards" => fitschan(|fc| {
            for card in [
                "INTKEY  =                   42 / an integer",
                "FLTKEY  =                  1.5 / a float",
                "STRKEY  = 'hello   '           / a string",
                "LOGKEY  =                    T",
            ] {
                fc.put_fits(card, false).unwrap();
            }
            fc.set_fits_cf("CPXF", (1.5, -2.25), "complex float", false)
                .unwrap();
            fc.set_fits_ci("CPXI", (3, 4), "", false).unwrap();
            for card in [
                "BIGINT  =         123456789012 / 64-bit",
                "UNDEFKEY=                      / no value",
                "COMMENT a comment card",
                "HISTORY   history text   ",
                "        blank keyword",
                "LONGSTR = 'abc&'",
                "CONTINUE  'def'",
            ] {
                fc.put_fits(card, false).unwrap();
            }
            fc.set_card(3).unwrap();
        }),
        "fitschan_attrs" => fitschan(|fc| {
            fc.set_encoding(Encoding::FitsWcs);
            fc.set_fits_digits(10);
            fc.set_fits_rounding(5);
            fc.set_alt_axes(AltAxes::Ident);
            fc.set_def_b1950(false);
            fc.set_ignore_bad_alt(true);
            fc.set_cd_matrix(true);
            fc.set_car_lin(true);
            fc.set_sip_replace(false);
            fc.set_fits_tol(0.5);
            fc.set_poly_tan(1);
            fc.set_sip_ok(false);
            fc.set_iwc(true);
            fc.set_clean(true);
            fc.set_warning_conditions("BadKeyName").unwrap();
            fc.set_fits_axis_order("<copy>");
            fc.set_ident("fc");
            fc.config_mut().set_skip(false);
            fc.config_mut().set_full(0);
        }),
        "fitschan_attrs_default" => fitschan(|fc| {
            fc.set_encoding(Encoding::Native);
            fc.set_fits_digits(17);
            fc.set_alt_axes(AltAxes::All);
            fc.set_def_b1950(true);
            fc.set_ignore_bad_alt(false);
            fc.set_cd_matrix(false);
            fc.set_car_lin(false);
            fc.set_sip_replace(true);
            fc.set_fits_tol(0.1);
            fc.set_poly_tan(-1);
            fc.set_sip_ok(true);
            fc.set_iwc(false);
            fc.set_clean(false);
            // C's astSet stores an empty value as a single space.
            fc.set_warning_conditions(" ").unwrap();
            fc.config_mut().set_skip(true);
            fc.config_mut().set_full(-1);
        }),
        "fitschan_guessed_encoding" => AnyObject::FitsChan(Box::new(wcs_header())),
        "fitschan_source" => fitschan(|fc| fc.set_source(Box::new(StringSource::new(SOURCE)))),
        "fitschan_used" => {
            let mut fc = wcs_header();
            fc.read().unwrap();
            AnyObject::FitsChan(Box::new(fc))
        }
        other => panic!("no case {other}"),
    }
}

fn fitschan(f: impl FnOnce(&mut FitsChan)) -> AnyObject {
    let mut fc = FitsChan::new().unwrap();
    f(&mut fc);
    AnyObject::FitsChan(Box::new(fc))
}

/// The FitsChan the `fitschan_guessed_encoding` and `fitschan_used` cases
/// start from: a FITS-WCS header whose CRVAL2 card is retained.
fn wcs_header() -> FitsChan {
    let mut fc = FitsChan::new().unwrap();
    for card in [
        "NAXIS   =                    2",
        "CTYPE1  = 'RA---TAN'",
        "CTYPE2  = 'DEC--TAN'",
        "CRVAL1  =                 10.0",
        "CRVAL2  =                 20.0",
        "CRPIX1  =                 50.0",
        "CRPIX2  =                 60.0",
        "CDELT1  =               -0.001",
        "CDELT2  =                0.001",
        "OTHER   =                    1",
    ] {
        fc.put_fits(card, false).unwrap();
    }
    fc.clear_card().unwrap();
    fc.find_fits("CRVAL2", false).unwrap();
    fc.retain_fits().unwrap();
    fc.clear_card().unwrap();
    fc
}

/// The cards the source of the `fitschan_source` case gives.
const SOURCE: &str = "A       =                    1\nB       = 'two'";

fn lines(text: &str) -> Vec<&str> {
    text.lines().collect()
}

#[test]
fn dumps_match_c() {
    for &(name, dump, reread) in cases::DUMPS {
        let text = native_dump(&object(name)).unwrap();
        assert_eq!(lines(&text), dump, "{name}: dump");
        let back = from_native_string(&text).unwrap();
        let text = native_dump(&back).unwrap();
        assert_eq!(lines(&text), reread, "{name}: dump read back");
    }
}

#[test]
fn full_dumps_match_c() {
    for &(name, dump) in cases::FULL_DUMPS {
        let mut ch = NativeChannel::with_string_sink();
        ch.config_mut().set_full(1);
        ch.write(&object(name)).unwrap();
        assert_eq!(lines(&ch.into_string()), dump, "{name}");
    }
}

#[test]
fn loads_match_c() {
    for &(name, text, dump, status) in cases::LOADS {
        match from_native_string(&text.join("\n")) {
            Ok(obj) => {
                assert_eq!(status, 0, "{name}: C reported an error");
                let out = native_dump(&obj).unwrap();
                assert_eq!(lines(&out), dump, "{name}");
            }
            Err(e) => {
                assert_eq!(e.code() as i32, status, "{name}: {e}");
                assert!(dump.is_empty(), "{name}: C read an object");
            }
        }
    }
}

#[test]
fn a_clone_shares_the_sink() {
    let mut ch = MocChan::with_string_sink();
    let mut copy = ch.clone();
    let mut moc = starlink_ast::regions::Moc::new();
    moc.add_cell(starlink_ast::regions::CmpOperator::Or, 1, 3)
        .unwrap();
    let moc = AnyObject::Moc(moc);
    ch.write(&moc).unwrap();
    copy.write(&moc).unwrap();
    assert_eq!(ch.into_string(), "1/3\n1/3\n");
}

/// The variable that tells a copy of this test program that it is the child
/// [`a_channel_read_from_a_dump_has_no_source`] started.
const NO_SOURCE_CHILD: &str = "AST_TEST_DUMP_NO_SOURCE_CHILD";

/// A Channel read from a dump has no source or SourceFile, so a read takes
/// standard input; here that is an empty pipe, and the read finds no text.
///
/// The read runs in a child process with piped, closed standard input, so it
/// cannot wait on the harness's own.
#[test]
fn a_channel_read_from_a_dump_has_no_source() {
    let text = native_dump(&object("mocchan_string")).unwrap();
    let AnyObject::MocChan(mut ch) = from_native_string(&text).unwrap() else {
        panic!("expected a MocChan");
    };
    assert_eq!(ch.moc_line_len(), 40);
    assert!(!ch.test_source_file());
    if std::env::var_os(NO_SOURCE_CHILD).is_some() {
        assert_eq!(
            ch.read().unwrap_err().code(),
            starlink_ast::error::ErrorCode::Inmoc
        );
        return;
    }
    let out = std::process::Command::new(std::env::current_exe().unwrap())
        .args([
            "test_channel_dump_oracle::a_channel_read_from_a_dump_has_no_source",
            "--exact",
            "--test-threads=1",
        ])
        .env(NO_SOURCE_CHILD, "1")
        .stdin(std::process::Stdio::null())
        .output()
        .unwrap();
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        out.status.success() && stdout.contains("1 passed"),
        "{stdout}{}",
        String::from_utf8_lossy(&out.stderr)
    );
}

#[test]
fn a_dump_leaves_the_source_cards_in_the_fitschan() {
    let mut fc = FitsChan::new().unwrap();
    fc.set_source(Box::new(StringSource::new(SOURCE)));
    let obj = AnyObject::FitsChan(Box::new(fc));
    let first = native_dump(&obj).unwrap();
    assert_eq!(native_dump(&obj).unwrap(), first);
    let AnyObject::FitsChan(mut fc) = obj else {
        unreachable!()
    };
    assert_eq!(fc.ncard().unwrap(), 2);
}

#[test]
fn a_keymap_holding_a_fitschan_round_trips() {
    let mut fc = FitsChan::new().unwrap();
    fc.put_fits("A       =                    1", false)
        .unwrap();
    let mut km = starlink_ast::KeyMap::new();
    km.put_0a("fc", AnyObject::FitsChan(Box::new(fc)), None)
        .unwrap();
    let text = native_dump(&AnyObject::KeyMap(Box::new(km))).unwrap();
    let AnyObject::KeyMap(km) = from_native_string(&text).unwrap() else {
        panic!("expected a KeyMap");
    };
    let Some(Some(AnyObject::FitsChan(mut fc))) = km.get_0a("fc").unwrap() else {
        panic!("expected a FitsChan");
    };
    fc.clear_card().unwrap();
    assert_eq!(fc.get_fits_i(Some("A")).unwrap(), Some(1));
}
