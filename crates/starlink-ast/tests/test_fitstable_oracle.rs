//! FitsTables against C (fitstable.c): adding columns, creating a FitsTable
//! from a FITS header, column null values and sizes, getting and putting
//! whole columns, getting and putting the header, copying, and the native
//! dump and its reading.
//!
//! Each case is a script of operations run through the C library by
//! `tools/oracle_fixtures/fitstable_probe.c`, which records the result of
//! each and dumps at the marked points; the same script is run here through
//! the public API and the two transcripts compared byte for byte. The
//! probe's header describes the operations. `fitstable_oracle/cases.rs` is
//! generated by the probe.

use crate::common::native_dump;
