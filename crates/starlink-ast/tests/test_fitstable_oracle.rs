use starlink_ast::error::AstError;
use starlink_ast::{AnyObject, AstType, ColumnData, FitsChan, FitsTable, from_native_string};

/// C's `%.{prec}g`, with "nan", "inf" and "-inf" for values that are not
/// finite.
fn c_g(v: f64, prec: usize) -> String {
    if v.is_nan() {
        return "nan".to_string();
    }
    if v.is_infinite() {
        return if v > 0.0 { "inf" } else { "-inf" }.to_string();
    }
    if v == 0.0 {
        return if v.is_sign_negative() { "-0" } else { "0" }.to_string();
    }
    let e = format!("{v:.*e}", prec - 1);
    let (mant, exp) = e.split_once('e').unwrap();
    let exp: i32 = exp.parse().unwrap();
    let strip = |s: &str| {
        if s.contains('.') {
            s.trim_end_matches('0').trim_end_matches('.').to_string()
        } else {
            s.to_string()
        }
    };
    if exp < -4 || exp >= prec as i32 {
        let sign = if exp < 0 { '-' } else { '+' };
        format!("{}e{sign}{:02}", strip(mant), exp.unsigned_abs())
    } else {
        let decimals = (prec as i32 - 1 - exp).max(0) as usize;
        strip(&format!("{v:.decimals$}"))
    }
}

/// The column data type the probe names with a letter or a number.
fn type_code(t: &str) -> AstType {
    match t {
        "I" => AstType::Int,
        "D" => AstType::Double,
        "F" => AstType::Float,
        "C" => AstType::String,
        "A" => AstType::Object,
        "S" => AstType::SInt,
        "B" => AstType::Byte,
        "K" => AstType::KInt,
        "U" => AstType::Undef,
        n => AstType::from_code(n.parse().unwrap_or(0)).unwrap_or(AstType::BadType),
    }
}

/// A list separated by `sep`, empty for an empty string.
fn list(s: &str, sep: char) -> Vec<&str> {
    if s.is_empty() {
        Vec::new()
    } else {
        s.split(sep).collect()
    }
}

/// C's `atoi`/`atof` of a value the probe reads.
fn num<T: std::str::FromStr>(s: &str) -> T
where
    T::Err: std::fmt::Debug,
{
    s.parse().unwrap()
}

/// A FitsChan holding the ';'-separated cards in `s`.
fn cards(s: &str) -> FitsChan {
    let mut fc = FitsChan::new().unwrap();
    for card in list(s, ';') {
        fc.put_fits(card, false).unwrap();
    }
    fc
}

/// The text the probe prints for an operation that returns nothing.
fn unit(r: Result<(), AstError>) -> (String, Option<AstError>) {
    ("=\n".to_string(), r.err())
}

/// The text the probe prints for a string result, which on failure is
/// "(null)".
fn text(r: Result<String, AstError>) -> (String, Option<AstError>) {
    match r {
        Ok(s) => (format!("= '{s}'\n"), None),
        Err(e) => ("= '(null)'\n".to_string(), Some(e)),
    }
}

/// The value of an attribute as `astGetC` formats it.
fn attribute(t: &FitsTable, attr: &str) -> Result<String, AstError> {
    let t = t.as_table();
    let column = |prefix: &str| {
        attr.strip_prefix(prefix)
            .and_then(|r| r.strip_prefix('('))
            .and_then(|r| r.strip_suffix(')'))
    };
    if attr == "NRow" {
        Ok(t.nrow().to_string())
    } else if attr == "NColumn" {
        Ok(t.ncolumn().to_string())
    } else if let Some(c) = column("ColumnType") {
        t.column_type(c).map(|ty| ty.code().to_string())
    } else if let Some(c) = column("ColumnUnit") {
        t.column_unit(c)
    } else if let Some(c) = column("ColumnNdim") {
        t.column_ndim(c).map(|n| n.to_string())
    } else if let Some(c) = column("ColumnLength") {
        t.column_length(c).map(|n| n.to_string())
    } else if let Some(c) = column("ColumnLenC") {
        t.column_len_c(c).map(|n| n.to_string())
    } else {
        panic!("attribute {attr} is not handled")
    }
}

/// The dump the probe writes, each line prefixed by "|".
fn dump(t: &FitsTable) -> String {
    native_dump(&AnyObject::FitsTable(Box::new(t.clone())))
        .unwrap()
        .lines()
        .map(|l| format!("|{l}\n"))
        .collect()
}

/// The values of column data as the probe shows them.
fn show_data(data: &ColumnData) -> String {
    let mut s = String::new();
    match data {
        ColumnData::Byte(v) => v.iter().for_each(|x| s.push_str(&format!(" {x}"))),
        ColumnData::SInt(v) => v.iter().for_each(|x| s.push_str(&format!(" {x}"))),
        ColumnData::Int(v) => v.iter().for_each(|x| s.push_str(&format!(" {x}"))),
        ColumnData::KInt(v) => v.iter().for_each(|x| s.push_str(&format!(" {x}"))),
        ColumnData::Float(v) => v
            .iter()
            .for_each(|x| s.push_str(&format!(" {}", c_g(f64::from(*x), 9)))),
        ColumnData::Double(v) => v
            .iter()
            .for_each(|x| s.push_str(&format!(" {}", c_g(*x, 17)))),
        ColumnData::String { values, .. } => {
            for value in values {
                s.push_str(" '");
                for &b in value {
                    if b == 0 {
                        s.push_str("\\0");
                    } else {
                        s.push(b as char);
                    }
                }
                s.push('\'');
            }
        }
    }
    s
}

/// The column data the probe builds from a list of values, for a column of
/// type `ty`, strings padded with nulls to `clen` as `strncpy` does.
fn column_data(ty: AstType, clen: usize, values: &[&str]) -> ColumnData {
    match ty {
        AstType::Byte => ColumnData::Byte(values.iter().map(|v| num::<i32>(v) as u8).collect()),
        AstType::SInt => ColumnData::SInt(values.iter().map(|v| num::<i32>(v) as i16).collect()),
        AstType::Int => ColumnData::Int(values.iter().map(|v| num(v)).collect()),
        AstType::KInt => ColumnData::KInt(values.iter().map(|v| num(v)).collect()),
        AstType::Float => ColumnData::Float(values.iter().map(|v| num::<f64>(v) as f32).collect()),
        AstType::Double => ColumnData::Double(values.iter().map(|v| num(v)).collect()),
        AstType::String => ColumnData::String {
            len: clen,
            values: values.iter().map(|v| v.as_bytes().to_vec()).collect(),
        },
        _ => panic!("no column data for {ty:?}"),
    }
}

/// Run one operation, returning its result text and any error.
fn run(t: &mut FitsTable, op: &str) -> (String, Option<AstError>) {
    let f: Vec<&str> = op.splitn(6, '|').collect();
    let key = f.get(1).copied().unwrap_or("");
    match f[0] {
        "NEW" => {
            let mut fc = cards(key);
            let result = FitsTable::from_header(&mut fc);
            let card = format!("= card {}\n", fc.card().unwrap());
            match result {
                Ok(new) => {
                    *t = new;
                    (card, None)
                }
                Err(e) => (card, Some(e)),
            }
        }
        "NEWH" => {
            let result = t
                .get_table_header()
                .and_then(|mut fc| FitsTable::from_header(&mut fc));
            match result {
                Ok(new) => {
                    *t = new;
                    ("=\n".to_string(), None)
                }
                Err(e) => ("=\n".to_string(), Some(e)),
            }
        }
        "AC" => {
            let dims: Vec<usize> = list(f[3], ',').iter().map(|d| num(d)).collect();
            unit(t.add_column(key, type_code(f[2]), &dims, f[4]))
        }
        "RC" => unit(t.remove_column(key)),
        "RR" => unit(t.remove_row(num(key))),
        "PR" => unit(t.purge_rows()),
        "MR" => unit(t.map_remove(key)),
        "P0I" => unit(t.put_0i(key, num(f[2]), None)),
        "P0D" => unit(t.put_0d(key, num(f[2]), None)),
        "P0F" => unit(t.put_0f(key, num::<f64>(f[2]) as f32, None)),
        "P0C" => unit(t.put_0c(key, f[2], None)),
        "P0S" => unit(t.put_0s(key, num::<i32>(f[2]) as i16, None)),
        "P0B" => unit(t.put_0b(key, num::<i32>(f[2]) as u8, None)),
        "P0K" => unit(t.put_0k(key, num(f[2]), None)),
        "PALL" => {
            let all: Vec<u8> = (0..=255).collect();
            unit(t.put_1b(key, &all, None))
        }
        "P1I" | "P1D" | "P1F" | "P1C" | "P1S" | "P1B" | "P1K" => {
            let v = list(f[2], ',');
            unit(match f[0] {
                "P1I" => t.put_1i(key, &v.iter().map(|x| num(x)).collect::<Vec<_>>(), None),
                "P1D" => t.put_1d(key, &v.iter().map(|x| num(x)).collect::<Vec<_>>(), None),
                "P1F" => t.put_1f(
                    key,
                    &v.iter().map(|x| num::<f64>(x) as f32).collect::<Vec<_>>(),
                    None,
                ),
                "P1C" => t.put_1c(key, &v, None),
                "P1S" => t.put_1s(
                    key,
                    &v.iter().map(|x| num::<i32>(x) as i16).collect::<Vec<_>>(),
                    None,
                ),
                "P1B" => t.put_1b(
                    key,
                    &v.iter().map(|x| num::<i32>(x) as u8).collect::<Vec<_>>(),
                    None,
                ),
                _ => t.put_1k(key, &v.iter().map(|x| num(x)).collect::<Vec<_>>(), None),
            })
        }
        "G1K" => match t.as_table().get_1k(key) {
            Ok(Some(v)) => (
                format!(
                    "={}\n",
                    v.iter().map(|x| format!(" {x}")).collect::<String>()
                ),
                None,
            ),
            Ok(None) => ("= none\n".to_string(), None),
            Err(e) => ("= none\n".to_string(), Some(e)),
        },
        "CNULL" | "CNULLN" => {
            let check = f[0] == "CNULL";
            let set = (num::<i32>(f[2]) != 0).then(|| num::<i64>(f[3]));
            let unset_hasnull = if check { 0 } else { -1 };
            match t.column_null(key, set, check) {
                Ok(r) => (
                    format!(
                        "= {} {} {}\n",
                        r.value,
                        i32::from(r.was_set),
                        r.has_null.map_or(-1, i32::from)
                    ),
                    None,
                ),
                Err(e) => (format!("= 0 0 {unset_hasnull}\n"), Some(e)),
            }
        }
        "CSZ" => match t.column_size(key) {
            Ok(n) => (format!("= {n}\n"), None),
            Err(e) => ("= 0\n".to_string(), Some(e)),
        },
        "GCD" => {
            let size = match t.column_size(key) {
                Ok(n) => n,
                Err(e) => return ("= -1\n".to_string(), Some(e)),
            };
            let mxsize = if f[4] == "all" { size } else { num(f[4]) };
            let nrow = t.as_table().nrow();
            let nbv = size.checked_div(nrow).unwrap_or(0);
            let max_rows = (nbv > 0 && mxsize < nbv * nrow).then(|| mxsize / nbv);
            match t.get_column_data(key, num::<f64>(f[2]) as f32, num(f[3]), max_rows) {
                Ok(data) => (format!("= {}{}\n", data.nelem(), show_data(&data)), None),
                Err(e) => ("= -1\n".to_string(), Some(e)),
            }
        }
        "PCD" => {
            let ty = match t.as_table().column_type(key) {
                Ok(ty) => ty,
                Err(e) => return ("=\n".to_string(), Some(e)),
            };
            let data = column_data(ty, num(f[2]), &list(f[3], ','));
            unit(t.put_column_data(key, &data))
        }
        "GTH" => match t.get_table_header() {
            Ok(mut fc) => {
                let mut s = format!("= card {}\n", fc.card().unwrap());
                while let Some(card) = fc.find_fits("%f", true).unwrap() {
                    s.push_str(&format!("|{card}\n"));
                }
                (s, None)
            }
            Err(e) => ("=\n".to_string(), Some(e)),
        },
        "PTH" => unit(t.put_table_header(&cards(key))),
        "GA" => text(attribute(t, key)),
        "CS" => {
            let mx: usize = num(f[2]);
            let shape = t.as_table().column_shape(key).unwrap();
            let mut s = format!("= {}", shape.len());
            for i in 0..mx {
                s.push_str(&format!(" {}", shape.get(i).copied().unwrap_or(1)));
            }
            (s + "\n", None)
        }
        "CP" => {
            *t = t.clone();
            unit(Ok(()))
        }
        "RW" => {
            let text = native_dump(&AnyObject::FitsTable(Box::new(t.clone()))).unwrap();
            let obj = from_native_string(&text).unwrap();
            let name = match &obj {
                AnyObject::FitsTable(_) => "FitsTable",
                _ => "another class",
            };
            if let AnyObject::FitsTable(read) = obj {
                *t = *read;
            }
            (format!("= {name}\n"), None)
        }
        "D" => (format!("=\n{}", dump(t)), None),
        other => panic!("operation {other} is not handled"),
    }
}

#[test]
fn fitstables_match_c() {
    let mut failed = Vec::new();
    for &(name, ops, want) in cases::CASES {
        let mut t = FitsTable::new().unwrap();
        let mut out = String::new();
        for op in ops {
            out.push_str(&format!("> {op}\n"));
            let (text, err) = run(&mut t, op);
            out.push_str(&text);
            if let Some(e) = err {
                out.push_str(&format!("! {}\n", e.code() as u32));
            }
        }
        if out != want {
            let line = out
                .lines()
                .zip(want.lines())
                .position(|(a, b)| a != b)
                .unwrap_or_else(|| out.lines().count().min(want.lines().count()));
            failed.push(format!(
                "{name}: first difference at line {}\n--- rust\n{}\n--- C\n{}",
                line + 1,
                out.lines()
                    .skip(line.saturating_sub(3))
                    .take(8)
                    .collect::<Vec<_>>()
                    .join("\n"),
                want.lines()
                    .skip(line.saturating_sub(3))
                    .take(8)
                    .collect::<Vec<_>>()
                    .join("\n"),
            ));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n\n"));
}
