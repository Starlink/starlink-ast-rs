//! The axis Labels a FITS-WCS read gives, against C: `WcsOthers`
//! (fitschan.c) labels each axis no other function claims with its CNAME,
//! else with the comment of its CTYPE card, else with its CTYPE value. It
//! uses the comments only when more than one axis is left to it, each has a
//! comment, and no comment repeats an earlier one, comparing each with those
//! at the positions of the earlier such axes counted from zero, so a repeat
//! is missed when the celestial axes come first.
//!
//! For each header the transcript gives, for each Frame read, its Domain and
//! the Label of each axis. `fitschan_labels_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/fitschan_labels_probe.c`.

#[rustfmt::skip]
#[path = "fitschan_labels_oracle/cases.rs"]
mod cases;

use starlink_ast::frames::FrameRef;
use starlink_ast::{AnyObject, Channel, FitsChan};

/// The transcript the port gives for `header`.
fn transcript(header: &[&str]) -> String {
    let mut fc = FitsChan::new().unwrap();
    for card in header {
        fc.put_fits(card, false).unwrap();
    }
    fc.clear_card().unwrap();
    match fc.read() {
        Err(e) => format!("! {}\n", e.code() as u32),
        Ok(None) => "= none\n".to_string(),
        Ok(Some(AnyObject::FrameSet(fs))) => {
            let mut out = String::new();
            for i in 1..=fs.nframe() {
                let frm = fs.frame(FrameRef::Index(i)).unwrap();
                out.push_str(&format!("= frame {i} {}\n", frm.domain()));
                for axis in 1..=frm.naxes() {
                    out.push_str(&format!("| {}\n", frm.label(axis).unwrap()));
                }
            }
            out
        }
        Ok(Some(_)) => panic!("read gave an Object that is not a FrameSet"),
    }
}

#[test]
fn labels_match_c() {
    let mut failed = Vec::new();
    for &(name, header, want) in cases::CASES {
        let got = transcript(header);
        if got != want {
            failed.push(format!("{name}:\n--- rust\n{got}--- C\n{want}"));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n"));
}
