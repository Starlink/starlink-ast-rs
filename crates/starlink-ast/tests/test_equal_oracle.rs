//! Mapping equality against C's `astEqual` where the classes treat the
//! Invert flag in their own ways: a WinMap compares its stored terms first
//! and its applied ones only when the Invert flags differ (winmap.c Equal);
//! a SelectorMap compares its number of inputs, Regions and bad value, not
//! the Invert flag (selectormap.c Equal); a TranMap compares its components
//! in the orientations it recorded (tranmap.c Equal); a WcsMap compares each
//! projection parameter, an unset one differing from one set to zero
//! (wcsmap.c Equal, fixed upstream in 47826767).
//!
//! `equal_oracle/cases.rs` is generated by `tools/oracle_fixtures/equal_probe.c`.

use crate::common::native_dump;
// Generated; formatted by its generator rather than rustfmt.
#[rustfmt::skip]
#[path = "equal_oracle/cases.rs"]
mod cases;

use starlink_ast::frames::BasicFrameBuilder;
use starlink_ast::mappings::{
    DynMapping, Mapping, SelectorMapBuilder, TranMap, WcsMap, WcsProjection, WinMap, ZoomMap,
};
use starlink_ast::regions::{BoxRegionBuilder, CircleBuilder, DynRegion};
use starlink_ast::{AnyObject, from_native_string};

fn winmap(ina: f64, inb: f64, outa: f64, outb: f64) -> WinMap {
    WinMap::from_corners(&[ina], &[inb], &[outa], &[outb]).unwrap()
}

fn circle(centre: [f64; 2]) -> DynRegion {
    Box::new(
        CircleBuilder::new(BasicFrameBuilder::new(2).build().unwrap(), centre.to_vec())
            .unwrap()
            .radius(1.0)
            .build()
            .unwrap(),
    )
}

fn selectormap(regions: Vec<DynRegion>) -> DynMapping {
    Box::new(SelectorMapBuilder::new(regions).unwrap().build())
}

fn inverted(map: &DynMapping) -> DynMapping {
    let mut m = map.clone_box();
    m.invert();
    m
}

/// The two Mappings a case compares.
fn pair(name: &str) -> (DynMapping, DynMapping) {
    match name {
        "winmap_self_inverse_vs_inverted_copy" => {
            let a: DynMapping = Box::new(winmap(0.0, 1.0, 0.0, -1.0));
            let b = inverted(&a);
            (a, b)
        }
        "winmap_inverse_of_its_inverse" => {
            let b: DynMapping = Box::new(winmap(0.0, 2.0, -0.5, 0.5));
            (Box::new(winmap(0.0, 1.0, 1.0, 3.0)), inverted(&b))
        }
        "selectormap_one_region_vs_two" => (
            selectormap(vec![circle([0.0, 0.0])]),
            selectormap(vec![circle([0.0, 0.0]), circle([5.0, 5.0])]),
        ),
        "selectormap_vs_inverted_copy" => {
            let a = selectormap(vec![circle([0.0, 0.0])]);
            let b = inverted(&a);
            (a, b)
        }
        "selectormap_1d_vs_inverted_copy" => {
            let frame = BasicFrameBuilder::new(1).build().unwrap();
            let interval: DynRegion = Box::new(
                BoxRegionBuilder::from_bounds(frame, &[0.0], &[1.0])
                    .unwrap()
                    .build()
                    .unwrap(),
            );
            let a = selectormap(vec![interval]);
            let b = inverted(&a);
            (a, b)
        }
        "tranmap_vs_reread_without_component_invert" => {
            let mut z2 = ZoomMap::new(1, 2.0).unwrap();
            z2.invert();
            let tm = TranMap::new(Box::new(z2), Box::new(ZoomMap::new(1, 0.5).unwrap())).unwrap();
            let dump = native_dump(&AnyObject::TranMap(tm.clone())).unwrap();
            assert!(dump.contains("InvA = 1"));
            // Drop the first component's Invert card, as the probe does.
            let mut dropped = false;
            let edited: String = dump
                .lines()
                .filter(|l| {
                    let drop = !dropped && l.contains(" Invert = 1");
                    dropped |= drop;
                    !drop
                })
                .map(|l| format!("{l}\n"))
                .collect();
            let AnyObject::TranMap(back) = from_native_string(&edited).unwrap() else {
                panic!("not a TranMap");
            };
            (Box::new(tm), Box::new(back))
        }
        "wcsmap_pv_vs_none"
        | "wcsmap_zero_pv_vs_none"
        | "wcsmap_pv_vs_pv_with_one_cleared"
        | "wcsmap_same_pv" => {
            let sin = |pvs: &[(usize, f64)]| -> WcsMap {
                let mut w = WcsMap::new(2, WcsProjection::Sin, 1, 2).unwrap();
                for &(m, v) in pvs {
                    w.set_pv(2, m, v).unwrap();
                }
                w
            };
            let (a, b) = match name {
                "wcsmap_pv_vs_none" => (sin(&[(1, 0.5)]), sin(&[])),
                "wcsmap_zero_pv_vs_none" => (sin(&[(1, 0.0)]), sin(&[])),
                "wcsmap_pv_vs_pv_with_one_cleared" => {
                    let mut b = sin(&[(1, 0.5), (2, 1.0)]);
                    b.clear_pv(2, 2).unwrap();
                    (sin(&[(1, 0.5)]), b)
                }
                _ => (sin(&[(1, 0.5)]), sin(&[(1, 0.5)])),
            };
            (Box::new(a), Box::new(b))
        }
        _ => panic!("no Rust construction for case {name}"),
    }
}

#[test]
fn equality_matches_the_c_library() {
    let failures: Vec<String> = cases::CASES
        .iter()
        .filter_map(|&(name, want)| {
            let (a, b) = pair(name);
            let got = a.equal(b.as_ref());
            (got != want).then(|| format!("{name}: {got}, C {want}"))
        })
        .collect();
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

/// testmapping.c `testwcsmapequal` asserts cases 1 and 3 in both directions,
/// so the reverse comparison must give the answer C gives forwards.
#[test]
fn wcsmap_equality_is_symmetric_where_c_checks_it() {
    for name in ["wcsmap_pv_vs_none", "wcsmap_pv_vs_pv_with_one_cleared"] {
        let want = cases::CASES.iter().find(|c| c.0 == name).unwrap().1;
        let (a, b) = pair(name);
        assert_eq!(b.equal(a.as_ref()), want, "{name}, reversed");
    }
}
