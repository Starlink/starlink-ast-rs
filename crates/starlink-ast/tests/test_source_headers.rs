//! Every source file the repository owns opens with its copyright and license.
//!
//! The two lines are the copyright of the Association of Universities for
//! Research in Astronomy and the SPDX identifier of the LGPL-3.0-or-later
//! license, in the comment syntax of the file's language and after the
//! shebang where there is one. A `cases.rs` that a probe in
//! `tools/oracle_fixtures` generates is exempt, its copyright being the
//! probe's. The vendored C under `crates/starlink-ast/vendor` carries its own
//! notices and is skipped, as are the fixture trees.

use std::fs;
use std::path::{Path, PathBuf};

const HOLDER: &str = "Association of Universities for Research in Astronomy (AURA)";
const SPDX: &str = "SPDX-License-Identifier: LGPL-3.0-or-later";
const EXTENSIONS: [&str; 5] = ["rs", "c", "h", "py", "sh"];
/// Directories whose files are not this repository's source: the vendored C
/// with its own notices, the fixture tree mirrored from upstream, and build
/// output.
const FOREIGN_DIRS: [&str; 3] = ["vendor", "fixtures", "target"];

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crates/starlink-ast has two ancestors")
        .to_path_buf()
}

/// Every source file under `dir`, skipping the directories that are not ours.
fn sources(dir: &Path, out: &mut Vec<PathBuf>) {
    for entry in fs::read_dir(dir).expect("directory readable") {
        let path = entry.expect("readable entry").path();
        if path.is_dir() {
            let name = path.file_name().unwrap().to_string_lossy();
            if !FOREIGN_DIRS.contains(&name.as_ref()) && !name.starts_with('.') {
                sources(&path, out);
            }
        } else if path
            .extension()
            .and_then(|e| e.to_str())
            .is_some_and(|e| EXTENSIONS.contains(&e))
        {
            out.push(path);
        }
    }
}

/// Whether `line` is the copyright line: a year or a year range, then the holder,
/// inside the comment syntax of any of the languages.
fn is_copyright(line: &str) -> bool {
    let line = line
        .trim()
        .trim_start_matches(['/', '*', '#', ' '])
        .trim_end_matches("*/")
        .trim_end();
    let Some(rest) = line.strip_prefix("Copyright ") else {
        return false;
    };
    let Some((years, holder)) = rest.split_once(' ') else {
        return false;
    };
    let year = |s: &str| s.len() == 4 && s.bytes().all(|b| b.is_ascii_digit());
    let years_ok = match years.split_once('-') {
        Some((from, to)) => year(from) && year(to),
        None => year(years),
    };
    years_ok && holder == HOLDER
}

#[test]
#[cfg_attr(ast_dist_tier = "cutdown", ignore = "needs the source repository")]
fn every_source_file_opens_with_the_copyright_and_license() {
    let root = repo_root();
    let mut files = Vec::new();
    sources(&root.join("crates"), &mut files);
    sources(&root.join("tools"), &mut files);
    files.sort();
    let mut missing = Vec::new();
    for path in &files {
        let text = fs::read_to_string(path).expect("source readable");
        let mut lines = text.lines();
        let mut first = lines.next().unwrap_or("");
        if first.starts_with("// Generated by tools/") {
            continue;
        }
        if first.starts_with("#!") {
            first = lines.next().unwrap_or("");
        }
        let second = lines.next().unwrap_or("");
        if !(is_copyright(first) && second.contains(SPDX)) {
            missing.push(path.strip_prefix(&root).unwrap().display().to_string());
        }
    }
    assert!(
        missing.is_empty(),
        "source files without the copyright and license header:\n  {}",
        missing.join("\n  ")
    );
}
