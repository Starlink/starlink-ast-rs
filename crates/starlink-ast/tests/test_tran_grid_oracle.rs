//! `Mapping::tran_grid` and `Mapping::quad_approx` against C's `astTranGrid`
//! and `astQuadApprox` (mapping.c).
//!
//! Each grid is compared bit for bit through a hash of every output, plus a
//! sample of positions so a mismatch shows where it is. The grids cover the
//! linear-fit paths C keeps separate (1-D, 2-D and general), sections divided
//! by the initial scale size, Mappings simplified because the grid is large,
//! blocks of positions, and the inverse transform.
//!
//! `tran_grid_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/tran_grid_probe.c`.

// Generated; formatted by its generator rather than rustfmt. The values are
// C's, printed with every digit that `%.17g` gives.
#[rustfmt::skip]
#[allow(clippy::excessive_precision)]
#[path = "tran_grid_oracle/cases.rs"]
mod cases;

use ndarray::array;
use starlink_ast::coords::PointSet;
use starlink_ast::fitschan::FitsChan;
use starlink_ast::mappings::{
    CmpMap, Composition, DynMapping, Mapping, MathMap, MatrixMap, PermMap, PolyMap, PolyTerm,
    ShiftMap, ZoomMap,
};
use starlink_ast::{AnyObject, Channel};

/// The FITS-WCS pixel-to-sky FrameSet of `testtrangrid.c`, with an `NAXIS`
/// card the port's FITS-AIPS reader needs (C counts the axes from the CRPIX
/// cards instead) and which leaves C's results unchanged.
fn tan() -> DynMapping {
    let mut fc = FitsChan::new().unwrap();
    for card in [
        "CTYPE1  = 'RA---TAN'",
        "CTYPE2  = 'DEC--TAN'",
        "CRPIX1  = 20",
        "CRPIX2  = 20",
        "CRVAL1  = 0.0",
        "CRVAL2  = 0.0",
        "CROTA1  = 30.0",
        "CDELT1  = -0.001",
        "CDELT2  = 0.001",
        "NAXIS   = 2",
    ] {
        fc.put_fits(card, false).unwrap();
    }
    fc.clear_card().unwrap();
    match fc.read().unwrap() {
        Some(AnyObject::FrameSet(fs)) => Box::new(fs),
        other => panic!("expected a FrameSet, got {other:?}"),
    }
}

/// The 3-D CmpMap of `testtrangrid.c`.
fn cmp3() -> DynMapping {
    let c1: DynMapping = Box::new(ShiftMap::new(vec![-1.0]));
    let c2: DynMapping = Box::new(MatrixMap::new(array![[1.0, 2.0], [-2.0, 3.0]]).unwrap());
    let c3 = CmpMap::new(c1, c2, Composition::Parallel).unwrap();
    let c1: DynMapping = Box::new(PermMap::new(&[3, 2, 1], &[3, 2, 1], &[]).unwrap());
    let mut c2 = ZoomMap::new(3, 0.25).unwrap();
    c2.invert();
    let mut c4 = CmpMap::new(c1, Box::new(c2), Composition::Series).unwrap();
    c4.invert();
    Box::new(CmpMap::new(Box::new(c3), Box::new(c4), Composition::Series).unwrap())
}

fn term(coeff: f64, powers: &[usize]) -> PolyTerm {
    PolyTerm {
        coeff,
        powers: powers.to_vec(),
        out_axis: 1,
    }
}

/// The Mapping a case names, built as the probe builds it.
fn mapping(name: &str) -> DynMapping {
    match name {
        "zoom2" => Box::new(ZoomMap::new(2, 2.0).unwrap()),
        "tan" => tan(),
        "cmp3" => cmp3(),
        "cubic" => {
            Box::new(MathMap::new(1, 1, &["y=x**3"], &["x=sign((abs(y)**(1/3)),y)"]).unwrap())
        }
        "matrix23" => {
            Box::new(MatrixMap::new(array![[1.0, 2.0], [3.0, -4.0], [0.5, 6.0]]).unwrap())
        }
        "poly" => {
            let fwd = [
                term(2.0, &[0, 0]),
                term(3.0, &[1, 0]),
                term(4.0, &[0, 1]),
                term(5.0, &[1, 1]),
                term(6.0, &[2, 0]),
                term(7.0, &[0, 2]),
            ];
            Box::new(PolyMap::new(2, 1, &fwd, None).unwrap())
        }
        "sqrt_part" => Box::new(MathMap::new(2, 1, &["o=sqrt(x)*y"], &["x", "y"]).unwrap()),
        "second_bad" => {
            Box::new(MathMap::new(2, 2, &["o1=x+2*y*y", "o2=sqrt(-1-x*x)"], &["x", "y"]).unwrap())
        }
        _ => panic!("no Mapping {name}"),
    }
}

/// FNV-1a over the bit patterns of every output, position by position.
fn hash(out: &PointSet) -> u64 {
    let mut h: u64 = 14695981039346656037;
    for i in 0..out.npoint() {
        for v in out.point(i) {
            h = (h ^ v.to_bits()).wrapping_mul(1099511628211);
        }
    }
    h
}

/// Mappings that run SphMap's forward transform, which is within 1 ULP of C
/// per arctangent; every case on them is compared by `sphmap_drift_eq` and
/// its variants.
const SPHMAP_DRIFT_MAPS_LICENSED: &[&str] = &["tan"];

#[test]
fn grids_match_c() {
    for &(name, map, lbnd, ubnd, tol, maxpix, forward, want_hash, sample) in cases::GRIDS {
        let m = mapping(map);
        let out = m.tran_grid(lbnd, ubnd, tol, maxpix, forward).unwrap();
        let got: Vec<f64> = (0..out.npoint())
            .step_by(97)
            .flat_map(|i| out.point(i).to_vec())
            .collect();
        let drift = SPHMAP_DRIFT_MAPS_LICENSED.contains(&map);
        if drift {
            assert!(
                crate::common::sphmap_drift_values_eq(&got, sample),
                "{name}: sampled positions: got {got:?}, C gives {sample:?}"
            );
        } else {
            crate::common::assert_c_values(&got, sample, &format!("{name}: sampled positions"));
        }
        // The hash pins every value bit for bit, so it is compared only on
        // the platform the C values were captured on, and not for a case that
        // drifts from C; otherwise the samples, compared within libm
        // rounding, are the check.
        if crate::common::on_capture_platform() && !drift {
            assert_eq!(hash(&out), want_hash, "{name}: every position");
        }
    }
}

#[test]
fn grid_errors_match_c() {
    let zoom = mapping("zoom2");
    let codes = [
        zoom.tran_grid(&[5, 0], &[3, 4], 0.5, 100, true),
        zoom.tran_grid(&[3, 4], &[3, 4], -1.0, 100, true),
        MathMap::new(1, 1, &["y=x**3"], &["x"])
            .unwrap()
            .tran_grid(&[0], &[4], 0.5, 100, false),
        zoom.tran_grid(&[0], &[4], 0.5, 100, true),
    ]
    .map(|r| r.unwrap_err().code() as i32);
    assert_eq!(codes, cases::GRID_ERRORS);
}

#[test]
fn quadratic_fits_match_c() {
    for &(name, map, lbnd, ubnd, nx, ny, fitted, rms, coeffs) in cases::QUADS {
        let fit = mapping(map).quad_approx(lbnd, ubnd, nx, ny).unwrap();
        assert_eq!(fit.fitted, fitted, "{name}: returned value");
        if SPHMAP_DRIFT_MAPS_LICENSED.contains(&map) {
            assert!(
                crate::common::sphmap_drift_eq(fit.rms, rms)
                    && crate::common::sphmap_drift_values_eq(&fit.coeffs, coeffs),
                "{name}: rms {} coefficients\n got {:?}\nwant {coeffs:?}",
                fit.rms,
                fit.coeffs
            );
            continue;
        }
        assert_eq!(fit.rms.to_bits(), rms.to_bits(), "{name}: rms {}", fit.rms);
        assert_eq!(
            fit.coeffs.iter().map(|v| v.to_bits()).collect::<Vec<_>>(),
            coeffs.iter().map(|v| v.to_bits()).collect::<Vec<_>>(),
            "{name}: coefficients\n got {:?}\nwant {coeffs:?}",
            fit.coeffs
        );
    }
}

#[test]
fn quadratic_fit_needs_two_inputs() {
    let err = mapping("cubic")
        .quad_approx([0.0, 0.0], [1.0, 1.0], 5, 5)
        .unwrap_err();
    assert_eq!(err.code() as i32, cases::QUAD_ONE_INPUT);
}
