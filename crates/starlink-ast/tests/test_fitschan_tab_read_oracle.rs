//! Reading FITS-WCS headers whose axes use the `-TAB` algorithm of
//! FITS-WCS paper III, against C (fitschan.c `TabMapping`): the look-up
//! tables the FrameSet uses, the errors, the tables left in the FitsChan,
//! the cards left after the read, and a table source.
//!
//! Each case is a script of operations run through the C library by
//! `tools/oracle_fixtures/fitschan_tab_read_probe.c`, which records the
//! result of each and dumps what is read; the same script is run here
//! through the public API and the two transcripts compared byte for byte.
//! The probe's header describes the operations.
//! `fitschan_tab_read_oracle/cases.rs` is generated by the probe.
//!
//! C's table source stores the table it reads with `astPutTable`; here the
//! source returns it, and the FitsChan stores it under the name asked for.

use crate::common::native_dump;
// Generated; formatted by its generator rather than rustfmt.
#[rustfmt::skip]
#[path = "fitschan_tab_read_oracle/cases.rs"]
mod cases;

use std::sync::{Arc, Mutex};

use starlink_ast::error::AstError;
use starlink_ast::{AnyObject, AstType, Channel, FitsChan, FitsTable};

/// Cases that differ from C for a reason unrelated to `-TAB`, each with the
/// reason. `excluded_cases_still_differ` fails when one starts to match.
const TAB_READ_EXCLUDED: &[(&str, &str)] = &[];

/// Cases whose C dump has one `IsSimp = 1` card more than the port's, at the
/// given line of the transcript, and why. The card records a merge probe C's
/// simplifier threw away, which the port cannot reproduce
/// (`docs/issues/c-library-quirks.md`, "An `IsSimp` card can record a merge
/// probe C threw away"); `fitschan_tab_spectral` in the simplify corpus is
/// the same Mapping.
const PROBE_STAMP_LICENSED: &[(&str, usize, &str)] = &[(
    "mixed",
    183,
    "on the CmpMap of the MatrixMap and SphMap of the celestial rotation",
)];

/// Cases one line of whose transcript differs from C's in a number by at
/// most the given number of ULP, the line, and why. Every other line is
/// compared byte for byte.
const ULP_LICENSED: &[(&str, usize, u64, &str)] = &[(
    "celestial_iwc",
    128,
    1,
    "the shift of the WinMap the IWC Mapping simplifies to, folded from an \
     inverted WinMap, a WinMap and two unit MatrixMaps in a different order; \
     `fitschan_tab_celestial_iwc` in the simplify corpus is the same Mapping, \
     compared there within its 4 ULP bound",
)];

/// Whether the port's transcript `out` matches C's `want` for case `name`.
fn matches(name: &str, out: &str, want: &str) -> bool {
    let Some(&(_, line, ulps, _)) = ULP_LICENSED.iter().find(|(n, ..)| *n == name) else {
        return crate::common::c_text_eq(out, want);
    };
    assert_ne!(
        out, want,
        "{name}: the licensed difference is no longer needed"
    );
    let (g, w): (Vec<&str>, Vec<&str>) = (out.lines().collect(), want.lines().collect());
    g.len() == w.len()
        && g.iter().zip(&w).enumerate().all(|(i, (a, b))| {
            if i + 1 == line {
                crate::common::line_tokens_equivalent(a, b, ulps)
            } else {
                crate::common::c_text_eq(a, b)
            }
        })
}

/// The transcripts of a case, the port's and C's, with any licensed
/// `IsSimp` card removed from C's.
fn transcripts(name: &str, ops: &[&str], want: &str) -> (String, String) {
    let mut fc = FitsChan::new().unwrap();
    let mut held = Held::new();
    let log = Arc::new(Mutex::new(String::new()));
    let mut out = String::new();
    for op in ops {
        out.push_str(&format!("> {op}\n"));
        let (text, err) = run(&mut fc, &mut held, &log, op);
        out.push_str(&text);
        if let Some(e) = err {
            out.push_str(&format!("! {}\n", e.code() as u32));
        }
    }
    let mut want = want.to_string();
    if let Some(&(_, line, _)) = PROBE_STAMP_LICENSED.iter().find(|(n, ..)| *n == name) {
        assert_ne!(
            out, want,
            "{name}: the licensed IsSimp card is no longer needed"
        );
        let mut lines: Vec<&str> = want.lines().collect();
        assert!(
            lines[line - 1]
                .trim_start_matches('|')
                .trim_start()
                .starts_with("IsSimp = 1"),
            "{name}: line {line} of C's transcript is not an IsSimp card"
        );
        lines.remove(line - 1);
        want = lines.join("\n") + "\n";
    }
    (out, want)
}

/// The tables the script has built, by extension name.
type Held = Vec<(String, FitsTable)>;

/// Run one operation, returning its result text and any error. Calls of the
/// table source are logged to `log`.
fn run(
    fc: &mut FitsChan,
    held: &mut Held,
    log: &Arc<Mutex<String>>,
    op: &str,
) -> (String, Option<AstError>) {
    let f: Vec<&str> = op.splitn(6, '|').collect();
    match f[0] {
        "C" => ("=\n".to_string(), fc.put_fits(f[1], false).err()),
        "S" => {
            match f[1].split_once('=') {
                Some(("TabOK", v)) => fc.set_tab_ok(v.parse().unwrap()),
                Some(("Iwc", v)) => fc.set_iwc(v != "0"),
                _ => panic!("setting {} is not handled", f[1]),
            }
            ("=\n".to_string(), None)
        }
        "TC" => {
            let (ext, col) = (f[1], f[2]);
            let i = match held.iter().position(|(name, _)| name == ext) {
                Some(i) => i,
                None => {
                    held.push((ext.to_string(), FitsTable::new().unwrap()));
                    held.len() - 1
                }
            };
            let table = &mut held[i].1;
            let dims: Vec<usize> = f[3]
                .split(',')
                .filter(|d| !d.is_empty())
                .map(|d| d.parse().unwrap())
                .collect();
            table.add_column(col, AstType::Double, &dims, " ").unwrap();
            let vals: Vec<f64> = f[4]
                .split(',')
                .filter(|v| !v.is_empty())
                .map(|v| v.parse().unwrap())
                .collect();
            let key = format!("{col}(1)");
            if vals.len() == 1 && dims.is_empty() {
                table.put_0d(&key, vals[0], None).unwrap();
            } else if !vals.is_empty() {
                table.put_1d(&key, &vals, None).unwrap();
            }
            ("=\n".to_string(), None)
        }
        "PT" => {
            for (name, table) in held.iter() {
                fc.put_table(table, name).unwrap();
            }
            ("=\n".to_string(), None)
        }
        "SRC" => {
            let tables = held.clone();
            let log = Arc::clone(log);
            fc.set_table_source(move |extname: &str, extver: i32, extlevel: i32| {
                log.lock()
                    .unwrap()
                    .push_str(&format!("~ source {extname} {extver} {extlevel}\n"));
                Ok(tables
                    .iter()
                    .find(|(name, _)| name == extname)
                    .map(|(_, t)| t.clone()))
            });
            ("=\n".to_string(), None)
        }
        "R" => {
            fc.clear_card().unwrap();
            let result = fc.read();
            let mut text = std::mem::take(&mut *log.lock().unwrap());
            match result {
                Ok(Some(obj)) => {
                    let class = match &obj {
                        AnyObject::FrameSet(_) => "FrameSet",
                        _ => "another class",
                    };
                    text.push_str(&format!("= {class}\n"));
                    for line in native_dump(&obj).unwrap().lines() {
                        text.push_str(&format!("|{line}\n"));
                    }
                    (text, None)
                }
                Ok(None) => (text + "= null\n", None),
                Err(e) => (text + "= null\n", Some(e)),
            }
        }
        "GT" => match fc.get_tables() {
            None => ("= null\n".to_string(), None),
            Some(km) => {
                let mut s = format!("= {}", km.map_size());
                for i in 0..km.map_size() {
                    s.push_str(&format!(" {}", km.map_key(i).unwrap()));
                }
                (s + "\n", None)
            }
        },
        "CARDS" => {
            fc.clear_card().unwrap();
            let mut s = "=\n".to_string();
            while let Some(card) = fc.find_fits("%f", true).unwrap() {
                s.push_str(&format!("|{card}\n"));
            }
            (s, None)
        }
        other => panic!("operation {other} is not handled"),
    }
}

#[test]
fn fitschan_tab_reads_match_c() {
    let mut failed = Vec::new();
    for &(name, ops, want) in cases::CASES {
        if TAB_READ_EXCLUDED.iter().any(|(n, _)| *n == name) {
            continue;
        }
        let (out, want) = transcripts(name, ops, want);
        if !matches(name, &out, &want) {
            let line = out
                .lines()
                .zip(want.lines())
                .position(|(a, b)| a != b)
                .unwrap_or_else(|| out.lines().count().min(want.lines().count()));
            failed.push(format!(
                "{name}: first difference at line {}\n--- rust\n{}\n--- C\n{}",
                line + 1,
                out.lines()
                    .skip(line.saturating_sub(3))
                    .take(8)
                    .collect::<Vec<_>>()
                    .join("\n"),
                want.lines()
                    .skip(line.saturating_sub(3))
                    .take(8)
                    .collect::<Vec<_>>()
                    .join("\n"),
            ));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n\n"));
}

#[test]
fn excluded_cases_still_differ() {
    for (name, reason) in TAB_READ_EXCLUDED {
        let &(_, ops, want) = cases::CASES
            .iter()
            .find(|(n, ..)| n == name)
            .expect("an excluded case is in the corpus");
        let (out, want) = transcripts(name, ops, want);
        assert_ne!(
            out, want,
            "{name} now matches C ({reason}); remove its exclusion"
        );
    }
}
