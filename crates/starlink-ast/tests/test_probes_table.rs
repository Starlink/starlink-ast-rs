//! `tools/oracle_fixtures/probes.tsv` names the probe behind every generated
//! C-oracle file.
//!
//! `check_probes_fresh.sh` checks only the files the table lists, so a
//! `tests/*_oracle/cases.rs` missing from it would never be compared with
//! the pinned C library. Each row must also name a probe source that exists,
//! a build recipe and run directory the script knows, and an output that
//! exists.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

/// Generated by a script rather than one probe, as the table's header says.
const NOT_FROM_A_PROBE: [&str; 1] = ["crates/starlink-ast/tests/grid_oracle/cases.rs"];
const RECIPES: [&str; 5] = ["make", "fast", "plain", "grflog", "grflog-ownerr"];
const RUN_DIRS: [&str; 3] = ["tools", "build", "fixtures"];
const STDINS: [&str; 2] = ["-", "fixtures-list"];

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crates/starlink-ast has two ancestors")
        .to_path_buf()
}

/// The table's rows, keyed by output, each with its probe name.
fn rows(root: &Path) -> BTreeMap<String, String> {
    let text = fs::read_to_string(root.join("tools/oracle_fixtures/probes.tsv"))
        .expect("probes.tsv readable");
    let mut out = BTreeMap::new();
    for line in text.lines() {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let cols: Vec<&str> = line.split('\t').collect();
        assert_eq!(
            cols.len(),
            7,
            "probes.tsv row has 7 tab-separated columns: {line}"
        );
        let [probe, recipe, run_dir, _env, stdin, output, _known] = cols[..] else {
            unreachable!()
        };
        assert!(
            root.join(format!("tools/oracle_fixtures/{probe}.c"))
                .is_file(),
            "probes.tsv names {probe}, which has no source in tools/oracle_fixtures"
        );
        assert!(
            RECIPES.contains(&recipe),
            "{probe}: unknown build recipe {recipe}"
        );
        assert!(
            RUN_DIRS.contains(&run_dir),
            "{probe}: unknown run_dir {run_dir}"
        );
        assert!(STDINS.contains(&stdin), "{probe}: unknown stdin {stdin}");
        assert!(
            root.join(output).is_file(),
            "{probe}: output {output} does not exist"
        );
        if let Some(other) = out.insert(output.to_string(), probe.to_string()) {
            panic!("{output} is the output of both {other} and {probe}");
        }
    }
    out
}

#[test]
#[cfg_attr(ast_dist_tier = "cutdown", ignore = "needs the source repository")]
fn every_generated_oracle_has_a_probe_row() {
    let root = repo_root();
    let listed = rows(&root);
    let tests = root.join("crates/starlink-ast/tests");
    let mut unlisted = Vec::new();
    for entry in fs::read_dir(&tests).expect("tests directory readable") {
        let dir = entry.expect("readable entry").path();
        let name = dir.file_name().unwrap().to_string_lossy().into_owned();
        if !name.ends_with("_oracle") || !dir.join("cases.rs").is_file() {
            continue;
        }
        let output = format!("crates/starlink-ast/tests/{name}/cases.rs");
        if !listed.contains_key(&output) && !NOT_FROM_A_PROBE.contains(&output.as_str()) {
            unlisted.push(output);
        }
    }
    assert!(
        unlisted.is_empty(),
        "generated oracle files with no row in tools/oracle_fixtures/probes.tsv: {unlisted:?}"
    );
}
