//! The FrameSet a FITS-WCS read gives, against C, for headers whose
//! simplified Mappings depend on how `WcsMapFrm` (fitschan.c) builds the
//! pixel to WCS chain before `astSimplify`:
//! `((((WcsIntWorld ; WcsCelestial) ; WcsSpectral) ; WcsOthers) ; tabmap)`.
//! `WcsIntWorld` makes the CDELT scaling a diagonal MatrixMap, which is a unit
//! one when every CDELT is equal to 1 within `astEQUAL`; `WcsCelestial` is a
//! UnitMap when there are no celestial axes; `WcsSpectral` and `WcsOthers`
//! join one Mapping per axis in parallel, `WcsOthers` using `LogWcs` for a
//! CTYPE ending in `-LOG`.
//!
//! Each case's native dump is compared byte for byte.
//! `fitschan_read_chain_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/fitschan_read_chain_probe.c`, and its
//! `other_log_crval_zero` case needs the C fix f6c0d187, without which C
//! crashes.

use crate::common::native_dump;
#[rustfmt::skip]
#[path = "fitschan_read_chain_oracle/cases.rs"]
mod cases;

use starlink_ast::{Channel, FitsChan};

/// The transcript the port gives for `header`.
fn transcript(header: &[&str]) -> String {
    let mut fc = FitsChan::new().unwrap();
    for card in header {
        fc.put_fits(card, false).unwrap();
    }
    fc.clear_card().unwrap();
    match fc.read() {
        Err(e) => format!("! {}\n", e.code() as u32),
        Ok(None) => "= none\n".to_string(),
        Ok(Some(obj)) => native_dump(&obj).unwrap(),
    }
}

#[test]
fn reads_match_c() {
    let mut failed = Vec::new();
    for &(name, header, want) in cases::CASES {
        let got = transcript(header);
        if got != want {
            let line = got
                .lines()
                .zip(want.lines())
                .position(|(a, b)| a != b)
                .unwrap_or_else(|| got.lines().count().min(want.lines().count()));
            failed.push(format!(
                "{name}: first difference at line {}\n--- rust\n{}\n--- C\n{}",
                line + 1,
                got.lines()
                    .skip(line.saturating_sub(3))
                    .take(8)
                    .collect::<Vec<_>>()
                    .join("\n"),
                want.lines()
                    .skip(line.saturating_sub(3))
                    .take(8)
                    .collect::<Vec<_>>()
                    .join("\n"),
            ));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n\n"));
}
