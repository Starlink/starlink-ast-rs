//! Whether formatted values carry graphical escape sequences.
//!
//! A Plot draws axis labels with escape sequences, which raise the "h" of
//! "12h" or the exponent of "10^4"; elsewhere a formatted value is plain
//! text. A Plot turns them on while it draws and restores the previous
//! state afterwards, and the axis formatters read the flag.
// C: object.c astEscapes (:8823), a per-thread flag, and the delimiters
// astTuneC gives for hrdel, mndel, scdel, dgdel, amdel, asdel and exdel
// (object.c:320). The port does not support tuning them.

use std::cell::Cell;

thread_local! {
    static ESCAPES: Cell<bool> = const { Cell::new(false) };
}

/// Whether formatted values carry escape sequences in this thread.
pub(crate) fn escapes() -> bool {
    ESCAPES.with(Cell::get)
}

/// Turn escape sequences in formatted values on or off for this thread
/// until the returned guard is dropped, which restores the previous state.
// C: astEscapes( new_value ), whose returned old value the caller passes
// back to restore it.
pub(crate) fn set_escapes(on: bool) -> EscapesGuard {
    EscapesGuard(ESCAPES.with(|e| e.replace(on)))
}

/// Restores the escapes flag when dropped.
pub(crate) struct EscapesGuard(bool);

impl Drop for EscapesGuard {
    fn drop(&mut self) {
        ESCAPES.with(|e| e.set(self.0));
    }
}

/// The delimiter after an hours field.
pub(crate) const HRDEL: &str = "%-%^50+%s70+h%+";
/// The delimiter after a minutes-of-time field.
pub(crate) const MNDEL: &str = "%-%^50+%s70+m%+";
/// The delimiter after a seconds-of-time field.
pub(crate) const SCDEL: &str = "%-%^50+%s70+s%+";
/// The delimiter after a degrees field.
pub(crate) const DGDEL: &str = "%-%^53+%s60+o%+";
/// The delimiter after an arcminutes field.
pub(crate) const AMDEL: &str = "%-%^20+%s85+'%+";
/// The delimiter after an arcseconds field.
pub(crate) const ASDEL: &str = "%-%^20+%s85+\"%+";
/// The delimiter between "10" and the exponent of a log value.
pub(crate) const EXDEL: &str = "10%-%^50+%s70+";

// Generated by tools/oracle_fixtures/escapes_probe.c.
#[cfg(test)]
#[rustfmt::skip]
#[path = "../tests/escapes_oracle/cases.rs"]
mod oracle;

#[cfg(test)]
mod tests {
    use super::*;
    use crate::frames::{BasicFrameBuilder, Frame, SkyFrame};

    use super::oracle;

    #[test]
    fn formatting_with_and_without_escapes_matches_the_c_library() {
        let mut failures = Vec::new();
        for &(sky, axis, fmt, value, esc, text, nc, read) in oracle::CASES {
            let mut frame: Box<dyn Frame> = if sky {
                Box::new(SkyFrame::unset_system())
            } else {
                Box::new(BasicFrameBuilder::new(2).build().unwrap())
            };
            frame.set_format_str(axis, fmt).unwrap();
            let _guard = set_escapes(esc);
            let got = frame.format(axis, value).unwrap();
            if got != text {
                failures.push(format!(
                    "{fmt} {value} escapes {esc}: got {got:?}, C gives {text:?}"
                ));
                continue;
            }
            let split = frame.fields(axis, fmt, text, 10).unwrap();
            let lens: Vec<usize> = split.fields.iter().map(|r| r.len()).collect();
            if lens != nc || split.value != read {
                failures.push(format!(
                    "{fmt} {text:?}: fields {lens:?} value {}, C gives {nc:?} {read}",
                    split.value
                ));
            }
        }
        assert!(!escapes());
        assert!(failures.is_empty(), "{}", failures.join("\n"));
    }
}
