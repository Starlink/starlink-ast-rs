/// Interpolation method for [`LutMap`] table lookups, the value of
/// [`LutMap::interp`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LutInterp {
    /// Linear interpolation between the two neighboring entries (the
    /// default).
    /// An input outside the table is extrapolated from the two entries at
    /// that end of the table.
    Linear,
    /// The nearest table entry.
    /// An input outside the table transforms to [`BAD_VALUE`].
    Nearest,
}

/// Transform 1-dimensional coordinates using a lookup table.
///
/// A LutMap transforms 1-dimensional coordinates by interpolating in a
/// lookup table; it always has one input and one output coordinate.
///
/// Each input coordinate value is first scaled to give the index of an entry
/// in the table by subtracting a starting value, [`start`](LutMap::start)
/// (the input coordinate of the first table entry), and dividing by an
/// increment, [`inc`](LutMap::inc) (the difference in input coordinate between
/// adjacent table entries).
/// The table entry at index `i` therefore corresponds to the input coordinate
/// `start + i * inc`.
///
/// The resulting index usually has a fractional part, so the output
/// coordinate is generated by interpolating linearly between the appropriate
/// entries in the table.
/// If the index lies outside the range of the table, linear extrapolation is
/// used, based on the two entries at the start or end of the table as
/// appropriate.
/// If either of the entries used for the interpolation is [`BAD_VALUE`], the
/// result is [`BAD_VALUE`].
/// [`interp`](LutMap::interp) selects nearest-neighbor lookup instead.
///
/// If the table entries increase or decrease monotonically, ignoring flat
/// sections and bad entries, the inverse transformation is also available.
/// The inverse transforms a value that lies within a flat section of the
/// table, or between two good entries that are both next to a bad entry, to
/// [`BAD_VALUE`].
///
/// [`lut_epsilon`](LutMap::lut_epsilon) states the relative error of the table
/// values, which decides whether simplification replaces a nearly-linear
/// LutMap with a [`WinMap`].
#[derive(Debug, Clone)]
pub struct LutMap {
    /// Table values.
    lut: Vec<f64>,
    /// Input coordinate at first entry.
    start: f64,
    /// Input spacing between entries.
    inc: f64,
    /// Interpolation method, `None` while unset (C's `-INT_MAX`). The
    /// constructor and the loader both set it, as C's do (lutmap.c:2418, 2586),
    /// so only [`LutMap::clear_interp`] unsets it.
    interp: Option<LutInterp>,
    /// Monotonicity: +1 increasing, -1 decreasing, 0 non-monotonic.
    monotonic: i8,
    /// The table the inverse searches, when `lut` has bad entries (C's
    /// `luti`, `flagsi` and `indexi`).
    inverse_table: Option<InverseTable>,
    /// Whether the mapping is inverted.
    inverted: bool,
    /// The stated relative error of the table values — C's `LutEpsilon`
    /// attribute, written as the `LutEps` card (`lutmap.c:2012`), defaulting to
    /// `DBL_EPSILON`.
    ///
    /// It scales the linearity tolerance in [`Self::table_is_linear`], so it
    /// decides whether a nearly-linear table is replaced by a WinMap.
    lut_epsilon: f64,
    /// Whether `LutEpsilon` holds a supplied value — C's `TestLutEpsilon`
    /// (`lutmap.c:1843`), which decides whether the `LutEps` card is written at
    /// all (`lutmap.c:2009-2013`).
    lut_epsilon_set: bool,
    /// Whether this mapping has already been simplified (C `IsSimple`).
    simplified: SimplifiedRecord,
    ident: Option<String>,
    /// The Object-class ID attribute, which a clone does not inherit.
    id: crate::object_id::ObjectId,
    /// The flags C keeps on the base Mapping class (mapping.c).
    mapping_flags: crate::mappings::MappingFlags,
    /// Whether the inverse transform is defined.
    tran_inverse: bool,
}

impl LutMap {
    /// Create a LutMap from a lookup table.
    ///
    /// `lut` holds the table entries, the output coordinate values.
    /// `start` is the input coordinate that corresponds to the center of the
    /// first entry, and `inc` is the table spacing, the increment in input
    /// coordinate between successive entries, which may be positive or
    /// negative.
    /// An infinite or NaN entry is stored as [`BAD_VALUE`].
    ///
    /// If the entries increase or decrease monotonically, the inverse
    /// transformation is available ([`has_inverse`](Mapping::has_inverse) is
    /// true); otherwise any attempt to use it is an error.
    ///
    /// ```
    /// use starlink_ast::mappings::{LutMap, Mapping};
    ///
    /// // Entries at inputs 1, 2 and 3.
    /// let map = LutMap::new(&[10.0, 20.0, 40.0], 1.0, 1.0).unwrap();
    /// assert_eq!(map.tran1(&[2.5], true).unwrap(), vec![30.0]);
    /// assert_eq!(map.tran1(&[30.0], false).unwrap(), vec![2.5]);
    /// ```
    ///
    /// # Errors
    ///
    /// - `ErrorCode::Lutin` if `lut` has fewer than two entries.
    /// - `ErrorCode::Lutii` if `inc` is zero.
    #[doc(alias = "astLutMap")]
    pub fn new(lut: &[f64], start: f64, inc: f64) -> AstResult<Self> {
        if lut.len() < 2 {
            return Err(AstError::new(
                ErrorCode::Lutin,
                format!(
                    "LutMap: invalid number of lookup table elements ({}); it should be \
                     at least 2",
                    lut.len()
                ),
            ));
        }
        if inc == 0.0 {
            return Err(AstError::new(
                ErrorCode::Lutii,
                "LutMap: the input value increment between lookup table elements is zero",
            ));
        }
        // The checks and the bad-value substitution follow astInitLutMap; a
        // non-finite entry is stored as BAD_VALUE (lutmap.c:2428-2432).
        let lut: Vec<f64> = lut
            .iter()
            .map(|&v| if v.is_finite() { v } else { BAD_VALUE })
            .collect();
        let (monotonic, inverse_table) = get_monotonic(&lut);
        Ok(Self {
            lut,
            start,
            inc,
            interp: Some(LutInterp::Linear),
            monotonic,
            inverse_table,
            inverted: false,
            simplified: SimplifiedRecord::default(),
            ident: None,
            id: Default::default(),
            mapping_flags: crate::mappings::MappingFlags::default(),
            tran_inverse: monotonic != 0,
            lut_epsilon: f64::EPSILON,
            lut_epsilon_set: false,
        })
    }

    /// Set [`interp`](LutMap::interp).
    ///
    /// A value different from the one held clears the record that the LutMap
    /// has been simplified.
    pub fn set_interp(&mut self, interp: LutInterp) {
        // `LutInterp` selects the interpolation the transformation performs,
        // so a conclusion an earlier simplification reached about it no longer
        // holds. LutMap's own MapMerge does not read the attribute, but C
        // discards the records on every setter it covers, because doing so costs
        // only a redundant simplification (lutmap.c:1793-1796, the convention at
        // mapping.h:449-472). The clear is guarded on the value differing, as C's
        // is: a set to the value already held cannot invalidate a recorded
        // simplification, and the guard is what lets `from_node` re-apply the
        // value it has just read without discarding the `IsSimp` card that came
        // with it.
        if Some(interp) != self.interp {
            self.simplified.clear();
        }
        self.interp = Some(interp);
    }

    /// The method used to find the output value for an input that lies part
    /// way between two table entries.
    ///
    /// [`LutInterp::Linear`] interpolates linearly, and extrapolates from the
    /// two end entries for an input outside the table.
    /// [`LutInterp::Nearest`] takes the nearest entry, and transforms an input
    /// outside the table to [`BAD_VALUE`].
    ///
    /// Default: [`LutInterp::Linear`].
    ///
    /// [`set_interp`](LutMap::set_interp),
    /// [`test_interp`](LutMap::test_interp) and
    /// [`clear_interp`](LutMap::clear_interp) set, test and clear it.
    #[doc(alias = "LutInterp")]
    pub fn interp(&self) -> LutInterp {
        self.interp.unwrap_or(LutInterp::Linear)
    }

    /// Whether [`interp`](LutMap::interp) is set.
    pub fn test_interp(&self) -> bool {
        // lutmap.c TestLutInterp.
        self.interp.is_some()
    }

    /// Clear [`interp`](LutMap::interp), so that it reads as the default
    /// [`LutInterp::Linear`].
    ///
    /// This also clears the record that the LutMap has been simplified.
    pub fn clear_interp(&mut self) {
        // lutmap.c ClearLutInterp, which also discards both simplified records.
        self.simplified.clear();
        self.interp = None;
    }

    /// The relative error of the values held in the lookup table.
    ///
    /// Simplification uses it to decide whether the LutMap should be
    /// considered linear.
    /// A larger value makes it more likely that the LutMap is replaced by a
    /// [`WinMap`] (a linear Mapping) when simplified.
    /// If the table values were derived from single-precision data, a value
    /// around 1e-7 may be appropriate.
    ///
    /// Default: `f64::EPSILON` (about 2.2e-16).
    ///
    /// [`set_lut_epsilon`](LutMap::set_lut_epsilon),
    /// [`test_lut_epsilon`](LutMap::test_lut_epsilon) and
    /// [`clear_lut_epsilon`](LutMap::clear_lut_epsilon) set, test and clear it.
    #[doc(alias = "LutEpsilon")]
    pub fn lut_epsilon(&self) -> f64 {
        // C's unset sentinel is AST__BAD, reported as the DBL_EPSILON default
        // (lutmap.c:1840-1841); the port stores the effective value.
        self.lut_epsilon
    }

    /// The value C keeps in the `lutepsilon` component, which is the raw value
    /// including the `AST__BAD` unset sentinel (`lutmap.c:1842`). The port stores
    /// what the getter reports plus a set flag, so the guard in
    /// [`set_lut_epsilon`](Self::set_lut_epsilon) has to rebuild it.
    fn stored_lut_epsilon(&self) -> f64 {
        if self.lut_epsilon_set {
            self.lut_epsilon
        } else {
            BAD_VALUE
        }
    }

    /// Set [`lut_epsilon`](LutMap::lut_epsilon).
    ///
    /// [`BAD_VALUE`] restores the default and leaves the attribute unset.
    /// A value different from the one held clears the record that the LutMap
    /// has been simplified.
    pub fn set_lut_epsilon(&mut self, epsilon: f64) {
        // The value scales the tolerance GetLinear works to (lutmap.c:599), so
        // it decides whether LutMap's own MapMerge sees a linear table and
        // replaces the LutMap with a WinMap — the first thing that merge does,
        // before it looks at any neighbor (lutmap.c:1142). Both simplified
        // records are discarded (lutmap.c:1842, the convention at
        // mapping.h:449-472). BAD_VALUE restores the f64::EPSILON default and
        // leaves the attribute untested, as the sentinel does in C
        // (lutmap.c:1839-1843), so the LutEps card is no longer written.
        if epsilon != self.stored_lut_epsilon() {
            self.simplified.clear();
        }
        self.lut_epsilon_set = epsilon != BAD_VALUE;
        self.lut_epsilon = if self.lut_epsilon_set {
            epsilon
        } else {
            f64::EPSILON
        };
    }

    /// Whether [`lut_epsilon`](LutMap::lut_epsilon) is set.
    pub fn test_lut_epsilon(&self) -> bool {
        // lutmap.c TestLutEpsilon.
        self.lut_epsilon_set
    }

    /// Clear [`lut_epsilon`](LutMap::lut_epsilon), so that it reads as the
    /// default `f64::EPSILON`.
    ///
    /// This also clears the record that the LutMap has been simplified.
    pub fn clear_lut_epsilon(&mut self) {
        // lutmap.c ClearLutEpsilon, which also discards both simplified records.
        self.simplified.clear();
        self.lut_epsilon_set = false;
        self.lut_epsilon = f64::EPSILON;
    }

    /// Return the number of entries in the lookup table.
    pub fn nlut(&self) -> usize {
        self.lut.len()
    }

    /// The lookup table values (C's `astGetLutMapInfo`).
    pub(crate) fn lut(&self) -> &[f64] {
        &self.lut
    }

    /// Whether the lookup table is linear, as C's `GetLinear`
    /// (`lutmap.c:578-627`) decides it.
    ///
    /// A nearest-neighbor table is never linear, whatever its values, because
    /// of the discontinuities at the first and last entries (`lutmap.c:578`).
    ///
    /// Otherwise the tolerance is scaled by the `LutEpsilon` attribute — the
    /// stated relative error of the table values, `f64::EPSILON` by default —
    /// and taken as the larger of two estimates: one from the table's full range
    /// and one from the interpolated value at the element under test, the second
    /// so that values near zero do not get an unusably tight bound. Linearity is
    /// accepted within twice that.
    fn table_is_linear(&self) -> bool {
        if self.interp() == LutInterp::Nearest {
            return false;
        }
        let n = self.lut.len();
        if n < 2 {
            return false;
        }
        let (mut lo, mut hi) = (self.lut[0], self.lut[0]);
        for &v in &self.lut {
            if v < lo {
                lo = v;
            }
            if v > hi {
                hi = v;
            }
        }
        // A constant table is linear by inspection, and the loop below would
        // divide the tolerance down to nothing (lutmap.c:595).
        if hi == lo {
            return true;
        }
        let eps = self.lut_epsilon;
        let tol1 = (hi - lo).abs() * eps;
        let last = n - 1;
        for ilut in 1..last {
            let fract = ilut as f64 / last as f64;
            let interp = self.lut[0] * (1.0 - fract) + self.lut[last] * fract;
            let tol = tol1.max(interp.abs() * eps);
            if (self.lut[ilut] - interp).abs() > 2.0 * tol {
                return false;
            }
        }
        true
    }

    /// The equivalent `WinMap` when the lookup table is linear, applied in the
    /// given direction — C `lutmap.c:1142-1174`.
    ///
    /// `None` when the table is not linear, is shorter than two entries, or has
    /// equal first and last values: C guards on `b1 != b2` (`:1154`), because a
    /// constant table would give a WinMap with a zero scale.
    ///
    /// The corner-point construction is C's, rather than computing shift and
    /// scale directly and inverting, so the arithmetic matches and the result
    /// is always a *forward* WinMap.
    pub(crate) fn linear_equivalent(&self, inverted: bool) -> Option<WinMap> {
        let n = self.lut.len();
        if n < 2 {
            return None;
        }
        if !self.table_is_linear() || self.lut[0] == self.lut[n - 1] {
            return None;
        }

        let a1 = self.start;
        let a2 = self.start + self.inc * (n - 1) as f64;
        let b1 = self.lut[0];
        let b2 = self.lut[n - 1];
        if !inverted {
            WinMap::from_corners(&[a1], &[a2], &[b1], &[b2]).ok()
        } else {
            WinMap::from_corners(&[b1], &[b2], &[a1], &[a2]).ok()
        }
    }

    /// Whether this LutMap, applied in direction `eff_inv`, is the same Mapping
    /// as `other` in its own stored direction. `equal` compares stored
    /// orientation, so the applied one has to be folded in first.
    fn applied_equal(&self, other: &LutMap, eff_inv: bool) -> bool {
        let mut probe = self.clone();
        if probe.inverted != eff_inv {
            probe.invert();
        }
        probe.equal(other)
    }

    /// Return the input value corresponding to the first table entry.
    pub fn start(&self) -> f64 {
        self.start
    }

    /// Return the input spacing between entries.
    pub fn inc(&self) -> f64 {
        self.inc
    }

    /// Return the monotonicity indicator.
    ///
    /// +1 if the table is monotonically increasing, -1 if monotonically
    /// decreasing, 0 if non-monotonic, ignoring flat sections and bad entries.
    /// The inverse transformation is available unless it is 0.
    pub fn monotonic(&self) -> i8 {
        self.monotonic
    }

    fn effective_forward(&self, forward: bool) -> bool {
        forward != self.inverted
    }

    /// Forward transform for a single input value.
    fn forward_one(&self, value_in: f64) -> f64 {
        // lutmap.c Transform, forward branch, transcribed: the scale is
        // `1/inc` applied as a product, nearest-neighbor takes
        // `floor(x + 0.5)`, and linear interpolation extrapolates from the
        // last two entries at and above the last node. The constructor
        // refuses a table of fewer than two entries, as C's does.
        if is_bad(value_in) {
            return BAD_VALUE;
        }
        let lut = &self.lut;
        let nlut = lut.len() as i64;
        let nlutm1 = nlut - 1;
        let scale = 1.0 / self.inc;
        let x = (value_in - self.start) * scale;
        if self.interp() == LutInterp::Nearest {
            let ix = (x + 0.5).floor() as i64;
            return if ix < 0 || ix >= nlut {
                BAD_VALUE
            } else {
                lut[ix as usize]
            };
        }
        let xi = x.floor();
        let ix = xi as i64;
        let n1 = nlutm1 as usize;
        if ix < 0 {
            if !is_bad(lut[0]) && !is_bad(lut[1]) {
                lut[0] + x * (lut[1] - lut[0])
            } else {
                BAD_VALUE
            }
        } else if ix >= nlutm1 {
            if !is_bad(lut[n1]) && !is_bad(lut[n1 - 1]) {
                lut[n1] + (x - nlutm1 as f64) * (lut[n1] - lut[n1 - 1])
            } else {
                BAD_VALUE
            }
        } else {
            let ix = ix as usize;
            if !is_bad(lut[ix]) && !is_bad(lut[ix + 1]) {
                let fract = x - xi;
                lut[ix] * (1.0 - fract) + lut[ix + 1] * fract
            } else {
                BAD_VALUE
            }
        }
    }

    /// Inverse transform of `input` into `out` (lutmap.c `Transform`,
    /// inverse branch), with the table and interpolation method fetched once
    /// for the array, as C does.
    ///
    /// The search runs over the table with its bad entries removed
    /// ([`InverseTable`]) when it has any, and over the full table otherwise.
    /// A bisection finds the adjacent pair of entries `i1`, `i2 = i1 + 1`
    /// bracketing `y`; `i1` is -1 when `y` lies beyond the first entry, and
    /// `nlut - 2` when it lies beyond the last.
    fn inverse_slice(&self, input: &[f64], out: &mut [f64]) {
        if self.monotonic == 0 {
            out[..input.len()].fill(BAD_VALUE);
            return;
        }
        let (lut, flags, index) = match &self.inverse_table {
            Some(t) => (&t.lut[..], Some(&t.flags[..]), Some(&t.index[..])),
            None => (&self.lut[..], None, None),
        };
        let nlutm1 = lut.len() - 1;
        let up = lut[nlutm1] > lut[0];
        let near = self.interp() == LutInterp::Nearest;
        let table_index = |i: usize| index.map_or(i, |index| index[i]);

        // The index `i1` of the lower entry bracketing `y`, or `isize::MIN`
        // for a bad `y`.
        let search = |y: f64| -> isize {
            if is_bad(y) {
                return isize::MIN;
            }
            // The bisection picks which end moves with a select rather
            // than a branch, as C's `*( cond ? &i1 : &i2 ) = i` does: the
            // comparison is unpredictable, so a branch mispredicts about
            // half the time.
            let mut i1: isize = -1;
            let mut i2: isize = nlutm1 as isize;
            while i2 > i1 + 1 {
                // i1 >= -1 and i2 >= i1 + 2, so the sum is never negative
                // and an unsigned halving (one shift) gives C's index.
                let i = ((i1 + i2) as usize / 2) as isize;
                let below = (y >= lut[i as usize]) == up;
                i1 = if below { i } else { i1 };
                i2 = if below { i2 } else { i };
            }
            i1
        };
        let one = |y: f64, i1: isize| -> f64 {
            if i1 == isize::MIN {
                return BAD_VALUE;
            }
            let i2 = (i1 + 1) as usize;

            // C reads `lut[i1]` and `flags[i1]` here even when `i1` is -1,
            // which is outside the array. Below, an `i1` of -1 has no entry,
            // so it equals no value and is not adjacent to a bad entry.
            let lo = usize::try_from(i1).ok();
            let lut_lo = lo.map(|i| lut[i]);

            // A value inside a flat run of the table has no unique inverse.
            let flat = if let Some(i1) = lo
                && lut[i1] == y
            {
                (i1 > 0 && lut[i1 - 1] == y) || lut[i2] == y
            } else {
                lut[i2] == y && i2 < nlutm1 && lut[i2 + 1] == y
            };
            if flat {
                return BAD_VALUE;
            }

            // Both entries were next to a bad entry in the full table.
            if let (Some(flags), Some(i1)) = (flags, lo)
                && flags[i1]
                && flags[i2]
            {
                return BAD_VALUE;
            }

            if near {
                // With no lower entry, C's sign test passes only when `y`
                // equals the first entry, whatever `d1` holds (a decreasing
                // table at its first value); any other value is beyond the
                // table.
                let Some(lut_lo) = lut_lo else {
                    return if lut[i2] == y {
                        self.start + self.inc * table_index(i2) as f64
                    } else {
                        BAD_VALUE
                    };
                };
                let d1 = lut_lo - y;
                let d2 = lut[i2] - y;
                if (d1 > 0.0 && d2 > 0.0) || (d1 < 0.0 && d2 < 0.0) {
                    return BAD_VALUE;
                }
                let nearest = if d1.abs() < d2.abs() { i1 as usize } else { i2 };
                return self.start + self.inc * table_index(nearest) as f64;
            }

            // Linear: interpolate within the bracketing pair, or extrapolate
            // from the first or last pair when `y` lies outside the table.
            let i1 = i1.clamp(0, nlutm1 as isize - 1) as usize;
            self.start
                + self.inc * (table_index(i1) as f64 + (y - lut[i1]) / (lut[i1 + 1] - lut[i1]))
        };
        // Each bisection is a chain of dependent loads, so its speed depends
        // on how many points' chains the processor runs at once. A loop
        // doing only the searches for a block of points keeps those chains
        // close together; the checks and interpolation follow in a second
        // loop over the same block. The result for each point is unchanged.
        // The block is small because its buffer is zeroed on every call,
        // which a one-point call must not pay much for.
        const CHUNK: usize = 32;
        let mut found = [0isize; CHUNK];
        for (ins, outs) in input.chunks(CHUNK).zip(out.chunks_mut(CHUNK)) {
            for (f, &y) in found.iter_mut().zip(ins) {
                *f = search(y);
            }
            for ((o, &y), &i1) in outs.iter_mut().zip(ins).zip(&found) {
                *o = one(y, i1);
            }
        }
    }

    /// Compose in series with another mapping.
    pub fn then(self, next: DynMapping) -> AstResult<CmpMap> {
        CmpMap::new(Box::new(self), next, Composition::Series)
    }

    /// Compose in parallel with another mapping.
    pub fn alongside(self, other: DynMapping) -> AstResult<CmpMap> {
        CmpMap::new(Box::new(self), other, Composition::Parallel)
    }
}

/// The lookup table the inverse transformation searches when the full table
/// has bad entries (lutmap.c `GetMonotonic`): its good values in order, whether
/// each was next to a bad value in the full table, and each one's index there.
#[derive(Debug, Clone)]
struct InverseTable {
    lut: Vec<f64>,
    flags: Vec<bool>,
    index: Vec<usize>,
}

/// Find the monotonicity of a lookup table, ignoring bad entries and runs of
/// equal values (lutmap.c `GetMonotonic`): +1 if increasing, -1 if
/// decreasing, 0 if neither or there are fewer than two distinct good values.
/// Also returns the [`InverseTable`] when the table has bad entries.
fn get_monotonic(lut: &[f64]) -> (i8, Option<InverseTable>) {
    let mut result: i8 = 0;
    let mut lval: Option<f64> = None;
    for &v in lut.iter().filter(|v| !is_bad(**v)) {
        match lval {
            None => lval = Some(v),
            Some(prev) if v != prev => {
                if result == 0 {
                    result = if v > prev { 1 } else { -1 };
                } else if (result == 1 && v < prev) || (result == -1 && v > prev) {
                    result = 0;
                    break;
                }
                lval = Some(v);
            }
            Some(_) => {}
        }
    }

    if !lut.iter().any(|v| is_bad(*v)) {
        return (result, None);
    }
    let bad_at = |i: Option<usize>| i.and_then(|i| lut.get(i)).is_some_and(|v| is_bad(*v));
    let mut table = InverseTable {
        lut: Vec::new(),
        flags: Vec::new(),
        index: Vec::new(),
    };
    for (i, &v) in lut.iter().enumerate().filter(|(_, v)| !is_bad(**v)) {
        table.lut.push(v);
        table
            .flags
            .push(bad_at(i.checked_sub(1)) || bad_at(Some(i + 1)));
        table.index.push(i);
    }
    (result, Some(table))
}

impl Mapping for LutMap {
    fn mapping_flags(&self) -> &crate::mappings::MappingFlags {
        &self.mapping_flags
    }

    fn mapping_flags_mut(&mut self) -> &mut crate::mappings::MappingFlags {
        &mut self.mapping_flags
    }

    fn nin(&self) -> usize {
        1
    }

    fn nout(&self) -> usize {
        1
    }

    fn is_inverted(&self) -> bool {
        self.inverted
    }

    fn invert_orientation(&mut self) {
        self.inverted = !self.inverted;
    }

    /// NaN-as-bad fast path. LutMap's lookup logic has many internal
    /// `BAD_VALUE` emit sites (binary search, BAD-skip logic, extrapolation
    /// boundary handling, etc.) and a `floor(x + 0.5) as i64` cast in the
    /// Nearest interp path that cannot accept NaN (NaN-as-i64 has unspecified
    /// behavior pre-Rust 1.45 and saturates to 0 / i64::MAX after, neither
    /// of which gives a useful table entry). So we keep the existing logic
    /// intact and post-process: any `BAD_VALUE` in the output becomes
    /// `f64::NAN` so downstream NaN-aware stages see the protocol-canonical
    /// sentinel. Cost is one O(N) sweep over the output (LutMap is 1D, so
    /// that's just N comparisons).
    fn transform_into_nan(
        &self,
        pts: Points<'_>,
        forward: bool,
        mut out: PointsMut<'_>,
    ) -> AstResult<()> {
        let npoint = pts.npoint();
        self.transform_into(pts, forward, out.reborrow())?;
        crate::mappings::bad_to_nan(self, forward, npoint, &mut out);
        Ok(())
    }

    fn transform_into(
        &self,
        pts: Points<'_>,
        forward: bool,
        mut out: PointsMut<'_>,
    ) -> AstResult<()> {
        crate::mappings::validate_transform_into(self, &pts, forward, Some(&out))?;
        let fwd = self.effective_forward(forward);
        let n = pts.npoint();
        let input = &pts.axis(0)[..n];
        let output = &mut out.axis_mut(0)[..n];
        if fwd {
            for (o, &x) in output.iter_mut().zip(input) {
                *o = self.forward_one(x);
            }
        } else {
            self.inverse_slice(input, output);
        }
        Ok(())
    }

    fn map_merge(
        &self,
        ctx: &mut super::simplify::MergeCtx,
        where_: usize,
        series: bool,
    ) -> Option<usize> {
        let eff_inv = ctx.entry(where_).1;

        // C `lutmap.c:1142-1174`: a linear LutMap is replaced by an equivalent
        // WinMap, stored forward with its invert flag cleared.
        if let Some(wm) = self.linear_equivalent(eff_inv) {
            ctx.set_pair_single(where_, (Box::new(wm), false, false));
            return Some(where_);
        }

        // C `lutmap.c:1177-1236`: in series, a LutMap adjacent to an equal
        // LutMap applied in the opposite direction collapses to a UnitMap. C
        // looks at the higher neighbor first, then the lower, and replaces the
        // *lower* of the two.
        if series {
            let neighbour =
                if where_ + 1 < ctx.len() && ctx.entry(where_ + 1).0.as_any().is::<LutMap>() {
                    Some((where_ + 1, where_))
                } else if where_ > 0 && ctx.entry(where_ - 1).0.as_any().is::<LutMap>() {
                    Some((where_ - 1, where_ - 1))
                } else {
                    None
                };

            if let Some((ineb, ilo)) = neighbour {
                let (neb_map, neb_inv, _) = ctx.entry(ineb);
                let neb = neb_map
                    .as_any()
                    .downcast_ref::<LutMap>()
                    .expect("checked immediately above");
                // C sets the neighbor's Invert to its list value and then
                // inverts it before comparing, so the two are equal-but-opposite
                // exactly when the applied directions differ and the tables
                // agree. Owned values make that a comparison, not a mutation.
                let mut probe = neb.clone();
                if probe.inverted != *neb_inv {
                    probe.invert();
                }
                probe.invert();
                if self.applied_equal(&probe, eff_inv) {
                    ctx.replace_pair_with(ilo, Box::new(UnitMap::new(1)), false);
                    // C reports `where`, not `ilo`, even when the pair it
                    // replaced started at `where - 1` (lutmap.c:1234).
                    return Some(where_);
                }
            }
        }

        // C's LutMap has no further branch: nothing else merges with a LutMap,
        // and an adjacent UnitMap is removed when the UnitMap itself is
        // nominated (unitmap.c:519).
        None
    }

    fn rate(&self, at: &[f64], ax1: usize, ax2: usize) -> AstResult<f64> {
        crate::mappings::validate_rate(self, at, ax1, ax2)?;
        numeric_rate(self, at, ax1, ax2)
    }

    fn equal(&self, other: &dyn Mapping) -> bool {
        let Some(other) = other.as_any().downcast_ref::<LutMap>() else {
            return false;
        };
        if self.inverted != other.inverted {
            return false;
        }
        ast_equal(self.start, other.start)
            && ast_equal(self.inc, other.inc)
            && self.interp == other.interp
            && self.lut.len() == other.lut.len()
            && self
                .lut
                .iter()
                .zip(&other.lut)
                .all(|(a, b)| ast_equal(*a, *b))
    }

    fn has_forward(&self) -> bool {
        // Intrinsically the forward transform is always defined and the
        // inverse only when the table is monotonic (lutmap.c:2391). Report
        // the *effective* direction so a parent CmpMap computes its own
        // definedness exactly as C's invert-aware `astGetTranForward`
        // (mapping.c:1823) does when the leaf is applied inverted.
        if self.inverted {
            self.tran_inverse
        } else {
            true
        }
    }

    fn has_inverse(&self) -> bool {
        if self.inverted {
            true
        } else {
            self.tran_inverse
        }
    }

    fn dump_tran_flags(&self) -> (bool, bool) {
        // C passes the monotonicity-derived inverse availability to
        // astInitMapping (lutmap.c) and dumps the raw base-struct fields,
        // which are unaffected by the Invert flag.
        (true, self.tran_inverse)
    }

    fn ident(&self) -> &str {
        self.ident.as_deref().unwrap_or("")
    }

    fn set_ident(&mut self, ident: &str) {
        self.ident = Some(ident.to_string());
    }

    fn clear_ident(&mut self) {
        self.ident = None;
    }

    fn test_ident(&self) -> bool {
        self.ident.is_some()
    }

    fn id(&self) -> &str {
        self.id.get()
    }
    fn set_id(&mut self, id: &str) {
        self.id.set(id);
    }
    fn clear_id(&mut self) {
        self.id.clear();
    }
    fn test_id(&self) -> bool {
        self.id.test()
    }

    fn has_been_simplified(&self) -> bool {
        self.simplified.get(self.inverted)
    }

    fn set_has_been_simplified(&mut self, flag: bool) {
        self.simplified.set(self.inverted, flag);
    }

    fn clone_box(&self) -> DynMapping {
        Box::new(self.clone())
    }
}

impl Serializable for LutMap {
    fn class_name(&self) -> &'static str {
        "LutMap"
    }

    fn to_node(&self) -> AstResult<Node> {
        let mut node = Node::new(self.class_name());
        node.class_comment = Some("Map 1-d coordinates using a lookup table".to_string());
        write_mapping_base(&mut node, self);

        node.push_int(
            "Nlut",
            self.lut.len() as i64,
            Some("Number of lookup table elements".to_string()),
        );

        // Match the C library's Dump (`lutmap.c`): both Start (helpful=1,
        // default 0.0) and Incr (helpful=1, default 1.0) are always emitted —
        // commented at default, uncommented when explicit.
        if self.start != 0.0 {
            node.push_double(
                "Start",
                self.start,
                Some("Input value at first element".to_string()),
            );
        } else {
            node.push_unset(
                "Start",
                NodeValue::Int(0),
                Some("Input value at first element".to_string()),
            );
        }
        if self.inc != 1.0 {
            node.push_double(
                "Incr",
                self.inc,
                Some("Input value increment between elements".to_string()),
            );
        } else {
            node.push_unset(
                "Incr",
                NodeValue::Int(1),
                Some("Input value increment between elements".to_string()),
            );
        }
        // lutmap.c Dump: LutInt is "helpful", so an unset value is written
        // commented, as its linear default.
        let interp_val = match self.interp() {
            LutInterp::Linear => 0,
            LutInterp::Nearest => 1,
        };
        let comment = Some("Interpolation method".to_string());
        if self.test_interp() {
            node.push_int("LutInt", interp_val, comment);
        } else {
            node.push_unset("LutInt", NodeValue::Int(interp_val), comment);
        }
        // C writes the precision only when it has been set (lutmap.c:2009-2013).
        if self.lut_epsilon_set {
            node.push_double(
                "LutEps",
                self.lut_epsilon,
                Some("Table relative error".to_string()),
            );
        }

        for (i, &v) in self.lut.iter().enumerate() {
            if !is_bad(v) {
                let comment = if i == 0 {
                    Some("Lookup table elements...".to_string())
                } else {
                    None
                };
                node.push_double(&format!("L{}", i + 1), v, comment);
            }
        }

        Ok(node)
    }

    fn from_node(node: &Node) -> AstResult<Self> {
        // Each class's items come from its own part of the description, as
        // C's loaders read them through astReadClassData (channel.c).
        let whole = node;
        let node = &whole.section("LutMap");
        let base = read_mapping_base(whole);
        let nlut = node.get_int("Nlut", 0) as usize;
        let start = node.get_double("Start", 0.0);
        let inc = node.get_double("Incr", 1.0);
        let interp_val = node.get_int("LutInt", 0);
        let interp = match interp_val {
            1 => LutInterp::Nearest,
            _ => LutInterp::Linear,
        };

        let mut lut = vec![BAD_VALUE; nlut];
        for (i, entry) in lut.iter_mut().enumerate() {
            *entry = node.get_double(&format!("L{}", i + 1), BAD_VALUE);
        }

        let lut_epsilon = node.get_double("LutEps", f64::EPSILON);
        let lut_epsilon_set = node.get("LutEps").is_some();
        let (monotonic, inverse_table) = get_monotonic(&lut);
        let mut m = LutMap {
            lut,
            start,
            inc,
            interp: Some(interp),
            monotonic,
            inverse_table,
            lut_epsilon,
            lut_epsilon_set,
            inverted: false,
            simplified: SimplifiedRecord::for_orientation(base.inverted, base.has_been_simplified),
            ident: None,
            id: Default::default(),
            mapping_flags: crate::mappings::MappingFlags::default(),
            tran_inverse: base.has_inverse,
        };
        if base.inverted {
            m.invert();
        }
        // C assigns the structure component and only then re-applies it through
        // the setter, so the set changes nothing and the setter's guarded
        // `astClearIsSimple` does not fire (lutmap.c:2572-2573): the struct literal above
        // already holds the value read from the card.
        if node.get("LutInt").is_some() {
            m.set_interp(interp);
        }
        // LutEpsilon the same way (lutmap.c:2576-2577).
        if node.get("LutEps").is_some() {
            m.set_lut_epsilon(lut_epsilon);
        }
        Ok(m)
    }
}
