//! Error types for the AST library.
//!
//! Every operation that can fail returns an [`AstResult`].
//! Its error, an [`AstError`], carries an [`ErrorCode`] naming the condition,
//! a message describing this occurrence of it, and any context added with
//! [`AstError::with_context`] as it was passed up the call stack.
//! There is no global error status: a failed call does not stop later calls
//! from running.
//!
//! ```
//! use ast_core::error::ErrorCode;
//! use ast_core::mappings::ZoomMap;
//!
//! let err = ZoomMap::new(1, 0.0).unwrap_err();
//! assert_eq!(err.code(), ErrorCode::Zoomi);
//! println!("{err}");
//! ```
//!
//! # See also
//!
//! - `astOK`, `astStatus`, `astClearStatus`, `astSetStatus` and `astWatch`:
//!   the C interface's error status, which an `Err` result replaces.
//! - `astSetPutErr`: in the C interface, where error messages are delivered;
//!   here the caller receives each [`AstError`] and decides.

// [`ErrorCode`] is generated by `build.rs` from `vendor/ast_err.msg`, one
// variant per `AST__XXXX` code, so that Rust and C codes stay in lockstep.
// It follows that some variants have no construction site in `ast-core`:
// either the subsystem that raises them is unported, or the condition cannot
// arise in the owned-value design. An unused variant is therefore not
// evidence of an unimplemented feature.
//
// `Immut` (`AST__IMMUT`, "Attempt to change an immutable attribute") is the
// second kind, and worth spelling out because it looks like an omission.
// C forbids changing the attributes of a Mapping that has been cloned or
// included in another Object, because `astClone` shares one object between
// two pointers, and mutating through one surprises the holder of the other.
// That situation cannot be constructed here:
//
// - `Clone` on `Box<dyn Mapping>` is `clone_box()`, a deep copy that
//   recurses through compound classes, so two owners never share one object.
// - `DynMapping` is a single-owner `Box` and compound constructors such as
//   `CmpMap::new` consume their arguments, so no caller-side handle survives.
// - Component accessors (`CmpMap::first`, `first_mut`, …) are `pub(crate)`,
//   so a component is not reachable from outside the crate at all.
//
// `ast-capi` is where the rule becomes load-bearing, because the design
// restores sharing at the handle boundary (`astClone` = `Arc::clone` over one
// `RefCell<AnyObject>`). See `PLAN.md` §7 for what the shim has to decide.

use std::fmt;
use std::panic::Location;

include!(concat!(env!("OUT_DIR"), "/error_codes.rs"));

/// An error produced by the AST library: an [`ErrorCode`], a message and
/// optional context.
///
/// Its [`Display`](fmt::Display) form is the code's description, a colon and
/// the message, followed by one indented `context:` line per piece of context
/// in the order it was added.
#[derive(Debug, Clone)]
pub struct AstError {
    code: ErrorCode,
    message: String,
    context: Vec<String>,
    source_location: Option<&'static Location<'static>>,
}

impl AstError {
    /// Create an error with the given code and message, and no context.
    pub fn new(code: ErrorCode, message: impl Into<String>) -> Self {
        let err = Self {
            code,
            message: message.into(),
            context: Vec::new(),
            source_location: None,
        };
        err.trace();
        err
    }

    /// Create an error with the given code and message, recording the
    /// caller's source location ([`source_location`](Self::source_location)).
    #[track_caller]
    pub fn new_tracked(code: ErrorCode, message: impl Into<String>) -> Self {
        let err = Self {
            code,
            message: message.into(),
            context: Vec::new(),
            source_location: Some(Location::caller()),
        };
        err.trace();
        err
    }

    /// Emit this error as a `tracing::error!` event.
    ///
    /// Called once per constructed error, from `new` and `new_tracked`.
    /// [`AstError::with_context`] does not re-emit: it decorates an error that
    /// has already been reported, and emitting again would log one failure
    /// once per frame it propagates through.
    ///
    /// Compiles to nothing without the `tracing` feature.
    #[inline]
    fn trace(&self) {
        #[cfg(feature = "tracing")]
        tracing::error!(
            code = ?self.code,
            code.raw = self.code.as_raw(),
            code.description = %self.code,
            location = self
                .source_location
                .map(|l| l.to_string())
                .unwrap_or_default(),
            "{}",
            self.message,
        );
    }

    /// The error code, naming the condition.
    pub fn code(&self) -> ErrorCode {
        self.code
    }

    /// The message describing this occurrence of the error.
    pub fn message(&self) -> &str {
        &self.message
    }

    /// The context added by [`with_context`](Self::with_context), oldest
    /// first.
    pub fn context(&self) -> &[String] {
        &self.context
    }

    /// Where in the source this error was created, when it was created with
    /// [`new_tracked`](Self::new_tracked).
    pub fn source_location(&self) -> Option<&'static Location<'static>> {
        self.source_location
    }

    /// Add a line of context to this error, such as which step of a larger
    /// operation failed, and return it.
    pub fn with_context(mut self, ctx: impl Into<String>) -> Self {
        self.context.push(ctx.into());
        self
    }
}

impl fmt::Display for AstError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}: {}", self.code, self.message)?;
        for ctx in &self.context {
            write!(f, "\n  context: {ctx}")?;
        }
        Ok(())
    }
}

impl std::error::Error for AstError {}

/// The result of an AST operation that can fail.
pub type AstResult<T> = Result<T, AstError>;
