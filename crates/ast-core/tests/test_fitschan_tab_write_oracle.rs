//! Writing FrameSets whose axes need the `-TAB` algorithm of FITS-WCS paper
//! III, against C (fitschan.c `IsMapTab1D`, `IsMapTab2D`, `AdaptLut`): the
//! header cards, the look-up tables left in the FitsChan, and the FrameSet
//! read back from the header and tables.
//!
//! Each case is a FrameSet built by
//! `tools/oracle_fixtures/fitschan_tab_write_probe.c`, which records its
//! native dump, the FitsChan's attributes and cards, and what C writes and
//! reads back; the FrameSet is read from its dump here, written through the
//! public API, and the two transcripts compared byte for byte. The probe's
//! header describes the transcript. `fitschan_tab_write_oracle/cases.rs` is
//! generated by the probe.

use crate::common::native_dump;
// Generated; formatted by its generator rather than rustfmt.
#[rustfmt::skip]
#[path = "fitschan_tab_write_oracle/cases.rs"]
mod cases;

use ast_core::{AnyObject, Channel, Encoding, FitsChan, from_native_string};

/// Cases that differ from C, each with the reason.
/// `excluded_cases_still_differ` fails when one starts to match.
const TAB_WRITE_EXCLUDED: &[(&str, &str)] = &[];

/// Each card of `fc` from the first, prefixed by "|".
fn cards(fc: &mut FitsChan) -> String {
    fc.clear_card().unwrap();
    let mut s = String::new();
    while let Some(card) = fc.find_fits("%f", true).unwrap() {
        s.push_str(&format!("|{card}\n"));
    }
    s
}

/// The native dump of `obj`, each line prefixed by "|".
fn dump(obj: &AnyObject) -> String {
    native_dump(obj)
        .unwrap()
        .lines()
        .map(|l| format!("|{l}\n"))
        .collect()
}

/// The FitsChan the probe writes to: its attributes, then its cards.
fn fitschan(attrs: &str, hdr: &str) -> FitsChan {
    let mut fc = FitsChan::new();
    for setting in attrs.split(',') {
        let (name, value) = setting.split_once('=').unwrap();
        match name {
            "Encoding" => fc.set_encoding(Encoding::from_name(value).unwrap()),
            "CDMatrix" => fc.set_cd_matrix(value != "0"),
            "TabOK" => fc.set_tab_ok(value.parse().unwrap()),
            "ForceTab" => fc.set_force_tab(value.parse().unwrap()),
            _ => panic!("attribute {name} is not handled"),
        }
    }
    for card in hdr.split(';').filter(|c| !c.is_empty()) {
        fc.put_fits(card, false).unwrap();
    }
    fc
}

/// The transcript of writing the FrameSet dumped as `fsdump`.
fn transcript(attrs: &str, hdr: &str, fsdump: &str) -> String {
    let fs = from_native_string(fsdump).unwrap();
    let mut fc = fitschan(attrs, hdr);
    let mut out = match fc.write(&fs) {
        Ok(n) => format!("= written {n}\n"),
        Err(e) => format!("! {}\n", e.code() as u32),
    };
    out.push_str(&cards(&mut fc));

    match fc.get_tables() {
        None => out.push_str("= tables null\n"),
        Some(km) => {
            out.push_str("= tables");
            for i in 0..km.map_size() {
                out.push_str(&format!(" {}", km.map_key(i).unwrap()));
            }
            out.push('\n');
            for i in 0..km.map_size() {
                let key = km.map_key(i).unwrap();
                if let Some(Some(obj)) = km.get_0a(&key).unwrap() {
                    out.push_str(&dump(&obj));
                    out.push_str("~\n");
                    if let AnyObject::FitsTable(mut table) = obj {
                        let mut header = table.get_table_header().unwrap();
                        out.push_str(&cards(&mut header));
                    }
                }
            }
        }
    }

    fc.set_tab_ok(1);
    fc.clear_card().unwrap();
    match fc.read() {
        Ok(Some(obj)) => {
            let class = match &obj {
                AnyObject::FrameSet(_) => "FrameSet",
                _ => "another class",
            };
            out.push_str(&format!("= read {class}\n"));
            out.push_str(&dump(&obj));
        }
        Ok(None) => out.push_str("= read null\n"),
        Err(e) => out.push_str(&format!("! {}\n", e.code() as u32)),
    }
    out
}

#[test]
fn fitschan_tab_writes_match_c() {
    let mut failed = Vec::new();
    for &(name, attrs, hdr, fsdump, want) in cases::CASES {
        if TAB_WRITE_EXCLUDED.iter().any(|(n, _)| *n == name) {
            continue;
        }
        let out = transcript(attrs, hdr, fsdump);
        if out != want {
            let line = out
                .lines()
                .zip(want.lines())
                .position(|(a, b)| a != b)
                .unwrap_or_else(|| out.lines().count().min(want.lines().count()));
            failed.push(format!(
                "{name}: first difference at line {}\n--- rust\n{}\n--- C\n{}",
                line + 1,
                out.lines()
                    .skip(line.saturating_sub(3))
                    .take(8)
                    .collect::<Vec<_>>()
                    .join("\n"),
                want.lines()
                    .skip(line.saturating_sub(3))
                    .take(8)
                    .collect::<Vec<_>>()
                    .join("\n"),
            ));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n\n"));
}

#[test]
fn excluded_cases_still_differ() {
    for (name, reason) in TAB_WRITE_EXCLUDED {
        let &(_, attrs, hdr, fsdump, want) = cases::CASES
            .iter()
            .find(|(n, ..)| n == name)
            .expect("an excluded case is in the corpus");
        assert_ne!(
            transcript(attrs, hdr, fsdump),
            want,
            "{name} now matches C ({reason}); remove its exclusion"
        );
    }
}
