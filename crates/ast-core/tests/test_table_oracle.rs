use ast_core::error::AstError;
use ast_core::{AnyObject, AstType, KeyMap, Table, from_native_string, to_native_string};

/// C's `%.17g`.
fn c_g17(v: f64) -> String {
    if v == 0.0 {
        return if v.is_sign_negative() { "-0" } else { "0" }.to_string();
    }
    let e = format!("{v:.16e}");
    let (mant, exp) = e.split_once('e').unwrap();
    let exp: i32 = exp.parse().unwrap();
    let strip = |s: &str| {
        if s.contains('.') {
            s.trim_end_matches('0').trim_end_matches('.').to_string()
        } else {
            s.to_string()
        }
    };
    if !(-4..17).contains(&exp) {
        let sign = if exp < 0 { '-' } else { '+' };
        format!("{}e{sign}{:02}", strip(mant), exp.unsigned_abs())
    } else {
        let decimals = (16 - exp).max(0) as usize;
        strip(&format!("{v:.decimals$}"))
    }
}

/// The class name the probe prints for an Object.
fn class(obj: &AnyObject) -> &'static str {
    match obj {
        AnyObject::KeyMap(_) => "KeyMap",
        AnyObject::Table(_) => "Table",
        _ => "another class",
    }
}

/// The column data type the probe names with a letter or a number.
fn type_code(t: &str) -> AstType {
    match t {
        "I" => AstType::Int,
        "D" => AstType::Double,
        "F" => AstType::Float,
        "C" => AstType::String,
        "A" => AstType::Object,
        "S" => AstType::SInt,
        "B" => AstType::Byte,
        "K" => AstType::KInt,
        "U" => AstType::Undef,
        n => AstType::from_code(n.parse().unwrap_or(0)).unwrap_or(AstType::BadType),
    }
}

/// A ','-separated list, empty for an empty string.
fn list(s: &str) -> Vec<&str> {
    if s.is_empty() {
        Vec::new()
    } else {
        s.split(',').collect()
    }
}

/// The text the probe prints for an operation that returns nothing.
fn unit(r: Result<(), AstError>) -> (String, Option<AstError>) {
    ("=\n".to_string(), r.err())
}

/// The text the probe prints for a get, which on failure is "none".
fn got<T>(
    r: Result<Option<T>, AstError>,
    show: impl FnOnce(T) -> String,
) -> (String, Option<AstError>) {
    match r {
        Ok(Some(v)) => (format!("= {}\n", show(v)), None),
        Ok(None) => ("= none\n".to_string(), None),
        Err(e) => ("= none\n".to_string(), Some(e)),
    }
}

/// The text the probe prints for a string result, which on failure is
/// "(null)".
fn text(r: Result<String, AstError>) -> (String, Option<AstError>) {
    match r {
        Ok(s) => (format!("= '{s}'\n"), None),
        Err(e) => ("= '(null)'\n".to_string(), Some(e)),
    }
}

/// The value of an attribute as `astGetC` formats it.
fn attribute(t: &Table, attr: &str) -> Result<String, AstError> {
    let column = |prefix: &str| {
        attr.strip_prefix(prefix)
            .and_then(|r| r.strip_prefix('('))
            .and_then(|r| r.strip_suffix(')'))
    };
    if attr == "NRow" {
        Ok(t.nrow().to_string())
    } else if attr == "NColumn" {
        Ok(t.ncolumn().to_string())
    } else if attr == "NParameter" {
        Ok(t.nparameter().to_string())
    } else if attr == "KeyCase" {
        Ok(i32::from(t.as_keymap().key_case()).to_string())
    } else if let Some(c) = column("ColumnType") {
        t.column_type(c).map(|ty| ty.code().to_string())
    } else if let Some(c) = column("ColumnUnit") {
        t.column_unit(c)
    } else if let Some(c) = column("ColumnNdim") {
        t.column_ndim(c).map(|n| n.to_string())
    } else if let Some(c) = column("ColumnLength") {
        t.column_length(c).map(|n| n.to_string())
    } else if let Some(c) = column("ColumnLenC") {
        t.column_len_c(c).map(|n| n.to_string())
    } else {
        panic!("attribute {attr} is not handled")
    }
}

/// The dump the probe writes, each line prefixed by "|".
fn dump(t: &Table) -> String {
    to_native_string(&AnyObject::Table(Box::new(t.clone())))
        .unwrap()
        .lines()
        .map(|l| format!("|{l}\n"))
        .collect()
}

/// Run one operation, returning its result text and any error.
fn run(t: &mut Table, op: &str) -> (String, Option<AstError>) {
    let f: Vec<&str> = op.splitn(6, '|').collect();
    let key = f.get(1).copied().unwrap_or("");
    let com = f.get(3).copied();
    match f[0] {
        "AC" => {
            let dims: Vec<usize> = list(f[3]).iter().map(|d| d.parse().unwrap()).collect();
            unit(t.add_column(key, type_code(f[2]), &dims, f[4]))
        }
        "AP" => unit(t.add_parameter(key)),
        "RC" => unit(t.remove_column(key)),
        "RP" => unit(t.remove_parameter(key)),
        "RR" => unit(t.remove_row(key.parse().unwrap())),
        "PR" => unit(t.purge_rows()),
        "MR" => unit(t.map_remove(key)),
        "MN" => unit(t.map_rename(key, f[2])),
        "P0I" => unit(t.put_0i(key, f[2].parse().unwrap(), com)),
        "P0D" => unit(t.put_0d(key, f[2].parse().unwrap(), com)),
        "P0F" => unit(t.put_0f(key, f[2].parse().unwrap(), com)),
        "P0C" => unit(t.put_0c(key, f[2], com)),
        "P0S" => unit(t.put_0s(key, f[2].parse().unwrap(), com)),
        "P0B" => unit(t.put_0b(key, f[2].parse().unwrap(), com)),
        "P0K" => unit(t.put_0k(key, f[2].parse().unwrap(), com)),
        "P0A" => unit(t.put_0a(key, AnyObject::KeyMap(Box::new(KeyMap::new())), com)),
        "P1I" => {
            let v: Vec<i32> = list(f[2]).iter().map(|v| v.parse().unwrap()).collect();
            unit(t.put_1i(key, &v, None))
        }
        "P1D" => {
            let v: Vec<f64> = list(f[2]).iter().map(|v| v.parse().unwrap()).collect();
            unit(t.put_1d(key, &v, None))
        }
        "P1C" => unit(t.put_1c(key, &list(f[2]), None)),
        "P1B" => {
            let v: Vec<u8> = list(f[2]).iter().map(|v| v.parse().unwrap()).collect();
            unit(t.put_1b(key, &v, None))
        }
        "P1K" => {
            let v: Vec<i64> = list(f[2]).iter().map(|v| v.parse().unwrap()).collect();
            unit(t.put_1k(key, &v, None))
        }
        "PEI" => unit(t.put_elem_i(key, f[2].parse().unwrap(), f[3].parse().unwrap())),
        "PED" => unit(t.put_elem_d(key, f[2].parse().unwrap(), f[3].parse().unwrap())),
        "PEC" => unit(t.put_elem_c(key, f[2].parse().unwrap(), f[3])),
        "PU" => unit(t.put_u(key, None)),
        "G0I" => got(t.get_0i(key), |v| v.to_string()),
        "G0D" => got(t.get_0d(key), c_g17),
        "G0C" => got(t.get_0c(key), |v| format!("'{v}'")),
        "G0A" => got(t.get_0a(key), |v| match v {
            Some(obj) => class(&obj).to_string(),
            None => "null".to_string(),
        }),
        "G1I" => got(t.get_1i(key), |v| {
            v.iter()
                .map(|x| x.to_string())
                .collect::<Vec<_>>()
                .join(" ")
        }),
        "G1D" => got(t.get_1d(key), |v| {
            v.iter().map(|x| c_g17(*x)).collect::<Vec<_>>().join(" ")
        }),
        "G1C" => got(t.get_1c(key), |v| {
            v.iter()
                .map(|x| format!("'{x}'"))
                .collect::<Vec<_>>()
                .join(" ")
        }),
        "GEI" => got(t.get_elem_i(key, f[2].parse().unwrap()), |v| v.to_string()),
        "GEC" => got(t.get_elem_c(key, f[2].parse().unwrap()), |v| {
            format!("'{v}'")
        }),
        "GA" => text(attribute(t, key)),
        "SA" => match key {
            "KeyError=1" => {
                t.set_key_error(true);
                unit(Ok(()))
            }
            "KeyCase=1" => unit(t.set_key_case(true)),
            _ => panic!("setting {key} is not handled"),
        },
        "CA" => match key {
            "KeyCase" => unit(t.clear_key_case()),
            _ => panic!("clearing {key} is not handled"),
        },
        "TA" => match key {
            "KeyCase" => (
                format!("= {}\n", i32::from(t.as_keymap().test_key_case())),
                None,
            ),
            _ => panic!("testing {key} is not handled"),
        },
        "CN" => text(t.column_name(key.parse().unwrap())),
        "PN" => text(t.parameter_name(key.parse().unwrap())),
        "CS" => {
            let mx: usize = f[2].parse().unwrap();
            let shape = t.column_shape(key).unwrap();
            let mut s = format!("= {}", shape.len());
            for i in 0..mx {
                s.push_str(&format!(" {}", shape.get(i).copied().unwrap_or(1)));
            }
            (s + "\n", None)
        }
        "HC" => (
            format!("= {}\n", i32::from(t.has_column(key).unwrap())),
            None,
        ),
        "HP" => (
            format!("= {}\n", i32::from(t.has_parameter(key).unwrap())),
            None,
        ),
        "MS" => (format!("= {}\n", t.as_keymap().map_size()), None),
        "MK" => text(t.as_keymap().map_key(key.parse().unwrap())),
        "CP" => {
            *t = t.clone();
            unit(Ok(()))
        }
        "RW" => {
            let text = to_native_string(&AnyObject::Table(Box::new(t.clone()))).unwrap();
            let obj = from_native_string(&text).unwrap();
            let name = class(&obj);
            if let AnyObject::Table(read) = obj {
                *t = *read;
            }
            (format!("= {name}\n"), None)
        }
        "D" => (format!("=\n{}", dump(t)), None),
        other => panic!("operation {other} is not handled"),
    }
}

#[test]
fn tables_match_c() {
    let mut failed = Vec::new();
    for &(name, ops, want) in cases::CASES {
        let mut t = Table::new();
        let mut out = String::new();
        for op in ops {
            out.push_str(&format!("> {op}\n"));
            let (text, err) = run(&mut t, op);
            out.push_str(&text);
            if let Some(e) = err {
                out.push_str(&format!("! {}\n", e.code() as u32));
            }
        }
        if out != want {
            let line = out
                .lines()
                .zip(want.lines())
                .position(|(a, b)| a != b)
                .unwrap_or_else(|| out.lines().count().min(want.lines().count()));
            failed.push(format!(
                "{name}: first difference at line {}\n--- rust\n{}\n--- C\n{}",
                line + 1,
                out.lines()
                    .skip(line.saturating_sub(3))
                    .take(8)
                    .collect::<Vec<_>>()
                    .join("\n"),
                want.lines()
                    .skip(line.saturating_sub(3))
                    .take(8)
                    .collect::<Vec<_>>()
                    .join("\n"),
            ));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n\n"));
}
