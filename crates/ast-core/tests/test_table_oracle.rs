//! Tables against C (table.c): adding, removing and querying columns and
//! parameters, putting and getting cell values, removing and purging rows,
//! the read-only attributes, copying, and the native dump and its reading.
//!
//! Each case is a script of operations run through the C library by
//! `tools/oracle_fixtures/table_probe.c`, which records the result of each
//! and dumps at the marked points; the same script is run here through the
//! public API and the two transcripts compared byte for byte. The probe's
//! header describes the operations. `table_oracle/cases.rs` is generated by
//! the probe.

// Generated; formatted by its generator rather than rustfmt.
