//! `mappings::rebin_seq` against sequences of calls to C's
//! `astRebinSeq<X>` for every pixel type it exists for: each sequence starts
//! with `rebin_init` and ends with `rebin_end`, some with a last call that
//! has no input. The cases cover nearest, linear and kernel spreading in
//! 1-D, 2-D and 3-D, variances from the input variances and from the spread
//! of input values, inverse-variance and constant weights, flux
//! conservation, unnormalised sums with and without weights, and a weight
//! limit. Each case compares every call's status, the count of input pixels
//! used, and every output value, variance and weight through a hash of
//! their bit patterns, with a sample of values to show where a mismatch is.
//!
//! `rebinseq_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/rebinseq_probe.c`, which documents the input data.

// Generated; formatted by its generator rather than rustfmt.
#[rustfmt::skip]
#[allow(clippy::excessive_precision)]
#[path = "rebinseq_oracle/cases.rs"]
mod cases;

use ast_core::mappings::{
    DynMapping, MathMap, PermMap, RebinInput, RebinOutput, RebinSeqFlags, RebinSeqOptions,
    ShiftMap, Spread, UnitMap, WinMap, ZoomMap, rebin_seq,
};
use ast_core::pixel::RebinValue;

fn mapping(name: &str) -> DynMapping {
    match name {
        "unit2" => Box::new(UnitMap::new(2)),
        "shift_half" => Box::new(ShiftMap::new(vec![0.5, -0.25])),
        "shift_whole" => Box::new(ShiftMap::new(vec![1.0, -2.0])),
        "far" => Box::new(ShiftMap::new(vec![1000.0, 1000.0])),
        "zoom2" => Box::new(ZoomMap::new(2, 1.7).unwrap()),
        "shrink2" => Box::new(ZoomMap::new(2, 0.45).unwrap()),
        "perm" => Box::new(PermMap::new(&[2, 1], &[2, 1], &[]).unwrap()),
        "nonlin2" => Box::new(
            MathMap::new(
                2,
                2,
                &["p=a+0.02*a*b-0.3", "q=b-0.015*a*a+0.2"],
                &["a=p", "b=q"],
            )
            .unwrap(),
        ),
        "cubic1" => Box::new(MathMap::new(1, 1, &["p=0.001*a*a*a+0.5*a"], &["a=p"]).unwrap()),
        "win3" => Box::new(
            WinMap::from_corners(
                &[0.0, 0.0, 0.0],
                &[1.0, 1.0, 1.0],
                &[0.3, -0.2, 0.1],
                &[1.1, 0.7, 1.4],
            )
            .unwrap(),
        ),
        "nonlin3" => Box::new(
            MathMap::new(
                3,
                3,
                &["p=a+0.05*b*c", "q=b-0.03*a*a", "r=0.9*c+0.1*a"],
                &["a=p", "b=q", "c=r"],
            )
            .unwrap(),
        ),
        "noforward" => Box::new(MathMap::new(2, 2, &["p", "q"], &["a=p", "b=q"]).unwrap()),
        _ => panic!("no Mapping {name}"),
    }
}

fn spread(name: &str) -> Spread {
    match name {
        "nearest" => Spread::Nearest,
        "linear" => Spread::Linear,
        "sinc" => Spread::Sinc,
        "sincsinc" => Spread::SincSinc,
        "sinccos" => Spread::SincCos,
        "sincgauss" => Spread::SincGauss,
        "gauss" => Spread::Gauss,
        "somb" => Spread::Somb,
        "sombcos" => Spread::SombCos,
        _ => panic!("no scheme {name}"),
    }
}

fn npix(l: &[i64], u: &[i64]) -> usize {
    l.iter().zip(u).map(|(l, u)| (u - l + 1) as usize).product()
}

fn fnv(hash: u64, v: f64) -> u64 {
    (hash ^ v.to_bits()).wrapping_mul(1099511628211)
}

/// Run one case for pixel type `T`, returning (statuses, count, hash,
/// samples).
fn run<T: RebinValue>(c: &cases::Case) -> (Vec<i32>, i64, u64, Vec<f64>) {
    let &(
        _,
        _,
        maps,
        end_only,
        _,
        lbnd_in,
        ubnd_in,
        lbnd_out,
        ubnd_out,
        lbnd,
        ubnd,
        scheme,
        f,
        in_var_given,
        out_var_given,
        weights_given,
        params,
        tol,
        maxpix,
        wlim,
        ..,
    ) = c;
    let nin = npix(lbnd_in, ubnd_in);
    let nout = npix(lbnd_out, ubnd_out);
    let mut out = vec![T::from_f64(77.0); nout];
    let mut out_var = vec![T::from_f64(77.0); nout];
    let mut weights = vec![5.0; 2 * nout];
    let nw = if f[2] { 2 * nout } else { nout };
    let mut nused: i64 = 9;
    let ncall = maps.len() + usize::from(end_only);
    let mut statuses = Vec::new();
    for call in 0..ncall {
        let (mut data, mut var) = (Vec::with_capacity(nin), Vec::with_capacity(nin));
        for k in 0..nin as i64 {
            let j = k + 13 * call as i64;
            let (mut d, mut v) = if T::FLOATING {
                (
                    T::from_f64(((7 * j) % 97) as f64 * 0.37 - 10.0),
                    T::from_f64(((3 * j) % 11) as f64 * 0.5 + 0.25),
                )
            } else {
                let ds = if T::SIGNED { 11 } else { 0 };
                (
                    T::from_f64(((7 * j) % 23 - ds) as f64),
                    T::from_f64(((3 * j) % 11 + 1) as f64),
                )
            };
            if f[0] && j % 17 == 3 {
                d = T::from_f64(120.0);
            }
            if f[0] && j % 19 == 5 {
                v = T::from_f64(120.0);
            }
            data.push(d);
            var.push(v);
        }
        let input = RebinInput {
            lbnd: lbnd_in,
            ubnd: ubnd_in,
            region_lbnd: lbnd,
            region_ubnd: ubnd,
            data: &data,
            var: in_var_given.then_some(&var[..]),
        };
        let m = mapping(maps[if call < maps.len() { call } else { 0 }]);
        let result = rebin_seq(
            m.as_ref(),
            (call < maps.len()).then_some(&input),
            &mut RebinOutput {
                lbnd: lbnd_out,
                ubnd: ubnd_out,
                data: &mut out,
                var: out_var_given.then_some(&mut out_var[..]),
            },
            weights_given.then_some(&mut weights[..nw]),
            weights_given.then_some(&mut nused),
            &RebinSeqOptions {
                spread: spread(scheme),
                params: &params,
                flags: RebinSeqFlags {
                    use_bad: f[0],
                    use_var: f[1],
                    gen_var: f[2],
                    var_wgt: f[3],
                    dis_var: f[4],
                    no_norm: f[5],
                    par_wgt: f[6],
                    conserve_flux: f[7],
                    rebin_init: call == 0,
                    rebin_end: call == ncall - 1,
                },
                tol,
                maxpix,
                wlim,
            },
            T::from_f64(120.0),
        );
        statuses.push(match result {
            Ok(()) => 0,
            Err(e) => e.code() as i32,
        });
    }
    let mut hash: u64 = 14695981039346656037;
    for k in 0..nout {
        hash = fnv(hash, out[k].to_f64());
        if out_var_given {
            hash = fnv(hash, out_var[k].to_f64());
        }
    }
    if weights_given {
        for &w in &weights[..nw] {
            hash = fnv(hash, w);
        }
    }
    let samples = out.iter().step_by(61).map(|v| v.to_f64()).collect();
    (statuses, nused, hash, samples)
}

#[test]
fn sequences_match_c() {
    let mut failures = Vec::new();
    for c in cases::CASES {
        let (name, ty) = (c.0, c.1);
        let (want_status, want_nused, want_hash, want_samples) = (c.20, c.21, c.22, c.23);
        let (status, nused, hash, samples) = match ty {
            "D" => run::<f64>(c),
            "F" => run::<f32>(c),
            "I" => run::<i32>(c),
            "B" => run::<i8>(c),
            "UB" => run::<u8>(c),
            _ => panic!("no type {ty}"),
        };
        let same_samples = samples.len() == want_samples.len()
            && samples
                .iter()
                .zip(want_samples)
                .all(|(a, b)| a.to_bits() == b.to_bits() || crate::common::c_value_eq(*a, *b));
        // The hash pins every value bit for bit, so it is compared only on
        // the platform the C values were captured on; elsewhere the samples,
        // compared within libm rounding, are the check.
        let hash_differs = crate::common::on_capture_platform() && hash != want_hash;
        if status != want_status || nused != want_nused || hash_differs || !same_samples {
            failures.push(format!(
                "{name} {ty}: status {status:?} want {want_status:?}; count {nused} want \
                 {want_nused}; hash {}; samples\n  got  {samples:?}\n  want {want_samples:?}",
                if hash == want_hash { "same" } else { "differs" }
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} cases differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

/// One error case of the probe: a call with both `rebin_init` and
/// `rebin_end` unless `seq` is false.
struct ErrorCase<'a> {
    ndim_in: usize,
    lbnd_in: &'a [i64],
    in_var: bool,
    out_var: bool,
    weights: bool,
    nused: bool,
    seq: bool,
    flags: RebinSeqFlags,
}

impl ErrorCase<'_> {
    fn run(&self) -> (i32, [f64; 4], i64) {
        let l2: &[i64] = &[1, 1];
        let u2: &[i64] = &[10, 10];
        let input: Vec<f64> = (0..100).map(|i| f64::from(i % 7)).collect();
        let in_var = vec![1.0; 100];
        let mut out = vec![7.0; 100];
        let mut out_var = vec![7.0; 100];
        let nw = if self.flags.gen_var { 200 } else { 100 };
        let mut weights = vec![5.0; nw];
        let mut nused: i64 = 9;
        let status = match rebin_seq(
            &UnitMap::new(2),
            Some(&RebinInput {
                lbnd: &self.lbnd_in[..self.ndim_in],
                ubnd: &u2[..self.ndim_in],
                region_lbnd: &l2[..self.ndim_in],
                region_ubnd: &u2[..self.ndim_in],
                data: &input[..if self.ndim_in == 1 { 10 } else { 100 }],
                var: self
                    .in_var
                    .then_some(&in_var[..if self.ndim_in == 1 { 10 } else { 100 }]),
            }),
            &mut RebinOutput {
                lbnd: l2,
                ubnd: u2,
                data: &mut out,
                var: self.out_var.then_some(&mut out_var[..]),
            },
            self.weights.then_some(&mut weights[..]),
            self.nused.then_some(&mut nused),
            &RebinSeqOptions {
                spread: Spread::Linear,
                params: &[],
                flags: RebinSeqFlags {
                    rebin_init: self.seq,
                    rebin_end: self.seq,
                    ..self.flags
                },
                tol: 0.0,
                maxpix: 50,
                wlim: 0.0,
            },
            -1.0,
        ) {
            Ok(()) => 0,
            Err(e) => e.code() as i32,
        };
        (status, [out[0], out[1], out_var[0], weights[0]], nused)
    }
}

#[test]
fn errors_match_c() {
    let l2: &[i64] = &[1, 1];
    let base = ErrorCase {
        ndim_in: 2,
        lbnd_in: l2,
        in_var: true,
        out_var: true,
        weights: true,
        nused: true,
        seq: true,
        flags: RebinSeqFlags::default(),
    };
    let flags = |f: fn(&mut RebinSeqFlags)| {
        let mut flags = RebinSeqFlags::default();
        f(&mut flags);
        flags
    };
    let got = [
        ErrorCase {
            flags: flags(|f| {
                f.use_var = true;
                f.gen_var = true
            }),
            ..base
        },
        ErrorCase {
            in_var: false,
            flags: flags(|f| f.use_var = true),
            ..base
        },
        ErrorCase {
            in_var: false,
            flags: flags(|f| f.var_wgt = true),
            ..base
        },
        ErrorCase {
            out_var: false,
            flags: flags(|f| f.use_var = true),
            ..base
        },
        ErrorCase {
            out_var: false,
            flags: flags(|f| f.gen_var = true),
            ..base
        },
        ErrorCase {
            flags: flags(|f| {
                f.no_norm = true;
                f.gen_var = true
            }),
            ..base
        },
        ErrorCase {
            weights: false,
            ..base
        },
        ErrorCase {
            nused: false,
            ..base
        },
        ErrorCase { ndim_in: 1, ..base },
        ErrorCase {
            ndim_in: 1,
            weights: false,
            ..base
        },
        ErrorCase {
            lbnd_in: &[11, 1],
            flags: flags(|f| f.use_var = true),
            ..base
        },
        ErrorCase {
            seq: false,
            flags: flags(|f| f.use_var = true),
            ..base
        },
    ]
    .map(|c| c.run());
    assert_eq!(got, cases::ERRORS);
}
