//! How a FITS-WCS write describes axes that each depend on both pixel axes,
//! against C: `IsMapLinear` (fitschan.c) cannot split such an axis off the
//! Mapping, so it holds the other output at its value where `astMapBox`
//! finds the tested output lowest, and widens the output's bounds when they
//! are equal. `OtherAxes` builds the same Mapping for an axis whether or not
//! `IsMapLinear` finds it linear, and tries `LogAxis` only when it does not,
//! so the exponential cases, written as `-LOG`, are the ones that show its
//! answer; the 1x1 images give equal bounds.
//!
//! Each FrameSet maps a 2-D GRID Frame to a 2-D Frame with a MathMap and is
//! written with NAXIS1 and NAXIS2 set. Compared with C: `map_box` over the
//! image for each output, bit for bit, and the value the write returns and
//! the cards written. `fitschan_coupled_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/fitschan_coupled_probe.c`.

#[rustfmt::skip]
#[path = "fitschan_coupled_oracle/cases.rs"]
mod cases;

use ast_core::frames::{BasicFrameBuilder, FrameRef, FrameSet};
use ast_core::mappings::{Mapping, MathMap};
use ast_core::{AnyObject, Channel, Encoding, FitsChan};

/// `map_box` over the image for each output, as `[lbnd, ubnd, xl, xu]`.
fn boxes(map: &MathMap, nx: i32, ny: i32) -> [Option<[f64; 6]>; 2] {
    let (lbnd, ubnd) = ([1.0, 1.0], [nx as f64, ny as f64]);
    [1, 2].map(|iout| {
        map.map_box(&lbnd, &ubnd, true, iout)
            .ok()
            .map(|b| [b.lbnd_out, b.ubnd_out, b.xl[0], b.xl[1], b.xu[0], b.xu[1]])
    })
}

/// The value the write returns and the cards written.
fn written(map: MathMap, nx: i32, ny: i32) -> (i32, Vec<String>) {
    let grid = BasicFrameBuilder::new(2).domain("GRID").build().unwrap();
    let wcs = BasicFrameBuilder::new(2).domain("X").build().unwrap();
    let mut fs = FrameSet::new(Box::new(grid));
    fs.add_frame(FrameRef::Base, Box::new(map), Box::new(wcs))
        .unwrap();
    let mut fc = FitsChan::new();
    fc.set_encoding(Encoding::FitsWcs);
    fc.put_fits(&format!("NAXIS1  = {nx}"), false).unwrap();
    fc.put_fits(&format!("NAXIS2  = {ny}"), false).unwrap();
    let ret = fc.write(&AnyObject::FrameSet(fs)).map_or(0, |n| n as i32);
    fc.clear_card().unwrap();
    let mut cards = Vec::new();
    while let Some(card) = fc.find_fits("%f", true).unwrap() {
        cards.push(card);
    }
    (ret, cards)
}

#[test]
fn coupled_axes_match_c() {
    let mut failed = Vec::new();
    for &(name, fwd, inv, nx, ny, mapbox, ret, cards) in cases::CASES {
        let map = MathMap::new(2, 2, &fwd, &inv).unwrap();
        let got = boxes(&map, nx, ny);
        let same = got.iter().zip(&mapbox).all(|(g, w)| match (g, w) {
            (Some(g), Some(w)) => crate::common::c_values_eq(g, w),
            (None, None) => true,
            _ => false,
        });
        if !same {
            failed.push(format!(
                "{name} map_box:\n--- rust\n{got:?}\n--- C\n{mapbox:?}"
            ));
        }
        let got = written(map, nx, ny);
        let want = (ret, cards.iter().map(|c| c.to_string()).collect::<Vec<_>>());
        if got.0 != want.0 || !crate::common::c_text_eq(&got.1.join("\n"), &want.1.join("\n")) {
            failed.push(format!("{name}:\n--- rust\n{got:#?}\n--- C\n{want:#?}"));
        }
    }
    assert!(failed.is_empty(), "{}", failed.join("\n"));
}
