//! The dumps of FrameSets whose current Frame has variants, against C's, for
//! a current Frame of each kind: a Frame, a SkyFrame, a SpecFrame and a
//! CmpFrame, and a Frame with Digits set, whose value the FrameSet's own
//! Frame part shows, unset, through its getter. frame.c `Dump` writes the variants FrameSet as `Vrnts`, last in
//! the Frame class's part, so for a subclass of Frame it comes before the
//! `IsA Frame` marker, where `astLoadFrame` reads it back. Each dump is read
//! back and dumped again, and written with Full = 1, less C's unset `RefCnt`
//! and `Nobj`, counts the port does not have.
//!
//! `frameset_variants_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/frameset_variants_probe.c`, which needs frameset.c
//! as fixed upstream at `5ac21af5`: before it, adding a variant left the
//! unset Domain of the current CmpFrame set.

#[rustfmt::skip]
#[path = "frameset_variants_oracle/cases.rs"]
mod cases;

use ast_core::frames::{
    BasicFrameBuilder, CmpFrame, DynFrame, FrameRef, FrameSet, SkyFrame, SkySystem, SpecFrame,
    SpecSystem,
};
use ast_core::mappings::{UnitMap, ZoomMap};
use ast_core::{AnyObject, Channel, NativeChannel, from_native_string, to_native_string};

fn basic(naxes: usize, domain: &str) -> DynFrame {
    Box::new(
        BasicFrameBuilder::new(naxes)
            .domain(domain)
            .build()
            .unwrap(),
    )
}

/// The probe's current Frame for `name`.
fn current(name: &str) -> DynFrame {
    match name {
        "frame" => basic(2, "CUR"),
        "skyframe" => {
            let mut f = SkyFrame::new(SkySystem::Icrs);
            f.clear_system();
            f.set_domain("SKY");
            Box::new(f)
        }
        "specframe" => {
            let mut f = SpecFrame::new(SpecSystem::Wavelen);
            f.clear_system().unwrap();
            f.set_domain("SPEC");
            Box::new(f)
        }
        "cmpframe" => Box::new(CmpFrame::new(basic(1, "A"), basic(1, "B"))),
        "frame_digits" => {
            let mut f = BasicFrameBuilder::new(2).domain("CUR").build().unwrap();
            f.set_digits(4);
            Box::new(f)
        }
        other => panic!("no case {other}"),
    }
}

/// A FrameSet from a Frame with Domain PIX to `name`'s current Frame, with a
/// variant of it two times larger.
fn frameset(name: &str) -> AnyObject {
    let frame = current(name);
    let naxes = frame.naxes();
    let mut fs = FrameSet::new(basic(naxes, "PIX"));
    fs.add_frame(FrameRef::Base, Box::new(UnitMap::new(naxes)), frame)
        .unwrap();
    fs.add_variant(Some(Box::new(ZoomMap::new(naxes, 2.0).unwrap())), "Two")
        .unwrap();
    AnyObject::FrameSet(fs)
}

#[test]
fn dumps_match_c() {
    for &(name, dump, reread, full) in cases::CASES {
        let fs = frameset(name);
        let text = to_native_string(&fs).unwrap();
        assert_eq!(text, dump, "{name}: dump");
        let back = from_native_string(&text).unwrap();
        assert_eq!(
            to_native_string(&back).unwrap(),
            reread,
            "{name}: read back"
        );

        let mut ch = NativeChannel::with_string_sink();
        ch.config_mut().set_full(1);
        ch.write(&fs).unwrap();
        assert_eq!(ch.into_string(), full, "{name}: Full = 1");
    }
}
