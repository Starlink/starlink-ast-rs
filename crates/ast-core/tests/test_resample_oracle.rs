//! `mappings::resample` against C's `astResample<X>` for every pixel type
//! and every interpolation scheme: nearest neighbour, linear, the 1-d
//! kernels, block averaging, a caller's kernel and a caller's interpolator,
//! with and without flux conservation. The cases cover 1-D, 2-D and 3-D
//! grids, linear and non-linear Mappings, linear fits, subdivision,
//! simplified and blocked outputs, bad pixels, `no_bad`, variances and an
//! output region. Each case compares the status, the number of bad pixels
//! and every output value and variance, through a hash of their bit
//! patterns, with a sample of values to show where a mismatch is; a case
//! that fails part way is compared on what it wrote before failing.
//!
//! `resample_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/resample_probe.c`, which documents the input data
//! and the caller's functions that [`tri_kernel`] and [`uinterp`] port.

