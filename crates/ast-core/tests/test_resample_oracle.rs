use ast_core::error::{AstError, AstResult, ErrorCode};
use ast_core::mappings::{
    DynMapping, Interp, InterpArgs, InterpFn, MathMap, PermMap, ResampleFlags, ResampleInput,
    ResampleOptions, ResampleOutput, ShiftMap, UnitMap, WinMap, ZoomMap, resample,
};
use ast_core::pixel::PixelValue;

fn mapping(name: &str) -> DynMapping {
    match name {
        "unit2" => Box::new(UnitMap::new(2)),
        "shift_half" => Box::new(ShiftMap::new(vec![0.5, -0.25])),
        "zoom2" => Box::new(ZoomMap::new(2, 1.7).unwrap()),
        "zoom1" => Box::new(ZoomMap::new(1, 1.3).unwrap()),
        "perm" => Box::new(PermMap::new(&[2, 1], &[2, 1], &[]).unwrap()),
        "nonlin2" => Box::new(
            MathMap::new(
                2,
                2,
                &["p=a", "q=b"],
                &["a=p+0.02*p*q-0.3", "b=q-0.015*p*p+0.2"],
            )
            .unwrap(),
        ),
        "cubic1" => Box::new(MathMap::new(1, 1, &["p=a"], &["a=0.001*p*p*p+0.5*p"]).unwrap()),
        "win3" => Box::new(
            WinMap::from_corners(
                &[0.0, 0.0, 0.0],
                &[1.0, 1.0, 1.0],
                &[0.3, -0.2, 0.1],
                &[1.1, 0.7, 1.4],
            )
            .unwrap(),
        ),
        "nonlin3" => Box::new(
            MathMap::new(
                3,
                3,
                &["p=a", "q=b", "r=c"],
                &["a=p+0.05*q*r", "b=q-0.03*p*p", "c=0.9*r+0.1*p"],
            )
            .unwrap(),
        ),
        "noinverse" => Box::new(MathMap::new(2, 2, &["p=a", "q=b"], &["a", "b"]).unwrap()),
        _ => panic!("no Mapping {name}"),
    }
}

/// The probe's `tri_kernel`: a triangle reaching two pixels either side,
/// scaled by `params[1]`, failing at an offset of exactly 1.5 when
/// `params[1]` is negative.
fn tri_kernel(offset: f64, params: &[f64], _flags: ResampleFlags) -> AstResult<f64> {
    let a = if offset < 0.0 { -offset } else { offset };
    if params[1] < 0.0 && a == 1.5 {
        return Err(AstError::new(ErrorCode::Badin, "tri_kernel: offset 1.5"));
    }
    Ok((if a < 2.0 { 1.0 - 0.5 * a } else { 0.0 }) * if params[1] < 0.0 { 1.0 } else { params[1] })
}

/// The probe's `uinterp_<X>`: each output value is `params[0]` times the
/// sum of the input coordinates, truncated, and each variance the first
/// input value; a point beyond the input grid's upper bound on the first
/// axis is bad. Fails when `params[0]` is negative.
fn uinterp<T: PixelValue>(
    a: &InterpArgs<'_, T>,
    out: &mut [T],
    mut out_var: Option<&mut [T]>,
) -> AstResult<usize> {
    if a.params[0] < 0.0 {
        return Err(AstError::new(ErrorCode::Badin, "uinterp: negative scale"));
    }
    let mut nbad = 0;
    for (point, &off) in a.offset.iter().enumerate() {
        let off = off as usize;
        if a.coords[0][point] > a.ubnd_in[0] as f64 {
            out[off] = a.badval;
            if let Some(v) = out_var.as_deref_mut() {
                v[off] = a.badval;
            }
            nbad += 1;
        } else {
            let mut sum = 0.0;
            for c in a.coords {
                sum += a.params[0] * c[point];
            }
            out[off] = T::from_f64(sum);
            if let Some(v) = out_var.as_deref_mut() {
                v[off] = a.input[0];
            }
        }
    }
    Ok(nbad)
}

fn interp<'a, T: PixelValue>(name: &str, uinterp: InterpFn<'a, T>) -> Interp<'a, T> {
    match name {
        "nearest" => Interp::Nearest,
        "linear" => Interp::Linear,
        "sinc" => Interp::Sinc,
        "sincsinc" => Interp::SincSinc,
        "sinccos" => Interp::SincCos,
        "sincgauss" => Interp::SincGauss,
        "gauss" => Interp::Gauss,
        "somb" => Interp::Somb,
        "sombcos" => Interp::SombCos,
        "blockave" => Interp::BlockAve,
        "ukern1" => Interp::UKern1(&tri_kernel),
        "uinterp" => Interp::UInterp(uinterp),
        _ => panic!("no scheme {name}"),
    }
}

fn npix(l: &[i64], u: &[i64]) -> usize {
    l.iter().zip(u).map(|(l, u)| (u - l + 1) as usize).product()
}

/// Run one case for pixel type `T`, returning (status, bad pixels, hash,
/// samples).
fn run<T: PixelValue>(c: &cases::Case) -> (i32, usize, u64, Vec<f64>) {
    let &(
        _,
        map,
        _,
        _,
        lbnd_in,
        ubnd_in,
        lbnd_out,
        ubnd_out,
        lbnd,
        ubnd,
        scheme,
        use_bad,
        no_bad,
        use_var,
        conserve_flux,
        params,
        tol,
        maxpix,
        ..,
    ) = c;
    let nin = npix(lbnd_in, ubnd_in);
    let nout = npix(lbnd_out, ubnd_out);
    let (mut data, mut var) = (Vec::with_capacity(nin), Vec::with_capacity(nin));
    for k in 0..nin as i64 {
        let (mut d, mut v) = if T::FLOATING {
            (
                T::from_f64(((7 * k) % 97) as f64 * 0.37 - 10.0),
                T::from_f64(((3 * k) % 11) as f64 * 0.5 - 1.0),
            )
        } else {
            let (ds, vs) = if T::SIGNED { (40, 2) } else { (0, 0) };
            (
                T::from_f64(((7 * k) % 97 - ds) as f64),
                T::from_f64(((3 * k) % 11 - vs) as f64),
            )
        };
        if use_bad && k % 17 == 3 {
            d = T::from_f64(120.0);
        }
        if use_bad && k % 19 == 5 {
            v = T::from_f64(120.0);
        }
        data.push(d);
        var.push(v);
    }
    let mut out = vec![T::from_f64(77.0); nout];
    let mut out_var = vec![T::from_f64(77.0); nout];
    let m = mapping(map);
    let result = resample(
        m.as_ref(),
        &ResampleInput {
            lbnd: lbnd_in,
            ubnd: ubnd_in,
            data: &data,
            var: use_var.then_some(&var[..]),
        },
        &mut ResampleOutput {
            lbnd: lbnd_out,
            ubnd: ubnd_out,
            region_lbnd: lbnd,
            region_ubnd: ubnd,
            data: &mut out,
            var: use_var.then_some(&mut out_var[..]),
        },
        &ResampleOptions {
            interp: interp(scheme, &uinterp::<T>),
            params: &params,
            flags: ResampleFlags {
                use_bad,
                no_bad,
                conserve_flux,
            },
            tol,
            maxpix,
        },
        T::from_f64(120.0),
    );
    let (status, nbad) = match result {
        Ok(nbad) => (0, nbad),
        Err(e) => (e.code() as i32, 0),
    };
    let mut hash: u64 = 14695981039346656037;
    for k in 0..nout {
        hash = (hash ^ out[k].to_f64().to_bits()).wrapping_mul(1099511628211);
        if use_var {
            hash = (hash ^ out_var[k].to_f64().to_bits()).wrapping_mul(1099511628211);
        }
    }
    let samples = out.iter().step_by(211).map(|v| v.to_f64()).collect();
    (status, nbad, hash, samples)
}

#[test]
fn resampling_matches_c() {
    let mut failures = Vec::new();
    for c in cases::CASES {
        let (name, ty, want_nbad, want_status, want_hash, want_samples) =
            (c.0, c.2, c.18, c.19, c.20, c.21);
        let (status, nbad, hash, samples) = match ty {
            "D" => run::<f64>(c),
            "F" => run::<f32>(c),
            "L" => run::<i64>(c),
            "UL" => run::<u64>(c),
            "I" => run::<i32>(c),
            "UI" => run::<u32>(c),
            "S" => run::<i16>(c),
            "US" => run::<u16>(c),
            "B" => run::<i8>(c),
            "UB" => run::<u8>(c),
            _ => panic!("no type {ty}"),
        };
        // C writes NaN where a block average's weights are infinite, so
        // samples are compared by bit pattern.
        let same_samples = samples.len() == want_samples.len()
            && samples.iter().zip(want_samples).all(|(a, b)| {
                a.to_bits() == b.to_bits()
                    || (a.is_nan() && b.is_nan())
                    || crate::common::c_value_eq(*a, *b)
            });
        // The hash pins every value bit for bit, so it is compared only on
        // the platform the C values were captured on; elsewhere the samples,
        // compared within libm rounding, are the check.
        let hash_differs = crate::common::on_capture_platform() && hash != want_hash;
        if status != want_status || nbad != want_nbad || hash_differs || !same_samples {
            failures.push(format!(
                "{name} {ty}: status {status} want {want_status}; bad {nbad} want {want_nbad}; \
                 hash {}; samples\n  got  {samples:?}\n  want {want_samples:?}",
                if hash == want_hash { "same" } else { "differs" }
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} cases differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

/// One error case of the probe: resample double data through `map` with
/// `interp`, `params`, `flags` and `tol`, returning the status.
struct ErrorCase<'a> {
    map: DynMapping,
    lbnd_in: &'a [i64],
    ubnd_in: &'a [i64],
    lbnd_out: &'a [i64],
    ubnd_out: &'a [i64],
    region: (&'a [i64], &'a [i64]),
    interp: Interp<'a, f64>,
    params: &'a [f64],
    flags: ResampleFlags,
    tol: f64,
}

impl ErrorCase<'_> {
    fn status(&self) -> i32 {
        let input: Vec<f64> = (0..400).map(f64::from).collect();
        let mut out = vec![0.0_f64; npix(self.lbnd_out, self.ubnd_out).min(400)];
        let n = npix(self.lbnd_in, self.ubnd_in).min(400);
        match resample(
            self.map.as_ref(),
            &ResampleInput {
                lbnd: self.lbnd_in,
                ubnd: self.ubnd_in,
                data: &input[..n],
                var: None,
            },
            &mut ResampleOutput {
                lbnd: self.lbnd_out,
                ubnd: self.ubnd_out,
                region_lbnd: self.region.0,
                region_ubnd: self.region.1,
                data: &mut out,
                var: None,
            },
            &ResampleOptions {
                interp: self.interp,
                params: self.params,
                flags: self.flags,
                tol: self.tol,
                maxpix: 50,
            },
            -1.0,
        ) {
            Ok(_) => 0,
            Err(e) => e.code() as i32,
        }
    }
}

#[test]
fn errors_match_c() {
    let l2: &[i64] = &[1, 1];
    let u2: &[i64] = &[10, 10];
    let bad: &[i64] = &[11, 1];
    let rl: &[i64] = &[0, 1];
    let ru: &[i64] = &[10, 11];
    let l3: &[i64] = &[1, 1, 1];
    let u3: &[i64] = &[10, 10, 1];
    let base = || ErrorCase {
        map: mapping("unit2"),
        lbnd_in: l2,
        ubnd_in: u2,
        lbnd_out: l2,
        ubnd_out: u2,
        region: (l2, u2),
        interp: Interp::Linear,
        params: &[],
        flags: ResampleFlags::default(),
        tol: 0.0,
    };
    let conserve = ResampleFlags {
        conserve_flux: true,
        ..Default::default()
    };
    let uinterp_d = uinterp::<f64>;
    let codes = [
        ErrorCase {
            lbnd_in: &l2[..1],
            ubnd_in: &u2[..1],
            ..base()
        },
        ErrorCase {
            lbnd_out: l3,
            ubnd_out: &[10, 10, 10],
            region: (l3, &[10, 10, 10]),
            ..base()
        },
        ErrorCase {
            lbnd_in: bad,
            ..base()
        },
        ErrorCase {
            lbnd_out: bad,
            ..base()
        },
        ErrorCase {
            region: (rl, u2),
            ..base()
        },
        ErrorCase {
            region: (l2, ru),
            ..base()
        },
        ErrorCase {
            tol: -1.0,
            ..base()
        },
        ErrorCase {
            map: mapping("noinverse"),
            ..base()
        },
        ErrorCase {
            flags: conserve,
            ..base()
        },
        ErrorCase {
            map: Box::new(PermMap::new(&[1, 2], &[1, 2, -1], &[0.5, 0.5]).unwrap()),
            lbnd_out: l3,
            ubnd_out: u3,
            region: (l3, u3),
            flags: conserve,
            tol: 0.1,
            ..base()
        },
        ErrorCase {
            map: mapping("nonlin2"),
            flags: conserve,
            tol: 1.0e-12,
            ..base()
        },
        ErrorCase {
            flags: ResampleFlags {
                no_bad: true,
                ..conserve
            },
            tol: 0.1,
            ..base()
        },
        ErrorCase {
            map: Box::new(ShiftMap::new(vec![0.5, 0.5])),
            interp: Interp::UKern1(&tri_kernel),
            params: &[2.0, -1.0],
            ..base()
        },
        ErrorCase {
            interp: Interp::UInterp(&uinterp_d),
            params: &[-1.0, 0.0],
            ..base()
        },
        ErrorCase {
            interp: Interp::UKern1(&tri_kernel),
            params: &[2.0, -1.0],
            ..base()
        },
    ]
    .map(|c| c.status());
    assert_eq!(codes, cases::ERRORS);
}

/// Parameters fewer than the scheme reads, which C cannot detect, are an
/// error.
#[test]
fn too_few_params_is_an_error() {
    let input = vec![1.0_f64; 100];
    let mut out = vec![0.0_f64; 100];
    let (l, u): (&[i64], &[i64]) = (&[1, 1], &[10, 10]);
    for (interp, params) in [
        (Interp::Sinc, &[][..]),
        (Interp::SincCos, &[2.0][..]),
        (Interp::Gauss, &[2.0][..]),
        (Interp::BlockAve, &[][..]),
    ] {
        let e = resample(
            &UnitMap::new(2),
            &ResampleInput {
                lbnd: l,
                ubnd: u,
                data: &input,
                var: None,
            },
            &mut ResampleOutput {
                lbnd: l,
                ubnd: u,
                region_lbnd: l,
                region_ubnd: u,
                data: &mut out,
                var: None,
            },
            &ResampleOptions {
                interp,
                params,
                flags: ResampleFlags::default(),
                tol: 0.0,
                maxpix: 50,
            },
            -1.0,
        )
        .unwrap_err();
        assert_eq!(e.code(), ErrorCode::Dimin, "{interp:?}");
    }
}
