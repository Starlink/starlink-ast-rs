//! Selecting a variant of a Frame whose node's Mapping is used in its inverse
//! direction, against C.
//!
//! A FrameSet joins Frame GRID to the current Frame B of a FrameSet A -> B,
//! so adding it re-roots A -> B at B and reverses the link to A, which is
//! written `Inv2 = 1`.
//! Selecting a variant replaces the Mapping of the current Frame's node with
//! that Mapping, used as the link says, followed by the change of variant,
//! simplified; the link then records the Invert of the result.
//! Each case adds a variant to Frame A or B and selects the Frame's own
//! variant again, and compares both dumps and the transformations with C's.
//! Each C dump is also read back and written again unchanged.
//!
//! `frameset_variant_link_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/frameset_variant_link_probe.c`.

use crate::common::native_dump;
#[rustfmt::skip]
#[path = "frameset_variant_link_oracle/cases.rs"]
mod cases;

use ast_core::AnyObject;
use ast_core::frames::{BasicFrameBuilder, DynFrame, FrameRef, FrameSet};
use ast_core::mappings::{DynMapping, MathMap, ShiftMap, UnitMap, ZoomMap};

fn frame(domain: &str) -> DynFrame {
    Box::new(BasicFrameBuilder::new(1).domain(domain).build().unwrap())
}

fn transforms(fs: &FrameSet) -> [f64; 2] {
    [2, 3].map(|to| {
        fs.mapping(FrameRef::Index(1), FrameRef::Index(to))
            .unwrap()
            .tran1(&[3.0], true)
            .unwrap()[0]
    })
}

fn dump(fs: &FrameSet) -> String {
    native_dump(&AnyObject::FrameSet(fs.clone())).unwrap()
}

/// The port's dumps and transformations for a case, in the order of the
/// probe's.
fn run(current: usize, link: &str, variant: &str) -> (String, [f64; 2], String, [f64; 2]) {
    let mut outer = FrameSet::new(frame("GRID"));
    let mut inner = FrameSet::new(frame("A"));
    let ab: DynMapping = match link {
        "shift" => Box::new(ShiftMap::new(vec![10.0])),
        _ => Box::new(MathMap::new(1, 1, &["y=x+10"], &["x=y-10"]).unwrap()),
    };
    inner.add_frame(FrameRef::Base, ab, frame("B")).unwrap();
    outer
        .add_frameset(
            FrameRef::Base,
            Box::new(ZoomMap::new(1, 2.0).unwrap()),
            inner,
        )
        .unwrap();
    outer.set_current(FrameRef::Index(current)).unwrap();
    let vmap: DynMapping = match variant {
        "unit" => Box::new(UnitMap::new(1)),
        "shift" => Box::new(ShiftMap::new(vec![5.0])),
        _ => Box::new(ZoomMap::new(1, 3.0).unwrap()),
    };
    outer.add_variant(Some(vmap), "V2").unwrap();
    let added = (dump(&outer), transforms(&outer));
    let domain = outer.current().domain().to_string();
    outer.set_variant(&domain).unwrap();
    (added.0, added.1, dump(&outer), transforms(&outer))
}

#[test]
fn selecting_a_variant_matches_c() {
    for &(name, current, link, variant, dump1, tran1, dump2, tran2) in cases::CASES {
        let (port1, port_tran1, port2, port_tran2) = run(current, link, variant);
        assert_eq!(port_tran1, tran1, "{name}: added");
        assert_eq!(port_tran2, tran2, "{name}: selected again");
        assert_eq!(port1, dump1, "{name}: added");
        assert_eq!(port2, dump2, "{name}: selected again");
    }
}

#[test]
fn c_dumps_read_back_unchanged() {
    for &(name, _, _, _, dump1, _, dump2, _) in cases::CASES {
        for text in [dump1, dump2] {
            let AnyObject::FrameSet(fs) = ast_core::from_native_string(text).unwrap() else {
                panic!("{name}: expected a FrameSet");
            };
            assert_eq!(dump(&fs), text, "{name}");
        }
    }
}
