//! ID, the Object attribute every AST Object has, against C's (object.c):
//! written first in the Object part of a dump whenever it is set, even
//! blank, and read back. A clone does not inherit it, as C's `astCopy` does
//! not copy it, and a move keeps it, so a composite keeps the IDs of the
//! parts it is made from. Each dump is read back and dumped again.
//!
//! C also drops the ID of a part it copies internally, and keeps that of an
//! object a simplification hands back unchanged. The port does not follow
//! C's internal choices of copy or shared reference: those cases are in
//! [`EXCLUDED`], and `excluded_cases_still_differ` fails when one matches.
//!
//! `object_id_oracle/cases.rs` is generated by
//! `tools/oracle_fixtures/object_id_probe.c`.

