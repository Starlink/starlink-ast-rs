fn lines(text: &str) -> Vec<&str> {
    text.lines().collect()
}

/// The difference between case `name` and C's dumps, if any.
fn difference(name: &str, dump: &[&str], reread: &[&str]) -> Option<String> {
    let text = to_native_string(&object(name)).unwrap();
    if lines(&text) != dump {
        return Some(format!("{name}: dump\n{text}"));
    }
    let back = from_native_string(&text).unwrap();
    let text = to_native_string(&back).unwrap();
    (lines(&text) != reread).then(|| format!("{name}: dump read back\n{text}"))
}

fn excluded(name: &str) -> bool {
    EXCLUDED.iter().any(|(n, _)| *n == name)
}

#[test]
fn dumps_match_c() {
    let failed: Vec<String> = cases::DUMPS
        .iter()
        .filter(|(name, ..)| !excluded(name))
        .filter_map(|&(name, dump, reread)| difference(name, dump, reread))
        .collect();
    assert!(failed.is_empty(), "{}", failed.join("\n"));
}

#[test]
fn excluded_cases_still_differ() {
    for (name, reason) in EXCLUDED {
        let &(_, dump, reread) = cases::DUMPS
            .iter()
            .find(|(n, ..)| n == name)
            .unwrap_or_else(|| panic!("no case {name}"));
        assert!(
            difference(name, dump, reread).is_some(),
            "{name} now matches C; remove it from EXCLUDED ({reason})"
        );
    }
}

#[test]
fn a_clone_has_no_id_and_keeps_ident() {
    let mut m = zoom(2.0, "id");
    m.set_ident("ident");
    let copy = m.clone();
    assert!(!copy.test_id());
    assert_eq!(copy.id(), "");
    assert_eq!(copy.ident(), "ident");
    assert_eq!(m.id(), "id");
}
