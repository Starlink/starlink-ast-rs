//! Every native fixture read through a Channel and written with Full = 1,
//! against C's text. With Full = 1 C writes every value a class's Dump
//! writes (channel.c `Use`): set values, and unset ones as comments, both
//! those it calls helpful and those it does not; every `IsA` marker; and a
//! Frame's Axes in full (frame.c `Dump`).
//!
//! The comparison leaves out what describes the C process rather than the
//! Object: C's Object part also writes the unset `RefCnt` and `Nobj`, counts
//! of pointers to the Object and of Objects of its class, which the port
//! does not have and the probe drops; and the unset `Seed` of a MathMap is
//! chosen at random when the MathMap is made, so both sides replace its
//! value with `<random>`.
//!
//! The text C writes for all the fixtures runs to megabytes, so
//! `fixture_full_dump_oracle/cases.rs`, generated by
//! `tools/oracle_fixtures/fixture_full_dump_probe.c`, holds the FNV-1a hash
//! of each fixture's text. To see a difference, run the probe with the
//! argument `text` and compare its output with that of the ignored test
//! `write_full_dumps`, which writes the port's text in the same form to the
//! file named by `AST_FULL_DUMP_TEXT`.

#[rustfmt::skip]
#[path = "fixture_full_dump_oracle/cases.rs"]
mod cases;

use std::path::{Path, PathBuf};

use ast_core::{Channel, NativeChannel, StringSource};

/// Fixtures whose Full = 1 text differs from C's, with the reason.
const EXCLUDED: &[(&str, &str)] = &[(
    "./serialisation/frame_in_map_slot.ast",
    "a CmpFrame in a Mapping slot, which the port refuses by design \
     (test_frame_in_map_slot.rs)",
)];

fn excluded(file: &str) -> bool {
    EXCLUDED.iter().any(|(f, _)| *f == file)
}

fn fixtures() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures")
}

/// The Objects in `fixture` written with Full = 1, one after another, each
/// line followed by a newline, or `None` if a read fails.
fn full_dump(fixture: &str) -> Option<String> {
    let text = std::fs::read_to_string(fixtures().join(fixture)).unwrap();
    let mut input = NativeChannel::new();
    input.set_source(Box::new(StringSource::new(&text)));
    let mut out = NativeChannel::with_string_sink();
    out.config_mut().set_full(1);
    for _ in 0..10 {
        match input.read() {
            Ok(Some(obj)) => {
                out.write(&obj).ok()?;
            }
            Ok(None) => break,
            Err(_) => return None,
        }
    }
    Some(
        out.into_string()
            .lines()
            .map(|line| normalise(line) + "\n")
            .collect(),
    )
}

/// `line` with the value of a MathMap's unset Seed replaced by `<random>`.
fn normalise(line: &str) -> String {
    const DEFAULT_SEED: &str = " \t# Default random number seed used";
    match line.split_once("Seed = ") {
        Some((head, tail)) if line.starts_with('#') && tail.ends_with(DEFAULT_SEED) => {
            format!("{head}Seed = <random>{DEFAULT_SEED}")
        }
        _ => line.to_string(),
    }
}

/// FNV-1a, 64 bits, as the probe computes it.
fn fnv1a(text: &str) -> u64 {
    text.bytes().fold(0xcbf2_9ce4_8422_2325, |h, b| {
        (h ^ u64::from(b)).wrapping_mul(0x0000_0100_0000_01b3)
    })
}

fn differs(file: &str, hash: u64) -> bool {
    full_dump(file).is_none_or(|text| fnv1a(&text) != hash)
}

#[test]
fn full_dumps_match_c() {
    let failed: Vec<&str> = cases::CASES
        .iter()
        .filter(|(file, _)| !excluded(file))
        .filter(|&&(file, hash)| differs(file, hash))
        .map(|(file, _)| *file)
        .collect();
    assert!(
        failed.is_empty(),
        "{} fixtures differ from C:\n{}",
        failed.len(),
        failed.join("\n")
    );
}

#[test]
fn excluded_fixtures_still_differ() {
    for (file, reason) in EXCLUDED {
        let &(_, hash) = cases::CASES
            .iter()
            .find(|(f, _)| f == file)
            .unwrap_or_else(|| panic!("no case {file}"));
        assert!(
            differs(file, hash),
            "{file} now matches C; remove it from EXCLUDED ({reason})"
        );
    }
}

/// Write the port's Full = 1 text for every fixture C reads to the file
/// named by `AST_FULL_DUMP_TEXT`, in the form of the probe's `text` output.
#[test]
#[ignore = "writes a file for comparison with the probe; run by hand"]
fn write_full_dumps() {
    let path = std::env::var("AST_FULL_DUMP_TEXT").expect("AST_FULL_DUMP_TEXT");
    let mut all = String::new();
    for (file, _) in cases::CASES {
        all.push_str(&format!("== {file}\n"));
        all.push_str(&full_dump(file).unwrap_or_default());
    }
    std::fs::write(path, all).unwrap();
}
