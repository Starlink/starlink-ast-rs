//! Per-class forward/inverse transform bench, paired with a C oracle bench.
//!
//! Each variant builds a deliberately non-trivial Mapping instance, serialises
//! it to the project's native text format, runs the Rust forward/inverse
//! transforms at a handful of point counts, and prints one row per
//! `(variant, direction, N)`. The same variants are loaded by
//! `bench_per_class_c.c` via `astFromString`, which emits matching rows. A
//! sibling script (or `join`/`paste`/`awk`) can merge the two outputs into a
//! single table comparing Rust ns/pt against C ns/pt per row.
//!
//! ## Running
//!
//!     # 1. Generate `.ast` files + Rust timings into /tmp/ast_bench_per_class/
//!     cargo run --release --example bench_per_class > /tmp/rust.tsv
//!
//!     # 2. Build + run the C side against the same manifest
//!     cc -O2 -o /tmp/bench_per_class_c crates/ast-core/tests/bench_per_class_c.c \
//!        -I reference/starlink-ast/build-ast -I reference/starlink-ast -I /opt/homebrew/include \
//!        -L reference/starlink-ast/build-ast -L /opt/homebrew/lib -last -lyaml -lm -lpthread
//!     DYLD_LIBRARY_PATH=reference/starlink-ast/build-ast /tmp/bench_per_class_c \
//!        /tmp/ast_bench_per_class/manifest.tsv > /tmp/c.tsv
//!
//!     # 3. Merge (join on variant + direction + npoint)
//!     paste /tmp/rust.tsv /tmp/c.tsv | column -t
//!
//! ## Caveats
//!
//! - Variants set `do_not_simplify = true` to ensure both sides bench the
//!   constructed mapping rather than its simplified form. (The C library's
//!   `astSimplify` is not called; `astTran2` does not auto-simplify by default.)
//! - Input points are generated by a deterministic linear scan over the
//!   variant's `input_range`, so Rust and C see identical inputs at each N.
//! - Inverse benches feed the forward output through the inverse, matching
//!   the realistic "round-trip" pattern (see bench_lsst.rs:32).
//! - Threshold below which timings are noisy: < 64 points. Included only
//!   to expose per-call overhead.

use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::time::Instant;

use ast_core::coords::PointSet;
use ast_core::mappings::{
    LutInterp, LutMap, Mapping, MatrixMap, PolyMap, PolyTerm, ShiftMap, SphMap, WcsMap,
    WcsProjection, WinMap, ZoomMap,
};
use ast_core::{AnyObject, to_native_string};
use ndarray::Array2;

/// One bench variant: a named mapping shape with a designated input domain.
struct Variant {
    name: &'static str,
    /// Construct the mapping. `do_not_simplify` should be set on the
    /// outermost object before serialisation so neither side simplifies away
    /// the workload.
    build: fn() -> AnyObject,
    /// Whether this mapping has a defined inverse (governs whether the
    /// inverse arm runs).
    has_inverse: bool,
    /// Per-axis range for input point generation: `(low, high)`.
    input_range: (f64, f64),
}

fn variants() -> Vec<Variant> {
    vec![
        Variant {
            name: "zoommap_2d_x2.5",
            build: build_zoommap,
            has_inverse: true,
            input_range: (-1.0, 1.0),
        },
        Variant {
            name: "shiftmap_2d",
            build: build_shiftmap,
            has_inverse: true,
            input_range: (-1.0, 1.0),
        },
        Variant {
            name: "matrixmap_3x3_full",
            build: build_matrixmap_full,
            has_inverse: true,
            input_range: (-1.0, 1.0),
        },
        Variant {
            name: "matrixmap_3x3_diagonal",
            build: build_matrixmap_diag,
            has_inverse: true,
            input_range: (-1.0, 1.0),
        },
        Variant {
            name: "winmap_2d",
            build: build_winmap,
            has_inverse: true,
            input_range: (-1.0, 1.0),
        },
        Variant {
            name: "polymap_2d_deg5",
            build: build_polymap_lsst_shape,
            has_inverse: true,
            input_range: (-0.5, 0.5),
        },
        Variant {
            name: "wcsmap_tan",
            build: build_wcsmap_tan,
            has_inverse: true,
            input_range: (-0.05, 0.05), // radians; small angles for projection domain
        },
        Variant {
            name: "sphmap_3d_to_2d",
            build: build_sphmap,
            has_inverse: false, // 3d->2d, separate inverse path
            input_range: (-1.0, 1.0),
        },
        Variant {
            name: "lutmap_100entries",
            build: build_lutmap,
            has_inverse: true,
            input_range: (0.0, 99.0),
        },
    ]
}

// --- variant builders -------------------------------------------------------
//
// All variants use deliberately non-trivial parameters so neither
// `Mapping::simplified()` (Rust) nor `astSimplify` (C) collapses them to
// `UnitMap` / identity. We do not call `simplify` on either side; `astTran2`
// does not auto-simplify, so what you serialise is what you bench.

fn build_zoommap() -> AnyObject {
    let m = ZoomMap::new(2, 2.5).expect("zoom 2.5 2D");
    AnyObject::ZoomMap(m)
}

fn build_shiftmap() -> AnyObject {
    let m = ShiftMap::new([0.25, -0.5]);
    AnyObject::ShiftMap(m)
}

fn build_matrixmap_full() -> AnyObject {
    // 3x3 rotation-like matrix (non-trivial; not diagonal).
    let m_arr = Array2::from_shape_vec(
        (3, 3),
        vec![
            0.866, -0.500, 0.000, 0.500, 0.866, 0.000, 0.100, 0.050, 0.995,
        ],
    )
    .unwrap();
    AnyObject::MatrixMap(MatrixMap::new(m_arr).expect("3x3 matrix"))
}

fn build_matrixmap_diag() -> AnyObject {
    // 3x3 diagonal — different code path inside MatrixMap.
    let m_arr = Array2::from_shape_vec((3, 3), vec![1.5, 0.0, 0.0, 0.0, 0.75, 0.0, 0.0, 0.0, 1.25])
        .unwrap();
    AnyObject::MatrixMap(MatrixMap::new(m_arr).expect("3x3 diagonal"))
}

fn build_winmap() -> AnyObject {
    let m = WinMap::new(&[0.5, -0.25], &[1.5, 0.75]).expect("winmap 2D");
    AnyObject::WinMap(m)
}

fn build_polymap_lsst_shape() -> AnyObject {
    // 2D polynomial similar in shape to the LSST simplified PolyMap:
    // ~20 terms per output, max power 5. Coefficients are chosen to be
    // safely invertible via Newton-Raphson in the input domain
    // [-0.5, 0.5]^2.
    let mut terms: Vec<PolyTerm> = Vec::new();
    // Output 1: dominantly linear in x, small higher-order corrections.
    for (px, py, coeff) in [
        (1, 0, 1.0),
        (0, 1, 0.05),
        (2, 0, 0.02),
        (1, 1, 0.01),
        (0, 2, 0.005),
        (3, 0, 0.003),
        (2, 1, 0.001),
        (1, 2, 0.001),
        (5, 0, 0.0001),
    ] {
        terms.push(PolyTerm {
            coeff,
            powers: vec![px, py],
            out_axis: 1,
        });
    }
    // Output 2: dominantly linear in y, similar pattern.
    for (px, py, coeff) in [
        (0, 1, 1.0),
        (1, 0, 0.05),
        (0, 2, 0.02),
        (1, 1, 0.01),
        (2, 0, 0.005),
        (0, 3, 0.003),
        (1, 2, 0.001),
        (2, 1, 0.001),
        (0, 5, 0.0001),
    ] {
        terms.push(PolyTerm {
            coeff,
            powers: vec![px, py],
            out_axis: 2,
        });
    }
    let mut m = PolyMap::new(2, 2, &terms, None).expect("polymap");
    // Iterative inverse so the inverse arm exercises NR.
    m.set_iter_inverse(true);
    m.set_niter_inverse(10);
    m.set_tol_inverse(1e-7);
    AnyObject::PolyMap(m)
}

fn build_wcsmap_tan() -> AnyObject {
    let m = WcsMap::new(2, WcsProjection::Tan, 1, 2).expect("WcsMap TAN");
    AnyObject::WcsMap(m)
}

fn build_sphmap() -> AnyObject {
    let m = SphMap::new();
    AnyObject::SphMap(m)
}

fn build_lutmap() -> AnyObject {
    // 100-entry strictly monotonic table — required for a defined inverse.
    // Use a smooth increasing function (i + 0.1 * i^1.3) that's
    // non-linear enough to make interpolation meaningful.
    let lut: Vec<f64> = (0..100)
        .map(|i| i as f64 + 0.1 * (i as f64).powf(1.3))
        .collect();
    let mut m = LutMap::new(&lut, 0.0, 1.0).expect("lutmap 100 entries");
    m.set_interp(LutInterp::Linear);
    AnyObject::LutMap(m)
}

// --- bench plumbing ---------------------------------------------------------

const NPOINTS: &[usize] = &[16, 256, 10_000, 100_000];

fn make_points(npoint: usize, nin: usize, range: (f64, f64)) -> PointSet {
    // Deterministic linear scan, slightly different stride per axis so points
    // are not all colinear. Identical formula on the C side.
    let (lo, hi) = range;
    let span = hi - lo;
    let mut rows = Vec::with_capacity(npoint);
    for i in 0..npoint {
        let t = if npoint > 1 {
            i as f64 / (npoint - 1) as f64
        } else {
            0.5
        };
        let mut row = Vec::with_capacity(nin);
        for axis in 0..nin {
            // Offset each axis by axis/(2*nin) so points form a diagonal
            // walk through input space rather than a colinear ramp.
            let offset = axis as f64 / (2.0 * nin as f64);
            let u = (t + offset).fract();
            row.push(lo + span * u);
        }
        rows.push(row);
    }
    PointSet::from_rows(rows)
}

fn iterations_for(npoint: usize) -> usize {
    // Target ~50 ms total per measurement at scalar speeds (~100 ns/pt).
    (500_000 / npoint.max(1)).max(3)
}

fn time_transform(map: &dyn Mapping, pts: &PointSet, forward: bool) -> f64 {
    // Pre-allocate output so the bench excludes allocation cost — that
    // mirrors how the C side benches via `astTran2` (caller-supplied
    // output buffers). For very-cheap mappings (Shift/Zoom/Win at
    // bulk N), allocation can be the dominant cost on Rust's side
    // (`transform` returns a new PointSet) which would make the
    // comparison apples-to-oranges.
    let nout = if forward { map.nout() } else { map.nin() };
    let mut out = PointSet::zeros(pts.npoint(), nout);
    map.transform_into(pts, forward, &mut out).expect("warmup");
    let iters = iterations_for(pts.npoint());
    let mut acc = 0.0_f64;
    let start = Instant::now();
    for _ in 0..iters {
        map.transform_into(pts, forward, &mut out)
            .expect("transform_into");
        // Prevent dead-code elimination by reading one output value.
        acc += out.point(0)[0];
    }
    let elapsed = start.elapsed().as_secs_f64();
    std::hint::black_box(acc);
    elapsed * 1e9 / (iters as f64 * pts.npoint() as f64)
}

fn write_manifest(entries: &[ManifestEntry], path: &Path) -> std::io::Result<()> {
    let mut f = fs::File::create(path)?;
    writeln!(f, "# variant\tast_file\tdirection\tnpoint")?;
    for e in entries {
        writeln!(
            f,
            "{}\t{}\t{}\t{}",
            e.variant,
            e.ast_file.display(),
            if e.forward { "forward" } else { "inverse" },
            e.npoint
        )?;
    }
    Ok(())
}

struct ManifestEntry {
    variant: String,
    ast_file: PathBuf,
    forward: bool,
    npoint: usize,
}

fn main() {
    let tmp = PathBuf::from("/tmp/ast_bench_per_class");
    fs::create_dir_all(&tmp).unwrap();

    let mut manifest_entries: Vec<ManifestEntry> = Vec::new();

    // Header — written to stdout for the user, not the manifest.
    println!(
        "{:<28}\t{:<7}\t{:>7}\t{:>12}",
        "variant", "dir", "npoint", "rust_ns/pt"
    );

    for v in variants() {
        let obj = (v.build)();
        let serialized = to_native_string(&obj).expect("serialize");
        let ast_path = tmp.join(format!("{}.ast", v.name));
        fs::write(&ast_path, &serialized).expect("write ast");

        let mapping = obj
            .into_mapping()
            .expect("variant build must produce a Mapping");
        let nin = mapping.nin();

        for &n in NPOINTS {
            let pts = make_points(n, nin, v.input_range);

            // Forward.
            let ns_pt = time_transform(mapping.as_ref(), &pts, true);
            println!(
                "{:<28}\t{:<7}\t{:>7}\t{:>12.1}",
                v.name, "forward", n, ns_pt
            );
            manifest_entries.push(ManifestEntry {
                variant: v.name.to_string(),
                ast_file: ast_path.clone(),
                forward: true,
                npoint: n,
            });

            // Inverse, when defined. Feed the forward output back so the
            // inverse sees in-domain inputs (matches realistic round-trip).
            if v.has_inverse {
                let fwd_out = mapping
                    .transform(&pts, true)
                    .expect("forward setup for inverse bench");
                let ns_pt = time_transform(mapping.as_ref(), &fwd_out, false);
                println!(
                    "{:<28}\t{:<7}\t{:>7}\t{:>12.1}",
                    v.name, "inverse", n, ns_pt
                );
                manifest_entries.push(ManifestEntry {
                    variant: v.name.to_string(),
                    ast_file: ast_path.clone(),
                    forward: false,
                    npoint: n,
                });
            }
        }
    }

    let manifest_path = tmp.join("manifest.tsv");
    write_manifest(&manifest_entries, &manifest_path).expect("write manifest");
    eprintln!("# manifest written to {}", manifest_path.display());
}
